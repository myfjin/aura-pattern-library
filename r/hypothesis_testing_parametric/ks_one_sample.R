# Sample 1: normal (should NOT reject)
x_normal <- rnorm(50, 0, 1)
# Sample 2: exponential (should reject when tested against normal)
x_exp <- rexp(50, 1)

# KS test for normal sample against standard normal
# ECDF at order statistics
x_sorted <- sort(x_normal)
n <- length(x_sorted)
F_emp_upper <- (1:n) / n  # Fn(x_i) = i/n
F_emp_lower <- (0:(n-1)) / n  # Fn(x_i-) = (i-1)/n

# Theoretical CDF: standard normal
F_theo <- pnorm(x_sorted, 0, 1)

# D+ = max(Fn(x_i) - F(x_i)), D- = max(F(x_i) - Fn(x_i-))
D_plus <- max(F_emp_upper - F_theo)
D_minus <- max(F_theo - F_emp_lower)
D_normal <- max(D_plus, D_minus)

# Oracle for normal sample
oracle_normal <- ks.test(x_normal, "pnorm", 0, 1)
stopifnot(all.equal(D_normal, unname(oracle_normal$statistic), tolerance=1e-6))
stopifnot(oracle_normal$p.value > 0.05)  # should NOT reject

# Now test exponential sample against normal (should reject)
x_exp_sorted <- sort(x_exp)
F_emp_upper_exp <- (1:n) / n
F_emp_lower_exp <- (0:(n-1)) / n
F_theo_exp <- pnorm(x_exp_sorted, 0, 1)

