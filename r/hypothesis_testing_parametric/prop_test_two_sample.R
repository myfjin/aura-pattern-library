# Group 1: successes x1 out of n1
x1 <- 20
n1 <- 50
p1 <- x1 / n1

# Group 2: successes x2 out of n2
x2 <- 36
n2 <- 60
p2 <- x2 / n2

# Pooled proportion under H0
p_pool <- (x1 + x2) / (n1 + n2)

# Standard error (pooled)
se <- sqrt(p_pool * (1 - p_pool) * (1/n1 + 1/n2))

# Z statistic
z <- (p1 - p2) / se
