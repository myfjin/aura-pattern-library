trend <- seq(0, 10, length.out = n)
remainder <- rnorm(n, 0, 1.5)
y <- seasonal + trend + remainder

period <- 4

# ===== Rolling Origin (Walk-Forward) CV =====
# Training window: t=1 to t=n_train
# Test point: t=n_train+1
# Repeat, incrementing n_train

n_train_init <- 50
n_test_total <- n - n_train_init

mae_seasonal_naive <- numeric(n_test_total)
mae_mean <- numeric(n_test_total)
mae_trend <- numeric(n_test_total)

for (i in 1:n_test_total) {
  n_train <- n_train_init + i - 1
  test_idx <- n_train + 1

  if (test_idx > n) break

  # Training data
  y_train <- y[1:n_train]

  # Test value
  y_test <- y[test_idx]

  # Forecast 1: Seasonal-naive (use value from one period ago)
  if (test_idx > period) {
    forecast_sn <- y[test_idx - period]
  } else {
    forecast_sn <- mean(y_train)
  }

  # Forecast 2: Mean
  forecast_mean <- mean(y_train)

  # Forecast 3: Trend (linear extrapolation)
  t_train <- 1:n_train
  fit_trend <- lm(y_train ~ t_train)
  forecast_trend <- coef(fit_trend)[1] + coef(fit_trend)[2] * test_idx

  # Errors
  mae_seasonal_naive[i] <- abs(y_test - forecast_sn)
  mae_mean[i] <- abs(y_test - forecast_mean)
  mae_trend[i] <- abs(y_test - forecast_trend)
}

