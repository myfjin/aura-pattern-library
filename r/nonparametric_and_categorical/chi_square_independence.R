obs_table <- matrix(c(20, 15, 10, 25, 30, 5), nrow=2, ncol=3)

# Manual chi-square
row_totals <- rowSums(obs_table)
col_totals <- colSums(obs_table)
n_total <- sum(obs_table)
expected <- outer(row_totals, col_totals) / n_total

chi_sq <- sum((obs_table - expected)^2 / expected)
df <- (nrow(obs_table) - 1) * (ncol(obs_table) - 1)
p_val <- 1 - pchisq(chi_sq, df)

# Oracle: chisq.test()
chi_oracle <- chisq.test(obs_table)

# Verify
