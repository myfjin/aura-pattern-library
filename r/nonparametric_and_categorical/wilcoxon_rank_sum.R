set.seed(42)
x <- rexp(12, 1)
y <- rexp(10, 1) + 2.5  # offset group, clearly separated

# From scratch: combined rank, group sums, U statistic
combined <- c(x, y)
ranks <- rank(combined)
n1 <- length(x)
n2 <- length(y)
rank_x <- sum(ranks[1:n1])
rank_y <- sum(ranks[(n1+1):(n1+n2)])

# U = n1*n2 + n1*(n1+1)/2 - R1
U <- n1 * n2 + n1 * (n1 + 1) / 2 - rank_x
# or equivalently U = n1*n2 + n2*(n2+1)/2 - R2 (check symmetry)
U_alt <- n1 * n2 + n2 * (n2 + 1) / 2 - rank_y
stopifnot(all.equal(U, n1*n2 - U_alt))  # one is complement

# Test statistic is the minimum of U and n1*n2 - U
W <- min(U, n1 * n2 - U)

# Normal approximation under H0: mean(U) = n1*n2/2, sd(U) = sqrt(n1*n2*(n1+n2+1)/12)
mu_U <- n1 * n2 / 2
sigma_U <- sqrt(n1 * n2 * (n1 + n2 + 1) / 12)
z <- (W - mu_U) / sigma_U
p_approx <- 2 * pnorm(abs(z), lower.tail=FALSE)

# Oracle: wilcox.test(correct=FALSE) gives p-value without continuity correction
oracle <- wilcox.test(x, y, correct=FALSE, exact=FALSE)
stopifnot(all.equal(p_approx, oracle$p.value, tolerance=1e-6))
stopifnot(all.equal(W, unname(oracle$statistic), tolerance=1e-6))

