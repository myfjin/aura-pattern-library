set.seed(42)
n <- 100
alpha <- 0.05
epsilon <- sqrt(log(2/alpha) / (2*n))

# Single sample ECDF + bands
x <- rnorm(n)
x_sorted <- sort(x)
Fn <- (1:n) / n
F_lower <- pmax(0, Fn - epsilon)
F_upper <- pmin(1, Fn + epsilon)
F_true <- pnorm(x_sorted)

# Check coverage for one sample
inside_bands <- (F_true >= F_lower) & (F_true <= F_upper)
coverage_one <- mean(inside_bands)
stopifnot(coverage_one > 0.9)  # should be close to 1-α

# Repeat over multiple samples to verify nominal coverage
n_reps <- 100
coverages <- numeric(n_reps)

for (rep in 1:n_reps) {
  x <- rnorm(n)
  x_sorted <- sort(x)
  Fn <- (1:n) / n
  F_lower <- pmax(0, Fn - epsilon)
  F_upper <- pmin(1, Fn + epsilon)
  F_true <- pnorm(x_sorted)
  inside <- mean((F_true >= F_lower) & (F_true <= F_upper))
  coverages[rep] <- inside
}

avg_coverage <- mean(coverages)
stopifnot(avg_coverage > 1 - alpha - 0.05)  # within tolerance of nominal

