x <- c(rnorm(50), 10, -10)  # Plant 2 outliers

# IQR method
q1 <- quantile(x, 0.25)
q3 <- quantile(x, 0.75)
iqr <- q3 - q1
lower_fence <- q1 - 1.5 * iqr
upper_fence <- q3 + 1.5 * iqr
outliers_iqr <- which(x < lower_fence | x > upper_fence)

# MAD method (Median Absolute Deviation)
median_x <- median(x)
mad <- median(abs(x - median_x))
z_mad <- abs(x - median_x) / mad
outliers_mad <- which(z_mad > 2.5)

# Verify planted outliers are caught
stopifnot(length(outliers_iqr) >= 2)
stopifnot(52 %in% outliers_iqr || 51 %in% outliers_iqr)

# Verify planted outliers are indeed extreme
