x <- c(rnorm(50, 0, 1), rnorm(50, 4, 1))

# Silverman bandwidth
n <- length(x)
bw <- (4 * var(x)^5 / (3 * n))^(1/5)

# KDE evaluation on a grid
grid <- seq(-5, 8, length.out=100)
kde_vals <- numeric(length(grid))
for (i in seq_along(grid)) {
  kde_vals[i] <- mean(dnorm(grid[i], mean=x, sd=bw))
}

# Oracle: density()
dens <- density(x, bw=bw)
dens_grid <- approx(dens$x, dens$y, grid)$y

# Verify (allow higher tolerance due to grid interpolation)
stopifnot(all.equal(kde_vals, dens_grid, tolerance=0.05))

