set.seed(42)
n <- 500
mu <- c(0, 0)
Sigma <- matrix(c(1, 0.6, 0.6, 1), nrow=2)

# Cholesky decomposition (my implementation)
# For 2x2: L11 = sqrt(Σ11), L21 = Σ21/L11, L22 = sqrt(Σ22 - L21²)
# L = [L11  0  ]  (column-major storage)
#     [L21  L22]
L11 <- sqrt(Sigma[1,1])
L21 <- Sigma[2,1] / L11
L22 <- sqrt(Sigma[2,2] - L21^2)
L <- matrix(c(L11, L21, 0, L22), nrow=2)  # default byrow=FALSE, column-major

# Verify against built-in chol()
L_oracle <- t(chol(Sigma))  # chol() returns upper triangular, we want lower
stopifnot(all.equal(L, L_oracle, tolerance=1e-6))

# Generate samples: Z ~ N(0,I), X_i = μ + Z_i %*% t(L) for each row
