set.seed(42)
alpha <- 2
beta_param <- 5

# Beta(2,5) density (unnormalized): f(x) = x^(α-1) * (1-x)^(β-1)
beta_density <- function(x) x^(alpha-1) * (1-x)^(beta_param-1)

# Find maximum of density on [0,1]
x_seq <- seq(0, 1, len=1000)
dens_seq <- beta_density(x_seq)
M <- max(dens_seq)  # envelope constant for uniform proposal

# Rejection sampling
samples <- numeric(0)
n_target <- 200
n_attempted <- 0

while (length(samples) < n_target) {
  X <- runif(1000)  # propose from Uniform(0,1)
  U <- runif(1000)
  # Accept if U < f(X) / (M * 1) where g(x)=1 for uniform
  accept_idx <- U < beta_density(X) / M
  samples <- c(samples, X[accept_idx])
  n_attempted <- n_attempted + 1000
}

samples <- samples[1:n_target]

# Acceptance rate (informational; KS test validates correctness)
acceptance_rate <- n_target / n_attempted

# KS test
ks_result <- ks.test(samples, "pbeta", alpha, beta_param)
stopifnot(ks_result$p.value > 0.05)

