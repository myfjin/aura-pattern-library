set.seed(42)
n <- 10
n_samples <- 200

# Min of n uniforms: X_{(1)} ~ Beta(1, n)
# Max of n uniforms: X_{(n)} ~ Beta(n, 1)
min_vals <- numeric(n_samples)
max_vals <- numeric(n_samples)

for (i in 1:n_samples) {
  u <- runif(n)
  min_vals[i] <- min(u)
  max_vals[i] <- max(u)
}

# Min should follow Beta(1, n) = 1 - (1-x)^n, i.e., CDF is (1-(1-x)^n)
# equivalently, F_min(x) = 1 - (1-x)^n
# PDF: f_min(x) = n(1-x)^{n-1}
ks_min <- ks.test(min_vals, "pbeta", 1, n)
stopifnot(ks_min$p.value > 0.05)

# Max should follow Beta(n, 1) = x^n
# F_max(x) = x^n
# PDF: f_max(x) = n*x^{n-1}
ks_max <- ks.test(max_vals, "pbeta", n, 1)
stopifnot(ks_max$p.value > 0.05)

# Median (for n=10, X_{(5)} and X_{(6)} are close, use their avg)
# X_{(5)} ~ Beta(5, 6), X_{(6)} ~ Beta(6, 5)
# Verify median sample is roughly symmetric around 0.5
mean_min <- mean(min_vals)
mean_max <- mean(max_vals)
stopifnot(mean_min < 0.1)  # min should be small
stopifnot(mean_max > 0.9)  # max should be large

