T <- 4
lambda_max <- 3.1  # upper bound on λ(t) = 2 + sin(πt/T)

# Lambda function
lambda_t <- function(t) 2 + sin(pi * t / T)

# Generate homogeneous Poisson with rate λ_max
arrivals_homo <- numeric()
t_curr <- 0
while (t_curr < T) {
  delta_t <- rexp(1, lambda_max)
  t_curr <- t_curr + delta_t
  if (t_curr < T) arrivals_homo <- c(arrivals_homo, t_curr)
}

# Thin: keep each arrival t with probability λ(t) / λ_max
keep <- numeric()
for (t in arrivals_homo) {
  if (runif(1) < lambda_t(t) / lambda_max) {
    keep <- c(keep, t)
  }
}

# Verify inter-arrival times of homogeneous subset match exponential(λ_max)
inter_arrivals_homo <- diff(arrivals_homo)
ks_homo <- ks.test(inter_arrivals_homo, "pexp", lambda_max)
stopifnot(ks_homo$p.value > 0.05)  # homogeneous inter-arrivals should be exponential

# Verify thinned process intensity
