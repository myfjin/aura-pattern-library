# Analytic truncated mean and variance
# E[X|a<X<b] = μ + σ * (φ(α) - φ(β)) / (Φ(β) - Φ(α))
# where α = (a-μ)/σ, β = (b-μ)/σ, φ=density, Φ=CDF
alpha <- (a - mu) / sigma
beta <- (b - mu) / sigma
Phi_diff <- pnorm(beta) - pnorm(alpha)
mean_trunc_analytic <- mu + sigma * (dnorm(alpha) - dnorm(beta)) / Phi_diff

# Var[X|a<X<b] = σ² * [1 + (α*φ(α) - β*φ(β))/Φ_diff - ((φ(α)-φ(β))/Φ_diff)²]
