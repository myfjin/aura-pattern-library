n <- 100
X <- cbind(1, rnorm(n), rnorm(n))
y <- rbinom(n, 1, plogis(X %*% c(0.5, 0.8, -0.5)))

# IRLS loop
beta <- rep(0, 3)
for (iter in 1:100) {
  eta <- X %*% beta
  p <- plogis(eta)
  w <- as.numeric(p * (1 - p))
  w[w < 1e-8] <- 1e-8
  z <- eta + (y - p) / w
  XwX <- t(X) %*% (X * w)
  Xwz <- t(X) %*% (w * z)
  beta_new <- solve(XwX) %*% Xwz
  if (max(abs(beta_new - beta)) < 1e-6) break
  beta <- beta_new
}

# Oracle: glm()
