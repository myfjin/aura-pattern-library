# ===== Data generation: true slope = 2.5 =====
true_slope <- 2.5
true_intercept <- 5
n <- 50
x <- rnorm(n, mean = 10, sd = 3)
y <- true_intercept + true_slope * x + rnorm(n, 0, 2)

# ===== Bootstrap regression CI =====
n_boot <- 1000
bootstrap_slopes <- numeric(n_boot)

for (b in 1:n_boot) {
  # Resample cases (pairs)
  idx_boot <- sample(1:n, n, replace = TRUE)
  x_boot <- x[idx_boot]
  y_boot <- y[idx_boot]

  # Fit and extract slope
  fit_boot <- lm(y_boot ~ x_boot)
  bootstrap_slopes[b] <- coef(fit_boot)[2]
}

# Percentile CI
ci_lower <- quantile(bootstrap_slopes, 0.025)
ci_upper <- quantile(bootstrap_slopes, 0.975)

