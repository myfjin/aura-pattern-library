set.seed(42)
n <- 60
X <- cbind(1, rnorm(n), rnorm(n), rnorm(n))  # intercept + 3 predictors
beta_true <- c(2, 1.5, -0.8, 0.5)
y <- X %*% beta_true + rnorm(n, 0, 0.5)

# Ridge regression for sequence of λ
lambdas <- c(0, 0.1, 1, 10, 100)
ridge_coefs <- matrix(NA, nrow=length(lambdas), ncol=ncol(X))

for (i in seq_along(lambdas)) {
  lambda <- lambdas[i]
  XtX <- t(X) %*% X
  Xty <- t(X) %*% y
  beta_ridge <- solve(XtX + lambda * diag(ncol(X))) %*% Xty
  ridge_coefs[i, ] <- beta_ridge
}

# Verify λ=0 matches lm()
lm_fit <- lm(y ~ X[, 2] + X[, 3] + X[, 4])
lm_coefs <- coef(lm_fit)
stopifnot(all.equal(ridge_coefs[1, ], unname(c(lm_coefs[1], lm_coefs[2:4])), tolerance=1e-6))

# Check monotonic shrinkage: L2 norm of coefficients decreases with λ (excluding intercept for stability)
coef_norms <- sqrt(rowSums(ridge_coefs[, 2:4]^2))
for (i in 1:(nrow(ridge_coefs)-1)) {
  stopifnot(coef_norms[i] >= coef_norms[i+1])  # should be non-increasing
}

cat("ridge_regression: λ=0 matches lm(), coef norms shrink:", round(coef_norms, 4))

