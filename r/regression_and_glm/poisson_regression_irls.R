set.seed(42)
n <- 50
x <- rnorm(n, 0, 1)
# Planted: η = -1 + 1.5*x, so μ = exp(η)
eta_true <- -1 + 1.5 * x
mu_true <- exp(eta_true)
y <- rpois(n, mu_true)

# IRLS for Poisson with log link
X <- cbind(1, x)  # design matrix with intercept
beta <- c(0, 0)   # initialize
max_iter <- 20
tol <- 1e-8

for (iter in 1:max_iter) {
  eta <- X %*% beta
  mu <- exp(eta)
  # Weights: for log link with Poisson, W_ii = μ_i (since Var=μ and (dη/dμ)²Var = (1/μ)²*μ = 1/μ)
  W <- diag(as.vector(mu))
  # Adjusted response: z = η + (y - μ)/μ = η + (y/μ - 1)
  z <- as.vector(eta + (y - mu) / mu)
  # Refit: (X'WX)β = X'Wz
  XWX <- t(X) %*% W %*% X
  Xwz <- t(X) %*% W %*% z
  beta_new <- solve(XWX) %*% Xwz

  if (max(abs(beta_new - beta)) < tol) break
  beta <- beta_new
}

# Oracle: glm(family=poisson)
oracle_fit <- glm(y ~ x, family=poisson)
stopifnot(all.equal(as.vector(beta), unname(coef(oracle_fit)), tolerance=1e-6))

