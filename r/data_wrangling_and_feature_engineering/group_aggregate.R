  idx <- which(groups == g)
  parts <- strsplit(g, "-")[[1]]
  agg_manual <- rbind(agg_manual, data.frame(
    group1 = parts[1],
    group2 = as.numeric(parts[2]),
    mean = mean(df$value[idx])
  ))
}

