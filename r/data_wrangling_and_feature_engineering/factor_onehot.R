set.seed(42)
f <- factor(rep(c("red", "blue", "green"), c(10, 15, 5)), levels=c("red", "blue", "green"))

# Manual one-hot
onehot <- matrix(0, nrow=length(f), ncol=nlevels(f))
colnames(onehot) <- levels(f)
for (i in seq_along(f)) {
  level_idx <- which(levels(f) == f[i])
  onehot[i, level_idx] <- 1
}

# Verify column sums match level counts
level_counts <- table(f)
col_sums <- colSums(onehot)
stopifnot(all.equal(as.numeric(col_sums), as.numeric(level_counts), tolerance=1e-8))

# Verify each row has exactly one 1
row_sums <- rowSums(onehot)
stopifnot(all(row_sums == 1))

# Unseen level policy: new observation would get zeros
unseen_vec <- rep(0, nlevels(f))
stopifnot(sum(unseen_vec) == 0)

