  y[i] <- phi * y[i - 1] + rnorm(1)
}

# ===== Manual Ljung-Box =====
# Q = n(n+2) * sum_{k=1}^h [ rho_k^2 / (n-k) ]
# where rho_k is sample ACF

h <- 10  # Number of lags

# Compute ACF manually
acf_manual <- numeric(h)
for (k in 1:h) {
  c0 <- sum((y - mean(y))^2) / n
  ck <- sum((y[1:(n-k)] - mean(y)) * (y[(k+1):n] - mean(y))) / n
  acf_manual[k] <- ck / c0
}

