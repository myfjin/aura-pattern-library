import random
from typing import List, Tuple

def mnar_missingness_bias() -> None:
    random.seed(42)

    n = 200
    # True values: x ~ Uniform(0, 100)
    true_values = [random.uniform(0, 100) for _ in range(n)]

    # MNAR mechanism: values > 70 are missing with high probability
    # (e.g., high-income respondents less likely to report income)
    mnar_observed = []
    for val in true_values:
        is_missing = random.random() < (0.7 if val > 70 else 0.1)
        mnar_observed.append(None if is_missing else val)

    # MCAR mechanism: completely random missingness, 30% rate
    mcar_observed = []
    for val in true_values:
        is_missing = random.random() < 0.3
        mcar_observed.append(None if is_missing else val)

    # Complete-case analysis
    def complete_case_mean(observed: List) -> float:
        observed_vals = [v for v in observed if v is not None]
        return sum(observed_vals) / len(observed_vals) if observed_vals else 0

    true_mean = sum(true_values) / n
    mnar_mean = complete_case_mean(mnar_observed)
    mcar_mean = complete_case_mean(mcar_observed)

    mnar_bias = abs(mnar_mean - true_mean)
    mcar_bias = abs(mcar_mean - true_mean)

    # MNAR should show systematic bias (towards lower values due to missing high values)
    assert mnar_mean < true_mean, (
        f"MNAR complete-case mean ({mnar_mean:.1f}) should be < true mean "
        f"({true_mean:.1f}) due to missing high values"
    )

    # MNAR bias should be significant (> 5)
    assert mnar_bias > 5, f"MNAR bias should be > 5, got {mnar_bias}"

    # MCAR bias should be much smaller (random sampling)
    assert mcar_bias < mnar_bias, (
        f"MCAR bias ({mcar_bias:.1f}) should be < MNAR bias ({mnar_bias:.1f})"
    )

