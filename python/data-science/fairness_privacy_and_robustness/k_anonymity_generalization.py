import random
from collections import Counter
from typing import List, Tuple

def k_anonymity_generalization() -> None:
    random.seed(42)

    # Dataset: (age, gender, sensitive_attribute)
    n = 100
    data = [
        (random.randint(18, 75), random.choice(["M", "F"]), random.randint(0, 1))
        for _ in range(n)
    ]

    # Generalize age to ranges: [18-30, 31-50, 51-75]
    def generalize_age(age: int) -> str:
        if age <= 30:
            return "18-30"
        elif age <= 50:
            return "31-50"
        else:
            return "51-75"

    generalized_data = [(generalize_age(age), gender) for age, gender, _ in data]

    # Count occurrences of each quasi-identifier combination
    combo_counts = Counter(generalized_data)

    # Verify k-anonymity (k=3)
    k = 3
    for combo, count in combo_counts.items():
        assert count >= k, f"Combination {combo} appears {count} times, need >= {k}"

    # Utility loss: precision lost in generalization
