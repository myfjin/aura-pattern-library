    generalized_variance = sum((age - 45) ** 2 for age in generalized_ages) / n

    utility_loss = abs(original_age_variance - generalized_variance) / original_age_variance
    assert utility_loss > 0.1, f"Utility loss should be > 0.1, got {utility_loss}"

