import random
from typing import List, Tuple


def iqr_outliers(data: List[float]) -> Tuple[List[int], float, float, float]:
    """
    Detect outliers using IQR method.
    Returns (outlier_indices, Q1, Q3, IQR).
    """
    if len(data) < 4:
        return [], 0, 0, 0

    sorted_data = sorted(data)
    n = len(sorted_data)

    # Compute quartiles (simple method: two halves)
    if n % 2 == 0:
        lower_half = sorted_data[:n // 2]
        upper_half = sorted_data[n // 2:]
    else:
        lower_half = sorted_data[:n // 2]
        upper_half = sorted_data[n // 2 + 1:]

    q1 = sorted_data[n // 4] if n >= 4 else sorted_data[0]
    q3 = sorted_data[3 * n // 4] if n >= 4 else sorted_data[-1]
    iqr = q3 - q1

    # Outlier bounds
    lower_bound = q1 - 1.5 * iqr
    upper_bound = q3 + 1.5 * iqr

    # Identify outliers
    outliers = [i for i, x in enumerate(data) if x < lower_bound or x > upper_bound]

    return outliers, q1, q3, iqr


