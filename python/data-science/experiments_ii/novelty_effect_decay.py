import math
from typing import List

def simulate_novelty_decay(n_users: int, true_long_run_effect: float, novelty_boost: float, decay_rate: float) -> List[List[float]]:
    """Simulate outcomes over time with novelty effect decay.

    Returns: list of [day1_obs, day2_obs, ..., day10_obs] per user (time-sliced).
    """
    import random
    random.seed(42)

    results = []
    for _ in range(n_users):
        user_outcomes = []
        for day in range(1, 11):
            # Long-run effect decays the novelty boost.
            novelty = novelty_boost * math.exp(-decay_rate * (day - 1))
            effect = true_long_run_effect + novelty
            outcome = effect + random.gauss(0, 0.5)
            user_outcomes.append(outcome)
        results.append(user_outcomes)

    return results

def time_sliced_ate(control_outcomes: List[List[float]], treatment_outcomes: List[List[float]], day: int) -> float:
    """Compute ATE on a specific day (time-slice)."""
    t_day = [t[day - 1] for t in treatment_outcomes]
    c_day = [c[day - 1] for c in control_outcomes]
    return sum(t_day) / len(t_day) - sum(c_day) / len(c_day)

