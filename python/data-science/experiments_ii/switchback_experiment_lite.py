def user_split_ab(n_users: int, true_effect: float, spillover: float) -> float:
    """User-split A/B under interference — controls are contaminated by spillover."""
    import random
    random.seed(42)
    treated = set(random.sample(range(n_users), n_users // 2))
    tr, co = [], []
    for u in range(n_users):
        if u in treated:
            tr.append(true_effect + random.gauss(0, 1))
        else:
            # Control is partially exposed to the treatment via the marketplace.
            co.append(true_effect * spillover + random.gauss(0, 1))
    return sum(tr) / len(tr) - sum(co) / len(co)

def switchback(n_blocks: int, block_size: int, true_effect: float) -> float:
    """Whole-market time blocks: no cross-contamination within a block."""
    import random
    random.seed(42)
    tr, co = [], []
    for b in range(n_blocks):
        is_treatment = (b % 2 == 0)
        for _ in range(block_size):
            if is_treatment:
                tr.append(true_effect + random.gauss(0, 1))
            else:
                co.append(0.0 + random.gauss(0, 1))
    return sum(tr) / len(tr) - sum(co) / len(co)

