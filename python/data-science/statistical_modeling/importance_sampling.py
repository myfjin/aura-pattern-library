import random
import math
from typing import List, Callable, Tuple


def importance_sampling(
    target_pdf: Callable[[float], float],
    proposal_pdf: Callable[[float], float],
    proposal_sample: Callable[[], float],
    h: Callable[[float], float],
    n_samples: int,
) -> Tuple[float, float]:
    """
    Estimate E_target[h(X)] via importance sampling.

    Args:
        target_pdf: unnormalized target density
        proposal_pdf: proposal density (must have support ⊇ target)
        proposal_sample: function that samples from proposal
        h: function to integrate
        n_samples: number of samples

    Returns:
        (estimate, effective_sample_size)
    """
    samples = []
    weights = []

    for _ in range(n_samples):
        x = proposal_sample()
        w = target_pdf(x) / proposal_pdf(x)
        samples.append(x)
        weights.append(w)

    # Normalize weights
    total_weight = sum(weights)
    if total_weight <= 0:
        raise ValueError("All weights non-positive")

    norm_weights = [w / total_weight for w in weights]

    # Estimate
    estimate = sum(h(x) * w for x, w in zip(samples, norm_weights))

    # Effective sample size: ESS = 1 / sum(w_norm^2)
    ess = 1.0 / sum(w ** 2 for w in norm_weights)

    return estimate, ess


