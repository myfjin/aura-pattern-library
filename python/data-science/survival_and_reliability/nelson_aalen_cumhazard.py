from typing import List, Tuple

def nelson_aalen_cumhazard(
    times: List[float],
    events: List[int]
) -> Tuple[List[float], List[float]]:
    """Compute Nelson-Aalen cumulative hazard estimate.

    Returns: (time_points, cumhazard_values).
    """
    n = len(times)
    event_times = sorted(set(t for t, e in zip(times, events) if e == 1))

    cumhazard = [0.0]
    times_out = [0.0]

    for t in event_times:
        d_t = sum(1 for i in range(n) if times[i] == t and events[i] == 1)
        y_t = sum(1 for i in range(n) if times[i] >= t)

        if y_t > 0:
            cumhazard.append(cumhazard[-1] + d_t / y_t)
            times_out.append(t)

    return times_out, cumhazard

