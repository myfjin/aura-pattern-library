def aft_fit(log_times: List[float], x: List[float]) -> Tuple[float, float, float]:
    """Fit AFT model: log(T) = μ + β·x + ε.

    Returns: (mu, beta, sigma).
    """
    n = len(log_times)
    mean_x = sum(x) / n
    mean_log_t = sum(log_times) / n

    cov_x_logt = sum((x[i] - mean_x) * (log_times[i] - mean_log_t) for i in range(n)) / n
    var_x = sum((x[i] - mean_x)**2 for i in range(n)) / n

    if var_x < 1e-14:
        return mean_log_t, 0.0, 1.0

    beta = cov_x_logt / var_x
    mu = mean_log_t - beta * mean_x

    residuals = [log_times[i] - (mu + beta * x[i]) for i in range(n)]
    sigma = (sum(r**2 for r in residuals) / n)**0.5

    return mu, beta, sigma

