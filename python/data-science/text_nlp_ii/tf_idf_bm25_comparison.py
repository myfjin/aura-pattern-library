import math
from typing import List, Dict

def tf_idf(docs: List[List[str]], query: List[str]) -> List[float]:
    """Compute TF-IDF scores for documents against query."""
    # Build IDF.
    idf = {}
    num_docs = len(docs)
    for term in set(t for doc in docs for t in doc):
        doc_count = sum(1 for doc in docs if term in doc)
        idf[term] = math.log(num_docs / (1 + doc_count))

    # Score each document.
    scores = []
    for doc in docs:
        score = 0.0
        for term in query:
            tf = doc.count(term)
            score += tf * idf.get(term, 0.0)
        scores.append(score)

    return scores

def bm25(docs: List[List[str]], query: List[str], k1: float = 1.5, b: float = 0.75) -> List[float]:
    """Compute BM25 scores (dampened TF, length-normalized)."""
    idf = {}
    num_docs = len(docs)
    for term in set(t for doc in docs for t in doc):
        doc_count = sum(1 for doc in docs if term in doc)
        idf[term] = math.log((num_docs - doc_count + 0.5) / (doc_count + 0.5) + 1)

    avg_len = sum(len(doc) for doc in docs) / num_docs if docs else 1.0
    scores = []
    for doc in docs:
        score = 0.0
        for term in query:
            tf = doc.count(term)
            # Standard BM25 denominator: tf + k1·(1 − b + b·|d|/avgdl)  (no spurious +1).
            norm_factor = k1 * (1 - b + b * len(doc) / avg_len)
            score += idf.get(term, 0.0) * tf * (k1 + 1) / (tf + norm_factor)
        scores.append(score)

    return scores

