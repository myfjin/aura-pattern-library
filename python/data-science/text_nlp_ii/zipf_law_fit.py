def fit_zipf(word_frequencies: List[int]) -> float:
    """Fit Zipf's law: log(f) ≈ a - b·log(r), return slope b."""
    freqs_sorted = sorted(word_frequencies, reverse=True)

    log_ranks = [math.log(i + 1) for i in range(len(freqs_sorted))]
    log_freqs = [math.log(f) if f > 0 else 0 for f in freqs_sorted]

    # Simple regression: slope = -cov(rank, freq) / var(rank).
    mean_rank = sum(log_ranks) / len(log_ranks)
    mean_freq = sum(log_freqs) / len(log_freqs)

    cov = sum((log_ranks[i] - mean_rank) * (log_freqs[i] - mean_freq) for i in range(len(log_ranks))) / len(log_ranks)
    var_rank = sum((r - mean_rank)**2 for r in log_ranks) / len(log_ranks)

    slope = -cov / var_rank if var_rank > 0 else 0.0
    return slope

