    assert len(basic) == 3, f"Expected 3 sentences, got {len(basic)}: {basic}"
    assert any("Hello" in s for s in basic), "Text should be preserved"

    # Defining property: the abbreviation period must NOT split the sentence.
    abbrev = split_sentences("Dr. Smith went home. He was tired.")
    assert len(abbrev) == 2, f"Abbreviation must not split; expected 2, got {len(abbrev)}: {abbrev}"
    assert abbrev[0] == "Dr. Smith went home.", f"Abbreviation kept intact: {abbrev[0]}"

