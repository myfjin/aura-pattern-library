from typing import List

ABBREVIATIONS = {"Dr", "Mr", "Mrs", "Ms", "Prof", "St", "Ave", "Inc", "Ltd", "vs", "etc"}

def split_sentences(text: str) -> List[str]:
    """Split text into sentences, protecting periods that belong to abbreviations."""
    sentences = []
    current = ""

    for i, ch in enumerate(text):
        current += ch
        if ch in ".!?":
            # Is this a real boundary (end of text, or followed by a space)?
            at_boundary = (i + 1 == len(text)) or (i + 1 < len(text) and text[i + 1] == " ")
            if not at_boundary:
                continue
            # Is the token ending here a known abbreviation? If so, do NOT split.
            words = current.strip().split()
            last_word = words[-1].rstrip(".!?") if words else ""
            if last_word in ABBREVIATIONS:
                continue
            sentences.append(current.strip())
            current = ""

    if current.strip():
        sentences.append(current.strip())

    return sentences

