def porter_stem_lite(word: str) -> str:
    """Simplified Porter stemmer: handle common English suffix removals.

    Applies STEP 1-3 reductions (common suffixes: -ing, -ed, -tion, -ness, etc).
    """
    word = word.lower()
    if len(word) <= 3:
        return word

    # Step 1: -SSES, -IES, -SS, -S
    if word.endswith("sses"):
        word = word[:-2]
    elif word.endswith("ies"):
        word = word[:-2]
    elif word.endswith("ss"):
        pass
    elif word.endswith("s"):
        word = word[:-1]

    # Step 2: -ATIONAL, -TIONAL, -ING, -ED
    if word.endswith("ational"):
        word = word[:-7] + "e"
    elif word.endswith("tional"):
        word = word[:-6]
    elif word.endswith("ing"):
        word = word[:-3]
    elif word.endswith("ed"):
        word = word[:-2]

    # Step 3: -LY, -NESS
    if word.endswith("ly"):
        word = word[:-2]
    elif word.endswith("ness"):
        word = word[:-4]

    return word

