def soundex(name: str) -> str:
    """Compute Soundex phonetic code for a name.

    Returns 4-char code: first letter + up to 3 digits.
    """
    name = name.upper()
    if not name:
        return ""

    first = name[0]
    code = first

    # Mapping: consonants → digits, vowels → 0.
    mapping = {
        'B': '1', 'F': '1', 'P': '1', 'V': '1',
        'C': '2', 'G': '2', 'J': '2', 'K': '2', 'Q': '2', 'S': '2', 'X': '2', 'Z': '2',
        'D': '3', 'T': '3',
        'L': '4',
        'M': '5', 'N': '5',
        'R': '6',
        'A': '0', 'E': '0', 'I': '0', 'O': '0', 'U': '0', 'W': '0', 'Y': '0', 'H': '0'
    }

    prev_digit = mapping.get(first, '0')

    for char in name[1:]:
        digit = mapping.get(char, '0')

        # Skip vowels and duplicates.
        if digit != '0' and digit != prev_digit:
            code += digit
            if len(code) == 4:
                break

        prev_digit = digit

    # Pad with zeros.
    code = (code + "000")[:4]
    return code

