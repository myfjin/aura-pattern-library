from typing import List, Tuple


def find_peaks_prominence(signal: List[float], prominence_threshold: float = 1.0) -> List[int]:
    """
    Detect peaks with prominence threshold.
    Prominence = height above max( min_left, min_right ) baseline.
    """
    n = len(signal)
    peaks = []

    for i in range(1, n - 1):
        # Check if local maximum
        if signal[i] > signal[i - 1] and signal[i] > signal[i + 1]:
            # Find left valley (minimum to the left)
            min_left = signal[0]
            for j in range(i):
                min_left = min(min_left, signal[j])

            # Find right valley (minimum to the right)
            min_right = signal[n - 1]
            for j in range(i + 1, n):
                min_right = min(min_right, signal[j])

            # Prominence
            baseline = max(min_left, min_right)
            prominence = signal[i] - baseline

            if prominence >= prominence_threshold:
                peaks.append(i)

    return peaks


