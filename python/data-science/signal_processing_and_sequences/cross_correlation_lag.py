from typing import List


def cross_correlation(signal1: List[float], signal2: List[float]) -> List[float]:
    """
    Compute cross-correlation: r[k] = Σ signal1[n] * signal2[n+k].
    k ranges from -(len-1) to (len-1).
    """
    n = len(signal1)
    assert len(signal2) == n, "Signals must have same length"

    result = []

    for k in range(-(n - 1), n):
        corr = 0.0
        for i in range(n):
            j = i + k
            if 0 <= j < n:
                corr += signal1[i] * signal2[j]
        result.append(corr)

    return result


