import random
from typing import List, Tuple

def sliding_window_regression(stream: List[Tuple[float, float]], window_size: int) -> float:
    """
    Sliding window OLS regression on (x, y) pairs; return final slope.
    Assert: coefficient tracks a planted change.
    Args:
        stream: list of (x, y) pairs
        window_size: size of regression window
    Returns:
        Final slope coefficient of the windowed OLS fit.
    """
    random.seed(42)
    assert window_size > 0

    # Plant drift: first half has slope m1, second half has slope m2
    n = len(stream)
    halfway = n // 2

    # Compute true slopes for each half
    def compute_slope(pairs: List[Tuple]) -> float:
        if len(pairs) < 2:
            return 0.0
        x_vals = [p[0] for p in pairs]
        y_vals = [p[1] for p in pairs]
        mean_x = sum(x_vals) / len(x_vals)
        mean_y = sum(y_vals) / len(y_vals)
        numerator = sum((x - mean_x) * (y - mean_y) for x, y in zip(x_vals, y_vals))
        denominator = sum((x - mean_x) ** 2 for x in x_vals)
        return numerator / max(1e-9, denominator)

    true_slope_first = compute_slope(stream[:halfway])
    true_slope_second = compute_slope(stream[halfway:])
    true_drift = abs(true_slope_second - true_slope_first)

    # Streaming: maintain windowed regression
    slopes = []
    for i in range(len(stream) - window_size + 1):
        window = stream[i:i + window_size]
        slope = compute_slope(window)
        slopes.append(slope)

    final_slope = slopes[-1] if slopes else 0.0

    # RECOVERY ASSERT: final windowed slope reflects the second half's true slope
    if true_drift > 0.1:
        assert abs(final_slope - true_slope_second) < 0.5, \
            f"Windowed regression failed to track drift: final {final_slope} vs true second-half {true_slope_second}"
    else:
        assert abs(final_slope - true_slope_second) < 0.3, \
            f"Windowed regression diverged: {final_slope} vs {true_slope_second}"

    return final_slope


