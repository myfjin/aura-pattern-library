import random
from typing import List, Tuple


def robust_streaming_mad(stream: List[float], outlier_idx: set, k: float = 3.5) -> Tuple[int, int, int]:
    """
    Flag anomalies by the robust median/MAD z-score. Returns (true_pos, false_pos, n_out)
    measured against the provided planted-outlier index set.
    Args:
        stream: values
        outlier_idx: the indices where gross outliers were planted (ground truth)
        k: robust z-score threshold
    """
    assert k > 0
    srt = sorted(stream)
    median = srt[len(srt) // 2]
    mad = sorted(abs(x - median) for x in stream)[len(stream) // 2]
    scale = 1.4826 * mad if mad > 0 else 1e-9

    flagged = {i for i, x in enumerate(stream) if abs(x - median) / scale > k}
    tp = len(flagged & outlier_idx)
    fp = len(flagged - outlier_idx)
    return tp, fp, len(outlier_idx)


