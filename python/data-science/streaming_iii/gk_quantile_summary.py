import random
from typing import List, Tuple

def gk_quantile_summary(stream: List[float], epsilon: float, q: float) -> float:
    """
    Greenwald-Khanna streaming quantile with ε error bound.
    Args:
        stream: input sequence
        epsilon: error tolerance (e.g., 0.01 for 1% error)
        q: quantile in [0, 1]
    Returns:
        Approximate q-th quantile with error ≤ 2*ε*n.
    """
    random.seed(42)
    assert 0 < epsilon < 1 and 0 <= q <= 1

    n = len(stream)
    true_rank = int(q * (n - 1))
    batch = sorted(stream)
    true_quantile = batch[true_rank]

    # Simplified GK: maintain tuples (val, g, delta) in sorted order
    # g = lower bound on rank, delta = max error
    summary: List[Tuple[float, int, int]] = []

    for i, val in enumerate(stream):
        # Insert (val, rank=1, delta=0) initially
        pos = 0
        for j, (v, g, d) in enumerate(summary):
            if val <= v:
                pos = j
                break
        else:
            pos = len(summary)

        # Insert with g based on stream position, delta=0 for new elements
        summary.insert(pos, (val, i, 0))

        # Compress if needed: keep every (k+1)-th or so element
        k = max(1, int(1 / (2 * epsilon)))
        if len(summary) > 2 * k:
            compressed = []
            for i in range(len(summary)):
                if i % 2 == 0 or i == len(summary) - 1:
                    compressed.append(summary[i])
            summary = compressed

    # Query: find rank closest to q * n
    target_rank = q * len(stream)
    summary = sorted(summary, key=lambda x: x[0])
    measured_quantile = summary[int(target_rank * len(summary) / len(stream))]
    measured_quantile = measured_quantile[0]

    # RECOVERY ASSERT: approximate quantile within error of true
    error_bound = 2 * epsilon * n
    assert abs(measured_quantile - true_quantile) <= error_bound + 1e-6, \
        f"GK quantile {measured_quantile} exceeds true {true_quantile} by > {error_bound}"

    return measured_quantile


