def conjugate_gradient(
    A: list,
    b: list,
    x0: list,
    tol: float = 1e-8,
    max_iter: int = None
) -> list:
    """Solve A·x = b for SPD matrix A via conjugate gradient.

    Returns solution x with ||A·x - b|| < tol.
    """
    n = len(A)
    if max_iter is None:
        max_iter = n

    x = x0[:]
    r = [b[i] - sum(A[i][j] * x[j] for j in range(n)) for i in range(n)]
    p = r[:]
    r_dot_r = sum(r[i]**2 for i in range(n))

    for iteration in range(max_iter):
        if r_dot_r < tol**2:
            break

        # Compute Ap.
        Ap = [sum(A[i][j] * p[j] for j in range(n)) for i in range(n)]

        # Step size.
        p_dot_Ap = sum(p[i] * Ap[i] for i in range(n))
        if abs(p_dot_Ap) < 1e-14:
            break

        alpha = r_dot_r / p_dot_Ap

        # Update x and r.
        x = [x[i] + alpha * p[i] for i in range(n)]
        r = [r[i] - alpha * Ap[i] for i in range(n)]

        r_dot_r_new = sum(r[i]**2 for i in range(n))
        beta = r_dot_r_new / r_dot_r

        # Update p.
        p = [r[i] + beta * p[i] for i in range(n)]
        r_dot_r = r_dot_r_new

    return x

