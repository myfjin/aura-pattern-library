import math
from typing import List, Tuple

def fit_gumbel(block_maxima: List[float]) -> Tuple[float, float]:
    """Fit Gumbel distribution to block maxima via moment matching.

    Returns: (location μ, scale σ).
    """
    n = len(block_maxima)
    mean = sum(block_maxima) / n
    variance = sum((x - mean)**2 for x in block_maxima) / n

    # Gumbel: E[X] = μ + γσ, Var[X] = (π²/6)σ²  where γ ≈ 0.5772.
    gamma_euler = 0.5772
    sigma = math.sqrt(6 * variance) / math.pi
    mu = mean - gamma_euler * sigma

    return mu, sigma

def gumbel_cdf(x: float, mu: float, sigma: float) -> float:
    """Gumbel CDF: F(x) = exp(-exp(-(x-μ)/σ))."""
    if sigma <= 0:
        return 0.0
    return math.exp(-math.exp(-(x - mu) / sigma))

def gumbel_return_level(T: float, mu: float, sigma: float) -> float:
    """Return level for T-period return: x_T where F(x_T) = 1 - 1/T."""
    return mu - sigma * math.log(math.log(T / (T - 1)))

