import math
from typing import List

def benford_expected_frequencies(n: int) -> List[float]:
    """Expected frequencies for first digit under Benford's law."""
    freqs = [n * math.log10(1 + 1 / d) for d in range(1, 10)]
    return freqs

def leading_digit(x: float) -> int:
    """Extract the leading (most-significant) decimal digit of a number.

    Scales by powers of 10 into [1, 10) — for x<1 that means multiplying up
    (0.05 → 5), not taking 1/x (which would wrongly give 2).
    """
    x = abs(x)
    if x == 0:
        return 0
    while x >= 10:
        x /= 10
    while x < 1:
        x *= 10
    return int(x)

def benford_chi_square_test(data: List[float]) -> float:
    """Chi-square statistic for Benford's law fit."""
    digit_counts = [0] * 9
    for x in data:
        d = leading_digit(x)
        if 1 <= d <= 9:
            digit_counts[d - 1] += 1

    n = len(data)
    expected = benford_expected_frequencies(n)

    chi_sq = sum((digit_counts[i] - expected[i])**2 / expected[i] for i in range(9) if expected[i] > 0)
    return chi_sq

