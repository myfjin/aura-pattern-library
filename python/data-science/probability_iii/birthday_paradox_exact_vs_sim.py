def birthday_probability_exact(n: int, days: int = 365) -> float:
    """Exact probability that ≥2 people share a birthday (n people, days possibilities)."""
    if n > days:
        return 1.0

    prob_all_diff = 1.0
    for i in range(n):
        prob_all_diff *= (days - i) / days

    return 1 - prob_all_diff

def birthday_probability_sim(n: int, days: int = 365, num_sim: int = 10000) -> float:
    """Simulated probability via collision detection."""
    import random
    successes = 0

    for _ in range(num_sim):
        birthdays = [random.randint(1, days) for _ in range(n)]
        if len(set(birthdays)) < n:  # At least one collision.
            successes += 1

    return successes / num_sim

