from typing import Callable

def simpson_basic(f: Callable[[float], float], a: float, b: float) -> float:
    """Basic Simpson's rule on [a, b]: (b-a) * (f(a) + 4*f(mid) + f(b)) / 6."""
    mid = (a + b) / 2.0
    return (b - a) * (f(a) + 4*f(mid) + f(b)) / 6.0

def adaptive_simpson_recursive(
    f: Callable[[float], float],
    a: float,
    b: float,
    tol: float,
    whole: float,
    depth: int = 0
) -> float:
    """Recursively refine Simpson estimate until error < tol."""
    if depth > 50:
        return whole

    mid = (a + b) / 2.0
    left = simpson_basic(f, a, mid)
    right = simpson_basic(f, mid, b)
    cumulative = left + right

    # Error estimate: |cumulative - whole| / 15.
    if abs(cumulative - whole) <= 15 * tol:
        return cumulative + (cumulative - whole) / 15.0

    return (adaptive_simpson_recursive(f, a, mid, tol / 2, left, depth + 1) +
            adaptive_simpson_recursive(f, mid, b, tol / 2, right, depth + 1))

def adaptive_simpson(
    f: Callable[[float], float],
    a: float,
    b: float,
    tol: float = 1e-6
) -> float:
    """Integrate f over [a, b] with adaptive Simpson's rule.

    Returns integral estimate with accuracy ~ tol.
    """
    whole = simpson_basic(f, a, b)
    return adaptive_simpson_recursive(f, a, b, tol, whole)

