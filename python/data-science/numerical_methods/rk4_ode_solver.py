from typing import Callable, Tuple

def rk4_step(
    f: Callable[[float, float], float],
    t: float,
    y: float,
    h: float
) -> float:
    """Single RK4 step: advance solution from (t, y) to (t+h, y_next)."""
    k1 = f(t, y)
    k2 = f(t + h / 2, y + (h / 2) * k1)
    k3 = f(t + h / 2, y + (h / 2) * k2)
    k4 = f(t + h, y + h * k3)

    y_next = y + (h / 6.0) * (k1 + 2*k2 + 2*k3 + k4)
    return y_next

def rk4_ode_solver(
    f: Callable[[float, float], float],
    t0: float,
    y0: float,
    t_final: float,
    num_steps: int
) -> Tuple[list, list]:
    """Solve dy/dt = f(t, y) from t0 to t_final.

    Returns lists of t and y values at num_steps points.
    """
    h = (t_final - t0) / num_steps
    t_vals, y_vals = [t0], [y0]
    t, y = t0, y0

    for _ in range(num_steps):
        y = rk4_step(f, t, y, h)
        t += h
        t_vals.append(t)
        y_vals.append(y)

    return t_vals, y_vals

