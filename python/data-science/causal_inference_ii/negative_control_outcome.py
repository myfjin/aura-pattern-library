from typing import List

def fit_regression_coef(x: List[float], y: List[float]) -> float:
    """Fit y = a + b*x; return b."""
    n = len(x)
    if n == 0:
        return 0.0
    x_mean = sum(x) / n
    y_mean = sum(y) / n
    num = sum((x[i] - x_mean) * (y[i] - y_mean) for i in range(n))
    denom = sum((x[i] - x_mean)**2 for i in range(n))
    if abs(denom) < 1e-10:
        return 0.0
    return num / denom

