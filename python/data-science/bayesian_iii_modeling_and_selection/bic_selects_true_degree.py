import math
from typing import List

def _solve(A: List[List[float]], b: List[float]) -> List[float]:
    """Solve A x = b by Gaussian elimination with partial pivoting."""
    n = len(A)
    M = [row[:] + [b[i]] for i, row in enumerate(A)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(M[r][c]))
        M[c], M[p] = M[p], M[c]
        if abs(M[c][c]) < 1e-12:
            continue
        for r in range(n):
            if r != c:
                f = M[r][c] / M[c][c]
                for k in range(c, n + 1):
                    M[r][k] -= f * M[c][k]
    return [M[i][n] / M[i][i] if abs(M[i][i]) > 1e-12 else 0.0 for i in range(n)]

def polynomial_rss(x: List[float], y: List[float], degree: int) -> float:
    """Fit degree-`degree` polynomial via least squares; return residual sum of squares."""
    n = len(x)
    V = [[xi ** j for j in range(degree + 1)] for xi in x]
    VtV = [[sum(V[i][a] * V[i][b] for i in range(n)) for b in range(degree + 1)] for a in range(degree + 1)]
    Vty = [sum(V[i][a] * y[i] for i in range(n)) for a in range(degree + 1)]
    coef = _solve(VtV, Vty)
    pred = [sum(coef[j] * xi ** j for j in range(degree + 1)) for xi in x]
    return sum((y[i] - pred[i]) ** 2 for i in range(n))

def bic(rss: float, n: int, k: int) -> float:
    return n * math.log(rss / n) + k * math.log(n)

