def detect_changepoint(data: List[float]) -> int:
    """Offline changepoint detection: find the point maximizing the log-likelihood.

    Assumes two segments with different means, known variance.
    """
    n = len(data)
    best_point = n // 2
    best_score = float('-inf')

    for t in range(1, n):
        # Split at t: segment 1 is [0:t], segment 2 is [t:n].
        seg1 = data[:t]
        seg2 = data[t:]

        if len(seg1) < 1 or len(seg2) < 1:
            continue

        mean1 = sum(seg1) / len(seg1)
        mean2 = sum(seg2) / len(seg2)

        # Log-likelihood (assumes known variance=1).
        loglik = -0.5 * sum((x - mean1)**2 for x in seg1) - 0.5 * sum((x - mean2)**2 for x in seg2)

        if loglik > best_score:
            best_score = loglik
            best_point = t

    return best_point

