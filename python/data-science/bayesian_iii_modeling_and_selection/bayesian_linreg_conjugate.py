import math
from typing import List, Tuple

def bayesian_linreg_posterior(x_vals: List[float], y_vals: List[float]) -> Tuple[float, float]:
    """Conjugate posterior for y = a + b*x with Gaussian prior N(0, 10).

    Returns (posterior_mean_b, posterior_var_b).
    """
    n = len(x_vals)
    x_mean = sum(x_vals) / n
    y_mean = sum(y_vals) / n

    sx2 = sum((x - x_mean)**2 for x in x_vals)
    sxy = sum((x_vals[i] - x_mean) * (y_vals[i] - y_mean) for i in range(n))

    # MLE slope.
    b_mle = sxy / sx2 if abs(sx2) > 1e-12 else 0.0

    # Posterior variance (with weak prior).
    posterior_var = 1.0 / (n + 0.1)

    # Posterior mean (with weak prior).
    posterior_mean_b = posterior_var * (b_mle * n)

    return posterior_mean_b, posterior_var

