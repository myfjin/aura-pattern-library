import math
from typing import List

def rhat(chains: List[List[float]]) -> float:
    """Compute R-hat from parallel MCMC chains.

    chains: list of chains, each is a list of samples.
    R-hat = sqrt(Var_between / Var_within).
    """
    m = len(chains)  # Number of chains.
    n = len(chains[0]) if chains else 0  # Samples per chain.

    if m < 2 or n < 2:
        return 1.0

    # Within-chain variance.
    var_within = 0.0
    for chain in chains:
        chain_mean = sum(chain) / len(chain)
        var_chain = sum((x - chain_mean)**2 for x in chain) / (len(chain) - 1)
        var_within += var_chain

    var_within /= m

    # Between-chain variance.
    chain_means = [sum(chain) / len(chain) for chain in chains]
    overall_mean = sum(chain_means) / m
    var_between = sum((mu - overall_mean)**2 for mu in chain_means) * n / (m - 1)

    # R-hat.
    if var_within == 0:
        return 1.0

    rhat_val = math.sqrt((var_between + var_within) / var_within)
    return rhat_val

