import math
from typing import Tuple

def black_scholes_call(S: float, K: float, T: float, r: float, sigma: float) -> float:
    """Closed-form Black-Scholes call option price."""
    d1 = (math.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * math.sqrt(T))
    d2 = d1 - sigma * math.sqrt(T)

    # Normal CDF approximation (simplified).
    def norm_cdf(x: float) -> float:
        return 0.5 * (1 + math.erf(x / math.sqrt(2)))

    call = S * norm_cdf(d1) - K * math.exp(-r * T) * norm_cdf(d2)
    return call

def monte_carlo_call(S: float, K: float, T: float, r: float, sigma: float, num_sim: int) -> Tuple[float, float]:
    """Monte Carlo call price and standard error."""
    import random
    payoffs = []

    for _ in range(num_sim):
        z = random.gauss(0, 1)
        S_T = S * math.exp((r - 0.5 * sigma**2) * T + sigma * math.sqrt(T) * z)
        payoff = max(S_T - K, 0)
        payoffs.append(payoff)

    price = math.exp(-r * T) * sum(payoffs) / num_sim
    variance = sum((p - price * math.exp(r * T))**2 for p in payoffs) / num_sim
    se = math.sqrt(variance / num_sim) * math.exp(-r * T)

    return price, se

