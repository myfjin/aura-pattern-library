import random
import math

def mm1_queue_littles_law() -> None:
    random.seed(42)

    # M/M/1 parameters
    lambda_rate = 0.8  # arrival rate
    mu_rate = 1.0      # service rate
    rho = lambda_rate / mu_rate  # utilization

    # Simulation
    n_arrivals = 1000
    queue = []  # list of (arrival_time, service_time)
    time_now = 0
    total_time_in_system = 0
    arrivals_count = 0

    # Generate arrivals and service times
    for arrival_num in range(n_arrivals):
        inter_arrival = random.expovariate(lambda_rate)
        time_now += inter_arrival

        service_time = random.expovariate(mu_rate)

        if len(queue) == 0:
            # Server idle, start service immediately
            time_served = time_now + service_time
            total_time_in_system += service_time
        else:
            # Wait in queue
            prev_service_end = queue[-1][1]
            wait_time = max(0, prev_service_end - time_now)
            time_served = time_now + wait_time + service_time
            total_time_in_system += wait_time + service_time

        queue.append((time_now, time_served))
        arrivals_count += 1

    # Empirical metrics
    L = total_time_in_system / n_arrivals  # average time in system
    W = L / lambda_rate  # average number in system (Little's law rearranged)
    Lambda = lambda_rate

    # Little's Law: L = lambda * W => W = L / lambda
    littles_law_check = abs(Lambda * W - L) / L
    assert littles_law_check < 0.3, f"Little's Law violated: {littles_law_check}"

    # Analytic M/M/1 formulas
    # E[W] = 1 / (mu - lambda) = 1 / (mu(1 - rho))
    expected_w = 1 / (mu_rate * (1 - rho))
    # E[L] = lambda / (mu - lambda) = rho / (1 - rho)
    expected_l = rho / (1 - rho)

    # Check that empirical values are within reasonable range of analytic
    assert 0.5 * expected_w < W < 2.0 * expected_w, (
        f"Empirical W ({W:.3f}) far from analytic ({expected_w:.3f})"
    )
    assert 0.5 * expected_l < L < 2.0 * expected_l, (
        f"Empirical L ({L:.3f}) far from analytic ({expected_l:.3f})"
    )

    print("PASS")

