import random
import math

def newsvendor_critical_fractile() -> None:
    random.seed(42)

    # Newsvendor parameters
    cost = 5          # cost per unit
    price = 10        # selling price
    underage_cost = price - cost  # 5
    overage_cost = cost           # 5
    critical_fractile = underage_cost / (underage_cost + overage_cost)  # 0.5

    # Demand distribution: Uniform(50, 150)
    demand_low = 50
    demand_high = 150
    # For Uniform, critical fractile quantile is at low + cf * (high - low)
    optimal_q = demand_low + critical_fractile * (demand_high - demand_low)

    def profit(order_qty: float, demand: float) -> float:
        sold = min(order_qty, demand)
        unsold = max(0, order_qty - demand)
        revenue = sold * price
        purchase_cost = order_qty * cost
        salvage_value = unsold * 0  # no salvage
        return revenue - purchase_cost

    # Simulate over many days
    n_days = 100
    profits_optimal = []
    profits_under = []  # order less than optimal
    profits_over = []   # order more than optimal

    for day in range(n_days):
        random.seed(42 + day)
        demand = random.uniform(demand_low, demand_high)

        prof_opt = profit(optimal_q, demand)
        prof_under = profit(optimal_q - 20, demand)
        prof_over = profit(optimal_q + 20, demand)

        profits_optimal.append(prof_opt)
        profits_under.append(prof_under)
        profits_over.append(prof_over)

    # Average profits
    avg_opt = sum(profits_optimal) / n_days
    avg_under = sum(profits_under) / n_days
    avg_over = sum(profits_over) / n_days

    # Optimal should beat both strategies
    assert avg_opt > avg_under, (
        f"Optimal profit ({avg_opt:.1f}) should beat under-stocking ({avg_under:.1f})"
    )
