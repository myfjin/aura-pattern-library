import random
import heapq

def discrete_event_simulation() -> None:
    random.seed(42)

    # Parameters
    lambda_rate = 0.9  # arrival rate
    mu_rate = 1.0      # service rate
    sim_time = 100.0

    # Event queue: (time, event_type, data)
    events = []
    time_now = 0.0

    # Generate first arrival
    first_arrival = random.expovariate(lambda_rate)
    heapq.heappush(events, (first_arrival, "arrival", None))

    # Tracking
    total_arrivals = 0
    total_served = 0
    queue_size = 0
    server_busy = False
    total_wait = 0
    wait_count = 0

    while events and time_now < sim_time:
        time_now, event_type, data = heapq.heappop(events)

        if event_type == "arrival":
            total_arrivals += 1
            queue_size += 1

            # Schedule next arrival
            next_arrival_time = time_now + random.expovariate(lambda_rate)
            if next_arrival_time < sim_time:
                heapq.heappush(events, (next_arrival_time, "arrival", None))

            # If server idle, start service
            if not server_busy and queue_size > 0:
                server_busy = True
                service_time = random.expovariate(mu_rate)
                service_end = time_now + service_time
                heapq.heappush(events, (service_end, "service_end", queue_size))
                queue_size -= 1

        elif event_type == "service_end":
            total_served += 1
            server_busy = False

            # Start service for next customer if any
            if queue_size > 0:
                server_busy = True
                service_time = random.expovariate(mu_rate)
                service_end = time_now + service_time
                heapq.heappush(events, (service_end, "service_end", queue_size))
                queue_size -= 1

    # Conservation check: arrivals == served + in_system
    in_system = queue_size + (1 if server_busy else 0)
    unaccounted = total_arrivals - total_served - in_system

    assert abs(unaccounted) <= 1, (
        f"Conservation violated: arrivals={total_arrivals}, "
        f"served={total_served}, in_system={in_system}"
    )

    # Verify simulation ran
    assert total_arrivals > 50, f"Too few arrivals: {total_arrivals}"
    assert total_served > 50, f"Too few served: {total_served}"

    print("PASS")

if __name__ == "__main__":
    discrete_event_simulation()
