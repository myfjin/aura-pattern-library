import random

def tornado_sensitivity() -> None:
    random.seed(42)

    # Base case values
    base_price = 100
    base_volume = 1000
    base_cost = 30
    base_overhead = 10000

    def profit(price: float, volume: float, cost: float, overhead: float) -> float:
        revenue = price * volume
        total_cost = cost * volume + overhead
        return revenue - total_cost

    base_profit = profit(base_price, base_volume, base_cost, base_overhead)

    # One-at-a-time sensitivity
    inputs = {
        "price": base_price,
        "volume": base_volume,
        "cost": base_cost,
        "overhead": base_overhead,
    }

    sensitivities = {}

    for input_name, base_value in inputs.items():
        # Vary by ±10%
        high_value = base_value * 1.1
        low_value = base_value * 0.9

        # Compute profits at high/low
        kwargs_base = inputs.copy()
        kwargs_high = inputs.copy()
        kwargs_low = inputs.copy()

        kwargs_high[input_name] = high_value
        kwargs_low[input_name] = low_value

        profit_high = profit(**kwargs_high)
        profit_low = profit(**kwargs_low)

        # Range of impact
        impact = abs(profit_high - profit_low)
        sensitivities[input_name] = impact

    # Rank by sensitivity
    ranked = sorted(sensitivities.items(), key=lambda x: x[1], reverse=True)

    # Price and volume should be top drivers (revenue-related)
    top_driver = ranked[0][0]
    assert top_driver in ["price", "volume"], (
        f"Top driver should be price or volume, got {top_driver}"
    )

    # Overhead should be a significant but lower driver
    overhead_impact = sensitivities["overhead"]
    cost_impact = sensitivities["cost"]
    assert overhead_impact > 0, f"Overhead should have nonzero impact"
    assert cost_impact > 0, f"Cost should have nonzero impact"

    print("PASS")

if __name__ == "__main__":
    tornado_sensitivity()
