from typing import List, Tuple


# Chi-square critical values (approximate) for common df and alpha=0.05
# Format: {df: critical_value}
CHI_SQUARE_CRITICAL_05 = {
    1: 3.841,
    2: 5.991,
    3: 7.815,
    4: 9.488,
    5: 11.070,
    6: 12.592,
    7: 14.067,
    8: 15.507,
    9: 16.919,
    10: 18.307,
}


def chi_square_independence(contingency_table: List[List[int]]) -> Tuple[float, float, bool]:
    """
    Perform chi-square test of independence.

    Args:
        contingency_table: 2D list of observed frequencies (rows are category A, cols are category B).

    Returns:
        Tuple of (chi2_statistic, p_value_approx, is_significant).
        p_value_approx is approximate based on critical values.
    """
    # Compute row and column totals
    n_rows = len(contingency_table)
    n_cols = len(contingency_table[0])
    row_totals = [sum(row) for row in contingency_table]
    col_totals = [sum(contingency_table[i][j] for i in range(n_rows)) for j in range(n_cols)]
    grand_total = sum(row_totals)

    # Compute chi-square statistic
    chi2 = 0.0
    for i in range(n_rows):
        for j in range(n_cols):
            observed = contingency_table[i][j]
            expected = (row_totals[i] * col_totals[j]) / grand_total
            if expected > 0:
                chi2 += (observed - expected) ** 2 / expected

    # Degrees of freedom
    df = (n_rows - 1) * (n_cols - 1)

    # Determine significance using critical value table
    critical_value = CHI_SQUARE_CRITICAL_05.get(df, 3.841)  # Default if not in table
    is_significant = chi2 > critical_value

    # Rough p-value approximation based on critical value
    # (For a full CDF we'd use a more sophisticated approximation, but critical values suffice here)
    p_value_approx = 0.05 if is_significant else 0.95

    return chi2, p_value_approx, is_significant


