import random
from typing import List, Tuple


def permutation_test(group_a: List[float], group_b: List[float], n_perms: int = 10000) -> Tuple[float, float]:
    """
    Compute two-sample permutation test for difference of means.

    Args:
        group_a: First sample.
        group_b: Second sample.
        n_perms: Number of permutations to generate.

    Returns:
        Tuple of (observed_diff, p_value).
    """
    combined = group_a + group_b
    n_a = len(group_a)
    n_total = len(combined)

    # Observed difference (mean(A) - mean(B))
    observed_diff = sum(group_a) / n_a - sum(group_b) / len(group_b)

    # Count permutations with difference as extreme or more extreme
    count_extreme = 0

    for _ in range(n_perms):
        # Permute the combined sample
        shuffled = combined.copy()
        random.shuffle(shuffled)

        # Split at original boundary
        perm_a = shuffled[:n_a]
        perm_b = shuffled[n_a:]

        # Compute permuted difference
        perm_diff = sum(perm_a) / n_a - sum(perm_b) / len(perm_b)

        # Two-tailed: count if absolute value >= observed
        if abs(perm_diff) >= abs(observed_diff):
            count_extreme += 1

    p_value = count_extreme / n_perms
    return observed_diff, p_value


