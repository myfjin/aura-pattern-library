from typing import List, Dict
from dataclasses import dataclass, field


@dataclass
class OneHotEncoder:
    """Fit vocabulary on training data, transform rows."""
    vocabulary: Dict[str, int] = field(default_factory=dict)  # category -> column index
    n_features: int = 0
    handle_unknown: str = "error"  # 'error' or 'ignore'

    def fit(self, data: List[str]) -> "OneHotEncoder":
        """Learn vocabulary from data."""
        self.vocabulary = {cat: i for i, cat in enumerate(sorted(set(data)))}
        self.n_features = len(self.vocabulary)
        return self

    def transform(self, data: List[str]) -> List[List[int]]:
        """Convert each value to one-hot vector."""
        result = []
        for value in data:
            if value not in self.vocabulary:
                if self.handle_unknown == "error":
                    raise ValueError(f"Unknown category: {value}")
                else:
                    # ignore: output all zeros
                    result.append([0] * self.n_features)
            else:
                vec = [0] * self.n_features
                vec[self.vocabulary[value]] = 1
                result.append(vec)
        return result

    def fit_transform(self, data: List[str]) -> List[List[int]]:
        """Fit and transform in one step."""
        return self.fit(data).transform(data)


