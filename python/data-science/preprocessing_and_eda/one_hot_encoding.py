    # Synthetic data: animal types with planted structure
    animals = ["cat", "dog", "cat", "bird", "dog", "cat", "bird"]

    enc = OneHotEncoder()
    transformed = enc.fit_transform(animals)

    # Verify vocabulary
    assert enc.vocabulary == {"bird": 0, "cat": 1, "dog": 2}, "Vocabulary mismatch"
    assert enc.n_features == 3, "Feature count mismatch"

    # Verify one-hot property: exactly one 1 per row
    for i, row in enumerate(transformed):
        assert sum(row) == 1, f"Row {i} not one-hot: {row}"

    # Verify round-trip: decode and check
    decoded = []
    for vec in transformed:
        idx = vec.index(1)
        for cat, col in enc.vocabulary.items():
            if col == idx:
                decoded.append(cat)
                break
    assert decoded == animals, f"Round-trip failed: {decoded} != {animals}"

    # Test unknown handling
    enc_ignore = OneHotEncoder(handle_unknown="ignore")
    enc_ignore.fit(animals)
    unknown_result = enc_ignore.transform(["cat", "elephant"])
