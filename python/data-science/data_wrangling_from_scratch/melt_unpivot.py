from typing import List, Dict, Any


def melt(
    wide_data: Dict[Any, Dict[Any, float]],
    row_key_name: str,
    col_key_name: str,
    val_key_name: str,
) -> List[Dict[str, Any]]:
    """Melt wide format to long format."""
    records = []

    for row_val, cols in wide_data.items():
        for col_val, value in cols.items():
            record = {
                row_key_name: row_val,
                col_key_name: col_val,
                val_key_name: value,
            }
            records.append(record)

    return records


def pivot_table(
    records: List[Dict[str, Any]],
    row_key: str,
    col_key: str,
    val_key: str,
) -> Dict[Any, Dict[Any, float]]:
    """Pivot long → wide."""
    pivot = {}

    for record in records:
        row = record[row_key]
        col = record[col_key]
        val = record[val_key]

        if row not in pivot:
            pivot[row] = {}

        pivot[row][col] = val

    return pivot


if __name__ == "__main__":
    # Start with wide data
    wide = {
        "A": {"US": 150, "EU": 75},
        "B": {"US": 30, "EU": 125},
    }

    # Melt to long
    long = melt(wide, "category", "region", "amount")

    # Verify: melt produces 4 records (2x2)
    assert len(long) == 4, f"Melt should produce 4 records, got {len(long)}"

    # Pivot back
    wide_again = pivot_table(long, "category", "region", "amount")

    # Verify: round-trip matches original
    assert wide_again == wide, (
        f"Round-trip mismatch: {wide_again} vs {wide}"
    )

    # Verify specific melted record
