import random
import math
from typing import List


def covariance(x: List[float], y: List[float]) -> float:
    """Covariance between x and y."""
    n = len(x)
    mean_x = sum(x) / n
    mean_y = sum(y) / n
    return sum((x[i] - mean_x) * (y[i] - mean_y) for i in range(n)) / (n - 1)


if __name__ == "__main__":
    random.seed(42)

    n = 300
    # True causal effect
    true_beta = 7.0

    # Exogenous instrument Z (random, independent of anything else initially)
    Z = [random.gauss(0, 1) for _ in range(n)]

    # Unobserved confounder U
    U = [random.gauss(0, 1) for _ in range(n)]

    # Endogenous treatment T: depends on both Z and U
    # Z is the instrument (exogenous), U creates endogeneity
    T = [0.5 * Z[i] + 0.8 * U[i] + random.gauss(0, 0.5) for i in range(n)]

    # Outcome Y: true effect of T is beta, but U also affects Y (endogeneity)
    Y = [
        true_beta * T[i] + 0.6 * U[i] + random.gauss(0, 1)
        for i in range(n)
    ]

    # Naive OLS (biased because T is endogenous)
    cov_yt = covariance(Y, T)
    cov_tt = covariance(T, T)
    naive_beta = cov_yt / cov_tt

    # IV estimate (2SLS-like): Cov(Y, Z) / Cov(T, Z)
    cov_yz = covariance(Y, Z)
    cov_tz = covariance(T, Z)
    iv_beta = cov_yz / cov_tz

    # Check: IV should be closer to true_beta than naive
    bias_naive = abs(naive_beta - true_beta)
    bias_iv = abs(iv_beta - true_beta)

    assert bias_iv < bias_naive, (
        f"IV did not reduce bias: naive_bias={bias_naive:.2f}, "
        f"iv_bias={bias_iv:.2f}"
    )
    assert bias_iv < 2.0, f"IV bias too large: {bias_iv:.2f}"

    print(
        f"True beta: {true_beta:.2f} | Naive: {naive_beta:.2f} (bias={bias_naive:.2f}) | "
        f"IV: {iv_beta:.2f} (bias={bias_iv:.2f}) | PASS"
    )
