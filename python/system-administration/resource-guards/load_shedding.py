import queue
import threading

def load_shedding_guard(capacity=64):
    """Sheds load when queue would exceed capacity.
    Returns: context with submit_request(), served_count, dropped_count, peak_queue.
    """
    class LoadShedder:
        def __init__(self, cap):
            self.capacity = cap
            self.q = queue.Queue(maxsize=cap)
            self.served = 0
            self.dropped = 0
            self.peak_queue = 0
            self.lock = threading.Lock()
            self.should_stop = False

        def submit_request(self, request_id):
            """Submit request; drop if queue full (shedding)."""
            try:
                self.q.put_nowait(request_id)
                with self.lock:
                    current_size = self.q.qsize()
                    self.peak_queue = max(self.peak_queue, current_size)
                return True
            except queue.Full:
                with self.lock:
                    self.dropped += 1
                return False

        def process_requests(self):
            """Background worker to process requests."""
            while not self.should_stop:
                try:
                    req = self.q.get(timeout=0.1)
                    with self.lock:
                        self.served += 1
                except queue.Empty:
                    pass

        def start_worker(self):
            """Start background worker thread."""
            t = threading.Thread(target=self.process_requests, daemon=True)
            t.start()
            return t

        def stop_worker(self):
            """Stop background worker."""
            self.should_stop = True

    return LoadShedder(capacity)

