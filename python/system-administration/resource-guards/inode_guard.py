import tempfile
import os

def inode_guard(inode_cap=100):
    """Guard that refuses file creation past inode_cap.
    Returns: context with create_file(), peak_inodes, refused_count.
    """
    class InodeGuard:
        def __init__(self, cap):
            self.cap = cap
            self.inode_count = 0
            self.peak_inodes = 0
            self.refused = 0
            self.tmpdir = tempfile.mkdtemp()
            self.created_files = []

        def can_create_file(self):
            """Check if inode count is at cap."""
            if self.inode_count >= self.cap:
                self.refused += 1
                return False
            return True

        def create_file(self):
            """Create a file if inode count permits."""
            if not self.can_create_file():
                return False
            try:
                f = tempfile.NamedTemporaryFile(dir=self.tmpdir, delete=False)
                f.write(b'x')
                f.close()
                self.inode_count += 1
                self.peak_inodes = max(self.peak_inodes, self.inode_count)
                self.created_files.append(f.name)
                return True
            except:
                return False

        def cleanup(self):
            """Remove created files."""
            for fname in self.created_files:
                try:
                    os.unlink(fname)
                except:
                    pass
            try:
                os.rmdir(self.tmpdir)
            except:
                pass

    return InodeGuard(inode_cap)

