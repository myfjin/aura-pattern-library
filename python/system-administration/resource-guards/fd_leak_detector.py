import tempfile

def fd_leak_detector(soft_cap=64):
    """Guard that limits open file descriptors."""
    class FdCapGuard:
        def __init__(self, cap):
            self.cap = cap
            self.open_count = 0
            self.peak = 0
            self.refused = 0

        def can_open(self):
            """Check if we can open another fd."""
            if self.open_count >= self.cap:
                self.refused += 1
                return False
            return True

        def opened(self):
            """Track that a fd was opened."""
            self.open_count += 1
            self.peak = max(self.peak, self.open_count)

        def closed(self):
            """Track that a fd was closed."""
            self.open_count = max(0, self.open_count - 1)

    return FdCapGuard(soft_cap)

