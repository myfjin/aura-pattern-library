import sys


class PrivilegeChecker:
    """Check if a user has the privilege to perform an action."""

    def __init__(self):
        self.privileges = {}  # user -> set of privileges

    def grant(self, user, privilege):
        """Grant a privilege to a user."""
        if user not in self.privileges:
            self.privileges[user] = set()
        self.privileges[user].add(privilege)

    def revoke(self, user, privilege):
        """Revoke a privilege."""
        if user in self.privileges:
            self.privileges[user].discard(privilege)

    def check(self, user, required_priv):
        """
        Check if user has required_priv.
        Raises ValueError if not.
        """
        if user not in self.privileges:
            raise ValueError(f"user not found: {user}")
        if required_priv not in self.privileges[user]:
            raise ValueError(
                f"user {user} not permitted to {required_priv} (has: {self.privileges[user]})"
            )
        return True


