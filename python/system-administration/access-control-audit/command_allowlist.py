import sys


class CommandAllowlist:
    """Enforce a command allowlist."""

    def __init__(self, allowed_commands):
        """
        allowed_commands = {cmd_name: [arg_patterns], ...}
        Example: {
            "ls": ["*"],  # ls with any args
            "cat": ["/etc/passwd", "/etc/hosts"],  # cat only these files
            "echo": ["*"],
        }
        """
        self.allowed = allowed_commands

    def check(self, cmd, args):
        """
        Check if cmd with args is allowed.
        Raises ValueError if not allowed.
        """
        if cmd not in self.allowed:
            raise ValueError(f"command not in allowlist: {cmd}")

        allowed_args = self.allowed[cmd]
        if "*" in allowed_args:
            return True  # any args allowed

        # Check if provided args match one of the allowed patterns.
        if args not in allowed_args:
            raise ValueError(
                f"args not allowed for {cmd}: {args} (allowed: {allowed_args})"
            )
        return True


