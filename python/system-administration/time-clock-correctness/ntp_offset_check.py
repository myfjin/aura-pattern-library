class NTPValidator:
    """Check NTP offset bounds."""
    def __init__(self, max_offset_seconds=1.0):
        self.max_offset = max_offset_seconds
        self.last_offset = None

    def validate(self, offset_seconds):
        """
        Check if offset is in bounds.
        Raise ValueError if out of bounds.
        Return True if in bounds.
        """
        self.last_offset = offset_seconds

        if abs(offset_seconds) > self.max_offset:
            raise ValueError(
                f"NTP offset {offset_seconds} exceeds max {self.max_offset}"
            )

        return True

    def get_offset(self):
        return self.last_offset


