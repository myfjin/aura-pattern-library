import os
import tempfile

def count_open_fds_from_dir(fd_dir_listing):
    """
    Count entries in a /proc/[pid]/fd-style directory listing.
    Input: newline-separated filenames (as from ls output or os.listdir).
    Ignore '.' and '..' and non-numeric names.
    Return count of numeric (FD) entries.
    """
    count = 0
    for entry in fd_dir_listing.strip().split('\n'):
        entry = entry.strip()
        if not entry or entry == '.' or entry == '..':
            continue
        if entry.isdigit():
            count += 1
    return count

def count_open_fds_real(pid):
    """
    Count open FDs for a real process. Return count or None if /proc unavailable.
    """
    fd_path = f"/proc/{pid}/fd"
    if not os.path.exists(fd_path):
        return None
    try:
        entries = os.listdir(fd_path)
        return sum(1 for e in entries if e.isdigit())
    except (OSError, PermissionError):
        return None

