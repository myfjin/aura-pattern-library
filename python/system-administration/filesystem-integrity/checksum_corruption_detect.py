import hashlib
from pathlib import Path


def compute_checksum(path, algo="sha256"):
    """Compute SHA256 checksum of file."""
    h = hashlib.new(algo)
    with open(path, "rb") as f:
        while True:
            chunk = f.read(65536)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def verify_checksum(path, expected_checksum, algo="sha256"):
    """Verify file matches expected checksum. Raises if mismatch."""
    actual = compute_checksum(path, algo)
    if actual != expected_checksum:
        raise ValueError(f"checksum mismatch: {actual} != {expected_checksum}")
    return True


