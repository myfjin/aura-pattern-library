import socket
import time
import threading
import sys

def latency_measure(host, port, timeout_sec=0.5):
    """Measure round-trip latency to host:port in milliseconds; return latency_ms or None if unreachable."""
    try:
        start = time.time()
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        sock.settimeout(timeout_sec)
        sock.connect((host, port))
        elapsed_sec = time.time() - start
        sock.close()
        return elapsed_sec * 1000  # Convert to milliseconds
    except (socket.timeout, OSError, ConnectionRefusedError):
        return None

