import tempfile, pathlib, os

class TailFollower:
    """Follow a log file, yielding only new lines since last read."""
    def __init__(self, log_path):
        self.log_path = log_path
        self.pos = 0

    def read_new_lines(self):
        """Yield lines appended since last read, update position."""
        try:
            with open(self.log_path, 'r') as f:
                f.seek(self.pos)
                lines = f.readlines()
                self.pos = f.tell()
                return [line.rstrip('\n') for line in lines]
        except:
            return []

