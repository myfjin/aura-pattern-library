import json, tempfile, pathlib, io, os, random

def structured_logger(log_path):
    """Log structured events as JSON lines."""
    log_file = pathlib.Path(log_path)

    def log_event(event_dict):
        line = json.dumps(event_dict) + "\n"
        log_file.write_text(log_file.read_text() + line)

    return log_event

def parse_json_log(log_path):
    """Parse JSON log file, count valid lines, skip malformed."""
    valid_count = 0
    skip_count = 0

    try:
        with open(log_path, 'r') as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    json.loads(line)
                    valid_count += 1
                except json.JSONDecodeError:
                    skip_count += 1
    except:
        pass

    return valid_count, skip_count

