import os, tempfile, pathlib, gzip

def compress_log_file(log_path, compression_level=9):
    """Compress log file to .gz, delete original, return compressed size."""
    log_file = pathlib.Path(log_path)
    if not log_file.exists():
        return 0

    gz_path = pathlib.Path(f"{log_path}.gz")
    original_size = log_file.stat().st_size

    with open(log_file, 'rb') as f_in:
        with gzip.open(gz_path, 'wb', compresslevel=compression_level) as f_out:
            f_out.write(f_in.read())

    log_file.unlink()
    compressed_size = gz_path.stat().st_size
    return original_size, compressed_size

