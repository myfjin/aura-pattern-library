import os, tempfile, pathlib, time

def prune_by_count(log_dir, keep_count=5):
    """Delete files in log_dir, keeping only the keep_count newest by mtime."""
    log_dir = pathlib.Path(log_dir)
    files = sorted(log_dir.glob("*.log"), key=lambda f: f.stat().st_mtime)

    deleted = 0
    for f in files[:-keep_count]:  # All but the N newest
        f.unlink()
        deleted += 1

    return deleted

