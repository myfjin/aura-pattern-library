    db_path = os.path.join(tmpdir, "test.db")

    c = sqlite3.connect(db_path)
    c.execute("PRAGMA page_size=4096")
    c.execute("CREATE TABLE t (id INTEGER PRIMARY KEY, val TEXT)")
