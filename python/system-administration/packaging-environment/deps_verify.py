import json
import hashlib
import tempfile
import os
import sys
from pathlib import Path


def verify_dependencies(manifest_path, actual_versions):
    """
    Verify that actual_versions dict matches manifest_path.
    manifest_path is a JSON file with {name: {version: <str>, sha256: <str>}, ...}.
    Returns True if all versions and hashes match, raises ValueError otherwise.
    """
    with open(manifest_path) as f:
        manifest = json.load(f)

    for name, expected in manifest.items():
        if name not in actual_versions:
            raise ValueError(f"missing dependency: {name}")
        actual = actual_versions[name]
        if actual.get("version") != expected.get("version"):
            raise ValueError(
                f"version mismatch for {name}: expected {expected['version']}, "
                f"got {actual.get('version')}"
            )
        if actual.get("sha256") != expected.get("sha256"):
            raise ValueError(
                f"checksum mismatch for {name}: expected {expected['sha256']}, "
                f"got {actual.get('sha256')}"
            )
    return True


