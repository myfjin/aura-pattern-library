import sys


def diff_environments(env1, env2):
    """
    Compare two env dicts. Returns {added, removed, changed} where each is a dict or set.
    """
    keys1 = set(env1.keys())
    keys2 = set(env2.keys())

    added = keys2 - keys1
    removed = keys1 - keys2
    common = keys1 & keys2

    changed = {}
    for key in common:
        if env1[key] != env2[key]:
            changed[key] = (env1[key], env2[key])

    return {"added": added, "removed": removed, "changed": changed}


