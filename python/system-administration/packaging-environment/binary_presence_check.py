import os
import tempfile
import sys
from pathlib import Path


def check_binaries_exist(binary_paths):
    """
    Verify that all binary_paths exist and are executable.
    binary_paths = ["/path/to/bin1", "/path/to/bin2", ...]
    Raises ValueError if any is missing or not executable.
    """
    for path in binary_paths:
        if not os.path.exists(path):
            raise ValueError(f"binary not found: {path}")
        if not os.path.isfile(path):
            raise ValueError(f"not a file: {path}")
        if not os.access(path, os.X_OK):
            raise ValueError(f"binary not executable: {path}")
    return True


