from pathlib import Path


def compute_sha256(data):
    """Compute SHA256 of data (bytes)."""
    return hashlib.sha256(data).hexdigest()


def verify_lockfile(lockfile_path, dep_contents):
    """
    Verify that each dep in dep_contents matches the hash in the lockfile.
    dep_contents: {name: bytes_content, ...}
    Raises ValueError if any hash mismatches.
    """
    with open(lockfile_path) as f:
        lockfile = json.load(f)

    for name, content in dep_contents.items():
        if name not in lockfile:
            raise ValueError(f"missing lockfile entry: {name}")
        expected_hash = lockfile[name]["hash"]
        actual_hash = compute_sha256(content)
        if actual_hash != expected_hash:
            raise ValueError(
                f"hash mismatch for {name}: expected {expected_hash}, got {actual_hash}"
            )
    return True


