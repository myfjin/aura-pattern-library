#!/usr/bin/env python3
"""build_robustness_md — generate <lane>/ROBUSTNESS.md from probe output + the entry registry.

The published file is DERIVED, never hand-written. It exists in the repo so the numbers in a
signed subtree can be re-derived by anyone, and so a future correction to the classifier
regenerates the claim instead of leaving it stale.

⛔ WHAT COUNTS AS A MEASUREMENT (this filter is the whole integrity of the file):
    FINITE / DIVERGED / NaN-Inf                          -> the call ran
    THREW with a NUMERICAL exception                      -> the call ran and the maths failed
    THREW TypeError/AttributeError/NameError, INCONCLUSIVE -> THE CALL NEVER HAPPENED; excluded
5S verified this filter against the raw data: including the excluded rows would OVER-report
fragility, not under-report it.

⛔ A pattern is eligible only if the CORRECTED classifier still calls it `numeric-matrix`. The six
input classes are linear-algebra classes; applying them to a text or scalar pattern produces a
confident number about nothing.

usage: build_robustness_md.py <results.tsv> <entry_points.jsonl> <out.md>
"""
import collections, csv, json, sys
from pathlib import Path

NUM_EXC = {"OverflowError", "ZeroDivisionError", "ValueError", "AuraInputError", "IndexError"}
SEV = {"THREW": 4, "NaN-Inf": 3, "DIVERGED": 2, "FINITE": 1}
CLASSES = ["uncentred", "near-collinear", "rank-deficient", "single-row", "constant-column",
           "wildly-scaled 1e+03", "wildly-scaled 1e+06", "wildly-scaled 1e+12",
           "wildly-scaled 1e+30", "wildly-scaled 1e+155"]
SH = {"uncentred": "unc", "near-collinear": "coll", "rank-deficient": "rank", "single-row": "1row",
      "constant-column": "const", "wildly-scaled 1e+03": "1e3", "wildly-scaled 1e+06": "1e6",
      "wildly-scaled 1e+12": "1e12", "wildly-scaled 1e+30": "1e30", "wildly-scaled 1e+155": "1e155"}
MARK = {"FINITE": "·", "NaN-Inf": "NaN", "DIVERGED": "DIV", "THREW": "THR"}


def measured(r) -> bool:
    return r["outcome"] in ("FINITE", "DIVERGED", "NaN-Inf") or (
        r["outcome"] == "THREW" and r["exception"] in NUM_EXC)


def main(tsv, registry, out) -> int:
    recs = [json.loads(l) for l in open(registry)]
    tier = [r for r in recs if r["lane"] == "python" and r["domain"] == "numeric-matrix"
            and r["derived_from"] == "ast"]
    eligible = {r["id"] for r in tier}
    drivable_pats = sum(1 for r in tier if any(f.get("drivable") for f in r["entry_fns"]))
    total_py = sum(1 for r in recs if r["lane"] == "python")

    agg = {}
    for r in csv.DictReader(open(tsv), delimiter="\t"):
        if r["function"] in ("_summary", "", None) or not r.get("pattern"):
            continue
        if r["pattern"] not in eligible or not measured(r):
            continue
        cl = r["class"] if r["class"] != "wildly-scaled" else f"wildly-scaled {r['wild_scale']}"
        prev = agg.get((r["pattern"], cl))
        if prev is None or SEV[r["outcome"]] > SEV[prev]:
            agg[(r["pattern"], cl)] = r["outcome"]

    pats = sorted({p for p, _ in agg})
    tab = collections.defaultdict(collections.Counter)
    for (p, c), o in agg.items():
        tab[c][o] += 1
    # ⛔ agg.get((p, c)) with NO DEFAULT. An earlier draft defaulted a missing cell to FINITE —
    # absence read as a pass, in the code that publishes the claim. 5S caught it.
    strict = [p for p in pats if all(agg.get((p, c)) == "FINITE" for c in CLASSES)]
    partial = [p for p in pats
               if p not in strict and all(agg.get((p, c), "FINITE") == "FINITE" for c in CLASSES)]

    L = []
    A = L.append
    A("# Python data-science lane — input robustness (PARTIAL COVERAGE)\n")
    A(f"**Measured 2026-08-07 over {len(pats)} patterns. Every cell below is an observed result, "
      f"not an estimate. Generated by `tools/build_robustness_md.py` — do not hand-edit.**\n")
    A("## ⛔ READ THE DENOMINATOR FIRST\n")
    A(f"This file covers **{len(pats)} patterns**. The python lane holds **{total_py}**. It is NOT "
      f"a lane-wide result and must never be quoted as one.\n")
    A("The probe calls a pattern's entry function with synthetic matrix input. It can only do that "
      "when the function genuinely takes a matrix and every other required parameter is something "
      "the probe can build. **An undriven function appears nowhere in this file** — it is absent, "
      "not passing.\n")
    A("How the number falls out, every step measured:\n")
    A(f"```\n{total_py:>3}  python patterns\n {len(tier):>2}  numeric-matrix domain with an "
      f"AST-derived entry point\n {drivable_pats:>2}  of those have at least one drivable function\n"
      f" {len(pats):>2}  patterns actually driven and measured   <- this file\n```\n")
    A("⚠️ Two corrections are baked into that chain, and **both had inflated an earlier draft**:\n\n"
      "1. **Static signature analysis over-predicted runtime callability by ~2x.** Restricting a "
      "run to the functions judged drivable returned a byte-identical `TypeError` count, because "
      "undriven functions never reach a call at all. Runtime is the ground truth.\n"
      "2. **Parameter roles are decided by the ANNOTATION, not the name.** An earlier classifier "
      "matched names case-insensitively against a set containing the single letter `A`, so "
      "`cosine(a: Dict[str, float], b: Dict[str, float])` read as taking a matrix. That published "
      "text and scalar patterns — `cross_domain_query_expansion`, `newton_method_optimization`, "
      "`bootstrap_confidence_interval` — under linear-algebra classes that do not apply to them.\n")
    A("## ⛔ NOT COMPARABLE WITH `javascript/ROBUSTNESS.md`\n")
    A("1. **Divergence threshold differs — `1e15` here, `1e6` there.** A value flagged DIVERGED "
      "there may read FINITE here.\n"
      "2. **The `uncentred` construction differs.** Measured on the shipped `linear_regression_gd`: "
      "FINITE to an offset of ~5.0, DIVERGED from ~6.0. This lane uses 10.0 — above that boundary. "
      "The JavaScript reference recorded the same pattern FINITE, so it used a smaller offset.\n\n"
      "Do not build a cross-lane table until both lanes are re-run under one declared configuration.\n")
    A("## What this file is, and what it is not\n")
    A("Each pattern carries a self-test that passes on its own fixture. This answers a different "
      "question: **what does it do on data its fixture does not contain?**\n")
    A("A non-FINITE cell is a **documented limit, not a defect**. Gradient descent that overflows "
      "on a column scaled 1e30 is behaving the way gradient descent behaves. The failure worth "
      "avoiding is not that limits exist — it is nobody knowing where they are.\n")
    A("⭐ **This reports; it does not judge.** `DIVERGED` is an observation, never a verdict.\n")
    A("## Method\n\n| setting | value |\n|---|---|\n"
      "| seed | `20260804` (fixed; two runs byte-identical) |\n"
      "| divergence threshold | `1e15` |\n| uncentred offset | `10.0` |\n"
      "| wildly-scaled | ladder: 1e3, 1e6, 1e12, 1e30, 1e155 |\n"
      "| probe | `probe_robustness.py` — built by 4Q, tested by 5S |\n")
    A(f"## Summary\n\n**{len(strict)} of {len(pats)} measured patterns are FINITE on all ten classes.**\n")
    if partial:
        A(f"⚠️ A further **{len(partial)}** ({', '.join('`' + p + '`' for p in partial)}) is FINITE on "
          f"every class it was measured on but was NOT measured on all ten. Counted in neither figure.\n")
    A("⛔ A blank cell means **NOT MEASURED, which is not a pass**.\n")
    A("| class | FINITE | NaN-Inf | DIVERGED | THREW | measured |\n|---|---|---|---|---|---|")
    for c in CLASSES:
        t = tab[c]
        A(f"| `{c}` | {t['FINITE']} | {t['NaN-Inf']} | {t['DIVERGED']} | {t['THREW']} | "
          f"{sum(t.values())}/{len(pats)} |")
    A("\n## Per pattern\n\n`·` FINITE · `DIV` diverged · `NaN` NaN/Inf · `THR` threw · "
      "**blank = NOT MEASURED**\n")
    A("| pattern | " + " | ".join(SH[c] for c in CLASSES) + " |")
    A("|---" * (len(CLASSES) + 1) + "|")
    for p in pats:
        A(f"| `{p}` | " + " | ".join(MARK.get(agg.get((p, c), ""), "") for c in CLASSES) + " |")
    A("\n---\n*△ AURA Pattern Library — © Reality Optimizer*\n")
    Path(out).write_text("\n".join(L), encoding="utf-8")
    print(f"{out}: {len(pats)} patterns | chain {total_py} -> {len(tier)} -> {drivable_pats} "
          f"-> {len(pats)} | FINITE-on-all {len(strict)} | partial {partial}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:4]))
