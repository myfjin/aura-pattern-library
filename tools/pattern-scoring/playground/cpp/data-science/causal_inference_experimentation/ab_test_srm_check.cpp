/*
 * Sample Ratio Mismatch (SRM) Check for A/B Tests.
 *
 * In a valid A/B test, the allocation ratio should match the design (e.g., 50/50).
 * A chi-square test on the observed counts detects when sample ratio deviates significantly.
 * SRM flags data quality issues (e.g., bugs, bot filtering).
 * We plant an SRM (skewed split) and a clean split; SRM caught vs clean passes.
 */

#include <iostream>
#include <vector>
#include <cmath>
#include <cassert>
#include <iomanip>
#include <random>

using namespace std;

// Chi-square goodness-of-fit test (matches Python oracle)
// Returns: (chi_sq_stat, p_value_flag)
// p_value_flag: 1.0 if chi_sq < 3.84 (not significant), 0.0 otherwise
pair<double, double> chi_square_gof(const vector<int>& observed, const vector<double>& expected) {
    double chi_sq = 0.0;
    for (size_t i = 0; i < observed.size(); i++) {
        double diff = observed[i] - expected[i];
        chi_sq += (diff * diff) / expected[i];
    }
    
    // Approximate p-value using chi-sq(1) critical value (3.84 for α=0.05)
    double p_value = (chi_sq < 3.84) ? 1.0 : 0.0;
    
    return {chi_sq, p_value};
}

int main() {
    // Seed the RNG with same seed as Python (42)
    mt19937 gen(42);
    uniform_real_distribution<double> dist(0.0, 1.0);
    
    int target_n = 10000;
    double target_ratio = 0.5;  // 50/50 split
    
    // Scenario 1: Clean split (no SRM)
    // Assign treatment/control uniformly
    vector<int> clean_split;
    for (int i = 0; i < target_n; i++) {
        clean_split.push_back(dist(gen) < target_ratio ? 1 : 0);
    }
    int n_treatment_clean = 0;
    for (int x : clean_split) n_treatment_clean += x;
    int n_control_clean = target_n - n_treatment_clean;
    
    // Scenario 2: Skewed split (SRM present)
    // Artificially skew the allocation (simulate bug that filters out some control)
    vector<int> skewed_split;
    for (int i = 0; i < target_n; i++) {
        skewed_split.push_back(dist(gen) < target_ratio ? 1 : 0);
    }
    // Artificially remove ~20% of control units
    vector<int> filtered;
    for (int x : skewed_split) {
        if (x == 1 || dist(gen) > 0.2) {
            filtered.push_back(x);
        }
    }
    skewed_split = filtered;
    
    int n_treatment_skewed = 0;
    for (int x : skewed_split) n_treatment_skewed += x;
    int n_control_skewed = skewed_split.size() - n_treatment_skewed;
    
    // Chi-square test for both scenarios
    vector<double> expected_clean = {target_n / 2.0, target_n / 2.0};
    vector<int> observed_clean = {n_treatment_clean, n_control_clean};
    auto [chi_sq_clean, p_clean] = chi_square_gof(observed_clean, expected_clean);
    
    vector<double> expected_skewed = {skewed_split.size() / 2.0, skewed_split.size() / 2.0};
    vector<int> observed_skewed = {n_treatment_skewed, n_control_skewed};
    auto [chi_sq_skewed, p_skewed] = chi_square_gof(observed_skewed, expected_skewed);
    
    cout << fixed << setprecision(2);
    double ratio_clean = (double)n_treatment_clean / target_n;
    double ratio_skewed = (double)n_treatment_skewed / skewed_split.size();
    
    cout << "Clean split: " << n_treatment_clean << "/" << target_n << " (" 
         << (ratio_clean * 100.0) << "%) | chi_sq=" << chi_sq_clean 
         << " (p=" << p_clean << ") | Skewed split: " << n_treatment_skewed << "/" 
         << skewed_split.size() << " (" << (ratio_skewed * 100.0) << "%) | chi_sq=" 
         << chi_sq_skewed << " (p=" << p_skewed << ") | PASS" << endl;
    
    // Assertions (matching Python oracle exactly)
    assert(p_clean > 0.05);  // Clean split should NOT be flagged as SRM
    assert(p_skewed < 0.05);  // Skewed split SHOULD be flagged as SRM
    assert(chi_sq_clean < 3.84);  // Clean chi-sq should be low
    assert(chi_sq_skewed > 3.84);  // Skewed chi-sq should be high
    
    return 0;
}
