std::vector<std::vector<double>> simulate_novelty_decay(
    std::size_t n_users,
    double true_long_run_effect,
    double novelty_boost,
    double decay_rate) {

    // Match Python: each call re-seeds from 42 so control and treatment share the same noise sequence.
    std::mt19937 rng(42);
    std::normal_distribution<double> noise_dist(0.0, 0.5);

    std::vector<std::vector<double>> results(n_users, std::vector<double>(10));
    for (std::size_t u = 0; u < n_users; ++u) {
        for (int day = 1; day <= 10; ++day) {
            double novelty = novelty_boost * std::exp(-decay_rate * (day - 1));
            double effect = true_long_run_effect + novelty;
            results[u][day - 1] = effect + noise_dist(rng);
        }
    }
    return results;
}

double time_sliced_ate(
    const std::vector<std::vector<double>>& control_outcomes,
    const std::vector<std::vector<double>>& treatment_outcomes,
    int day) {

    std::size_t n = treatment_outcomes.size();
    double t_sum = 0.0, c_sum = 0.0;
    for (std::size_t i = 0; i < n; ++i) {
        t_sum += treatment_outcomes[i][day - 1];
        c_sum += control_outcomes[i][day - 1];
    }
    return (t_sum / static_cast<double>(n)) - (c_sum / static_cast<double>(n));
}

