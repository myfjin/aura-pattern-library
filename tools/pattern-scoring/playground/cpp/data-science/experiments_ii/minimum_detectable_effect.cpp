    int n_per_arm = 100;
    double mde = mde_normal_approx(n_per_arm);
    double power_at_mde = simulate_power(n_per_arm, mde, 400, 42);
    double power_at_1_5x = simulate_power(n_per_arm, 1.5 * mde, 400, 43);
    double power_at_0_7x = simulate_power(n_per_arm, 0.7 * mde, 400, 44);

    assert(power_at_mde > 0.65 && power_at_mde < 0.95);
