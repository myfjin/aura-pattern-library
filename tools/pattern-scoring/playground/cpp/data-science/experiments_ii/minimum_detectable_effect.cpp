/*
 * Minimum Detectable Effect (MDE): smallest effect size detectable with given n, α, power.
 *
 * Oracle asserts:
 *   0.65 < power_at_mde < 0.95
 *   power_at_1_5x > power_at_mde
 *   power_at_0_7x < power_at_mde
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>

double mde_normal_approx(int n_per_arm, double alpha = 0.05, double power = 0.8, double sigma = 1.0) {
    double z_alpha = (std::abs(alpha - 0.05) < 0.001) ? 1.96 : 2.58;
    double z_beta = (std::abs(power - 0.8) < 0.001) ? 0.84 : 1.28;
    return (z_alpha + z_beta) * sigma * std::sqrt(2.0 / n_per_arm);
}

double simulate_power(int n_per_arm, double true_effect, int reps, int seed) {
    std::mt19937_64 rng(seed);
    std::normal_distribution<double> treat(true_effect, 1.0);
    std::normal_distribution<double> control(0.0, 1.0);
    int rejections = 0;
    for (int r = 0; r < reps; ++r) {
        std::vector<double> t, c;
        for (int i = 0; i < n_per_arm; ++i) { t.push_back(treat(rng)); c.push_back(control(rng)); }
        double mt = 0.0, mc = 0.0;
        for (double x : t) mt += x;
        mt /= t.size();
        for (double x : c) mc += x;
        mc /= c.size();
        double vt = 0.0, vc = 0.0;
        for (double x : t) vt += (x - mt) * (x - mt);
        vt /= (n_per_arm - 1);
        for (double x : c) vc += (x - mc) * (x - mc);
        vc /= (n_per_arm - 1);
        double se = std::sqrt(vt / n_per_arm + vc / n_per_arm);
        double tstat = se > 0 ? (mt - mc) / se : 0.0;
        double p = std::erfc(std::abs(tstat) / std::sqrt(2.0));
        if (p < 0.05) ++rejections;
    }
    return rejections / static_cast<double>(reps);
}

