/*
 * Bayesian Changepoint Detection
 * 
 * Find the point where mean shifts.
 * Core claim: detected changepoint ≈ true location within tolerance.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <limits>

int detect_changepoint(const std::vector<double>& data) {
    /*
     * Offline changepoint detection: find the point maximizing the log-likelihood.
     * Assumes two segments with different means, known variance.
     */
    int n = static_cast<int>(data.size());
    int best_point = n / 2;
    double best_score = -std::numeric_limits<double>::infinity();

    for (int t = 1; t < n; ++t) {
        // Split at t: segment 1 is [0:t], segment 2 is [t:n].
        double sum1 = 0.0, sum2 = 0.0;
        int count1 = t, count2 = n - t;

        for (int i = 0; i < t; ++i) {
            sum1 += data[i];
        }
        for (int i = t; i < n; ++i) {
            sum2 += data[i];
        }

        double mean1 = sum1 / count1;
        double mean2 = sum2 / count2;

        // Log-likelihood (assumes known variance=1).
        double loglik = 0.0;
        for (int i = 0; i < t; ++i) {
            double diff = data[i] - mean1;
            loglik -= 0.5 * diff * diff;
        }
        for (int i = t; i < n; ++i) {
            double diff = data[i] - mean2;
            loglik -= 0.5 * diff * diff;
        }

        if (loglik > best_score) {
            best_score = loglik;
            best_point = t;
        }
    }

    return best_point;
}

int main() {
    std::mt19937 rng(42);
    std::normal_distribution<double> normal(0.0, 1.0);

    // Planted: changepoint at position 30.
    const int changepoint_true = 30;
    const int n = 60;

    std::vector<double> data(n);
    for (int i = 0; i < n; ++i) {
        if (i < changepoint_true) {
            data[i] = normal(rng) + 1.0;  // Segment 1: mean 1.0
        } else {
            data[i] = normal(rng) + 3.0;  // Segment 2: mean 3.0
        }
    }

    // Detect changepoint.
    int detected = detect_changepoint(data);

    // Should be close to true changepoint.
    assert(std::abs(detected - changepoint_true) < 5);

    std::cout << "bayesian_changepoint_offline.cpp PASS" << std::endl;
    return 0;
}
