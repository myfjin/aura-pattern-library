/*
 * Gradient Boosting with Decision Stumps.
 * Additively fits depth-1 trees (stumps) to the current residuals with
 * learning-rate shrinkage, summing their shrunken predictions into an ensemble.
 * Use to learn a piecewise function that a single stump cannot capture. Oracle:
 * on a 4-quadrant target, a 50-round boosted ensemble cuts MSE by more than 15%
 * relative to the best single stump.
 */

#include <vector>
#include <cmath>
#include <random>
#include <algorithm>
#include <cassert>
#include <iostream>
#include <utility>

std::tuple<int, double, double, double> fit_stump(
    const std::vector<std::pair<double, double>>& X,
    const std::vector<double>& y
) {
    if (X.empty()) return {0, 0.0, 0.0, 0.0};

    int best_feature = 0;
    double best_threshold = 0.0, best_mse = 1e18, best_left_val = 0.0, best_right_val = 0.0;

    for (int feat = 0; feat < 2; ++feat) {
        std::vector<double> feature_vals;
        for (const auto& x : X) feature_vals.push_back(feat == 0 ? x.first : x.second);
        std::sort(feature_vals.begin(), feature_vals.end());

        for (size_t i = 0; i + 1 < feature_vals.size(); ++i) {
            double threshold = (feature_vals[i] + feature_vals[i + 1]) / 2.0;

            std::vector<double> left_y, right_y;
            for (size_t j = 0; j < X.size(); ++j) {
                double val = (feat == 0 ? X[j].first : X[j].second);
                if (val < threshold) left_y.push_back(y[j]);
                else right_y.push_back(y[j]);
            }

            if (left_y.empty() || right_y.empty()) continue;

            double left_mean = 0.0;
            for (double v : left_y) left_mean += v;
            left_mean /= left_y.size();

            double right_mean = 0.0;
            for (double v : right_y) right_mean += v;
            right_mean /= right_y.size();

            double mse = 0.0;
            for (size_t j = 0; j < X.size(); ++j) {
                double val = (feat == 0 ? X[j].first : X[j].second);
                double pred = (val < threshold) ? left_mean : right_mean;
                double diff = y[j] - pred;
                mse += diff * diff;
            }
            mse /= y.size();

            if (mse < best_mse) {
                best_mse = mse;
                best_feature = feat;
                best_threshold = threshold;
                best_left_val = left_mean;
                best_right_val = right_mean;
            }
        }
    }

    return {best_feature, best_threshold, best_left_val, best_right_val};
}

double predict_stump(const std::pair<double, double>& x, int feature, double threshold,
                     double left_val, double right_val) {
    double val = (feature == 0) ? x.first : x.second;
    return (val < threshold) ? left_val : right_val;
}

std::pair<std::vector<std::tuple<int, double, double, double>>, double> gradient_boost(
    const std::vector<std::pair<double, double>>& X,
    const std::vector<double>& y,
    int n_rounds = 10,
    double learning_rate = 0.1
) {
    std::vector<std::tuple<int, double, double, double>> stumps;
    std::vector<double> pred(y.size(), 0.0);

    for (int round_num = 0; round_num < n_rounds; ++round_num) {
        std::vector<double> residuals(y.size());
        for (size_t i = 0; i < y.size(); ++i) residuals[i] = y[i] - pred[i];

        auto [feature, threshold, left_val, right_val] = fit_stump(X, residuals);
        stumps.push_back({feature, threshold, learning_rate * left_val, learning_rate * right_val});

        for (size_t i = 0; i < X.size(); ++i) {
            pred[i] += predict_stump(X[i], feature, threshold, learning_rate * left_val, learning_rate * right_val);
        }
    }

    double mse = 0.0;
    for (size_t i = 0; i < y.size(); ++i) {
        double diff = y[i] - pred[i];
        mse += diff * diff;
    }
    mse /= y.size();

    return {stumps, mse};
}

int main() {
    std::mt19937 rng(42);
    std::uniform_real_distribution<double> uniform(0.0, 10.0);
    std::normal_distribution<double> normal(0.0, 0.2);

    int n = 100;
    std::vector<std::pair<double, double>> X;
    std::vector<double> y;

    for (int i = 0; i < n; ++i) {
        double x0 = uniform(rng);
        double x1 = uniform(rng);
        X.push_back({x0, x1});

        double base;
        if (x0 <= 5.0 && x1 <= 5.0) base = 1.0;
        else if (x0 <= 5.0 && x1 > 5.0) base = 3.0;
        else if (x0 > 5.0 && x1 <= 5.0) base = 2.0;
        else base = 4.0;
        y.push_back(base + normal(rng));
    }

    auto [feature, threshold, left_val, right_val] = fit_stump(X, y);
    std::vector<double> single_stump_pred;
    for (const auto& x : X) {
        single_stump_pred.push_back(predict_stump(x, feature, threshold, left_val, right_val));
    }

    double single_stump_mse = 0.0;
    for (int i = 0; i < n; ++i) {
        double diff = y[i] - single_stump_pred[i];
        single_stump_mse += diff * diff;
    }
    single_stump_mse /= n;

    auto [stumps, gb_mse] = gradient_boost(X, y, 50, 0.25);

    std::vector<double> gb_pred(n, 0.0);
    for (int i = 0; i < n; ++i) {
        for (const auto& [feat, thr, lv, rv] : stumps) {
            gb_pred[i] += predict_stump(X[i], feat, thr, lv, rv);
        }
    }

    double gb_final_mse = 0.0;
    for (int i = 0; i < n; ++i) {
        double diff = y[i] - gb_pred[i];
        gb_final_mse += diff * diff;
    }
    gb_final_mse /= n;

    double improvement_ratio = single_stump_mse / (gb_final_mse + 1e-10);
    assert(improvement_ratio > 1.15);

    std::cout << "gradient_boosting_stumps.cpp PASS" << std::endl;
    return 0;
}
