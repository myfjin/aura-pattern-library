/*
 * Bayesian Linear Regression (Conjugate Normal Prior)
 * 
 * Core idea: prior N(μ₀, Σ₀); likelihood N(y | Xβ, σ²I); posterior is N(μ_post, Σ_post)
 * with closed-form updates. Posterior mean is between prior and OLS; variance shrinks with data.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <utility>

std::pair<double, double> bayesian_linreg_conjugate(
    const std::vector<double>& X,
    const std::vector<double>& y,
    double mu0 = 0.0,
    double sigma0_sq = 100.0,
    double sigma_sq = 1.0
) {
    /*
     * Conjugate normal posterior for simple univariate linear regression.
     * y_i = β * x_i + ε_i, ε ~ N(0, σ²)
     * Prior: β ~ N(μ₀, σ₀²)
     * Return: (posterior mean, posterior variance)
     */
    int n = static_cast<int>(X.size());
    if (n == 0) {
        return {mu0, sigma0_sq};
    }

    // Sufficient statistics
    double sum_x = 0.0, sum_y = 0.0, sum_xy = 0.0, sum_x_sq = 0.0;
    for (int i = 0; i < n; ++i) {
        sum_x += X[i];
        sum_y += y[i];
        sum_xy += X[i] * y[i];
        sum_x_sq += X[i] * X[i];
    }

    // OLS estimate
    double denom = n * sum_x_sq - sum_x * sum_x;
    double ols_beta = (std::abs(denom) > 1e-10) ? 
        (n * sum_xy - sum_x * sum_y) / denom : 0.0;

    // Conjugate posterior (univariate case)
    double prior_prec = 1.0 / sigma0_sq;
    double likelihood_prec = sum_x_sq / sigma_sq;
    double post_prec = prior_prec + likelihood_prec;

    double mu_post = (prior_prec * mu0 + likelihood_prec * ols_beta) / post_prec;
    double sigma_sq_post = 1.0 / post_prec;

    return {mu_post, sigma_sq_post};
}

int main() {
    std::mt19937 rng(42);
    std::normal_distribution<double> normal(0.0, 0.5);

    // Generate data from y = 2*x + noise
    const double true_beta = 2.0;
    std::vector<double> X(20), y(20);
    for (int i = 0; i < 20; ++i) {
        X[i] = (i + 1) / 10.0;
        y[i] = true_beta * X[i] + normal(rng);
    }

    // Weak prior: μ₀=0, σ₀²=100 (very uncertain)
    auto [mu_weak, sigma_sq_weak] = bayesian_linreg_conjugate(X, y, 0.0, 100.0, 0.5);

    // Strong prior: μ₀=1.5, σ₀²=0.1 (centered near wrong value)
    auto [mu_strong, sigma_sq_strong] = bayesian_linreg_conjugate(X, y, 1.5, 0.1, 0.5);

    // OLS estimate (no prior)
    double sum_x = 0.0, sum_y = 0.0, sum_xy = 0.0, sum_x_sq = 0.0;
    int n = 20;
    for (int i = 0; i < n; ++i) {
        sum_x += X[i];
        sum_y += y[i];
        sum_xy += X[i] * y[i];
        sum_x_sq += X[i] * X[i];
    }
    double ols_beta = (n * sum_xy - sum_x * sum_y) / (n * sum_x_sq - sum_x * sum_x);

    // Weak prior posterior mean should be close to OLS
    assert(std::abs(mu_weak - ols_beta) < 0.5);

    // Strong prior posterior mean should be pulled toward prior mean
    assert(mu_strong > 1.5 && mu_strong < ols_beta);

    // Posterior variance should shrink with data compared to prior
    assert(sigma_sq_weak < 100.0);
    assert(sigma_sq_strong < 0.1);

    // Posterior mean should be reasonable
    assert(std::abs(mu_weak - true_beta) < 1.0);

    // Strong prior posterior should be between prior and data
    assert(mu_strong > 1.5 && mu_strong < ols_beta);

    std::cout << "bayesian_linear_regression.cpp PASS" << std::endl;
    return 0;
}
