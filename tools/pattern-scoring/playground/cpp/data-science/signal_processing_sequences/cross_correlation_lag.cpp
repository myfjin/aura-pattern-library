/*
 * Cross-Correlation and Lag Detection
 * 
 * Compute cross-correlation between two signals.
 * The lag at which cross-correlation is maximum indicates the time shift.
 */

#include <vector>
#include <cmath>
#include <random>
#include <algorithm>
#include <cassert>
#include <iostream>

std::vector<double> cross_correlation(const std::vector<double>& signal1, const std::vector<double>& signal2) {
    /* Compute cross-correlation: r[k] = Σ signal1[n] * signal2[n+k]. */
    int n = static_cast<int>(signal1.size());
    assert(static_cast<int>(signal2.size()) == n);

    std::vector<double> result;
    result.reserve(2 * n - 1);

    for (int k = -(n - 1); k < n; ++k) {
        double corr = 0.0;
        for (int i = 0; i < n; ++i) {
            int j = i + k;
            if (j >= 0 && j < n) {
                corr += signal1[i] * signal2[j];
            }
        }
        result.push_back(corr);
    }

    return result;
}

int main() {
    std::mt19937 rng(42);
    std::normal_distribution<double> normal(0.0, 0.1);

    const int n = 100;
    const int true_lag = 15;

    // Create base signal
    std::vector<double> base_signal(n);
    for (int t = 0; t < n; ++t) {
        base_signal[t] = std::sin(2.0 * M_PI * t / 20.0);
    }

    // Create lagged version with some noise
    std::vector<double> lagged_signal(n, 0.0);
    for (int i = true_lag; i < n; ++i) {
        lagged_signal[i] = base_signal[i - true_lag] + normal(rng);
    }

    // Compute cross-correlation
    auto xcorr = cross_correlation(base_signal, lagged_signal);

    // Find lag: argmax of xcorr (middle index corresponds to lag 0)
    auto max_it = std::max_element(xcorr.begin(), xcorr.end());
    int max_xcorr_idx = static_cast<int>(std::distance(xcorr.begin(), max_it));
    int detected_lag = max_xcorr_idx - (n - 1);

    int lag_error = std::abs(detected_lag - true_lag);
    assert(lag_error <= 2);

    // Verify that xcorr[lag=0] is much lower than xcorr[lag=true_lag]
    double xcorr_at_true_lag = *max_it;
    double xcorr_at_zero_lag = xcorr[n - 1];  // Middle index
    assert(xcorr_at_true_lag > xcorr_at_zero_lag);

    std::cout << "cross_correlation_lag.cpp PASS" << std::endl;
    return 0;
}
