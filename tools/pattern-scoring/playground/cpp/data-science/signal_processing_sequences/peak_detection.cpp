#include <iostream>
#include <vector>
#include <random>
#include <cmath>
#include <cassert>
#include <algorithm>

using std::vector;

static vector<size_t> find_peaks_prominence(const vector<double>& signal,
                                            double prominence_threshold) {
    vector<size_t> peaks;
    size_t n = signal.size();
    for (size_t i = 1; i + 1 < n; ++i) {
        if (signal[i] > signal[i - 1] && signal[i] > signal[i + 1]) {
            double min_left = signal[0];
            for (size_t j = 0; j < i; ++j) min_left = std::min(min_left, signal[j]);
            double min_right = signal[n - 1];
            for (size_t j = i + 1; j < n; ++j) min_right = std::min(min_right, signal[j]);
            double baseline = std::max(min_left, min_right);
            if (signal[i] - baseline >= prominence_threshold)
                peaks.push_back(i);
        }
    }
    return peaks;
}

int main() {
    std::mt19937 rng(42);
    std::normal_distribution<double> noise(1.0, 0.3);

    size_t n = 100;
    vector<double> signal(n);
    for (size_t i = 0; i < n; ++i) signal[i] = noise(rng);
    signal[25] = 5.0;
    signal[75] = 4.0;
    signal[40] = 1.8;
    signal[60] = 1.7;

    auto peaks = find_peaks_prominence(signal, 2.0);

    assert(std::find(peaks.begin(), peaks.end(), 25) != peaks.end());
    assert(std::find(peaks.begin(), peaks.end(), 75) != peaks.end());

    size_t noise_detections = 0;
    for (size_t p : peaks)
        if (p == 40 || p == 60) ++noise_detections;
    assert(noise_detections <= 1);

    vector<double> prominences;
    for (size_t p : peaks) {
        double min_left = signal[0];
        for (size_t j = 0; j < p; ++j) min_left = std::min(min_left, signal[j]);
        double min_right = signal[n - 1];
        for (size_t j = p + 1; j < n; ++j) min_right = std::min(min_right, signal[j]);
        prominences.push_back(signal[p] - std::max(min_left, min_right));
    }

    std::cout << "Detected peaks at indices: ";
    for (size_t p : peaks) std::cout << p << " ";
    std::cout << "| Prominences: ";
    for (double p : prominences) std::cout << p << " ";
    double rej = (1.0 - static_cast<double>(noise_detections) / 2.0) * 100.0;
    std::cout << "| Noise rejection rate: " << rej << "% | PASS\n";
    return 0;
}
