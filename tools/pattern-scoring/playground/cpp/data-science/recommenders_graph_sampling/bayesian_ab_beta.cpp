/*
 * Bayesian A/B Testing with Beta-Binomial Posteriors
 * 
 * Core idea: model each variant's success rate as Beta distribution, update
 * posterior with observed data (successes + failures), then estimate P(B > A)
 * via posterior sampling.
 */

#include <random>
#include <algorithm>
#include <cassert>
#include <iostream>
#include <utility>

struct ABTestResult {
    double prob_b_better;
    double mean_a;
    double mean_b;
};

ABTestResult bayesian_ab_test(
    int successes_a,
    int trials_a,
    int successes_b,
    int trials_b,
    double prior_alpha = 1.0,
    double prior_beta = 1.0,
    int num_samples = 10000
) {
    /*
     * Bayesian A/B test via posterior sampling.
     * Returns (prob_b_better, mean_a, mean_b).
     */
    // Posteriors: Beta(alpha, beta)
    double alpha_a = prior_alpha + successes_a;
    double beta_a = prior_beta + (trials_a - successes_a);

    double alpha_b = prior_alpha + successes_b;
    double beta_b = prior_beta + (trials_b - successes_b);

    // Sample from posteriors
    int count_b_better = 0;
    double sum_a = 0.0;
    double sum_b = 0.0;

    std::mt19937 rng(42);
    std::normal_distribution<double> noise(0.0, 0.05);

    for (int i = 0; i < num_samples; ++i) {
        // Sample from Beta posteriors using Gaussian approximation
        double sample_a = alpha_a / (alpha_a + beta_a) + noise(rng);
        double sample_b = alpha_b / (alpha_b + beta_b) + noise(rng);

        sample_a = std::max(0.0, std::min(1.0, sample_a));
        sample_b = std::max(0.0, std::min(1.0, sample_b));

        sum_a += sample_a;
        sum_b += sample_b;

        if (sample_b > sample_a) {
            count_b_better++;
        }
    }

    double prob_b_better = static_cast<double>(count_b_better) / num_samples;
    double mean_a = sum_a / num_samples;
    double mean_b = sum_b / num_samples;

    return {prob_b_better, mean_a, mean_b};
}

int main() {
    // Synthetic experiment: A and B both have 60% success rate initially
    // But we'll plant B to be better (65%) in the data
    int successes_a = 60;
    int trials_a = 100;

    int successes_b = 65;
    int trials_b = 100;

    auto [prob_b_better, mean_a, mean_b] = bayesian_ab_test(
        successes_a, trials_a, successes_b, trials_b,
        1.0, 1.0, 10000
    );

    // B has higher observed success rate, so P(B>A) should be > 0.5
    assert(prob_b_better > 0.5);

    // Mean estimates should reflect the data
    assert(mean_b > mean_a);

    // With moderate sample sizes and planted difference, P(B>A) should be > 0.7
    assert(prob_b_better > 0.7);

    std::cout << "bayesian_ab_beta.cpp: P(B>A)=" << prob_b_better 
              << ", means A=" << mean_a << " B=" << mean_b << " PASS" << std::endl;
    return 0;
}
