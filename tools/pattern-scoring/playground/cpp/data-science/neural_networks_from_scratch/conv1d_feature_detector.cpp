/*
 * 1D Convolution Layer Learning to Detect a Planted Motif
 * 
 * Implement 1D convolution from scratch. Convolve a learnable kernel
 * over a 1D sequence. Data contains a planted motif; over training the kernel
 * learns to detect it.
 */

#include <vector>
#include <random>
#include <cmath>
#include <cassert>
#include <iostream>

class Conv1D {
public:
    int kernel_size;
    double lr;
    std::vector<double> kernel;
    double bias;

    Conv1D(int ks = 3, double learning_rate = 0.01) 
        : kernel_size(ks), lr(learning_rate), bias(0.0) {
        kernel.resize(ks, 0.0);
    }

    std::vector<double> convolve(const std::vector<double>& x) {
        /* Apply 1D convolution: valid padding. */
        std::vector<double> output;
        output.reserve(x.size() - kernel_size + 1);
        for (size_t i = 0; i <= x.size() - kernel_size; ++i) {
            double conv_sum = bias;
            for (int k = 0; k < kernel_size; ++k) {
                conv_sum += kernel[k] * x[i + k];
            }
            output.push_back(conv_sum);
        }
        return output;
    }

    double backward(const std::vector<double>& x, 
                   const std::vector<double>& conv_out,
                   const std::vector<double>& target_responses) {
        /* Backward pass: update kernel and bias based on response errors. */
        double total_loss = 0.0;
        std::vector<double> dkernel(kernel_size, 0.0);
        double dbias = 0.0;

        for (size_t i = 0; i < conv_out.size(); ++i) {
            double error = conv_out[i] - target_responses[i];
            double loss = error * error / 2.0;
            total_loss += loss;
            dbias += error;
            for (int k = 0; k < kernel_size; ++k) {
                dkernel[k] += error * x[i + k];
            }
        }

        // Update
        for (int k = 0; k < kernel_size; ++k) {
            kernel[k] -= lr * dkernel[k] / conv_out.size();
        }
        bias -= lr * dbias / conv_out.size();

        return total_loss / conv_out.size();
    }
};

int main() {
    std::mt19937 rng(42);
    std::normal_distribution<double> noise(0.0, 0.3);
    std::normal_distribution<double> small_noise(0.0, 0.1);

    // Motif: [1.0, -0.5, 1.0]
    std::vector<double> motif = {1.0, -0.5, 1.0};
    int kernel_size = 3;

    // Generate training data: sequences with motif planted at specific positions
    std::vector<std::vector<double>> data;
    for (int i = 0; i < 10; ++i) {
        std::vector<double> seq(20);
        for (int j = 0; j < 20; ++j) {
            seq[j] = noise(rng);
        }
        // Plant motif at random position
        std::uniform_int_distribution<int> dist(0, 20 - kernel_size);
        int motif_pos = dist(rng);
        for (int k = 0; k < kernel_size; ++k) {
            seq[motif_pos + k] = motif[k] + small_noise(rng);
        }
        data.push_back(seq);
    }

    // Create training targets
    std::vector<std::vector<double>> targets_per_sample;
    for (const auto& seq : data) {
        std::vector<double> targets;
        for (size_t i = 0; i <= seq.size() - kernel_size; ++i) {
            double similarity = 0.0;
            for (int k = 0; k < kernel_size; ++k) {
                similarity += seq[i + k] * motif[k];
            }
            double target = std::max(0.0, std::min(1.0, (similarity + 1.0) / 2.0));
            targets.push_back(target);
        }
        targets_per_sample.push_back(targets);
    }

    // Train
    Conv1D conv_layer(kernel_size, 0.1);
    for (int epoch = 0; epoch < 200; ++epoch) {
        for (size_t i = 0; i < data.size(); ++i) {
            auto conv_out = conv_layer.convolve(data[i]);
            conv_layer.backward(data[i], conv_out, targets_per_sample[i]);
        }
    }

    // Evaluate: planted motif should produce high response
    std::vector<double> test_seq(30);
    for (int i = 0; i < 30; ++i) {
        test_seq[i] = noise(rng);
    }
    int motif_pos = 10;
    for (int k = 0; k < kernel_size; ++k) {
        test_seq[motif_pos + k] = motif[k];
    }

    auto responses = conv_layer.convolve(test_seq);
    double response_at_motif = responses[motif_pos];
    double sum_elsewhere = 0.0;
    for (size_t i = 0; i < responses.size(); ++i) {
        if (static_cast<int>(i) != motif_pos) {
            sum_elsewhere += responses[i];
        }
    }
    double avg_response_elsewhere = sum_elsewhere / (responses.size() - 1);

    // Assertion: response at motif should be much higher
    assert(response_at_motif > avg_response_elsewhere * 2.0);

    std::cout << "conv1d_feature_detector.cpp PASS" << std::endl;
    return 0;
}
