/*
 * Gaussian Copula
 * 
 * Model dependence structure separately from marginals.
 * Copula C(u, v) = P(U ≤ u, V ≤ v) where U, V ~ uniform.
 */

#include <vector>
#include <cmath>
#include <random>
#include <algorithm>
#include <cassert>
#include <iostream>

std::pair<std::vector<double>, std::vector<double>> gaussian_copula_sample(double rho, int n) {
    /* Sample from bivariate Gaussian copula with correlation rho. */
    std::mt19937 rng(42);
    std::normal_distribution<double> normal(0.0, 1.0);

    std::vector<double> samples_u, samples_v;
    samples_u.reserve(n);
    samples_v.reserve(n);

    for (int i = 0; i < n; ++i) {
        double z1 = normal(rng);
        double z2 = normal(rng);

        double x = z1;
        double y = rho * z1 + std::sqrt(1.0 - rho * rho) * z2;

        // Transform to uniform via CDF (error function)
        double u = 0.5 * (1.0 + std::erf(x / std::sqrt(2.0)));
        double v = 0.5 * (1.0 + std::erf(y / std::sqrt(2.0)));

        samples_u.push_back(u);
        samples_v.push_back(v);
    }

    return {samples_u, samples_v};
}

double rank_correlation(const std::vector<double>& x, const std::vector<double>& y) {
    /* Spearman rank correlation. */
    int n = static_cast<int>(x.size());
    
    // Get ranks
    std::vector<int> indices(n);
    for (int i = 0; i < n; ++i) indices[i] = i;

    std::sort(indices.begin(), indices.end(), [&x](int i, int j) { return x[i] < x[j]; });
    std::vector<int> rank_x(n);
    for (int r = 0; r < n; ++r) rank_x[indices[r]] = r + 1;

    std::sort(indices.begin(), indices.end(), [&y](int i, int j) { return y[i] < y[j]; });
    std::vector<int> rank_y(n);
    for (int r = 0; r < n; ++r) rank_y[indices[r]] = r + 1;

    double mean_rx = (n + 1.0) / 2.0;
    double mean_ry = (n + 1.0) / 2.0;

    double cov = 0.0, var_rx = 0.0, var_ry = 0.0;
    for (int i = 0; i < n; ++i) {
        double dx = rank_x[i] - mean_rx;
        double dy = rank_y[i] - mean_ry;
        cov += dx * dy;
        var_rx += dx * dx;
        var_ry += dy * dy;
    }
    cov /= n;
    var_rx /= n;
    var_ry /= n;

    return (var_rx * var_ry > 0.0) ? cov / std::sqrt(var_rx * var_ry) : 0.0;
}

