/*
 * Stirling's approximation for log(n!): n*ln(n) - n + 0.5*ln(2*pi*n), checked against
 * the exact log-factorial (summed logs) at n = 10, 100, 1000. Demonstrates that the
 * approximation's relative error shrinks as n grows.
 * Use when you need a cheap log-factorial for large n (combinatorics, log-likelihoods).
 * Guarantees: the relative error is strictly decreasing across n = 10 -> 100 -> 1000
 * and is below 0.01 (well under 1%) by n = 1000.
 */
#include <cmath>
#include <vector>
#include <cassert>
#include <iostream>

// Stirling's approximation for log(n!).
double stirling_log_factorial(int n) {
    if (n == 0) return 0.0;
    return n * std::log(n) - n + 0.5 * std::log(2.0 * M_PI * n);
}

// Exact log(n!) = log(1) + log(2) + ... + log(n).
double exact_log_factorial(int n) {
    double sum = 0.0;
    for (int i = 1; i <= n; ++i) sum += std::log(i);
    return sum;
}

int main() {
    std::vector<std::pair<int, double>> errors;
    for (int n : {10, 100, 1000}) {
        double log_exact = exact_log_factorial(n);
        double log_stirling = stirling_log_factorial(n);
        double relative_error = std::abs(log_stirling - log_exact) / log_exact;
        errors.push_back({n, relative_error});
    }

    // Error should decrease as n increases.
    assert(errors[0].second > errors[1].second);
    assert(errors[1].second > errors[2].second);

    // Error at n=1000 should be small.
    assert(errors[2].second < 0.01);

    std::cout << "stirling_approximation_error: PASS" << std::endl;
    return 0;
}
