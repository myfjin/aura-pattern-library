/*
 * Coupon Collector Problem
 * 
 * Expected trials to collect all n distinct items: E[T] = n * H_n where H_n is harmonic sum.
 */

#include <vector>
#include <random>
#include <set>
#include <cmath>
#include <cassert>
#include <iostream>

double harmonic_sum(int n) {
    double sum = 0.0;
    for (int i = 1; i <= n; ++i) {
        sum += 1.0 / i;
    }
    return sum;
}

double coupon_collector_expected(int n) {
    return n * harmonic_sum(n);
}

double coupon_collector_simulate(int n, int num_sim = 1000) {
    std::mt19937 rng(42);
    std::uniform_int_distribution<int> uniform(1, n);

    int total_trials = 0;
    for (int sim = 0; sim < num_sim; ++sim) {
        std::set<int> collected;
        int trials = 0;
        while (static_cast<int>(collected.size()) < n) {
            collected.insert(uniform(rng));
            trials++;
        }
        total_trials += trials;
    }
    return static_cast<double>(total_trials) / num_sim;
}

int main() {
    const int n = 10;
    double expected_exact = coupon_collector_expected(n);
    double expected_sim = coupon_collector_simulate(n, 1000);

    // Simulated should be close to exact (within 10%)
    assert(std::abs(expected_sim - expected_exact) < expected_exact * 0.1);

    std::cout << "coupon_collector.cpp PASS" << std::endl;
    return 0;
}
