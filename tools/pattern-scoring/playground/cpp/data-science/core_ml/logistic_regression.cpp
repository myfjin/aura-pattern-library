double sigmoid(double z) {
    if (z > 100) return 1.0;
    if (z < -100) return 0.0;
    return 1.0 / (1.0 + std::exp(-z));
}

std::pair<std::vector<double>, double> logistic_regression_fit(
    const std::vector<std::vector<double>>& X,
    const std::vector<int>& y,
    double learning_rate = 0.01,
    int iterations = 100) {

    int n = static_cast<int>(X.size());
    int f = static_cast<int>(X[0].size());
    std::vector<double> weights(f, 0.0);
    double bias = 0.0;

    for (int iter = 0; iter < iterations; ++iter) {
        std::vector<double> predictions(n);
        for (int i = 0; i < n; ++i) {
            double z = bias;
            for (int j = 0; j < f; ++j) z += weights[j] * X[i][j];
            predictions[i] = sigmoid(z);
        }
        std::vector<double> dw(f, 0.0);
        double db = 0.0;
        for (int i = 0; i < n; ++i) {
            double err = predictions[i] - y[i];
            for (int j = 0; j < f; ++j) dw[j] += err * X[i][j];
            db += err;
        }
        for (int j = 0; j < f; ++j) weights[j] -= learning_rate * (dw[j] / n);
        bias -= learning_rate * (db / n);
    }
    return {weights, bias};
}

