double pooled_ols(const std::vector<double>& y, const std::vector<double>& x) {
    int n = static_cast<int>(y.size());
    double mean_x = 0.0, mean_y = 0.0;
    for (double v : x) mean_x += v;
    for (double v : y) mean_y += v;
    mean_x /= n;
    mean_y /= n;

    double cov = 0.0, var_x = 0.0;
    for (int i = 0; i < n; ++i) {
        cov += (x[i] - mean_x) * (y[i] - mean_y);
        var_x += (x[i] - mean_x) * (x[i] - mean_x);
    }
    cov /= n;
    var_x /= n;

    return (var_x > 1e-14) ? cov / var_x : 0.0;
}

double within_estimator(const Panel& panel) {
    std::vector<double> y_demeaned, x_demeaned;
    for (size_t i = 0; i < panel.y.size(); ++i) {
        double mean_y_i = 0.0, mean_x_i = 0.0;
        for (double v : panel.y[i]) mean_y_i += v;
        for (double v : panel.x[i]) mean_x_i += v;
        mean_y_i /= panel.y[i].size();
        mean_x_i /= panel.x[i].size();

        for (size_t t = 0; t < panel.y[i].size(); ++t) {
            y_demeaned.push_back(panel.y[i][t] - mean_y_i);
            x_demeaned.push_back(panel.x[i][t] - mean_x_i);
        }
    }
    return pooled_ols(y_demeaned, x_demeaned);
}

