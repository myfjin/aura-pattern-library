/*
 * Value averaging vs dollar-cost averaging over a simulated price path.
 * DCA invests a fixed cash amount each period; value averaging instead buys just
 * enough to hit a linearly growing target portfolio value each period. Use to
 * compare the two contribution schedules' terminal wealth. Oracle: both strategies
 * end with positive value and their terminal-value ratio stays within [0.5, 2.0]
 * (neither wildly dominates on this path). Not investment advice.
 */
#include <cassert>
#include <cmath>
#include <iostream>
#include <random>
#include <vector>

using namespace std;

double dollar_cost_averaging(const vector<double>& prices, double invest_per_period) {
    double shares = 0.0;
    for (double price : prices) shares += invest_per_period / price;
    return shares * prices.back();
}

double value_averaging(const vector<double>& prices, double target_growth_rate) {
    double shares = 0.0;
    double p0 = prices[0];
    for (size_t t = 0; t < prices.size(); ++t) {
        double target_value = target_growth_rate * (t + 1) * p0;
        double current_value = shares * prices[t];
        double needed = max(0.0, target_value - current_value);
        shares += needed / prices[t];
    }
    return shares * prices.back();
}

int main() {
    mt19937 rng(42);
    normal_distribution<double> d(0.05, 0.1);
    vector<double> prices;
    double price = 100.0;
    for (int i = 0; i < 12; ++i) {
        price *= (1.0 + d(rng));
        prices.push_back(price);
    }

    double invest_per_period = 100.0;
    double final_dca = dollar_cost_averaging(prices, invest_per_period);
    double target_rate = invest_per_period / prices[0];
    double final_va = value_averaging(prices, target_rate);

    assert(final_dca > 0.0 && final_va > 0.0);
    double ratio = (final_dca > 0.0) ? final_va / final_dca : 1.0;
    assert(0.5 < ratio && ratio < 2.0);

    cout << "value_averaging_vs_dca PASS\n";
    return 0;
}
