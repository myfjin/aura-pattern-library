double sharpeRatio(const std::vector<double>& returns, double riskFreeRate = 0.0) {
    double meanRet = 0.0;
    for (double r : returns) meanRet += r;
    meanRet /= returns.size();

    double variance = 0.0;
    for (double r : returns) variance += (r - meanRet) * (r - meanRet);
    variance /= returns.size();
    double stdDev = std::sqrt(variance);

    return stdDev > 1e-14 ? (meanRet - riskFreeRate) / stdDev : 0.0;
}

double sortinoRatio(const std::vector<double>& returns, double targetReturn = 0.0) {
    double meanRet = 0.0;
    for (double r : returns) meanRet += r;
    meanRet /= returns.size();

    double downsideVar = 0.0;
    for (double r : returns) {
        double d = std::min(r - targetReturn, 0.0);
        downsideVar += d * d;
    }
    downsideVar /= returns.size();
    double downsideStd = std::sqrt(downsideVar);

    return downsideStd > 1e-14 ? (meanRet - targetReturn) / downsideStd : 0.0;
}

