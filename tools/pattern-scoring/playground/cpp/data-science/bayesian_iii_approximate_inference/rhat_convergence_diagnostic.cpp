/*
Gelman-Rubin R-hat convergence diagnostic for MCMC: combines between-chain and
within-chain variance as sqrt((B+W)/W), which approaches 1 when chains agree.
Use to decide whether multiple sampler chains have mixed. Oracle: four
well-mixed chains from one target give an R-hat well below that of chains stuck
at different means, and the stuck case exceeds the 1.1 non-convergence flag.
*/
#include <cassert>
#include <cmath>
#include <cstdio>
#include <random>
#include <vector>

double rhat(const std::vector<std::vector<double>>& chains) {
    int m = static_cast<int>(chains.size());
    if (m == 0) return 1.0;
    int n = static_cast<int>(chains[0].size());
    if (m < 2 || n < 2) return 1.0;

    double var_within = 0.0;
    for (const auto& chain : chains) {
        int len = static_cast<int>(chain.size());
        double chain_mean = 0.0;
        for (double x : chain) chain_mean += x;
        chain_mean /= len;

        double var_chain = 0.0;
        for (double x : chain) var_chain += (x - chain_mean) * (x - chain_mean);
        var_chain /= (len - 1);
        var_within += var_chain;
    }
    var_within /= m;

    std::vector<double> chain_means(m);
    for (int i = 0; i < m; ++i) {
        double s = 0.0;
        for (double x : chains[i]) s += x;
        chain_means[i] = s / chains[i].size();
    }

    double overall_mean = 0.0;
    for (double mu : chain_means) overall_mean += mu;
    overall_mean /= m;

    double var_between = 0.0;
    for (double mu : chain_means) var_between += (mu - overall_mean) * (mu - overall_mean);
    var_between *= static_cast<double>(n) / (m - 1);

    if (var_within == 0.0) return 1.0;
    return std::sqrt((var_between + var_within) / var_within);
}

int main() {
    std::vector<std::vector<double>> well_mixed;
    for (int chain_idx = 0; chain_idx < 4; ++chain_idx) {
        std::mt19937 gen(42 + chain_idx);
        std::normal_distribution<double> dist(0.0, 1.0);
        std::vector<double> chain;
        for (int i = 0; i < 100; ++i) chain.push_back(dist(gen));
        well_mixed.push_back(chain);
    }

    double rhat_good = rhat(well_mixed);

    std::vector<std::vector<double>> stuck;
    for (int chain_idx = 0; chain_idx < 4; ++chain_idx) {
        std::mt19937 gen(42 + chain_idx);
        double start_mean = chain_idx * 2.0;
        std::normal_distribution<double> dist(start_mean, 1.0);
        std::vector<double> chain;
        for (int i = 0; i < 100; ++i) chain.push_back(dist(gen));
        stuck.push_back(chain);
    }

    double rhat_bad = rhat(stuck);

    assert(rhat_good < rhat_bad);
    assert(rhat_bad > 1.1);

    printf("rhat_good=%.4f rhat_bad=%.4f PASS\n", rhat_good, rhat_bad);
    return 0;
}
