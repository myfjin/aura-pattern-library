#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <algorithm>

void monte_carlo_var_es() {
    std::mt19937_64 rng(42);
    std::normal_distribution<double> normal(-0.01, 0.02);
    std::exponential_distribution<double> extreme(10.0);
    std::uniform_real_distribution<double> uniform(0.0, 1.0);

    int n_simulations = 10000;
    std::vector<double> returns;
    for (int i = 0; i < n_simulations; ++i) {
        double ret;
        if (uniform(rng) < 0.95) ret = normal(rng);
        else ret = -extreme(rng);
        returns.push_back(ret);
    }
    std::sort(returns.begin(), returns.end());

    double alpha = 0.05;
    int var_index = static_cast<int>(alpha * n_simulations);
    double var_95 = returns[var_index];

    double es_95 = 0.0;
    for (int i = 0; i < var_index; ++i) es_95 += returns[i];
    es_95 /= var_index;

    assert(var_95 < 0.0);
    assert(es_95 < var_95);
    assert(std::abs(es_95) >= std::abs(var_95));

    int exceedances = 0;
    for (double r : returns) if (r < var_95) ++exceedances;
    double exceedance_rate = exceedances / static_cast<double>(n_simulations);
    assert(exceedance_rate > 0.03 && exceedance_rate < 0.07);

    std::cout << "monte_carlo_var_es.cpp PASS" << std::endl;
}

