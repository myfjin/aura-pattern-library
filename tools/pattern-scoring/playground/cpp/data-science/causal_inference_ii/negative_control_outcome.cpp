double fit_regression_coef(const std::vector<double>& x, const std::vector<double>& y) {
    int n = static_cast<int>(x.size());
    if (n == 0) return 0.0;
    double xm = 0.0, ym = 0.0;
    for (double v : x) xm += v;
    for (double v : y) ym += v;
    xm /= n; ym /= n;
    double num = 0.0, den = 0.0;
    for (int i = 0; i < n; ++i) {
        num += (x[i] - xm) * (y[i] - ym);
        den += (x[i] - xm) * (x[i] - xm);
    }
    return std::abs(den) < 1e-10 ? 0.0 : num / den;
}

