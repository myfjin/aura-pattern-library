#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <tuple>

std::tuple<std::vector<std::vector<double>>,
           std::vector<std::vector<double>>,
           std::vector<std::vector<double>>> lu_decomposition_pivoting(
    const std::vector<std::vector<double>>& A) {

    int n = static_cast<int>(A.size());
    std::vector<std::vector<double>> A_work = A;
    std::vector<int> piv(n);
    for (int i = 0; i < n; ++i) piv[i] = i;

    for (int k = 0; k < n; ++k) {
        int max_idx = k;
        for (int i = k + 1; i < n; ++i) {
            if (std::abs(A_work[i][k]) > std::abs(A_work[max_idx][k])) max_idx = i;
        }
        std::swap(A_work[k], A_work[max_idx]);
        std::swap(piv[k], piv[max_idx]);

        for (int i = k + 1; i < n; ++i) {
            A_work[i][k] /= A_work[k][k];
            for (int j = k + 1; j < n; ++j) A_work[i][j] -= A_work[i][k] * A_work[k][j];
        }
    }

    std::vector<std::vector<double>> L(n, std::vector<double>(n, 0.0));
    std::vector<std::vector<double>> U(n, std::vector<double>(n, 0.0));
    for (int i = 0; i < n; ++i) {
        for (int j = 0; j < n; ++j) {
            if (i == j) L[i][j] = 1.0;
            else if (j < i) L[i][j] = A_work[i][j];
            if (j >= i) U[i][j] = A_work[i][j];
        }
    }

    std::vector<std::vector<double>> P(n, std::vector<double>(n, 0.0));
    for (int i = 0; i < n; ++i) P[i][piv[i]] = 1.0;
    return {P, L, U};
}

std::vector<std::vector<double>> matrix_mult(const std::vector<std::vector<double>>& A,
                                            const std::vector<std::vector<double>>& B) {
    int n = static_cast<int>(A.size()), m = static_cast<int>(B[0].size()), p = static_cast<int>(B.size());
    std::vector<std::vector<double>> C(n, std::vector<double>(m, 0.0));
    for (int i = 0; i < n; ++i)
        for (int j = 0; j < m; ++j)
            for (int k = 0; k < p; ++k) C[i][j] += A[i][k] * B[k][j];
    return C;
}

