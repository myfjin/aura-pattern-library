static pair<double,double> dp_metrics(const vector<int>& predictions,
                                       const vector<int>& groups) {
    int sum_a = 0, cnt_a = 0, sum_b = 0, cnt_b = 0;
    for (size_t i = 0; i < predictions.size(); ++i) {
        if (groups[i] == 0) { sum_a += predictions[i]; ++cnt_a; }
        else { sum_b += predictions[i]; ++cnt_b; }
    }
    double rate_a = cnt_a ? static_cast<double>(sum_a) / cnt_a : 0.0;
    double rate_b = cnt_b ? static_cast<double>(sum_b) / cnt_b : 0.0;
    double dp_diff = fabs(rate_a - rate_b);
    double disparate_impact = rate_a > 0 ? rate_b / rate_a : 0.0;
    return {dp_diff, disparate_impact};
}

