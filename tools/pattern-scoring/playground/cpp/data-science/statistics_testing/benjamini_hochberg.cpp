/*
 * Benjamini-Hochberg False Discovery Rate Correction
 * 
 * Controls the False Discovery Rate (FDR): the expected proportion of false positives among
 * rejected hypotheses. Sort p-values, find largest index i where p_i <= (i/m) * alpha,
 * then reject all p-values up to that index.
 */

#include <vector>
#include <algorithm>
#include <random>
#include <cassert>
#include <iostream>
#include <utility>

std::pair<std::vector<bool>, double> benjamini_hochberg(
    const std::vector<double>& p_values,
    double alpha = 0.05
) {
    /*
     * Benjamini-Hochberg FDR procedure.
     * Returns: (rejected, threshold)
     */
    int m = static_cast<int>(p_values.size());

    // Pair each p-value with its original index
    std::vector<std::pair<double, int>> indexed_pvals(m);
    for (int i = 0; i < m; ++i) {
        indexed_pvals[i] = {p_values[i], i};
    }

    // Sort by p-value
    std::sort(indexed_pvals.begin(), indexed_pvals.end());

    // Find largest index i where p_values[i] <= (i+1)/m * alpha
    double threshold = 0.0;
    int largest_i = -1;

    for (int rank = 0; rank < m; ++rank) {
        double p_val = indexed_pvals[rank].first;
        int i = rank + 1;  // 1-indexed rank
        if (p_val <= (static_cast<double>(i) / m) * alpha) {
            largest_i = rank;
            threshold = p_val;
        }
    }

    // Reject all hypotheses with p-value <= threshold
    std::vector<bool> rejected(m, false);
    if (largest_i >= 0) {
        for (int rank = 0; rank <= largest_i; ++rank) {
            int orig_idx = indexed_pvals[rank].second;
            rejected[orig_idx] = true;
        }
    }

    return {rejected, threshold};
}

