# Uptrend: y increases over time
time_index <- 1:30
y_trend <- 5 + 0.8 * time_index + rnorm(30, 0, 2)

# White noise (no trend)
y_noise <- rnorm(30, 10, 2)

# Mann-Kendall for trend
mk_test <- function(time, value) {
  n <- length(value)
  S <- 0
  # Count concordant pairs
  for (i in 1:(n-1)) {
    for (j in (i+1):n) {
      sign_time <- sign(time[j] - time[i])
      sign_val <- sign(value[j] - value[i])
      S <- S + sign_time * sign_val  # since time is 1,2,...,n, always +1; use for clarity
    }
  }

  # Variance of S under H0 (no trend)
  var_S <- n * (n - 1) * (2*n + 5) / 18

  # Z-score
  if (S > 0) z <- (S - 1) / sqrt(var_S)
  else if (S < 0) z <- (S + 1) / sqrt(var_S)
  else z <- 0

  p_value <- 2 * pnorm(abs(z), lower.tail=FALSE)
  tau <- S / (n * (n - 1) / 2)

  list(S=S, tau=tau, z=z, p_value=p_value)
}

# Test trend series
result_trend <- mk_test(time_index, y_trend)
stopifnot(result_trend$p_value < 0.05)  # should reject H0 (have trend)

# Test noise series
result_noise <- mk_test(time_index, y_noise)
stopifnot(result_noise$p_value > 0.05)  # should NOT reject H0 (no trend)

# Oracle: cor.test(method="kendall")
oracle_trend <- cor.test(time_index, y_trend, method="kendall")
stopifnot(all.equal(result_trend$tau, unname(oracle_trend$estimate), tolerance=1e-6))
stopifnot(all.equal(result_trend$p_value, oracle_trend$p.value, tolerance=1e-5))

