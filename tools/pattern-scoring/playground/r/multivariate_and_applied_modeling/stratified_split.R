y <- factor(c(rep("pos", 60), rep("neg", 40)))
n <- length(y)

# Manual stratified split (80-20)
split_prop <- 0.8
train_indices <- integer()
test_indices <- integer()

for (level in levels(y)) {
  level_idx <- which(y == level)
  n_level <- length(level_idx)
  n_train <- floor(n_level * split_prop)

  selected_train <- sample(level_idx, n_train)
  train_indices <- c(train_indices, selected_train)

  remaining <- setdiff(level_idx, selected_train)
  test_indices <- c(test_indices, remaining)
}

y_train <- y[train_indices]
y_test <- y[test_indices]

# Verify proportions
prop_train <- table(y_train) / length(y_train)
prop_test <- table(y_test) / length(y_test)
prop_orig <- table(y) / length(y)

# Check within tolerance (5% relative)
