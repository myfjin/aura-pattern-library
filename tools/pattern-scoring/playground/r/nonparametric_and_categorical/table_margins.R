x <- factor(rep(c("A", "B"), each=25))
y <- factor(rep(c(1, 2, 1, 2), c(12, 13, 13, 12)))

# Manual contingency table
levels_x <- levels(x)
levels_y <- levels(y)
manual_table <- matrix(0, nrow=length(levels_x), ncol=length(levels_y))
rownames(manual_table) <- levels_x
colnames(manual_table) <- levels_y

for (i in seq_along(x)) {
  row_idx <- which(levels_x == x[i])
  col_idx <- which(levels_y == y[i])
  manual_table[row_idx, col_idx] <- manual_table[row_idx, col_idx] + 1
}

# Manual margins
row_margins <- rowSums(manual_table)
col_margins <- colSums(manual_table)
total <- sum(manual_table)

# Oracle: table() + addmargins()
oracle_table <- table(x, y)
oracle_margins <- addmargins(oracle_table)

# Verify
stopifnot(all(manual_table == oracle_table))
stopifnot(all.equal(row_margins, c(table(x)), tolerance=1e-8))
stopifnot(all.equal(col_margins, c(table(y)), tolerance=1e-8))
stopifnot(total == sum(manual_table))

