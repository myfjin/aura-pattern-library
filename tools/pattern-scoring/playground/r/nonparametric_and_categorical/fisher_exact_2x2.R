# 2x2 table: rows=Disease(yes/no), cols=Exposure(yes/no)
#       Yes  No   Total
# Exp+   12   4     16
# Exp-    3  15     18
# Total  15  19     34

a <- 12  # top-left cell
b <- 4   # top-right
c <- 3   # bottom-left
d <- 15  # bottom-right

m1 <- a + c  # col 1 margin
m2 <- b + d  # col 2 margin
n1 <- a + b  # row 1 margin
n2 <- c + d  # row 2 margin
N <- a + b + c + d

# Hypergeometric probability for cell value a:
# P(A=a) = C(m1,a)*C(m2,n1-a) / C(N,n1)
hypergeo_prob <- function(a_val, m1, m2, n1, N) {
  # Using log-scale to avoid overflow
  log_num <- lchoose(m1, a_val) + lchoose(m2, n1 - a_val)
  log_den <- lchoose(N, n1)
  exp(log_num - log_den)
}

# Find min and max possible a
a_min <- max(0, n1 - m2)
a_max <- min(n1, m1)
a_vals <- a_min:a_max

# Compute probabilities for all valid tables
probs <- sapply(a_vals, hypergeo_prob, m1=m1, m2=m2, n1=n1, N=N)

# One-tailed p-value: alternative="greater" means sum P(A >= a_obs)
# (in terms of the hypergeometric parameter, not probability)
p_one_tail <- sum(probs[a_vals >= a])

# Oracle: fisher.test (must match table structure: rows=first factor, cols=second)
table_2x2 <- matrix(c(a, b, c, d), nrow=2, byrow=TRUE)
oracle_result <- fisher.test(table_2x2, alternative="greater")
stopifnot(all.equal(p_one_tail, oracle_result$p.value, tolerance=1e-6))

