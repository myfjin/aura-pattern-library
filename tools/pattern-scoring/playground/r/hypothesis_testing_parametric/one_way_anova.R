groups <- rep(1:4, each=15)
y <- c(rnorm(15, 5, 1), rnorm(15, 6, 1), rnorm(15, 5.5, 1), rnorm(15, 7, 1))

# Manual ANOVA
grand_mean <- mean(y)
ss_total <- sum((y - grand_mean)^2)
group_means <- tapply(y, groups, mean)
ss_between <- sum(table(groups) * (group_means - grand_mean)^2)
ss_within <- ss_total - ss_between

k <- length(unique(groups))
n <- length(y)
df_between <- k - 1
df_within <- n - k

ms_between <- ss_between / df_between
ms_within <- ss_within / df_within
