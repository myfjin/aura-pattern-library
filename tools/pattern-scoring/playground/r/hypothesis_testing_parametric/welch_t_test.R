set.seed(42)
x1 <- rnorm(20, mean=5, sd=1)
x2 <- rnorm(25, mean=4.5, sd=2)

# Manual Welch t-test
n1 <- length(x1)
n2 <- length(x2)
m1 <- mean(x1)
m2 <- mean(x2)
s1 <- var(x1)
s2 <- var(x2)

t_stat <- (m1 - m2) / sqrt(s1/n1 + s2/n2)
df_num <- (s1/n1 + s2/n2)^2
df_denom <- (s1/n1)^2/(n1-1) + (s2/n2)^2/(n2-1)
df <- df_num / df_denom

# Two-tailed p-value
p_val <- 2 * (1 - pt(abs(t_stat), df))

# Oracle: t.test()
t_oracle <- t.test(x1, x2)

# Verify
stopifnot(all.equal(t_stat, as.numeric(t_oracle$statistic), tolerance=1e-8))
stopifnot(all.equal(p_val, t_oracle$p.value, tolerance=1e-8))

