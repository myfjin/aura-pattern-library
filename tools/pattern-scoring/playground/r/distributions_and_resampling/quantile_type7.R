# Quantile function, type 7 (default)
quantile_type7 <- function(x, p) {
  x <- sort(x)
  n <- length(x)
  h <- (n - 1) * p
  h_floor <- floor(h)
  h_frac <- h - h_floor

  # Interpolate between x_{h_floor} and x_{h_floor+1}
  # Note: R uses 1-indexing, so h_floor+1 and h_floor+2 indices
  q <- x[h_floor + 1] + h_frac * (x[h_floor + 2] - x[h_floor + 1])
  return(q)
}

