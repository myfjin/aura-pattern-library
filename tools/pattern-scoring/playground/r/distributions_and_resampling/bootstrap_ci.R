true_mean <- 5
y <- rnorm(100, mean=true_mean, sd=2)

# Bootstrap percentile CI (95%)
B <- 1000
boot_means <- numeric(B)
for (b in 1:B) {
  boot_sample <- sample(y, replace=TRUE)
  boot_means[b] <- mean(boot_sample)
}

ci_lower <- quantile(boot_means, 0.025)
ci_upper <- quantile(boot_means, 0.975)

# Verify: true mean is in CI
stopifnot(true_mean >= ci_lower && true_mean <= ci_upper)

# Additional: SE estimate
boot_se <- sd(boot_means)
sample_se <- sd(y) / sqrt(length(y))
stopifnot(all.equal(boot_se, sample_se, tolerance=0.1))

