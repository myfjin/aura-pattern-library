import subprocess
import threading
import time
import sys
import os

class Supervisor:
    def __init__(self):
        self.child_process = None
        self.restart_count = 0
        self.running = True
        self.lock = threading.Lock()

    def spawn_child(self):
        """Spawn a new child process."""
        # Child that sleeps indefinitely
        self.child_process = subprocess.Popen(
            [sys.executable, "-c", "import time; time.sleep(100)"]
        )

    def supervise(self):
        """Monitor child; restart if it dies."""
        while self.running:
            if self.child_process is None or self.child_process.poll() is not None:
                # Child is dead or doesn't exist; restart
                with self.lock:
                    self.spawn_child()
                    self.restart_count += 1
            time.sleep(0.05)

    def kill_child(self):
        """Force kill the child to test restart."""
        if self.child_process:
            try:
                os.kill(self.child_process.pid, 9)  # SIGKILL
                self.child_process.wait()
            except:
                pass

    def stop_supervise(self):
        """Stop the supervisor."""
        self.running = False
        if self.child_process:
            try:
                os.kill(self.child_process.pid, 9)
            except:
                pass

