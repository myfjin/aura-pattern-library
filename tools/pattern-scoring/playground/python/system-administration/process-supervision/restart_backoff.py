def restart_with_backoff(max_backoff=2.0, backoff_factor=2.0):
    """Supervise child; on crash, restart with increasing delay."""
    delay = 0.1
    restart_times = []

    for i in range(4):
        # Record when we restart
        restart_times.append(time.time())

        # Spawn child that exits immediately
        child = subprocess.Popen([sys.executable, "-c", "import sys; sys.exit(1)"])
        child.wait()

        # Delay before next restart
        if i < 3:  # Don't sleep after last restart
            time.sleep(delay)
            # Increase delay for next iteration
            delay = min(delay * backoff_factor, max_backoff)

    # Compute inter-restart delays
    inter_restart_delays = [restart_times[i+1] - restart_times[i] for i in range(len(restart_times)-1)]

    return inter_restart_delays

