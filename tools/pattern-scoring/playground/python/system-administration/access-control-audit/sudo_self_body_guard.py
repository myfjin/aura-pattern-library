import sys
import re


class SudoGuard:
    """Guard against self-destructive sudo commands."""

    # Dangerous command patterns.
    DANGEROUS_PATTERNS = [
        (r"rm\s+-rf\s+/", "rm -rf / (deletes entire filesystem)"),
        (r"dd\s+if=/dev/zero\s+of=/", "dd to root (destroys filesystem)"),
        (r"chmod\s+-[rwx]*\s+/", "chmod on root (removes permissions)"),
        (r"mkfs\b", "mkfs (formats filesystem)"),
        (r"shred\s+-.*\s+/boot", "shred /boot (destroys bootloader)"),
    ]

    def check_command(self, cmd):
        """
        Check if a command is dangerous.
        Raises ValueError if dangerous, returns True if safe.
        """
        for pattern, reason in self.DANGEROUS_PATTERNS:
            if re.search(pattern, cmd, re.IGNORECASE):
                raise ValueError(f"blocked dangerous command: {reason}")
        return True


