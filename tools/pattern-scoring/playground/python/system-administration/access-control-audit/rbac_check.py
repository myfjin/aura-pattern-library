import sys


def rbac_enforce(user_role, resource, action, role_perms):
    """
    Enforce RBAC. role_perms = {role: {resource: [actions], ...}, ...}
    Raises ValueError if action is not permitted for role on resource.
    """
    if user_role not in role_perms:
        raise ValueError(f"unknown role: {user_role}")
    if resource not in role_perms[user_role]:
        raise ValueError(f"no permissions for {user_role} on {resource}")
    allowed_actions = role_perms[user_role][resource]
    if action not in allowed_actions:
        raise ValueError(
            f"{user_role} not permitted to {action} {resource} (allowed: {allowed_actions})"
        )
    return True


