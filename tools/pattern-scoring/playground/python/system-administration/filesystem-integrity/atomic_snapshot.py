import os
import tempfile
import sys
from pathlib import Path


def atomic_snapshot(source_path, snapshot_path):
    """
    Take an atomic snapshot of source_path to snapshot_path.
    Writes to temp, then renames (atomic).
    """
    source_data = Path(source_path).read_bytes()
    fd, temp_path = tempfile.mkstemp(dir=os.path.dirname(snapshot_path) or ".")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(source_data)
        os.rename(temp_path, snapshot_path)
    except:
        try:
            os.unlink(temp_path)
        except:
            pass
        raise


