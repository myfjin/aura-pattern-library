def schema_validate(config, schema):
    """Validate config against schema. schema = {key: type_name}.
    Raises ValueError with exact field name on mismatch.
    """
    for key, expected_type in schema.items():
        if key not in config:
            raise ValueError(f"Missing required config field: '{key}'")
        actual = type(config[key]).__name__
        if actual != expected_type:
            raise ValueError(f"Field '{key}' expects type {expected_type} but got {actual}")
    return True

