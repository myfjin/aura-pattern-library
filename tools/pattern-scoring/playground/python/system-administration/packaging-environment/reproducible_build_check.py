def build_artifact(sources):
    """
    Build an artifact from sources (dict: {filename: content_bytes}).
    Artifact = concatenated sorted filenames + hashes of all content.
    Deterministic: order is sorted, content is hashed consistently.
    """
    sorted_names = sorted(sources.keys())
    artifact = b""
    for name in sorted_names:
        content = sources[name]
        h = hashlib.sha256(content).hexdigest().encode()
        artifact += name.encode() + b":" + h + b"\n"
    return artifact


def build_and_hash(sources):
    """Build artifact and return its SHA256."""
    artifact = build_artifact(sources)
    return hashlib.sha256(artifact).hexdigest(), artifact


