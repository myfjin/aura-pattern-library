import sys


def detect_cycle_dfs(graph):
    """
    Detect a cycle in a directed graph. graph = {node: [neighbors], ...}.
    Returns (has_cycle, cycle_path) where cycle_path is a list of nodes forming the cycle.
    """
    visited = set()
    rec_stack = set()

    def dfs(node, path):
        visited.add(node)
        rec_stack.add(node)
        path.append(node)

        for neighbor in graph.get(node, []):
            if neighbor not in visited:
                cycle = dfs(neighbor, path[:])
                if cycle:
                    return cycle
            elif neighbor in rec_stack:
                # Found cycle: from neighbor to end of path
                cycle_start = path.index(neighbor)
                return path[cycle_start:] + [neighbor]

        rec_stack.remove(node)
        return None

    for node in graph:
        if node not in visited:
            cycle = dfs(node, [])
            if cycle:
                return True, cycle

    return False, []


