import os, tempfile, pathlib, glob
import random

def rotate_by_size(log_path, size_cap_bytes=1000, keep_rotations=2):
    """Write to log; if it exceeds size_cap_bytes, rotate old ones, keep the N newest."""
    log_file = pathlib.Path(log_path)

    def append_line(text):
        current_size = log_file.stat().st_size if log_file.exists() else 0
        if current_size + len(text) + 1 > size_cap_bytes:
            # Delete oldest rotation
            for i in range(keep_rotations, 0, -1):
                old = pathlib.Path(f"{log_path}.{i}")
                if old.exists():
                    old.unlink()
            # Shift rotations: .1 -> .2, .2 -> .3, etc.
            for i in range(keep_rotations - 1, 0, -1):
                old = pathlib.Path(f"{log_path}.{i}")
                new = pathlib.Path(f"{log_path}.{i+1}")
                if old.exists():
                    old.rename(new)
            # Rotate current to .1
            if log_file.exists():
                log_file.rename(pathlib.Path(f"{log_path}.1"))
            log_file.touch()

        # Append to current log
        with open(log_file, 'a') as f:
            f.write(text + "\n")

    return append_line

