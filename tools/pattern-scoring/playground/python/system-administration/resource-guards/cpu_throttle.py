import threading
import time

def cpu_throttle_guard(max_concurrent=4):
    """Guard that limits concurrent CPU-bound workers.
    Returns: context with spawn_worker(), current_running, peak_concurrent, refused_count.
    """
    class CpuThrottle:
        def __init__(self, max_concurrent):
            self.max_concurrent = max_concurrent
            self.current_running = 0
            self.peak_concurrent = 0
            self.refused = 0
            self.lock = threading.Lock()
            self.sem = threading.Semaphore(max_concurrent)

        def spawn_worker(self, work_fn):
            """Spawn a worker if capacity allows; return True/False."""
            if not self.sem.acquire(blocking=False):
                with self.lock:
                    self.refused += 1
                return False

            def worker_wrapper():
                with self.lock:
                    self.current_running += 1
                    self.peak_concurrent = max(self.peak_concurrent, self.current_running)
                try:
                    work_fn()
                finally:
                    with self.lock:
                        self.current_running -= 1
                    self.sem.release()

            t = threading.Thread(target=worker_wrapper, daemon=True)
            t.start()
            return True

    return CpuThrottle(max_concurrent)

