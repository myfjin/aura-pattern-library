def memory_cap_guard(cap_mb=256):
    """Guard that refuses allocation past cap_mb threshold.
    Returns: context object with peak_bytes, refused_count, and can_allocate() method.
    """
    class MemCapGuard:
        def __init__(self, cap):
            self.cap_bytes = cap * 1024 * 1024
            self.allocated_bytes = 0
            self.peak_bytes = 0
            self.refused = 0

        def can_allocate(self, size_bytes):
            if self.allocated_bytes + size_bytes > self.cap_bytes:
                self.refused += 1
                return False
            return True

        def allocate(self, size_bytes):
            """Allocate REAL bytes (full size) so peak reflects actual RAM, not a counter."""
            if not self.can_allocate(size_bytes):
                raise MemoryError(f"Allocation refused: {size_bytes} bytes would exceed cap")
            self.allocated_bytes += size_bytes
            self.peak_bytes = max(self.peak_bytes, self.allocated_bytes)
            return bytearray(size_bytes)  # hold the REAL bytes — peak == actual RAM held

        def free(self, size_bytes):
            """Simulate deallocation."""
            self.allocated_bytes = max(0, self.allocated_bytes - size_bytes)

    return MemCapGuard(cap_mb)

