import queue
import threading

def backpressure_queue(max_size=64, timeout_sec=0.1):
    """Bounded queue that blocks or refuses when full.
    Returns: context with put_item(), get_item(), peak_depth, refused_count.
    """
    class BackpressureQ:
        def __init__(self, size, timeout):
            self.q = queue.Queue(maxsize=size)
            self.max_size = size
            self.peak_depth = 0
            self.refused = 0
            self.timeout = timeout

        def put_item(self, item):
            """Try to put item; return True if accepted, False if refused."""
            try:
                self.q.put_nowait(item)
                current_size = self.q.qsize()
                self.peak_depth = max(self.peak_depth, current_size)
                return True
            except queue.Full:
                self.refused += 1
                return False

        def get_item(self):
            """Try to get item with timeout."""
            try:
                return self.q.get(timeout=self.timeout)
            except queue.Empty:
                return None

    return BackpressureQ(max_size, timeout_sec)

