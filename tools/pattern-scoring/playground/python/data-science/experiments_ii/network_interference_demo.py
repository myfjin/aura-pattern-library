from typing import List, Set

def simulate_spillover_network(n: int, treatment: List[int], effect_direct: float, effect_spillover: float) -> List[float]:
    """Simulate outcomes with network spillover.

    A simple graph: user i connected to user i-1 and i+1 (ring).
    If neighbor is treated, spillover boost applied.
    """
    outcomes = []
    for i in range(n):
        y = effect_direct * treatment[i]  # Direct effect.

        # Spillover from neighbors.
        neighbors = [(i - 1) % n, (i + 1) % n]
        y += effect_spillover * sum(treatment[j] for j in neighbors) / len(neighbors)

        y += (i % 3) * 0.1  # Small baseline.
        outcomes.append(y)

    return outcomes

def naive_ate(treatment: List[int], outcomes: List[float]) -> float:
    """Compute naive ATE ignoring spillover."""
    y_t1 = [outcomes[i] for i in range(len(treatment)) if treatment[i] == 1]
    y_t0 = [outcomes[i] for i in range(len(treatment)) if treatment[i] == 0]
    if not y_t1 or not y_t0:
        return 0.0
    return sum(y_t1) / len(y_t1) - sum(y_t0) / len(y_t0)

