def gauss_legendre_4(f: Callable[[float], float], a: float, b: float) -> float:
    """Integrate f over [a, b] using 4-point Gauss–Legendre quadrature.

    Nodes and weights are hardcoded for [-1, 1]; linear transform to [a, b].
    Exact for polynomials up to degree 7.
    """
