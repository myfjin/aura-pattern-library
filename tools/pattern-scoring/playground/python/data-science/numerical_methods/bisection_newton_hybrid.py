def bisection_newton_hybrid(
    f: Callable[[float], float],
    df: Callable[[float], float],
    a: float,
    b: float,
    tol: float = 1e-8,
    max_iter: int = 100
) -> float:
    """Find root of f in [a, b] using hybrid bisection–Newton.

    Returns root x with |f(x)| < tol.
    Uses Newton for speed; reverts to bisection if Newton drifts outside [a, b].
    """
    if f(a) * f(b) > 0:
        raise ValueError("f(a) and f(b) must have opposite signs")

    x = (a + b) / 2.0

    for iteration in range(max_iter):
        fx = f(x)
        if abs(fx) < tol:
            return x

