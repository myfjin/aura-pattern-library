from typing import Callable

def secant_method(
    f: Callable[[float], float],
    x0: float,
    x1: float,
    tol: float = 1e-8,
    max_iter: int = 100
) -> float:
    """Find root via secant method.

    Returns root x with |f(x)| < tol.
    Needs only function values, not derivatives.
    """
    for iteration in range(max_iter):
        f0, f1 = f(x0), f(x1)

        if abs(f1) < tol:
            return x1

        denom = f1 - f0
        if abs(denom) < 1e-14:
            return x1

        x_next = x1 - f1 * (x1 - x0) / denom
        x0, x1 = x1, x_next

    return x1

