from typing import Callable

def romberg_integration(
    f: Callable[[float], float],
    a: float,
    b: float,
    n: int = 5
) -> float:
    """Integrate f over [a, b] via Romberg method.

    Returns integral estimate with O(h⁴) convergence.
    n = number of rows in Romberg table.
    """
    h = b - a
    r = [[0.0] * n for _ in range(n)]

    # First column: trapezoid rule with 2^k intervals.
    r[0][0] = h * (f(a) + f(b)) / 2.0

    for k in range(1, n):
        h /= 2.0
        sum_pts = sum(f(a + (2*i + 1) * h) for i in range(2**(k - 1)))
        r[k][0] = r[k - 1][0] / 2.0 + h * sum_pts

        # Richardson extrapolation: fill upper triangle.
        for j in range(1, k + 1):
            power = 4 ** j
            r[k][j] = (power * r[k][j - 1] - r[k - 1][j - 1]) / (power - 1.0)

    return r[n - 1][n - 1]

