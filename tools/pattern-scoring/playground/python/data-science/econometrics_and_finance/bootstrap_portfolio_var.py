import math
from typing import List, Tuple

def _quantile(sorted_vals: List[float], q: float) -> float:
    """Lower-index empirical quantile of an already-sorted list."""
    idx = int(q * len(sorted_vals))
    return sorted_vals[max(0, min(idx, len(sorted_vals) - 1))]

def portfolio_var_bootstrap(
    returns: List[float],
    confidence_level: float = 0.95,
    num_bootstrap: int = 1000,
) -> Tuple[float, float]:
    """Estimate Value-at-Risk via bootstrap.

    Returns: (var_estimate, var_se) where var_estimate is the mean bootstrap
    (1−confidence) return quantile and var_se is its bootstrap standard error.
    """
    import random
    n = len(returns)
    tail = 1.0 - confidence_level
    resample_vars = []
    for _ in range(num_bootstrap):
        sample = sorted(random.choice(returns) for _ in range(n))
        resample_vars.append(_quantile(sample, tail))

    mean_var = sum(resample_vars) / len(resample_vars)
    var_se = math.sqrt(sum((v - mean_var)**2 for v in resample_vars) / len(resample_vars))
    return mean_var, var_se

