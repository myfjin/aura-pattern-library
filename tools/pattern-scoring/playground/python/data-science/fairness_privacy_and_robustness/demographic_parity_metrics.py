import random
from typing import Tuple

def demographic_parity_metrics() -> None:
    random.seed(42)
    n = 200
    # Planted dataset: group A (0) and group B (1)
    groups = [0] * (n // 2) + [1] * (n // 2)
    labels = [random.randint(0, 1) for _ in range(n)]

    # Biased classifier: always predicts 1 for group A, random for group B
    pred_biased = [1 if g == 0 else random.randint(0, 1) for g in groups]

    # Unbiased classifier: predicts label itself
    pred_unbiased = labels[:]

    # Compute demographic parity metrics
    def dp_metrics(predictions: list[int], groups_list: list[int]) -> Tuple[float, float]:
        group_a_pred = [p for p, g in zip(predictions, groups_list) if g == 0]
        group_b_pred = [p for p, g in zip(predictions, groups_list) if g == 1]

        rate_a = sum(group_a_pred) / len(group_a_pred) if group_a_pred else 0
        rate_b = sum(group_b_pred) / len(group_b_pred) if group_b_pred else 0

        dp_diff = abs(rate_a - rate_b)
        disparate_impact = (rate_b / rate_a) if rate_a > 0 else 0
        return dp_diff, disparate_impact

    dp_b, di_b = dp_metrics(pred_biased, groups)
    dp_u, di_u = dp_metrics(pred_unbiased, groups)

    # Biased classifier should show high DP_diff and low disparate impact
    assert dp_b > 0.2, f"Biased classifier DP_diff should be > 0.2, got {dp_b}"
    assert di_b < 0.7, f"Biased classifier disparate impact should be < 0.7, got {di_b}"

    # Unbiased classifier should show low DP_diff and disparate impact near 1
    assert dp_u < 0.3, f"Unbiased classifier DP_diff should be < 0.3, got {dp_u}"
    assert 0.7 < di_u < 1.3, f"Unbiased classifier disparate impact should be near 1, got {di_u}"

    print("PASS")

if __name__ == "__main__":
    demographic_parity_metrics()
