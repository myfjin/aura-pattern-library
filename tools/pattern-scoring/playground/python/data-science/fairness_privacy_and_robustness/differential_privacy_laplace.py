import random
import math
from typing import List

def differential_privacy_laplace() -> None:
    random.seed(42)

    # True dataset: count of "positive" items
    true_count = 50
    epsilon = 1.0
    scale = 1.0 / epsilon

    # Laplace mechanism: add Laplace(0, scale) noise
    laplace_noise = random.expovariate(1.0 / scale) - random.expovariate(1.0 / scale)
    noisy_count = true_count + laplace_noise

    # Neighboring dataset: count differs by 1
    neighbor_count = true_count + 1

    # Likelihood ratio check (theoretical bound)
    # For Laplace mechanism with sensitivity 1 and scale, likelihood ratio should be <= e^eps
    # P(output | D) / P(output | D') should be bounded by e^eps
    # We verify this holds for the empirical case
    max_likelihood_ratio = math.exp(epsilon)

    # Empirical likelihood ratio (simplified: ratio of PDF at noisy_count)
    laplace_pdf_at_noise = lambda x, scale: (1 / (2 * scale)) * math.exp(-abs(x) / scale)
    pdf_d = laplace_pdf_at_noise(noisy_count - true_count, scale)
    pdf_neighbor = laplace_pdf_at_noise(noisy_count - neighbor_count, scale)

    likelihood_ratio = pdf_d / pdf_neighbor if pdf_neighbor > 1e-10 else 1000
    assert likelihood_ratio <= max_likelihood_ratio, (
        f"Likelihood ratio {likelihood_ratio} exceeds e^eps {max_likelihood_ratio}"
    )

    # Utility loss: absolute difference from true count
    utility_loss = abs(noisy_count - true_count)
    assert utility_loss < 100, f"Utility loss should be reasonable, got {utility_loss}"

    print("PASS")

