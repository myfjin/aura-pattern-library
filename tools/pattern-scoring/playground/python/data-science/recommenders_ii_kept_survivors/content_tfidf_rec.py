import math

def tfidf_similarity(doc1: list, doc2: list) -> float:
    """Cosine similarity of two documents (word counts)."""
    dot = sum(doc1[i] * doc2[i] for i in range(len(doc1)))
    norm1 = math.sqrt(sum(x**2 for x in doc1))
    norm2 = math.sqrt(sum(x**2 for x in doc2))
    return dot / (norm1 * norm2 + 1e-10)

