from typing import Iterable


def catalog_coverage(recommendations: Iterable[int], catalog_size: int) -> float:
    """Return the catalog coverage ratio for a recommendation list.

    Args:
        recommendations: Item identifiers recommended to the user.
        catalog_size:    Total number of distinct items available.

    Returns:
        Fraction of the catalog represented in the recommendations, in [0, 1].

    Guarantees:
        - Empty recommendations → coverage 0.0.
        - All catalog items recommended at least once → coverage 1.0.
        - Repeated recommendations do not inflate coverage.

    Failure scenario:
        A recommender that always returns the same few popular items yields
        low coverage, indicating poor catalog exploration.
    """
    if catalog_size <= 0:
        raise ValueError("catalog_size must be positive")
    seen = set(recommendations)
    if not seen:
        return 0.0
    # Clamp to 1.0 in case recommendations contain IDs beyond the declared catalog.
    return min(len(seen) / catalog_size, 1.0)


