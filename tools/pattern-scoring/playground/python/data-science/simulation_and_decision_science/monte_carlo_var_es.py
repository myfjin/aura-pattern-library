import random

def monte_carlo_var_es() -> None:
    random.seed(42)

    # Generate heavy-tailed returns (exponential left tail)
    n_simulations = 10000
    returns = []

    for _ in range(n_simulations):
        # Heavy-tailed: mix of normal and extreme events
        if random.random() < 0.95:
            ret = random.gauss(-0.01, 0.02)  # Normal returns
        else:
            ret = -random.expovariate(10)     # Extreme losses
        returns.append(ret)

    returns.sort()

    # Compute VaR and ES at 5% confidence level (alpha = 0.05)
    alpha = 0.05
    var_index = int(alpha * n_simulations)
    var_95 = returns[var_index]

    # ES: average of returns below VaR
    es_95 = sum(returns[:var_index]) / var_index if var_index > 0 else 0

    # VaR and ES properties
    assert var_95 < 0, f"VaR should be negative (a loss), got {var_95}"
    assert es_95 < var_95, f"ES ({es_95:.4f}) should be worse (more negative) than VaR ({var_95:.4f})"

    # ES >= VaR (in absolute terms, ES is larger loss)
    assert abs(es_95) >= abs(var_95), (
        f"ES absolute ({abs(es_95):.4f}) should be >= VaR absolute ({abs(var_95):.4f})"
    )

    # Verify empirical exceedance rate
    exceedances = sum(1 for r in returns if r < var_95)
    exceedance_rate = exceedances / n_simulations

    # Should be approximately alpha (5%)
    assert 0.03 < exceedance_rate < 0.07, (
        f"Exceedance rate {exceedance_rate:.3f} should be near alpha {alpha}"
    )

    print("PASS")

