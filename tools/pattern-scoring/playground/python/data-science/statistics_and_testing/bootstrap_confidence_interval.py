import random
import statistics
from typing import List, Tuple


def bootstrap_ci(data: List[float], n_boots: int = 10000, ci: float = 0.95) -> Tuple[float, float]:
    """
    Compute bootstrap confidence interval for the sample mean.

    Args:
        data: Observed sample.
        n_boots: Number of bootstrap resamples.
        ci: Confidence level (e.g., 0.95 for 95% CI).

    Returns:
        Tuple of (lower_bound, upper_bound).
    """
    n = len(data)
    bootstrap_means = []

    for _ in range(n_boots):
        # Resample with replacement
        boot_sample = [random.choice(data) for _ in range(n)]
        boot_mean = statistics.mean(boot_sample)
        bootstrap_means.append(boot_mean)

    # Sort to compute quantiles
    bootstrap_means.sort()

    # Compute bounds via percentile method
    alpha = 1 - ci
    lower_idx = int(alpha / 2 * n_boots)
    upper_idx = int((1 - alpha / 2) * n_boots)

    lower_bound = bootstrap_means[lower_idx]
    upper_bound = bootstrap_means[upper_idx]

    return lower_bound, upper_bound


