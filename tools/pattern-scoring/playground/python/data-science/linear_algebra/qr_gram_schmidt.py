def qr_gram_schmidt(A: list) -> Tuple[list, list]:
    """Compute QR factorization via Gram–Schmidt.

    Returns: (Q, R) where Q is orthonormal, R is upper triangular, A = Q·R.
    """
    n = len(A)
    m = len(A[0])
    Q = [[0.0] * m for _ in range(n)]
    R = [[0.0] * m for _ in range(m)]

    for j in range(m):
        # Extract column j of A.
        v = [A[i][j] for i in range(n)]

        # Orthogonalize against previous columns.
        for i in range(j):
            R[i][j] = sum(Q[k][i] * v[k] for k in range(n))
            v = [v[k] - R[i][j] * Q[k][i] for k in range(n)]

