import math
from typing import List

def crp_sample_num_tables(n: int, alpha: float) -> int:
    """Simulate CRP: n customers, α concentration.

    Returns number of occupied tables.
    """
    import random
    tables = [1]  # First customer starts table 1.

    for _ in range(1, n):
        # Probability of joining existing table i ∝ table_i_size.
        # Probability of new table ∝ α.
        total_size = sum(tables)
        new_table_prob = alpha / (alpha + total_size)

        if random.random() < new_table_prob:
            tables.append(1)  # New table.
        else:
            # Join existing table (uniformly weighted by size here, simplified).
            table_idx = int(random.random() * len(tables))
            tables[table_idx] += 1

    return len(tables)

