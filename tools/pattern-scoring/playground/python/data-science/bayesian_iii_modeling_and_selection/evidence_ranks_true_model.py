import math
from typing import List

def gaussian_bic(data: List[float]) -> float:
    """BIC of a Gaussian model at its MLE (μ, σ²); k = 2 params."""
    n = len(data)
    mu = sum(data) / n
    var = sum((d - mu) ** 2 for d in data) / n
    log_lik = sum(-0.5 * math.log(2 * math.pi * var) - 0.5 * (d - mu) ** 2 / var for d in data)
    return -2 * log_lik + 2 * math.log(n)

def exponential_bic(data: List[float]) -> float:
    """BIC of an Exponential model at its MLE rate; k = 1 param (positive data only)."""
    pos = [d for d in data if d > 0]
    n = len(pos)
    rate = n / sum(pos)
    log_lik = sum(math.log(rate) - rate * d for d in pos)
    return -2 * log_lik + 1 * math.log(n)

