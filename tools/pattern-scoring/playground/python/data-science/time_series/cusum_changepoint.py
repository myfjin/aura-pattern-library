from typing import List, Tuple


def cusum_detector(
    series: List[float], target: float, k: float, h: float
) -> Tuple[List[float], List[int]]:
    """
    Run CUSUM detector.
    target: reference mean
    k: slack parameter (drift tolerance)
    h: decision threshold
    Returns (cusum_values, changepoint_indices)
    """
    cusum = [0.0]
    changepoints = []
    for i in range(len(series)):
        new_cusum = max(0.0, cusum[-1] + (series[i] - target) - k)
        cusum.append(new_cusum)
        if new_cusum > h:
            changepoints.append(i)
            # Reset after detection
            cusum[-1] = 0.0
    return cusum[1:], changepoints  # Return without initial 0


def estimate_mean(series: List[float]) -> float:
    """Simple mean."""
    return sum(series) / len(series) if series else 0.0


