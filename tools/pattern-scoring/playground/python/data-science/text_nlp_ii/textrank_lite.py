def jaccard_similarity(sent1: List[str], sent2: List[str]) -> float:
    """Jaccard similarity between sentence word sets: |∩| / |∪|."""
    set1, set2 = set(sent1), set(sent2)
    if not set1 or not set2:
        return 0.0
    union = len(set1 | set2)
    return len(set1 & set2) / union if union > 0 else 0.0

def textrank_sentences(sentences: List[List[str]], damping: float = 0.85, iterations: int = 50) -> List[float]:
    """Rank sentences via damped power iteration on the Jaccard-similarity graph."""
    n = len(sentences)
    if n == 0:
        return []

    W = [[jaccard_similarity(sentences[i], sentences[j]) if i != j else 0.0 for j in range(n)] for i in range(n)]
    out_degree = [sum(W[j]) for j in range(n)]  # symmetric graph → row sum = "out" weight of j

    ranks = [1.0 / n] * n
    for _ in range(iterations):
        new_ranks = []
        for i in range(n):
            incoming = 0.0
            for j in range(n):
                if i != j and out_degree[j] > 0:
                    incoming += (W[j][i] / out_degree[j]) * ranks[j]
            new_ranks.append((1 - damping) / n + damping * incoming)
        ranks = new_ranks
    return ranks

