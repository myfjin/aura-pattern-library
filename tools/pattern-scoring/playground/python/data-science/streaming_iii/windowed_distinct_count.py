import random
from typing import List
from collections import deque

def windowed_distinct_count(stream: List, window_size: int) -> int:
    """
    Count distinct elements in the most recent window_size items.
    Args:
        stream: input sequence
        window_size: window length
    Returns:
        Number of distinct elements in the final window.
    """
    random.seed(42)
    assert window_size > 0

    # Truth: exact distinct count on last window_size elements
    if len(stream) < window_size:
        batch = stream
    else:
        batch = stream[-window_size:]
    true_distinct = len(set(batch))

    # Streaming: maintain window buffer
    window = deque(maxlen=window_size)
    final_distinct = 0

    for elem in stream:
        window.append(elem)
        if len(window) == window_size:
            final_distinct = len(set(window))

    # RECOVERY ASSERT: streaming distinct matches exact batch
    assert final_distinct == true_distinct, \
        f"Windowed distinct mismatch: {final_distinct} vs {true_distinct}"

    return final_distinct


