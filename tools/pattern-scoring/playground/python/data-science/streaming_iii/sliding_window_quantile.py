import random
from typing import List
from collections import deque

def sliding_window_quantile(stream: List[float], window_size: int, q: float) -> float:
    """
    Compute exact quantile q on the most recent window_size elements.
    Args:
        stream: input sequence
        window_size: size of the sliding window
        q: quantile in [0, 1]
    Returns:
        The exact q-th quantile of the most recent window_size elements.
    """
    random.seed(42)
    assert 0 <= q <= 1 and window_size > 0

    # Truth: compute exact quantile batch on the LAST window_size elements
    if len(stream) < window_size:
        batch = sorted(stream)
    else:
        batch = sorted(stream[-window_size:])

    idx = q * (len(batch) - 1)
    lower, upper = int(idx), int(idx) + 1
    if lower == upper:
        true_quantile = batch[lower]
    else:
        alpha = idx - lower
        true_quantile = batch[lower] * (1 - alpha) + batch[upper] * alpha

    # Streaming: maintain deque of last window_size elements, sort when needed
    window = deque(maxlen=window_size)
    for val in stream:
        window.append(val)

    # Compute quantile on sorted window
    sorted_window = sorted(window)
    idx = q * (len(sorted_window) - 1)
    lower, upper = int(idx), int(idx) + 1
    if lower == upper:
        measured_quantile = sorted_window[lower]
    else:
        alpha = idx - lower
        measured_quantile = sorted_window[lower] * (1 - alpha) + sorted_window[upper] * alpha

