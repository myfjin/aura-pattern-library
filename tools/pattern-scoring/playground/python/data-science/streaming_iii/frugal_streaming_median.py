import random
from typing import List


def frugal_streaming_median(stream: List[float], step: float = 1.0) -> float:
    """
    Estimate the median with a single integer of state (Frugal-1, q=0.5).
    Args:
        stream: input sequence
        step: increment size (data scale)
    Returns:
        Estimated median after the whole stream.
    """
    q = 0.5
    m = 0.0  # start FAR from the answer -- the estimator must walk to the median itself
    for x in stream:
        r = random.random()
        if x > m and r > 1 - q:
            m += step
        elif x < m and r > q:
            m -= step
    return m


