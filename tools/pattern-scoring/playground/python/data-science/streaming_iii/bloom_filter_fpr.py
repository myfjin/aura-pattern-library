import hashlib
import random
from typing import Set

def bloom_filter_fpr(stream: list, size: int = 1000, k: int = 3) -> float:
    """
    Bloom filter membership test; return measured false-positive rate.
    Args:
        stream: items to insert (no duplicates assumed)
        size: size of bit array
        k: number of hash functions
    Returns:
        Measured false-positive rate on items not in filter.
    """
    random.seed(42)
    assert size > 0 and k > 0

    # Initialize bit array
    bits = [False] * size

    # Insert stream items
    inserted = set(stream)
    for item in stream:
        for i in range(k):
            h = int(hashlib.md5(f"{item}_{i}".encode()).hexdigest(), 16) % size
            bits[h] = True

    # Test: query items not in stream for false positives
    test_items = [random.randint(100000, 200000) for _ in range(1000)]
    test_items = [str(x) for x in test_items if x not in inserted]

    false_positives = 0
    for test_item in test_items:
        test_passes = all(
            bits[int(hashlib.md5(f"{test_item}_{i}".encode()).hexdigest(), 16) % size]
            for i in range(k)
        )
        if test_passes:
            false_positives += 1

    measured_fpr = false_positives / max(1, len(test_items))

    # Theoretical FPR: (1 - e^(-k*n/m))^k
    n = len(inserted)
    m = size
    import math
    theoretical_fpr = (1 - math.exp(-k * n / m)) ** k

    # RECOVERY ASSERT: measured FPR <= theoretical AND zero false negatives
    # Test for false negatives: all inserted items should pass membership test
    false_negatives = 0
    for item in list(inserted)[:min(100, len(inserted))]:
        query_passes = all(
            bits[int(hashlib.md5(f"{item}_{i}".encode()).hexdigest(), 16) % size]
            for i in range(k)
        )
        if not query_passes:
            false_negatives += 1

    assert false_negatives == 0, f"Bloom filter has {false_negatives} false negatives"
    assert measured_fpr <= theoretical_fpr + 0.05, \
        f"Measured FPR {measured_fpr:.3f} exceeds theoretical {theoretical_fpr:.3f}"

    return measured_fpr


