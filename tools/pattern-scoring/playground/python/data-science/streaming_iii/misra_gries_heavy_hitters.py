from typing import Dict, Tuple


def misra_gries_heavy_hitters(stream: list, k: int) -> Dict:
    """
    Misra-Gries. Returns the surviving {item: counter} map (approximate counts).
    Args:
        stream: input sequence
        k: number of counters + 1 (threshold ~ n/k)
    """
    assert k > 1
    counters: Dict = {}
    for item in stream:
        if item in counters:
            counters[item] += 1
        elif len(counters) < k - 1:
            counters[item] = 1
        else:
            for c in list(counters.keys()):
                counters[c] -= 1
                if counters[c] == 0:
                    del counters[c]
    return counters


