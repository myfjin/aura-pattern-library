use std::sync::{Arc, Condvar, Mutex};
use std::thread;

struct WaitGroup {
    count: Mutex<usize>,
    cond: Condvar,
}

impl WaitGroup {
    fn new() -> Self {
        WaitGroup {
            count: Mutex::new(0),
            cond: Condvar::new(),
        }
    }

    fn add(&self, n: usize) {
        let mut c = self.count.lock().expect("lock poisoned");
        *c += n;
    }

    fn done(&self) {
        let mut c = self.count.lock().expect("lock poisoned");
        if *c > 0 {
            *c -= 1;
            if *c == 0 {
                self.cond.notify_all();
            }
        }
    }

    fn wait(&self) {
        let mut c = self.count.lock().expect("lock poisoned");
        while *c > 0 {
            c = self.cond.wait(c).expect("wait failed");
        }
    }
}

