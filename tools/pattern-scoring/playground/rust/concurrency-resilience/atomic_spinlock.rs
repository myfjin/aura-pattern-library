use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::Arc;
use std::thread;

struct SpinLock {
    locked: AtomicBool,
}

impl SpinLock {
    fn new() -> Self {
        SpinLock { locked: AtomicBool::new(false) }
    }

    fn acquire(&self) {
        loop {
            match self.locked.compare_exchange(false, true, Ordering::Acquire, Ordering::Relaxed) {
                Ok(_) => break,
                Err(_) => std::hint::spin_loop(),
            }
        }
    }

    fn release(&self) {
        self.locked.store(false, Ordering::Release);
    }
}

struct GuardedCounter {
    lock: SpinLock,
    value: AtomicU64,
}

impl GuardedCounter {
    fn new() -> Self {
        GuardedCounter {
            lock: SpinLock::new(),
            value: AtomicU64::new(0),
        }
    }

    fn incr(&self) {
        self.lock.acquire();
        let v = self.value.load(Ordering::Relaxed);
        self.value.store(v + 1, Ordering::Relaxed);
        self.lock.release();
    }

    fn load(&self) -> u64 {
        self.lock.acquire();
        let v = self.value.load(Ordering::Relaxed);
        self.lock.release();
        v
    }
}

fn main() {
    let n_threads = 8;
    let increments_per_thread: u64 = 1000;
    let counter = Arc::new(GuardedCounter::new());

    let mut handles = Vec::new();
    for _ in 0..n_threads {
        let c = Arc::clone(&counter);
        handles.push(thread::spawn(move || {
            for _ in 0..increments_per_thread {
                c.incr();
            }
        }));
    }

    for h in handles {
        h.join().expect("thread panicked");
    }

    let final_count = counter.load();
    let expected = n_threads as u64 * increments_per_thread;

    assert_eq!(final_count, expected, "spinlock lost updates under contention");

    println!("atomic_spinlock: {} threads × {} incr, final count {} — PASS", n_threads, increments_per_thread, final_count);
}
