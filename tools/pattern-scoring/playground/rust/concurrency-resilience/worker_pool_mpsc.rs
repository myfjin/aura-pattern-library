use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::mpsc::{channel, Receiver};
use std::sync::{Arc, Mutex};
use std::thread;

fn run_pool(n_workers: usize, jobs: Vec<u64>) -> (u64, u64) {
    let (tx, rx) = channel::<u64>();
    for j in &jobs {
        tx.send(*j).expect("send failed");
    }
    drop(tx); // closing the only sender lets workers observe the drain

    let rx = Arc::new(Mutex::new(rx));
    let sum = Arc::new(AtomicU64::new(0));
    let done = Arc::new(AtomicU64::new(0));

    let mut handles = Vec::new();
    for _ in 0..n_workers {
        let rx: Arc<Mutex<Receiver<u64>>> = Arc::clone(&rx);
        let sum = Arc::clone(&sum);
        let done = Arc::clone(&done);
        handles.push(thread::spawn(move || loop {
            // Pull one job under the lock, then release it before "working".
            let job = {
                let guard = rx.lock().expect("receiver poisoned");
                guard.recv()
            };
            match job {
                Ok(v) => {
                    sum.fetch_add(v * v, Ordering::Relaxed); // the "work": square it
                    done.fetch_add(1, Ordering::Relaxed);
                }
                Err(_) => break, // channel drained and closed
            }
        }));
    }
    for h in handles {
        h.join().expect("worker panicked");
    }
    (sum.load(Ordering::Relaxed), done.load(Ordering::Relaxed))
}

fn main() {
    // Planted jobs 1..=100; the work squares each → a known sum of squares.
    let jobs: Vec<u64> = (1..=100).collect();
    let expected_sum: u64 = jobs.iter().map(|v| v * v).sum();
    let n_jobs = jobs.len() as u64;

    let (sum, done) = run_pool(4, jobs);

    // THE ONE LAW: every job ran exactly once (count exact) and the sum is exact,
    // regardless of which worker took which job or in what order.
    assert_eq!(done, n_jobs, "job count wrong: dropped or double-ran jobs");
    assert_eq!(sum, expected_sum, "result sum wrong under parallel execution");

    println!("worker_pool_mpsc: {n_jobs} jobs across 4 workers, sum-of-squares {sum} — PASS");
}
