use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::thread;

struct RefCounted {
    count: AtomicU64,
}

impl RefCounted {
    fn new() -> Self {
        RefCounted { count: AtomicU64::new(1) }
    }

    fn clone_ref(&self) -> u64 {
        let old = self.count.fetch_add(1, Ordering::Relaxed);
        old + 1
    }

    fn drop_ref(&self) -> u64 {
        let old = self.count.fetch_sub(1, Ordering::Release);
        old - 1
    }

    fn count(&self) -> u64 {
        self.count.load(Ordering::Acquire)
    }
}

fn main() {
    let n_threads = 8;
    let ops_per_thread = 500;
    let rc = Arc::new(RefCounted::new()); // baseline count = 1

    let mut handles = Vec::new();

    // Each thread does K *balanced* clone/drop pairs. Net effect on the count is zero,
    // but only if every atomic op is accounted for. A lost update lands off baseline.
    for _ in 0..n_threads {
        let r = Arc::clone(&rc);
        handles.push(thread::spawn(move || {
            for _ in 0..ops_per_thread {
                let after_clone = r.clone_ref();
                assert!(after_clone >= 2, "clone must lift count to >= 2, saw {after_clone}");
                r.drop_ref();
            }
        }));
    }

    for h in handles {
        h.join().expect("thread panicked");
    }

    // Balanced ops ⇒ count is back to the baseline of exactly 1 (not merely > 0).
    let baseline = rc.count();
    assert_eq!(baseline, 1, "atomic refcount drifted off baseline: {baseline} (lost updates)");

    // Now release the baseline reference: the count must reach exactly 0.
    let last = rc.drop_ref();
    assert_eq!(last, 0, "final drop of baseline must reach 0, saw {last}");

    println!("atomic_refcount: {n_threads} threads × {ops_per_thread} balanced pairs, baseline exact, final count 0 — PASS");
}
