#[derive(Debug, PartialEq)]
enum FieldType {
    Int,
    Float,
    String,
}

fn infer_type(s: &str) -> FieldType {
    if s.parse::<i64>().is_ok() {
        FieldType::Int
    } else if s.parse::<f64>().is_ok() {
        FieldType::Float
    } else {
        FieldType::String
    }
}

fn parse_csv_line(line: &str) -> Vec<String> {
    let mut fields = Vec::new();
    let mut current = String::new();
    let mut in_quotes = false;
    let mut chars = line.chars().peekable();

    while let Some(ch) = chars.next() {
        match ch {
            '"' => {
                if in_quotes && chars.peek() == Some(&'"') {
                    // Escaped quote.
                    current.push('"');
                    chars.next();
                } else {
                    in_quotes = !in_quotes;
                }
            }
            ',' if !in_quotes => {
                fields.push(current.trim().to_string());
                current = String::new();
            }
            _ => current.push(ch),
        }
    }
    fields.push(current.trim().to_string());

    fields
}

fn main() {
    let csv_data = r#"Name,Age,Score,Description
Alice,30,95.5,"She scored well"
Bob,25,87,"He did okay"
"Smith, John",45,92.0,"Name has comma, quoted"
Charlie,28,91,"Regular string"
"#;

    let mut rows = Vec::new();
    let mut col_types: Vec<Vec<FieldType>> = (0..4).map(|_| Vec::new()).collect();

    for (line_idx, line) in csv_data.lines().enumerate() {
        if line_idx == 0 {
            continue; // Skip header.
        }
        let fields = parse_csv_line(line);
        rows.push(fields.clone());

        // Infer types for each column.
        for (col_idx, field) in fields.iter().enumerate() {
            if col_idx < col_types.len() {
                col_types[col_idx].push(infer_type(field));
            }
        }
    }

    // THE ONE LAW: exact row count and field count.
    assert_eq!(rows.len(), 4, "row count mismatch");
    for row in &rows {
        assert_eq!(row.len(), 4, "field count mismatch");
    }

    // Verify specific values.
    assert_eq!(rows[0][0], "Alice");
    assert_eq!(rows[0][1], "30");
    assert_eq!(rows[0][2], "95.5");
    assert_eq!(rows[0][3], "She scored well");

    // Quoted field with comma inside.
    assert_eq!(rows[2][0], "Smith, John", "quoted field with comma failed");
    assert_eq!(rows[2][1], "45");

    // Type inference.
    assert_eq!(infer_type("42"), FieldType::Int);
    assert_eq!(infer_type("3.14"), FieldType::Float);
    assert_eq!(infer_type("hello"), FieldType::String);

    println!("csv_reader_typed: {} rows parsed, quoted fields exact — PASS", rows.len());
}
