type CrashLoopDetector struct {
	threshold         int
	window            time.Duration
	restartTimes      []time.Time
	crashLoopDetected bool
}

func newCrashLoopDetector(restartThreshold int, windowSeconds float64) *CrashLoopDetector {
	return &CrashLoopDetector{
		threshold:    restartThreshold,
		window:       time.Duration(windowSeconds * float64(time.Second)),
		restartTimes: []time.Time{},
	}
}

func (d *CrashLoopDetector) recordRestart() {
	now := time.Now()
	windowStart := now.Add(-d.window)
	kept := d.restartTimes[:0]
	for _, t := range d.restartTimes {
		if t.After(windowStart) {
			kept = append(kept, t)
		}
	}
	d.restartTimes = kept
	d.restartTimes = append(d.restartTimes, now)

	if len(d.restartTimes) > d.threshold {
		d.crashLoopDetected = true
	}
}

func (d *CrashLoopDetector) shouldRestart() bool {
	return !d.crashLoopDetected
}

