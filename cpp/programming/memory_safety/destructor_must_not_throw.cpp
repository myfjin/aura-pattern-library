static const char* EXPECTED = "terminate called";

// PORTABLE SIGNATURE: "terminate called ..." is libstdc++'s wording. libc++ (macOS, and any
// clang/libc++ build) prints "libc++abi: terminating due to ..." instead, so the named
// signature never appears and the pattern reports a false negative on half the toolchains.
// A std::terminate handler is the standard, portable hook: it runs at the EVENT -- the
// runtime has already decided to terminate -- prints the signature itself, and then aborts
// because a terminate handler must not return. The real termination still happens, so the
// platform's own message (and ASan) corroborate wherever they are emitted.
static void report_terminate() {
    fprintf(stderr, "%s: the runtime terminated the process\n", EXPECTED);
    fflush(stderr);
    std::abort();
}
