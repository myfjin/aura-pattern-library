static const char* EXPECTED = "stack-buffer-overflow";

// PORTABLE LEDGER: the real capacity is recorded AT THE ALLOCATION, and the index about to be
// touched is compared against it BEFORE the access -- both observed independently of the value
// under test. The out-of-bounds access still happens, so ASan corroborates on Linux; with no
// sanitizer (macOS/arm64, or the library's own -O2 harness) this comparison IS the oracle.
// It must report BEFORE the access: without a sanitizer the process may die on the access.
static bool g_oob = false;
static void note_oob(long idx, long cap) {
    if (idx >= cap) {
        g_oob = true;
        fprintf(stderr, "%s: index %ld touched in an allocation holding %ld element(s)\n",
                EXPECTED, idx, cap);
    }
}
static const long BUF_N = 8;
static const long EXPECT_SUM = 36;

// Separate function: compiler cannot see the array bound, so ASan catches it
static void fill(int* p, int n) {
    for (int i = 0; i < n; ++i) p[i] = i + 1;
}

// Safe version: takes the capacity and bounds itself
static int fill_safe(int* p, int n, int cap) {
    int written = std::min(n, cap);
    for (int i = 0; i < written; ++i) p[i] = i + 1;
    return written;
}

static int unsafe_arm() {
    g_oob = false;
    int buf[BUF_N];
    note_oob(11, (long)BUF_N);   // element 11 of an 8-element buffer
    fill(buf, 12);   // writes 12 elements into an 8-element buffer
    if (!g_oob)
        fprintf(stderr, "unsafe arm stayed in bounds - the disaster did not happen\n");
    return g_oob ? 1 : 0;
}

static int safe_arm() {
    int buf[BUF_N] = {};
    int written = fill_safe(buf, 12, BUF_N);
    if (written != BUF_N) { fprintf(stderr, "FAIL: written %d != %ld\n", written, BUF_N); return 1; }
    long sum = 0;
    for (int i = 0; i < BUF_N; ++i) sum += buf[i];
    if (sum != EXPECT_SUM) { fprintf(stderr, "FAIL: sum %ld != %ld\n", sum, EXPECT_SUM); return 1; }
    if (buf[BUF_N - 1] != 8) { fprintf(stderr, "FAIL: buf[7] %d != 8\n", buf[BUF_N - 1]); return 1; }
    return 0;
}

