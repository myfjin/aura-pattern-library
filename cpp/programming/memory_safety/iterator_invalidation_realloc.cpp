// PORTABLE LIVENESS LEDGER: a tracking allocator that counts deallocations.
// When the vector reallocates, the old buffer is deallocated — the counter is an
// independent witness that the original buffer was freed. The ledger is written
// AT THE EVENT (in deallocate), never derived from the value under test.
static int g_dealloc_count = 0;

template <typename T>
struct TrackAlloc {
    using value_type = T;
    template <typename U>
    struct rebind { using other = TrackAlloc<U>; };
    T* allocate(size_t n) {
        return static_cast<T*>(::operator new(n * sizeof(T)));
    }
    void deallocate(T* p, size_t) {
        ++g_dealloc_count;
        ::operator delete(p);
    }
    bool operator==(const TrackAlloc<T>&) const { return true; }
};

