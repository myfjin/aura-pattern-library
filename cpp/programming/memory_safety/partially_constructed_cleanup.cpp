static int g_allocs = 0;
static int g_frees  = 0;
static const long EXPECT_SUM = 496;
static const long EXPECT_N = 32;

struct HalfUnsafe {
    int* a;
    int* b;
    HalfUnsafe() : a(new int[EXPECT_N]), b(nullptr) {
        ++g_allocs;
        for (int i = 0; i < EXPECT_N; ++i) a[i] = i;
        throw std::runtime_error("ctor failed after first alloc");
    }
    ~HalfUnsafe() { ++g_frees; delete[] a; delete[] b; }   // never runs: object never fully constructed
};

struct HalfSafe {
    std::unique_ptr<int[]> a;
    std::unique_ptr<int[]> b;
    HalfSafe() : a(std::make_unique<int[]>(EXPECT_N)), b(nullptr) {
        for (int i = 0; i < EXPECT_N; ++i) a[i] = i;
        throw std::runtime_error("ctor failed after first alloc");
    }
};

