struct PFStepResult {
    std::vector<double> particles;
    std::vector<double> weights;
    double ess;
};

PFStepResult particle_filter_step(const std::vector<double>& particles,
                                  const std::vector<double>& weights,
                                  double observation,
                                  LCG& rng,
                                  double process_noise = 0.2,
                                  double obs_noise = 0.5) {
    std::size_t n = particles.size();

    std::vector<double> predicted;
    predicted.reserve(n);
    for (double p : particles) predicted.push_back(p + rng.gauss() * process_noise);

    std::vector<double> log_likelihoods;
    log_likelihoods.reserve(n);
    double max_ll = -1e300;
    for (double x : predicted) {
        double ll = -0.5 * std::pow((observation - x) / obs_noise, 2);
        log_likelihoods.push_back(ll);
        if (ll > max_ll) max_ll = ll;
    }

    std::vector<double> likelihoods;
    likelihoods.reserve(n);
    for (double ll : log_likelihoods) likelihoods.push_back(std::exp(ll - max_ll));

    double denom = 0.0;
    for (std::size_t i = 0; i < n; ++i) denom += weights[i] * likelihoods[i];
    if (denom < 1e-10) denom = 1e-10;

    std::vector<double> new_weights;
    new_weights.reserve(n);
    for (std::size_t i = 0; i < n; ++i) {
        new_weights.push_back(weights[i] * likelihoods[i] / denom);
    }

    double total_weight = 0.0;
    for (double w : new_weights) total_weight += w;
    if (total_weight > 0.0) {
        for (double& w : new_weights) w /= total_weight;
    } else {
        for (double& w : new_weights) w = 1.0 / static_cast<double>(n);
    }

    double ess = 1.0 / std::max(std::inner_product(new_weights.begin(), new_weights.end(),
                                                    new_weights.begin(), 0.0),
                                1e-10);

    if (ess < static_cast<double>(n) / 2.0) {
        // Multinomial resampling via cumulative weights
        std::vector<double> cumsum;
        cumsum.reserve(n);
        double acc = 0.0;
        for (double w : new_weights) {
            acc += w;
            cumsum.push_back(acc);
        }
        std::vector<double> resampled;
        resampled.reserve(n);
        for (std::size_t i = 0; i < n; ++i) {
            double u = rng.next();
            auto it = std::lower_bound(cumsum.begin(), cumsum.end(), u);
            std::size_t idx = static_cast<std::size_t>(std::distance(cumsum.begin(), it));
            if (idx >= n) idx = n - 1;
            resampled.push_back(predicted[idx]);
        }
        predicted = std::move(resampled);
        for (double& w : new_weights) w = 1.0 / static_cast<double>(n);
    }

    return {predicted, new_weights, ess};
}

