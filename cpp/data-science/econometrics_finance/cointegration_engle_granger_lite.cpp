/*
 * Engle-Granger Cointegration Test
 * 
 * Two I(1) series are cointegrated if their linear combination is I(0) (stationary).
 * Test: (1) regress y on x by OLS; (2) test residuals for unit root (Dickey-Fuller).
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <utility>

std::vector<double> ols_residuals(const std::vector<double>& y, const std::vector<double>& x) {
    /* Residuals of the OLS regression y = a + b*x. */
    int n = static_cast<int>(y.size());
    double mean_x = 0.0, mean_y = 0.0;
    for (int i = 0; i < n; ++i) {
        mean_x += x[i];
        mean_y += y[i];
    }
    mean_x /= n;
    mean_y /= n;

    double cov = 0.0, var_x = 0.0;
    for (int i = 0; i < n; ++i) {
        cov += (x[i] - mean_x) * (y[i] - mean_y);
        var_x += (x[i] - mean_x) * (x[i] - mean_x);
    }
    cov /= n;
    var_x /= n;

    double beta = (var_x > 1e-14) ? cov / var_x : 0.0;
    double alpha = mean_y - beta * mean_x;

    std::vector<double> residuals(n);
    for (int i = 0; i < n; ++i) {
        residuals[i] = y[i] - (alpha + beta * x[i]);
    }
    return residuals;
}

double adf_tstat(const std::vector<double>& e) {
    /* Dickey-Fuller t-statistic on residuals: regress Δe_t on e_{t-1}. */
    int m = static_cast<int>(e.size()) - 1;
    std::vector<double> lag(m), dif(m);
    for (int t = 0; t < m; ++t) {
        lag[t] = e[t];
        dif[t] = e[t + 1] - e[t];
    }

    double sxx = 0.0;
    for (double v : lag) sxx += v * v;
    if (sxx < 1e-14) return 0.0;

    double gamma = 0.0;
    for (int i = 0; i < m; ++i) {
        gamma += lag[i] * dif[i];
    }
    gamma /= sxx;

    double ssr = 0.0;
    for (int i = 0; i < m; ++i) {
        double u = dif[i] - gamma * lag[i];
        ssr += u * u;
    }
    double s2 = (m > 1) ? ssr / (m - 1) : 0.0;
    double se = (s2 > 0.0) ? std::sqrt(s2 / sxx) : 1e-14;

    return gamma / se;
}

// Engle-Granger asymptotic 5% critical value ≈ -3.34. This lite demo uses -4.5.
const double COINT_ADF_THRESHOLD = -4.5;

std::pair<double, bool> engle_granger_test(const std::vector<double>& y, const std::vector<double>& x) {
    /* Engle-Granger cointegration test. Returns (adf_tstat, is_cointegrated). */
    auto residuals = ols_residuals(y, x);
    double adf_t = adf_tstat(residuals);
    return {adf_t, adf_t < COINT_ADF_THRESHOLD};
}

