/*
 * Black-Scholes Monte Carlo: European Option Pricing via Simulation
 * 
 * True closed-form price vs MC estimate. Core claim: MC price within CI of
 * closed-form; as simulations increase, confidence tightens.
 */

#include <cmath>
#include <random>
#include <vector>
#include <cassert>
#include <iostream>
#include <utility>

double norm_cdf(double x) {
    /* Normal CDF approximation using error function. */
    return 0.5 * (1.0 + std::erf(x / std::sqrt(2.0)));
}

double black_scholes_call(double S, double K, double T, double r, double sigma) {
    /* Closed-form Black-Scholes call option price. */
    double d1 = (std::log(S / K) + (r + 0.5 * sigma * sigma) * T) / (sigma * std::sqrt(T));
    double d2 = d1 - sigma * std::sqrt(T);

    return S * norm_cdf(d1) - K * std::exp(-r * T) * norm_cdf(d2);
}

std::pair<double, double> monte_carlo_call(
    double S, double K, double T, double r, double sigma, int num_sim
) {
    /* Monte Carlo call price and standard error. */
    std::mt19937 rng(42);
    std::normal_distribution<double> normal(0.0, 1.0);

    std::vector<double> payoffs;
    payoffs.reserve(num_sim);

    for (int i = 0; i < num_sim; ++i) {
        double z = normal(rng);
        double S_T = S * std::exp((r - 0.5 * sigma * sigma) * T + sigma * std::sqrt(T) * z);
        double payoff = std::max(S_T - K, 0.0);
        payoffs.push_back(payoff);
    }

    double sum = 0.0;
    for (double p : payoffs) sum += p;
    double price = std::exp(-r * T) * sum / num_sim;

    // Compute variance
    double var_sum = 0.0;
    for (double p : payoffs) {
        double diff = p - price * std::exp(r * T);
        var_sum += diff * diff;
    }
    double variance = var_sum / num_sim;
    double se = std::sqrt(variance / num_sim) * std::exp(-r * T);

    return {price, se};
}

int main() {
    // Planted option parameters.
    const double S0 = 100.0;
    const double K = 100.0;
    const double T = 1.0;
    const double r = 0.05;
    const double sigma = 0.2;

    double call_bs = black_scholes_call(S0, K, T, r, sigma);
    auto [call_mc, mc_se] = monte_carlo_call(S0, K, T, r, sigma, 10000);

    // Check: MC price within ~2 SE of BS price.
    assert(std::abs(call_mc - call_bs) < 3.0 * mc_se);
    assert(call_bs > 0.0 && call_mc > 0.0);

    std::cout << "black_scholes_monte_carlo.cpp PASS" << std::endl;
    return 0;
}
