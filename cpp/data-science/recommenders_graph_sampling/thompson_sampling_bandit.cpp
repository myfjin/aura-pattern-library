// Thompson sampling for multi-armed bandits.

static uint64_t rng_state = 0x123456789abcdef0ULL;
static double uniform01() {
    rng_state = rng_state * 6364136223846793005ULL + 1442695040888963407ULL;
    return ((rng_state >> 11) & 0x1FFFFFFFFFFFFFULL) / 9007199254740992.0;
}
static double gauss(double mean, double std) {
    double u1 = uniform01(), u2 = uniform01();
    while (u1 == 0.0) u1 = uniform01();
    double mag = std * sqrt(-2.0 * log(u1));
    return mean + mag * cos(2.0 * M_PI * u2);
}
static double sample_beta_approx(double alpha, double beta) {
    double x = gauss(alpha / (alpha + beta), 0.1);
    return max(0.0, min(1.0, x));
}

struct BanditResult {
    double cumulative_reward;
    vector<int> pulls_per_arm;
    vector<double> alpha_final;
    vector<double> beta_final;
};

BanditResult thompson_sampling_bandit(int num_arms, int num_rounds, const vector<double>& true_probs) {
    vector<double> alpha(num_arms, 1.0), beta(num_arms, 1.0);
    double cumulative_reward = 0.0;
    vector<int> pulls(num_arms, 0);
    for (int r=0;r<num_rounds;++r) {
        vector<double> samples(num_arms);
        for (int i=0;i<num_arms;++i) samples[i] = sample_beta_approx(alpha[i], beta[i]);
        int arm = max_element(samples.begin(), samples.end()) - samples.begin();
        pulls[arm]++;
        double reward = (uniform01() < true_probs[arm]) ? 1.0 : 0.0;
        cumulative_reward += reward;
        if (reward == 1.0) alpha[arm] += 1.0; else beta[arm] += 1.0;
    }
    return {cumulative_reward, pulls, alpha, beta};
}

