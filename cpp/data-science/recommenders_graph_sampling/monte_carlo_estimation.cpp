/*
 * Monte Carlo estimation: pi and definite integrals.
 *
 * Oracle asserts:
 *   error_10000 < error_1000
 *   error_int_10000 < error_int_1000
 *   abs(pi_estimate_10000 - pi) < 0.1
 *   abs(integral_10000 - 1/3) < 0.05
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <functional>

class MonteCarlo {
public:
    MonteCarlo(int seed = 42) : rng_(seed) {}

    double estimate_pi(int num_samples) {
        std::uniform_real_distribution<double> dist(0.0, 1.0);
        int inside = 0;
        for (int i = 0; i < num_samples; ++i) {
            double x = dist(rng_), y = dist(rng_);
            if (x * x + y * y <= 1.0) ++inside;
        }
        return 4.0 * inside / num_samples;
    }

    double estimate_integral(std::function<double(double)> func, double a, double b, int num_samples) {
        std::uniform_real_distribution<double> dist(a, b);
        double total = 0.0;
        for (int i = 0; i < num_samples; ++i) total += func(dist(rng_));
        return (b - a) * total / num_samples;
    }

private:
    std::mt19937_64 rng_;
};

int main() {
    MonteCarlo mc(42);

    double pi_1000 = mc.estimate_pi(1000);
    double pi_10000 = mc.estimate_pi(10000);
    double error_1000 = std::abs(pi_1000 - M_PI);
    double error_10000 = std::abs(pi_10000 - M_PI);
    assert(error_10000 < error_1000);

    auto quadratic = [](double x) { return x * x; };
    double int_1000 = mc.estimate_integral(quadratic, 0.0, 1.0, 1000);
    double int_10000 = mc.estimate_integral(quadratic, 0.0, 1.0, 10000);
    double error_int_1000 = std::abs(int_1000 - 1.0 / 3.0);
    double error_int_10000 = std::abs(int_10000 - 1.0 / 3.0);
    assert(error_int_10000 < error_int_1000);

    assert(std::abs(pi_10000 - M_PI) < 0.1);
    assert(std::abs(int_10000 - 1.0 / 3.0) < 0.05);

    std::cout << "monte_carlo_estimation.cpp PASS" << std::endl;
    return 0;
}
