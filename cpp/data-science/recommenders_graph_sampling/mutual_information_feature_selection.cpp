double entropy(const std::vector<int>& values) {
    std::map<int, int> counts;
    for (int v : values) ++counts[v];
    double h = 0.0;
    int n = static_cast<int>(values.size());
    for (const auto& kv : counts) {
        double p = kv.second / static_cast<double>(n);
        h -= p * std::log2(p);
    }
    return h;
}

double mutual_information(const std::vector<int>& feature, const std::vector<int>& label) {
    double h_label = entropy(label);
    std::set<int> fvals(feature.begin(), feature.end());
    double h_label_given = 0.0;
    int n = static_cast<int>(label.size());
    for (int fval : fvals) {
        std::vector<int> subset;
        for (size_t i = 0; i < feature.size(); ++i) if (feature[i] == fval) subset.push_back(label[i]);
        if (!subset.empty()) {
            double p_x = subset.size() / static_cast<double>(n);
            h_label_given += p_x * entropy(subset);
        }
    }
    return std::max(0.0, h_label - h_label_given);
}

