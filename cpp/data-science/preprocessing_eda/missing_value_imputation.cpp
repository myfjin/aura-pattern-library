#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <optional>
#include <algorithm>

class MissingValueImputer {
public:
    explicit MissingValueImputer(const std::string& strategy) : strategy_(strategy) {}

    double fit(const std::vector<std::optional<double>>& data) {
        std::vector<double> present;
        for (const auto& x : data) if (x.has_value()) present.push_back(x.value());
        if (present.empty()) return 0.0;
        if (strategy_ == "mean") fill_value_ = mean(present);
        else if (strategy_ == "median") fill_value_ = median(present);
        return fill_value_;
    }

    std::pair<std::vector<double>, std::vector<int>> transform(
        const std::vector<std::optional<double>>& data) const {
        std::vector<double> imputed;
        std::vector<int> indicators;
        for (const auto& x : data) {
            if (x.has_value()) {
                imputed.push_back(x.value());
                indicators.push_back(0);
            } else {
                imputed.push_back(fill_value_);
                indicators.push_back(1);
            }
        }
        return {imputed, indicators};
    }

private:
    std::string strategy_;
    double fill_value_ = 0.0;

    static double mean(const std::vector<double>& v) {
        double s = 0.0;
        for (double x : v) s += x;
        return s / v.size();
    }

    static double median(std::vector<double> v) {
        std::sort(v.begin(), v.end());
        if (v.size() % 2 == 1) return v[v.size() / 2];
        return (v[v.size() / 2 - 1] + v[v.size() / 2]) / 2.0;
    }
};

