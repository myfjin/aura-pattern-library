using std::vector;

static double pearson_correlation(const vector<double>& x, const vector<double>& y) {
    size_t n = x.size();
    if (n != y.size()) throw std::invalid_argument("Length mismatch");
    if (n < 2) throw std::invalid_argument("Need at least 2 points");

    double mx = 0.0, my = 0.0;
    for (size_t i = 0; i < n; ++i) { mx += x[i]; my += y[i]; }
    mx /= n; my /= n;

    double cov = 0.0, vx = 0.0, vy = 0.0;
    for (size_t i = 0; i < n; ++i) {
        double dx = x[i] - mx;
        double dy = y[i] - my;
        cov += dx * dy;
        vx += dx * dx;
        vy += dy * dy;
    }
    double denom = std::sqrt(vx * vy);
    if (denom == 0.0) return 0.0;
    return cov / denom;
}

static vector<vector<double>> correlation_matrix(const vector<vector<double>>& data) {
    size_t k = data.size();
    if (k == 0) return {};
    size_t n = data[0].size();
    for (const auto& col : data)
        if (col.size() != n) throw std::invalid_argument("Columns must have same length");

    vector<vector<double>> C(k, vector<double>(k, 0.0));
    for (size_t i = 0; i < k; ++i)
        for (size_t j = 0; j < k; ++j)
            C[i][j] = pearson_correlation(data[i], data[j]);
    return C;
}

