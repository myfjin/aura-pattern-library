using VecD = std::vector<double>;
using VecI = std::vector<int>;

static VecI quantile_binning(const VecD& data, int n_bins) {
    std::size_t n = data.size();
    std::vector<std::pair<std::size_t, double>> indexed;
    for (std::size_t i = 0; i < n; ++i) indexed.emplace_back(i, data[i]);
    std::sort(indexed.begin(), indexed.end(),
              [](const auto& a, const auto& b) { return a.second < b.second; });

    double bin_size = static_cast<double>(n) / n_bins;
    VecD edges;
    for (int i = 1; i < n_bins; ++i) {
        std::size_t idx = static_cast<std::size_t>(std::min(static_cast<double>(i) * bin_size,
                                                        static_cast<double>(n - 1)));
        edges.push_back(indexed[idx].second);
    }

    VecI result(n, 0);
    for (const auto& p : indexed) {
        int bin_num = 0;
        for (double edge : edges) {
            if (p.second >= edge) ++bin_num;
        }
        result[p.first] = bin_num;
    }
    return result;
}

static VecI equal_width_binning(const VecD& data, int n_bins) {
    double min_val = *std::min_element(data.begin(), data.end());
    double max_val = *std::max_element(data.begin(), data.end());
    double bin_width = (max_val - min_val) / n_bins;
    VecI result;
    result.reserve(data.size());
    for (double x : data) {
        int bin_num;
        if (x == max_val) {
            bin_num = n_bins - 1;
        } else {
            bin_num = static_cast<int>((x - min_val) / bin_width);
            if (bin_num >= n_bins) bin_num = n_bins - 1;
        }
        result.push_back(bin_num);
    }
    return result;
}

