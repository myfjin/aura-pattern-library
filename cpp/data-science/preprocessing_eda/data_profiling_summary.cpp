#include <cmath>
#include <limits>

struct Cell {
    bool is_null;
    std::string text;  // stored as string for both numeric and categorical
};

bool is_numeric(const std::string& s) {
    if (s.empty()) return false;
    char* end = nullptr;
    std::strtod(s.c_str(), &end);
    return *end == '\0';
}

struct Profile {
    std::string type;
    int missing_count = 0;
    int cardinality = 0;
    double min_val = 0.0, max_val = 0.0, mean_val = 0.0;
    bool has_stats = false;
    std::vector<std::string> top_values;
    std::vector<int> top_counts;
};

Profile profile_column(const std::vector<Cell>& col) {
    Profile p;
    int n = static_cast<int>(col.size());
    std::vector<Cell> non_null;
    for (const auto& c : col) if (!c.is_null) non_null.push_back(c);
    p.missing_count = n - static_cast<int>(non_null.size());
    if (non_null.empty()) {
        p.type = "unknown";
        p.cardinality = 0;
        return p;
    }
    p.type = is_numeric(non_null[0].text) ? "numeric" : "categorical";
    std::set<std::string> uniq;
    for (const auto& c : non_null) uniq.insert(c.text);
    p.cardinality = static_cast<int>(uniq.size());
    if (p.type == "numeric") {
        double mn = std::numeric_limits<double>::infinity();
        double mx = -std::numeric_limits<double>::infinity();
        double sum = 0.0;
        int cnt = 0;
        for (const auto& c : non_null) {
            double v = std::stod(c.text);
            if (v < mn) mn = v;
            if (v > mx) mx = v;
            sum += v;
            ++cnt;
        }
        p.min_val = mn; p.max_val = mx; p.mean_val = sum / cnt;
        p.has_stats = true;
    } else {
        std::map<std::string, int> counts;
        for (const auto& c : non_null) ++counts[c.text];
        std::vector<std::pair<std::string,int>> items(counts.begin(), counts.end());
        std::sort(items.begin(), items.end(), [](const auto& a, const auto& b){
            if (a.second != b.second) return a.second > b.second;
            return a.first < b.first;
        });
        int limit = std::min(3, static_cast<int>(items.size()));
        for (int i = 0; i < limit; ++i) {
            p.top_values.push_back(items[i].first);
            p.top_counts.push_back(items[i].second);
        }
    }
    return p;
}

std::map<std::string, Profile> profile_dataset(const std::vector<std::vector<Cell>>& rows,
                                                  const std::vector<std::string>& names) {
    std::map<std::string, Profile> result;
    if (rows.empty()) return result;
    int n_cols = static_cast<int>(rows[0].size());
    for (int i = 0; i < n_cols; ++i) {
        std::vector<Cell> col;
        for (const auto& row : rows) col.push_back(row[i]);
        result[names[i]] = profile_column(col);
    }
    return result;
}

