std::tuple<std::vector<double>, std::vector<std::vector<double>>, std::vector<std::vector<double>>, std::vector<int>>
fit_gaussian_naive_bayes(
    const std::vector<std::pair<double, double>>& X,
    const std::vector<int>& y
) {
    std::set<int> class_set(y.begin(), y.end());
    std::vector<int> classes(class_set.begin(), class_set.end());
    int n_samples = static_cast<int>(y.size());
    int n_features = 2;

    std::vector<double> class_priors;
    std::vector<std::vector<double>> means_per_class, stds_per_class;

    for (int cls : classes) {
        std::vector<int> indices;
        for (int i = 0; i < n_samples; ++i) {
            if (y[i] == cls) indices.push_back(i);
        }
        int n_cls = static_cast<int>(indices.size());
        class_priors.push_back(static_cast<double>(n_cls) / n_samples);

        std::vector<double> means(n_features, 0.0), stds(n_features, 0.0);
        for (int feat = 0; feat < n_features; ++feat) {
            for (int idx : indices) {
                means[feat] += (feat == 0 ? X[idx].first : X[idx].second);
            }
            means[feat] /= n_cls;

            double variance = 0.0;
            for (int idx : indices) {
                double diff = (feat == 0 ? X[idx].first : X[idx].second) - means[feat];
                variance += diff * diff;
            }
            variance /= std::max(1, n_cls - 1);
            stds[feat] = std::sqrt(variance);
            if (stds[feat] <= 0.0) stds[feat] = 1e-6;
        }

        means_per_class.push_back(means);
        stds_per_class.push_back(stds);
    }

    return {class_priors, means_per_class, stds_per_class, classes};
}

double gaussian_probability(double x, double mean, double std) {
    if (std == 0.0) return 0.0;
    double exponent = -((x - mean) * (x - mean)) / (2.0 * std * std);
    return std::exp(exponent) / (std::sqrt(2.0 * M_PI) * std);
}

int predict_gaussian_naive_bayes(
    const std::pair<double, double>& sample,
    const std::vector<double>& class_priors,
    const std::vector<std::vector<double>>& means_per_class,
    const std::vector<std::vector<double>>& stds_per_class,
    const std::vector<int>& classes
) {
    double best_posterior = -1.0;
    int best_class = classes[0];
    for (size_t idx = 0; idx < classes.size(); ++idx) {
        double posterior = class_priors[idx];
        posterior *= gaussian_probability(sample.first, means_per_class[idx][0], stds_per_class[idx][0]);
        posterior *= gaussian_probability(sample.second, means_per_class[idx][1], stds_per_class[idx][1]);
        if (posterior > best_posterior) {
            best_posterior = posterior;
            best_class = classes[idx];
        }
    }
    return best_class;
}

