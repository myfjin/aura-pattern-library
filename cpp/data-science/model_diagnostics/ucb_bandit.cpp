#include <algorithm>
#include <cassert>
#include <cmath>
#include <iostream>
#include <vector>
#include <random>

using namespace std;

class BernoulliArm {
public:
    double p;
    explicit BernoulliArm(double p_) : p(p_) {}
    int draw(mt19937& rng) const {
        uniform_real_distribution<double> u(0.0, 1.0);
        return u(rng) < p ? 1 : 0;
    }
};

int ucb1_select_arm(const vector<int>& counts, const vector<double>& rewards, double c, int total_pulls) {
    if (total_pulls == 0) return 0;
    int n = counts.size();
    int best = 0;
    double best_ucb = -1e300;
    for (int i = 0; i < n; ++i) {
        double ucb;
        if (counts[i] == 0) {
            ucb = 1e300;
        } else {
            double avg = rewards[i] / counts[i];
            ucb = avg + c * sqrt(log(static_cast<double>(total_pulls)) / counts[i]);
        }
        if (ucb > best_ucb) {
            best_ucb = ucb;
            best = i;
        }
    }
    return best;
}

void run_ucb1_experiment(const vector<BernoulliArm>& arms, int n_pulls, double c, mt19937& rng,
                         vector<int>& counts, vector<double>& rewards) {
    counts.assign(arms.size(), 0);
    rewards.assign(arms.size(), 0.0);
    int total = 0;
    for (int i = 0; i < n_pulls; ++i) {
        int arm_idx = ucb1_select_arm(counts, rewards, c, total);
        int reward = arms[arm_idx].draw(rng);
        counts[arm_idx] += 1;
        rewards[arm_idx] += reward;
        total += 1;
    }
}

