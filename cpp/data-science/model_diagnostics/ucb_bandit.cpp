    mt19937 rng(42);
    vector<BernoulliArm> arms = {BernoulliArm(0.1), BernoulliArm(0.5), BernoulliArm(0.9)};
    int n_pulls = 500;
    vector<int> counts;
    vector<double> rewards;
    run_ucb1_experiment(arms, n_pulls, 1.0, rng, counts, rewards);

    int best = counts[2];
