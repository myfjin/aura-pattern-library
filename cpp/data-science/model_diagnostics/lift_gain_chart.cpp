#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <algorithm>

std::vector<std::pair<double, int>> generate_scored_labels(int n_positive, int n_negative,
                                                    double signal_strength, int seed) {
    std::mt19937_64 rng(seed);
    std::normal_distribution<double> nd(0.0, 0.15);
    std::vector<std::pair<double, int>> data;
    for (int i = 0; i < n_positive; ++i) {
        double score = 0.5 + signal_strength * 0.3 + nd(rng);
        score = std::max(0.0, std::min(1.0, score));
        data.push_back({score, 1});
    }
    for (int i = 0; i < n_negative; ++i) {
        double score = 0.5 - signal_strength * 0.3 + nd(rng);
        score = std::max(0.0, std::min(1.0, score));
        data.push_back({score, 0});
    }
    return data;
}

std::tuple<std::vector<int>, std::vector<double>, std::vector<double>> lift_gain_chart(
    const std::vector<double>& scores,
    const std::vector<int>& labels,
    int n_deciles = 10) {

    std::vector<std::pair<double, int>> scored_labels;
    for (size_t i = 0; i < scores.size(); ++i) scored_labels.push_back({scores[i], labels[i]});
    std::sort(scored_labels.begin(), scored_labels.end(),
              [](const auto& a, const auto& b) { return a.first > b.first; });

    int n_total = static_cast<int>(scored_labels.size());
    int n_positive = 0;
    for (const auto& sl : scored_labels) n_positive += sl.second;
    double base_rate = n_positive / static_cast<double>(n_total);

    std::vector<int> decile_percentages;
    std::vector<double> gains, lifts;
    for (int decile = 1; decile <= n_deciles; ++decile) {
        int n_in_decile = std::max(1, decile * n_total / n_deciles);
        int n_pos_in_decile = 0;
        for (int i = 0; i < n_in_decile; ++i) n_pos_in_decile += scored_labels[i].second;
        double gain = n_positive > 0 ? (n_pos_in_decile / static_cast<double>(n_positive)) * 100.0 : 0.0;
        double pos_rate = n_in_decile > 0 ? n_pos_in_decile / static_cast<double>(n_in_decile) : 0.0;
        double lift = base_rate > 0 ? pos_rate / base_rate : 1.0;
        decile_percentages.push_back(decile * 10);
        gains.push_back(gain);
        lifts.push_back(lift);
    }
    return {decile_percentages, gains, lifts};
}

