#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>

std::vector<std::pair<double, double>> generate_linear_data(int n, int seed) {
    std::mt19937_64 rng(seed);
    std::uniform_real_distribution<double> xdist(-5.0, 5.0);
    std::normal_distribution<double> noise(0.0, 1.0);
    std::vector<std::pair<double, double>> data;
    for (int i = 0; i < n; ++i) {
        double x = xdist(rng);
        data.push_back({x, 2.0 * x + noise(rng)});
    }
    return data;
}

double mean_squared_error(const std::vector<double>& y_true,
                          const std::vector<double>& y_pred) {
    double s = 0.0;
    for (size_t i = 0; i < y_true.size(); ++i) s += (y_true[i] - y_pred[i]) * (y_true[i] - y_pred[i]);
    return s / y_true.size();
}

std::pair<double, double> fit_linear_model(const std::vector<double>& x_train,
                                          const std::vector<double>& y_train) {
    int n = static_cast<int>(x_train.size());
    double x_mean = 0.0, y_mean = 0.0;
    for (double x : x_train) x_mean += x;
    for (double y : y_train) y_mean += y;
    x_mean /= n; y_mean /= n;
    double num = 0.0, den = 0.0;
    for (int i = 0; i < n; ++i) {
        num += (x_train[i] - x_mean) * (y_train[i] - y_mean);
        den += (x_train[i] - x_mean) * (x_train[i] - x_mean);
    }
    if (den == 0.0) return {0.0, y_mean};
    double m = num / den;
    return {m, y_mean - m * x_mean};
}

int main() {
    auto all_data = generate_linear_data(200, 42);
    std::vector<std::pair<double, double>> train_data(all_data.begin(), all_data.begin() + 150);
    std::vector<std::pair<double, double>> val_data(all_data.begin() + 150, all_data.end());

    std::vector<double> val_x, val_y;
    for (const auto& p : val_data) { val_x.push_back(p.first); val_y.push_back(p.second); }

    std::vector<double> train_errors, val_errors, train_sizes;
    for (int size : {10, 30, 50, 80, 120, 150}) {
        std::vector<double> sx, sy;
        for (int i = 0; i < size; ++i) { sx.push_back(train_data[i].first); sy.push_back(train_data[i].second); }
        auto [m, b] = fit_linear_model(sx, sy);
        std::vector<double> pred_train, pred_val;
        for (double x : sx) pred_train.push_back(m * x + b);
        for (double x : val_x) pred_val.push_back(m * x + b);
        train_errors.push_back(mean_squared_error(sy, pred_train));
        val_errors.push_back(mean_squared_error(val_y, pred_val));
        train_sizes.push_back(static_cast<double>(size));
    }

    assert(train_errors.back() < 2.0);
    assert(val_errors[0] > train_errors[0]);
    assert(val_errors.back() < val_errors[0]);

    std::cout << "learning_curve.cpp PASS" << std::endl;
    return 0;
}
