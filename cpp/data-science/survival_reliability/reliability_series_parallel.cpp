#include <cassert>
#include <cstdio>
#include <random>
#include <vector>

// Series system reliability (all components must work).
double reliability_series(const std::vector<double>& r) {
    double result = 1.0;
    for (double ri : r) result *= ri;
    return result;
}

// Parallel system reliability (at least one must work).
double reliability_parallel(const std::vector<double>& r) {
    double result = 1.0;
    for (double ri : r) result *= (1.0 - ri);
    return 1.0 - result;
}

double simulate_series(const std::vector<double>& r, int num_sim, std::mt19937& gen) {
    std::uniform_real_distribution<double> unit(0.0, 1.0);
    int successes = 0;
    for (int i = 0; i < num_sim; ++i) {
        bool ok = true;
        for (double ri : r) {
            if (!(unit(gen) < ri)) { ok = false; break; }
        }
        if (ok) ++successes;
    }
    return static_cast<double>(successes) / num_sim;
}

double simulate_parallel(const std::vector<double>& r, int num_sim, std::mt19937& gen) {
    std::uniform_real_distribution<double> unit(0.0, 1.0);
    int successes = 0;
    for (int i = 0; i < num_sim; ++i) {
        bool ok = false;
        for (double ri : r) {
            if (unit(gen) < ri) { ok = true; break; }
        }
        if (ok) ++successes;
    }
    return static_cast<double>(successes) / num_sim;
}

