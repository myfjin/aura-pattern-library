/*
 * Censoring Bias Demo
 * 
 * Ignoring censoring biases survival estimates downward.
 * Naive mean of observed times vs Kaplan-Meier estimate shows that censored data
 * underestimates true mean survival time.
 */

#include <vector>
#include <cmath>
#include <random>
#include <algorithm>
#include <cassert>
#include <iostream>
#include <set>

double kaplan_meier_mean(const std::vector<double>& times, const std::vector<int>& events) {
    /* Approximate mean survival time via Kaplan-Meier (trapezoidal integration). */
    int n = static_cast<int>(times.size());
    
    // Get unique event times sorted
    std::set<double> event_times_set(times.begin(), times.end());
    std::vector<double> event_times(event_times_set.begin(), event_times_set.end());

    double surv = 1.0;
    double integral = 0.0;
    double prev_t = 0.0;

    for (double t : event_times) {
        int y_t = 0, d_t = 0;
        for (int i = 0; i < n; ++i) {
            if (times[i] >= t) y_t++;
            if (times[i] == t && events[i] == 1) d_t++;
        }

        if (y_t > 0) {
            surv *= (1.0 - static_cast<double>(d_t) / y_t);
            integral += surv * (t - prev_t);
            prev_t = t;
        }
    }

    return integral;
}

int main() {
    std::mt19937 rng(42);
    std::uniform_real_distribution<double> uniform(0.0, 1.0);
    
    // Planted: true survival times ~ Exponential(mean 100).
    const double lambda_true = 0.01;
    const double true_mean = 1.0 / lambda_true;
    const int n = 200;

    std::vector<double> true_times(n);
    for (int i = 0; i < n; ++i) {
        true_times[i] = -std::log(uniform(rng)) / lambda_true;
    }

    // RANDOM censoring: each subject has its own censoring time.
    std::vector<double> censor_times(n);
    for (int i = 0; i < n; ++i) {
        censor_times[i] = -std::log(uniform(rng)) * 120.0;  // Exponential with mean 120
    }

    std::vector<double> observed_times(n);
    std::vector<int> events(n);
    for (int i = 0; i < n; ++i) {
        observed_times[i] = std::min(true_times[i], censor_times[i]);
        events[i] = (true_times[i] <= censor_times[i]) ? 1 : 0;
    }

    // Naive mean: average observed times, ignoring which are censored.
    double naive_mean = 0.0;
    for (double t : observed_times) naive_mean += t;
    naive_mean /= n;

    // KM mean estimate (integral of the Kaplan-Meier survival curve).
    double km_mean = kaplan_meier_mean(observed_times, events);

    // Defining property: the naive mean UNDERESTIMATES; KM corrects toward the true mean.
    assert(naive_mean < km_mean - 10.0);
    assert(naive_mean < 0.75 * true_mean);
    assert(std::abs(km_mean - true_mean) < 30.0);

    std::cout << "censoring_bias_demo.cpp PASS" << std::endl;
    return 0;
}
