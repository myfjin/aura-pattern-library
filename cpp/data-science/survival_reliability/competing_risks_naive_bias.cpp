/*
 * Competing Risks: Naive KM vs Aalen-Johansen CIF
 * 
 * With competing events, naive 1-KM overestimates incidence; Aalen-Johansen is correct.
 */

#include <vector>
#include <algorithm>
#include <set>
#include <cassert>
#include <iostream>
#include <utility>
#include <random>

std::pair<std::vector<double>, std::vector<double>> naive_km_cif(
    const std::vector<double>& times,
    const std::vector<int>& events,
    int event_type
) {
    /* NAIVE cumulative incidence = 1 - (cause-specific Kaplan-Meier). */
    int n = static_cast<int>(times.size());
    std::set<double> event_times_set(times.begin(), times.end());
    std::vector<double> event_times(event_times_set.begin(), event_times_set.end());

    double surv = 1.0;
    std::vector<double> cif = {0.0};
    std::vector<double> times_out = {0.0};

    for (double t : event_times) {
        int d_type = 0;
        int y_t = 0;
        for (int i = 0; i < n; ++i) {
            if (times[i] >= t) y_t++;
            if (times[i] == t && events[i] == event_type) d_type++;
        }
        if (y_t > 0) {
            surv *= (1.0 - static_cast<double>(d_type) / y_t);
        }
        cif.push_back(1.0 - surv);
        times_out.push_back(t);
    }

    return {times_out, cif};
}

std::pair<std::vector<double>, std::vector<double>> aalen_johansen_cif(
    const std::vector<double>& times,
    const std::vector<int>& events,
    int event_type
) {
    /* CORRECT cumulative incidence (Aalen-Johansen): cause-1 hazard weighted by S(t-). */
    int n = static_cast<int>(times.size());
    std::set<double> event_times_set(times.begin(), times.end());
    std::vector<double> event_times(event_times_set.begin(), event_times_set.end());

    std::vector<double> cif = {0.0};
    std::vector<double> times_out = {0.0};
    double surv = 1.0;  // overall survival S(t-), all causes

    for (double t : event_times) {
        int d_type = 0, d_any = 0, y_t = 0;
        for (int i = 0; i < n; ++i) {
            if (times[i] >= t) y_t++;
            if (times[i] == t && events[i] == event_type) d_type++;
            if (times[i] == t && events[i] != 0) d_any++;
        }
        if (y_t > 0) {
            cif.push_back(cif.back() + (static_cast<double>(d_type) / y_t) * surv);
            surv *= (1.0 - static_cast<double>(d_any) / y_t);
        } else {
            cif.push_back(cif.back());
        }
        times_out.push_back(t);
    }

    return {times_out, cif};
}

int main() {
    std::mt19937 rng(42);
    std::exponential_distribution<double> exp1(0.5), exp2(0.3), exp3(0.15);

    std::vector<double> times;
    std::vector<int> events;  // 0 = censored, 1 = cause 1, 2 = cause 2
    times.reserve(300);
    events.reserve(300);

    for (int i = 0; i < 300; ++i) {
        double t1 = exp1(rng);
        double t2 = exp2(rng);
        double c = exp3(rng);
        double t = std::min({t1, t2, c});
        times.push_back(t);
        if (t == c) {
            events.push_back(0);
        } else if (t1 < t2) {
            events.push_back(1);
        } else {
            events.push_back(2);
        }
    }

    auto [_, cif_naive] = naive_km_cif(times, events, 1);
    auto [__, cif_correct] = aalen_johansen_cif(times, events, 1);

    double final_naive = cif_naive.back();
    double final_correct = cif_correct.back();

    // Defining property: naive (1-KM) OVERSTATES incidence vs Aalen-Johansen.
    assert(final_naive > final_correct + 0.1);
    assert(final_correct > 0.0 && final_correct < 1.0);
    assert(final_naive <= 1.0 + 1e-9);

    std::cout << "competing_risks_naive_bias.cpp PASS" << std::endl;
    return 0;
}
