/*
 * Hazard-survival conversion: verify duality h(t) = -d/dt[log S(t)].
 */

#include <cmath>
#include <cassert>
#include <iostream>
#include <functional>

double hazard_from_survival(std::function<double(double)> S, double t, double eps = 1e-6) {
    double s_plus = S(t + eps);
    double s_minus = S(t - eps);

    if (s_plus < 1e-14 || s_minus < 1e-14) return 0.0;

    double d_log_s = (std::log(s_plus) - std::log(s_minus)) / (2.0 * eps);
    return -d_log_s;
}

double survival_from_cumhazard(std::function<double(double)> H, double t) {
    return std::exp(-H(t));
}

int main() {
    const double lambda_val = 0.1;
    auto S_planted = [lambda_val](double t) { return std::exp(-lambda_val * t); };
    auto H_planted = [lambda_val](double t) { return lambda_val * t; };

    double h_est = hazard_from_survival(S_planted, 5.0, 1e-5);
    double h_true = lambda_val;
    assert(std::abs(h_est - h_true) < 0.01);

    double S_recon = survival_from_cumhazard(H_planted, 5.0);
    double S_true = S_planted(5.0);
    assert(std::abs(S_recon - S_true) < 1e-10);

    std::cout << "hazard_vs_survival_conversion.cpp PASS" << std::endl;
    return 0;
}
