/* CUSUM changepoint detector: detect mean shifts in time series.
 *
 * Core claim: CUSUM detects step changes near the true change point.
 */
#include <cassert>
#include <cmath>
#include <iostream>
#include <vector>

std::vector<int> cusum_detector(
    const std::vector<double>& series,
    double threshold = 5.0
) {
    double mean_ref = 0.0;
    int n_ref = std::min(static_cast<int>(series.size()) / 2, 30);
    for (int i = 0; i < n_ref; ++i) mean_ref += series[i];
    mean_ref /= n_ref;

    double pos_sum = 0.0, neg_sum = 0.0;
    std::vector<int> changepoints;

    for (size_t t = n_ref; t < series.size(); ++t) {
        pos_sum = std::max(0.0, pos_sum + series[t] - mean_ref);
        neg_sum = std::max(0.0, neg_sum + mean_ref - series[t]);

        if (pos_sum > threshold || neg_sum > threshold) {
            changepoints.push_back(static_cast<int>(t));
            pos_sum = 0.0;
            neg_sum = 0.0;
        }
    }
    return changepoints;
}

double estimate_mean(const std::vector<double>& series) {
    double sum = 0.0;
    for (double v : series) sum += v;
    return sum / series.size();
}

int main() {
    std::vector<double> series(100, 0.0);
    // First 50: mean 0, last 50: mean 2
    for (int i = 50; i < 100; ++i) series[i] = 2.0;

    auto changepoints = cusum_detector(series);

    assert(!changepoints.empty());
    int first_cp = changepoints[0];
    assert(first_cp > 40 && first_cp < 60);

    // CUSUM should rise after shift
    double cusum_before = 0.0, cusum_after = 0.0;
    for (int i = 0; i < first_cp; ++i) cusum_before += series[i];
    for (size_t i = first_cp; i < series.size(); ++i) cusum_after += series[i];
    cusum_before /= first_cp;
    cusum_after /= (series.size() - first_cp);
    assert(cusum_after > cusum_before);

    std::cout << "PASS" << std::endl;
    return 0;
}
