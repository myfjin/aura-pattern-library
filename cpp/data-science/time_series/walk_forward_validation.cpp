vector<double> naive_mean_forecast(const vector<double>& train, int steps_ahead = 1) {
    double mean = train.empty() ? 0.0 : accumulate(train.begin(), train.end(), 0.0) / train.size();
    return vector<double>(steps_ahead, mean);
}

vector<double> naive_last_value_forecast(const vector<double>& train, int steps_ahead = 1) {
    double last = train.empty() ? 0.0 : train.back();
    return vector<double>(steps_ahead, last);
}

using ForecastFunc = vector<double> (*)(const vector<double>&, int);

pair<vector<double>, vector<double>>
walk_forward_validation(const vector<double>& series, int initial_window, ForecastFunc fc) {
    if (initial_window >= (int)series.size()) throw invalid_argument("initial_window must be < len(series)");
    vector<double> actuals, predictions;
    for (int t = initial_window; t < (int)series.size(); ++t) {
        vector<double> train(series.begin(), series.begin() + t);
        double actual = series[t];
        auto fcst = fc(train, 1);
        double pred = fcst.empty() ? 0.0 : fcst[0];
        actuals.push_back(actual);
        predictions.push_back(pred);
    }
    return {actuals, predictions};
}

double compute_mae(const vector<double>& actual, const vector<double>& predicted) {
    if (actual.size() != predicted.size()) throw invalid_argument("Length mismatch");
    double s = 0.0;
    for (size_t i = 0; i < actual.size(); ++i) s += abs(actual[i] - predicted[i]);
    return s / actual.size();
}

