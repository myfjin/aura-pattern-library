std::vector<double> simple_moving_average(const std::vector<double>& series, int window) {
    std::vector<double> result;
    for (size_t i = 0; i < series.size(); ++i) {
        int w = static_cast<int>(i + 1) < window ? static_cast<int>(i + 1) : window;
        double s = 0.0;
        for (int j = 0; j < w; ++j) s += series[i - j];
        result.push_back(s / w);
    }
    return result;
}

std::vector<double> weighted_moving_average(const std::vector<double>& series, int window) {
    std::vector<double> result;
    for (size_t i = 0; i < series.size(); ++i) {
        int w = static_cast<int>(i + 1) < window ? static_cast<int>(i + 1) : window;
        double s = 0.0, ws = 0.0;
        for (int j = 0; j < w; ++j) {
            double weight = j + 1;
            s += series[i - j] * weight;
            ws += weight;
        }
        result.push_back(s / ws);
    }
    return result;
}

double compute_variance(const std::vector<double>& series) {
    if (series.size() < 2) return 0.0;
    double mean = 0.0;
    for (double x : series) mean += x;
    mean /= series.size();
    double s = 0.0;
    for (double x : series) s += (x - mean) * (x - mean);
    return s / (series.size() - 1);
}

