double clustering_accuracy(const std::vector<int>& pred, const std::vector<int>& truth) {
    size_t n = truth.size();
    size_t direct = 0, flipped = 0;
    for (size_t i = 0; i < n; ++i) {
        if (pred[i] == truth[i]) ++direct;
        if (1 - pred[i] == truth[i]) ++flipped;
    }
    return std::max(static_cast<double>(direct) / n, static_cast<double>(flipped) / n);
}

std::vector<int> kmeans_baseline(const std::vector<Point>& X, int k, int n_iter, std::mt19937& gen) {
    size_t n = X.size();
    std::uniform_int_distribution<int> idx_dist(0, static_cast<int>(n) - 1);
    std::vector<Point> centroids;
    for (int i = 0; i < k; ++i) centroids.push_back(X[idx_dist(gen)]);

    std::vector<int> assignments(n);
    for (int it = 0; it < n_iter; ++it) {
        for (size_t i = 0; i < n; ++i) {
            double best = 1e300;
            int best_c = 0;
            for (int c = 0; c < k; ++c) {
                double d = euclidean_distance(X[i], centroids[c]);
                if (d < best) { best = d; best_c = c; }
            }
            assignments[i] = best_c;
        }
        for (int c = 0; c < k; ++c) {
            double sx = 0.0, sy = 0.0;
            int cnt = 0;
            for (size_t i = 0; i < n; ++i) {
                if (assignments[i] == c) {
                    sx += X[i].first;
                    sy += X[i].second;
                    ++cnt;
                }
            }
            if (cnt > 0) centroids[c] = {sx / cnt, sy / cnt};
        }
    }
    return assignments;
}

