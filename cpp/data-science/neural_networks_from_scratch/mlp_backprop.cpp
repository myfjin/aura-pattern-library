#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>

class SimpleMLPBackprop {
public:
    SimpleMLPBackprop(int hidden_dim = 4, double lr = 1.0, int seed = 42)
        : hidden_dim_(hidden_dim), lr_(lr) {
        std::mt19937_64 rng(seed);
        std::normal_distribution<double> nd(0.0, 0.5);
        w1_.assign(hidden_dim, std::vector<double>(2));
        for (int i = 0; i < hidden_dim; ++i)
            for (int j = 0; j < 2; ++j) w1_[i][j] = nd(rng);
        b1_.assign(hidden_dim, 0.0);
        w2_.resize(hidden_dim);
        for (int i = 0; i < hidden_dim; ++i) w2_[i] = nd(rng);
        b2_ = 0.0;
    }

    std::pair<double, std::vector<double>> forward(const std::vector<double>& x) const {
        std::vector<double> h(hidden_dim_);
        for (int i = 0; i < hidden_dim_; ++i) {
            double z = b1_[i] + w1_[i][0] * x[0] + w1_[i][1] * x[1];
            h[i] = sigmoid(z);
        }
        double z2 = b2_;
        for (int i = 0; i < hidden_dim_; ++i) z2 += w2_[i] * h[i];
        return {sigmoid(z2), h};
    }

    void backward(const std::vector<double>& x, double y_true, double y_pred,
                  const std::vector<double>& h) {
        double dy = y_pred - y_true;
        std::vector<double> dw2(hidden_dim_);
        for (int i = 0; i < hidden_dim_; ++i) dw2[i] = dy * h[i];
        double db2 = dy;
        std::vector<double> dh(hidden_dim_);
        for (int i = 0; i < hidden_dim_; ++i) dh[i] = dy * w2_[i] * sigmoid_derivative(h[i]);

        for (int i = 0; i < hidden_dim_; ++i) {
            for (int j = 0; j < 2; ++j) w1_[i][j] -= lr_ * dh[i] * x[j];
            b1_[i] -= lr_ * dh[i];
            w2_[i] -= lr_ * dw2[i];
        }
        b2_ -= lr_ * db2;
    }

    double train(const std::vector<std::pair<std::vector<double>, double>>& data, int epochs) {
        for (int epoch = 0; epoch < epochs; ++epoch) {
            for (const auto& sample : data) {
                auto [y_pred, h] = forward(sample.first);
                backward(sample.first, sample.second, y_pred, h);
            }
        }
        double total = 0.0;
        for (const auto& sample : data) {
            auto [y_pred, _] = forward(sample.first);
            total += 0.5 * (y_pred - sample.second) * (y_pred - sample.second);
        }
        return data.empty() ? 0.0 : total / data.size();
    }

private:
    int hidden_dim_;
    double lr_;
    std::vector<std::vector<double>> w1_;
    std::vector<double> b1_;
    std::vector<double> w2_;
    double b2_;

    static double sigmoid(double x) {
        if (x < -500) return 0.0;
        if (x > 500) return 1.0;
        return 1.0 / (1.0 + std::exp(-x));
    }

    static double sigmoid_derivative(double s) { return s * (1.0 - s); }
};

