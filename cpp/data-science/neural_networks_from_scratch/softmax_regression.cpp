// Multi-class softmax regression with cross-entropy loss.

std::vector<double> softmax(const std::vector<double>& logits) {
    double max_logit = *std::max_element(logits.begin(), logits.end());
    std::vector<double> exp_logits(logits.size());
    double sum_exp = 0.0;
    for (size_t i = 0; i < logits.size(); ++i) {
        exp_logits[i] = std::exp(logits[i] - max_logit);
        sum_exp += exp_logits[i];
    }
    for (double& e : exp_logits) e /= sum_exp;
    return exp_logits;
}

double cross_entropy(const std::vector<double>& probs, size_t target_class) {
    return -std::log(std::max(probs[target_class], 1e-10));
}

class SoftmaxRegression {
public:
    size_t input_dim;
    size_t num_classes;
    double lr;
    std::vector<std::vector<double>> W;
    std::vector<double> b;

    SoftmaxRegression(size_t input_dim_, size_t num_classes_, double lr_, std::mt19937& gen)
        : input_dim(input_dim_), num_classes(num_classes_), lr(lr_) {
        std::normal_distribution<double> dist(0.0, 0.1);
        W.assign(num_classes, std::vector<double>(input_dim));
        for (auto& row : W)
            for (double& w : row) w = dist(gen);
        b.assign(num_classes, 0.0);
    }

    std::vector<double> forward(const std::vector<double>& x) const {
        std::vector<double> logits(num_classes);
        for (size_t c = 0; c < num_classes; ++c) {
            logits[c] = b[c];
            for (size_t d = 0; d < input_dim; ++d) {
                logits[c] += W[c][d] * x[d];
            }
        }
        return logits;
    }

    void backward(const std::vector<double>& x, const std::vector<double>& probs, size_t target_class) {
        std::vector<double> grad_logits = probs;
        grad_logits[target_class] -= 1.0;
        for (size_t c = 0; c < num_classes; ++c) {
            for (size_t d = 0; d < input_dim; ++d) {
                W[c][d] -= lr * grad_logits[c] * x[d];
            }
            b[c] -= lr * grad_logits[c];
        }
    }

    double train_epoch(const std::vector<std::pair<std::vector<double>, size_t>>& data) {
        for (const auto& sample : data) {
            auto logits = forward(sample.first);
            auto probs = softmax(logits);
            backward(sample.first, probs, sample.second);
        }

        double total_loss = 0.0;
        for (const auto& sample : data) {
            auto logits = forward(sample.first);
            auto probs = softmax(logits);
            total_loss += cross_entropy(probs, sample.second);
        }
        return data.empty() ? 0.0 : total_loss / data.size();
    }

    size_t predict(const std::vector<double>& x) const {
        auto logits = forward(x);
        return std::max_element(logits.begin(), logits.end()) - logits.begin();
    }
};

