double cosine(const std::vector<double>& a, const std::vector<double>& b) {
    double dot = 0.0, n1 = 0.0, n2 = 0.0;
    for (size_t i = 0; i < a.size(); ++i) {
        dot += a[i] * b[i];
        n1 += a[i] * a[i];
        n2 += b[i] * b[i];
    }
    return dot / ((std::sqrt(n1) + 1e-10) * (std::sqrt(n2) + 1e-10));
}

