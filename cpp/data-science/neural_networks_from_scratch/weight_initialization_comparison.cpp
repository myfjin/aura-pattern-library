double sigmoid(double x) {
    if (x < -500.0) return 0.0;
    if (x > 500.0) return 1.0;
    return 1.0 / (1.0 + exp(-x));
}

struct DeepNetwork {
    string init_scheme;
    vector<int> layer_dims = {10, 32, 32, 32, 16, 1};
    vector<vector<vector<double>>> W;
    vector<vector<double>> b;
    mt19937* rng;

    DeepNetwork(const string& scheme, mt19937* rng_) : init_scheme(scheme), rng(rng_) {
        int nl = layer_dims.size() - 1;
        W.resize(nl);
        b.resize(nl);
        for (int layer = 0; layer < nl; ++layer) {
            int fan_in = layer_dims[layer];
            int fan_out = layer_dims[layer + 1];
            W[layer].assign(fan_out, vector<double>(fan_in));
            for (int i = 0; i < fan_out; ++i)
                for (int j = 0; j < fan_in; ++j) {
                    if (init_scheme == "small") W[layer][i][j] = uniform(-0.1, 0.1);
                    else if (init_scheme == "large") W[layer][i][j] = uniform(-1.0, 1.0);
                    else { double lim = sqrt(1.0 / fan_in); W[layer][i][j] = uniform(-lim, lim); }
                }
            b[layer].assign(fan_out, 0.0);
        }
    }

    double uniform(double lo, double hi) {
        return std::uniform_real_distribution<double>(lo, hi)(*rng);
    }

    tuple<double, vector<vector<double>>, vector<vector<double>>>
    forward(const vector<double>& x) {
        vector<vector<double>> activations;
        vector<vector<double>> preactivations;
        vector<double> h = x;
        activations.push_back(h);
        for (size_t layer = 0; layer + 1 < layer_dims.size(); ++layer) {
            vector<double> z(layer_dims[layer + 1]);
            for (int i = 0; i < layer_dims[layer + 1]; ++i) {
                double s = b[layer][i];
                for (int j = 0; j < layer_dims[layer]; ++j) s += W[layer][i][j] * h[j];
                z[i] = s;
            }
            preactivations.push_back(z);
            h.resize(z.size());
            for (size_t i = 0; i < z.size(); ++i) h[i] = sigmoid(z[i]);
            activations.push_back(h);
        }
        return {h[0], activations, preactivations};
    }

    void backward(double y_true, double y_pred, const vector<vector<double>>& activations, double lr) {
        double dy = y_pred - y_true;
        int m = layer_dims[layer_dims.size() - 2];
        for (int i = 0; i < m; ++i) W.back()[0][i] -= lr * dy * activations[activations.size() - 2][i];
        b.back()[0] -= lr * dy;
    }

    pair<double, vector<double>> train(const vector<pair<vector<double>, double>>& train_data, int epochs, double lr) {
        for (int e = 0; e < epochs; ++e) {
            for (const auto& sample : train_data) {
                auto [y_pred, acts, preacts] = forward(sample.first);
                backward(sample.second, y_pred, acts, lr);
            }
        }

        vector<double> layer_variances;
        int num_test_samples = 50;
        for (size_t layer_idx = 0; layer_idx + 1 < layer_dims.size(); ++layer_idx) {
            vector<double> all_pre;
            normal_distribution<double> nd(0.0, 1.0);
            for (int s = 0; s < num_test_samples; ++s) {
                vector<double> x(layer_dims[0]);
                for (double& v : x) v = nd(*rng);
                auto [_, __, preacts] = forward(x);
                all_pre.insert(all_pre.end(), preacts[layer_idx].begin(), preacts[layer_idx].end());
            }
            double mean = accumulate(all_pre.begin(), all_pre.end(), 0.0) / all_pre.size();
            double var = 0.0;
            for (double v : all_pre) var += (v - mean) * (v - mean);
            var /= all_pre.size();
            layer_variances.push_back(var);
        }

        double final_loss = 0.0;
        for (const auto& sample : train_data) {
            auto [y_pred, _, __] = forward(sample.first);
            final_loss += (y_pred - sample.second) * (y_pred - sample.second) / 2.0;
        }
        final_loss /= train_data.size();
        return {final_loss, layer_variances};
    }
};

