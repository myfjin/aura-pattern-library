using Docs = std::map<std::string, std::string>;
using Terms = std::vector<std::string>;

static std::string lower(const std::string& s) {
    std::string r = s;
    for (char& c : r) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    return r;
}

static std::set<std::string> words_in(const std::string& text) {
    std::set<std::string> result;
    std::istringstream iss(text);
    std::string w;
    while (iss >> w) result.insert(lower(w));
    return result;
}

static std::vector<std::string> split(const std::string& text) {
    std::vector<std::string> result;
    std::istringstream iss(text);
    std::string w;
    while (iss >> w) result.push_back(lower(w));
    return result;
}

static std::vector<std::string> tf_search(const Terms& query_terms, const Docs& docs) {
    std::map<std::string, int> scores;
    for (const auto& kv : docs) {
        const std::string& doc_id = kv.first;
        auto words = words_in(kv.second);
        int score = 0;
        for (const auto& term : query_terms) {
            if (words.count(term)) ++score;
        }
        if (score > 0) scores[doc_id] = score;
    }
    std::vector<std::pair<std::string, int>> v(scores.begin(), scores.end());
    std::sort(v.begin(), v.end(), [](const auto& a, const auto& b) {
        return a.second > b.second;
    });
    std::vector<std::string> result;
    for (const auto& p : v) result.push_back(p.first);
    return result;
}

static Terms expand_query_prf(const Terms& query_terms,
                              const Docs& docs,
                              int k,
                              int expansion_terms) {
    auto initial_results = tf_search(query_terms, docs);
    std::string top_k_text;
    for (int i = 0; i < k && i < static_cast<int>(initial_results.size()); ++i) {
        if (i > 0) top_k_text += " ";
        top_k_text += docs.at(initial_results[i]);
    }

    std::map<std::string, int> freq;
    for (const auto& w : split(top_k_text)) {
        ++freq[w];
    }

    std::vector<std::pair<std::string, int>> candidates;
    for (const auto& kv : freq) {
        if (std::find(query_terms.begin(), query_terms.end(), kv.first) == query_terms.end()) {
            candidates.push_back(kv);
        }
    }
    std::sort(candidates.begin(), candidates.end(), [](const auto& a, const auto& b) {
        return a.second > b.second;
    });

    Terms expanded = query_terms;
    for (int i = 0; i < expansion_terms && i < static_cast<int>(candidates.size()); ++i) {
        expanded.push_back(candidates[i].first);
    }
    return expanded;
}

