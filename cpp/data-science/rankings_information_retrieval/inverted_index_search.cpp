/*
 * Inverted Index and Boolean Search.
 *
 * Oracle asserts:
 *   query_and({"python","machine"}) == {"doc1"}
 *   query_or({"python","machine"}) == {"doc1","doc2","doc3","doc5"}
 *   index["python"] == {"doc1","doc2","doc5"}
 *   "doc4" not in or_result
 */

#include <map>
#include <set>
#include <vector>
#include <string>
#include <cassert>
#include <iostream>
#include <sstream>
#include <algorithm>

std::map<std::string, std::set<std::string>> build_inverted_index(const std::map<std::string, std::string>& docs) {
    std::map<std::string, std::set<std::string>> index;
    for (const auto& kv : docs) {
        std::istringstream iss(kv.second);
        std::string word;
        while (iss >> word) {
            for (char& c : word) c = std::tolower(static_cast<unsigned char>(c));
            index[word].insert(kv.first);
        }
    }
    return index;
}

std::set<std::string> query_and(const std::map<std::string, std::set<std::string>>& index,
                               const std::vector<std::string>& terms) {
    if (terms.empty()) return {};
    auto it = index.find(terms[0]);
    if (it == index.end()) return {};
    std::set<std::string> result = it->second;
    for (size_t i = 1; i < terms.size(); ++i) {
        auto it2 = index.find(terms[i]);
        if (it2 == index.end()) return {};
        std::set<std::string> tmp;
        std::set_intersection(result.begin(), result.end(),
                              it2->second.begin(), it2->second.end(),
                              std::inserter(tmp, tmp.begin()));
        result = tmp;
    }
    return result;
}

std::set<std::string> query_or(const std::map<std::string, std::set<std::string>>& index,
                              const std::vector<std::string>& terms) {
    std::set<std::string> result;
    for (const auto& term : terms) {
        auto it = index.find(term);
        if (it != index.end()) result.insert(it->second.begin(), it->second.end());
    }
    return result;
}

