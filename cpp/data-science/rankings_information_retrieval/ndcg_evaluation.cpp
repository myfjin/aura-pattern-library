/*
 * NDCG (Normalized Discounted Cumulative Gain).
 *
 * Oracle asserts:
 *   ideal DCG matches expected within 0.01
 *   perfect NDCG ~1.0
 *   degraded NDCG < 0.5
 *   perfect > 2 * degraded
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>

double dcg(const std::vector<double>& relevances) {
    double s = 0.0;
    for (size_t i = 0; i < relevances.size(); ++i) {
        s += relevances[i] / std::log2(static_cast<double>(i + 2));
    }
    return s;
}

double ndcg(const std::vector<double>& predicted, const std::vector<double>& ideal) {
    double dcg_pred = dcg(predicted);
    double dcg_ideal = dcg(ideal);
    return dcg_ideal == 0.0 ? 0.0 : dcg_pred / dcg_ideal;
}

