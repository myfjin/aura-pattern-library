#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <set>

double reciprocal_rank(const std::vector<int>& ranking, const std::set<int>& relevant) {
    for (size_t i = 0; i < ranking.size(); ++i)
        if (relevant.count(ranking[i])) return 1.0 / static_cast<double>(i + 1);
    return 0.0;
}

double mean_reciprocal_rank(const std::vector<std::vector<int>>& rankings,
                          const std::vector<std::set<int>>& relevant_sets) {
    double s = 0.0;
    for (size_t i = 0; i < rankings.size(); ++i) s += reciprocal_rank(rankings[i], relevant_sets[i]);
    return s / rankings.size();
}

double precision_at_k(const std::vector<int>& ranking, const std::set<int>& relevant, int k) {
    int hits = 0;
    for (int i = 0; i < k; ++i) if (relevant.count(ranking[i])) ++hits;
    return hits / static_cast<double>(k);
}

double recall_at_k(const std::vector<int>& ranking, const std::set<int>& relevant, int k) {
    if (relevant.empty()) return 0.0;
    int hits = 0;
    for (int i = 0; i < k; ++i) if (relevant.count(ranking[i])) ++hits;
    return hits / static_cast<double>(relevant.size());
}

