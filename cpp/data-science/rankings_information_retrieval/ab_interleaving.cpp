/*
 * Team-Draft Interleaving for A/B Testing Rankers.
 *
 * Compare two rankers (A and B) by interleaving their results in a single ranking.
 * Users click on interleaved results. The ranker whose document the user clicked on wins
 * that "team". We count wins and determine which ranker is better.
 * We plant a stronger ranker and verify it wins the interleaving.
 */

#include <iostream>
#include <vector>
#include <string>
#include <unordered_set>
#include <random>
#include <utility>
#include <cassert>

using namespace std;

// Team-draft interleaving: alternately pick the next unchosen document from A or B.
// Returns list of (doc, source) where source is 'A' or 'B'.
vector<pair<string, char>> interleave_team_draft(const vector<string>& ranking_a, 
                                                   const vector<string>& ranking_b) {
    vector<pair<string, char>> interleaved;
    size_t a_idx = 0, b_idx = 0;
    int team_idx = 0;
    
    while (a_idx < ranking_a.size() || b_idx < ranking_b.size()) {
        char source = (team_idx % 2 == 0) ? 'A' : 'B';
        
        if (source == 'A' && a_idx < ranking_a.size()) {
            interleaved.push_back({ranking_a[a_idx], 'A'});
            a_idx++;
        } else if (source == 'B' && b_idx < ranking_b.size()) {
            interleaved.push_back({ranking_b[b_idx], 'B'});
            b_idx++;
        } else {
            // Fall back to other source if current is exhausted
            char other = (source == 'A') ? 'B' : 'A';
            if (other == 'B' && b_idx < ranking_b.size()) {
                interleaved.push_back({ranking_b[b_idx], 'B'});
                b_idx++;
            } else if (other == 'A' && a_idx < ranking_a.size()) {
                interleaved.push_back({ranking_a[a_idx], 'A'});
                a_idx++;
            }
        }
        
        team_idx++;
    }
    
    return interleaved;
}

// Simulate user clicks on interleaved ranking.
// Returns win count for each ranker.
pair<int, int> simulate_clicks_on_interleaving(const vector<pair<string, char>>& interleaved,
                                                const unordered_set<string>& relevant_docs,
                                                mt19937& gen,
                                                double click_prob_relevant = 0.8) {
    int wins_a = 0, wins_b = 0;
    uniform_real_distribution<double> dist(0.0, 1.0);
    
    for (const auto& [doc, source] : interleaved) {
        // Click if document is relevant
        if (relevant_docs.count(doc) && dist(gen) < click_prob_relevant) {
            if (source == 'A') wins_a++;
            else wins_b++;
        }
    }
    
    return {wins_a, wins_b};
}

int main() {
    // Seed the RNG with same seed as Python (42)
    mt19937 gen(42);
    
    // True relevant documents
    unordered_set<string> relevant_docs = {"A1", "A2", "B1", "B2"};
    
    // Ranker A: strong (finds most relevant docs)
    vector<string> ranking_a = {"A1", "A2", "B1", "B2", "C1"};
    
    // Ranker B: weak (misses some relevant docs)
    vector<string> ranking_b = {"B1", "C1", "A1", "A2", "C2"};
    
    // Interleave
    auto interleaved = interleave_team_draft(ranking_a, ranking_b);
    
    // Simulate clicks over 50 trials
    int total_wins_a = 0, total_wins_b = 0;
    for (int trial = 0; trial < 50; trial++) {
        auto [wins_a, wins_b] = simulate_clicks_on_interleaving(interleaved, relevant_docs, gen, 0.7);
        total_wins_a += wins_a;
        total_wins_b += wins_b;
    }
    
    // Check: A should win more than B
    assert(total_wins_a > total_wins_b);
    
    // A's win ratio should be significant
    int total_clicks = total_wins_a + total_wins_b;
    double a_win_ratio = (total_clicks > 0) ? (double)total_wins_a / total_clicks : 0.0;
    
    assert(a_win_ratio > 0.5);
    
    cout << "Interleaved results: " << interleaved.size() << " docs | "
         << "A wins: " << total_wins_a << " | B wins: " << total_wins_b << " | "
         << "A win ratio: " << (a_win_ratio * 100.0) << "% | PASS" << endl;
    
    return 0;
}
