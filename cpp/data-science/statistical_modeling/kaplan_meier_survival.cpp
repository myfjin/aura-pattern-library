std::vector<std::pair<double, double>> kaplan_meier(const std::vector<double>& times,
                                                  const std::vector<int>& events) {
    int n = static_cast<int>(times.size());
    std::vector<std::pair<double, int>> data(n);
    for (int i = 0; i < n; ++i) data[i] = {times[i], events[i]};
    std::sort(data.begin(), data.end());

    std::vector<double> unique_times;
    for (const auto& de : data) {
        if (de.second == 1) {
            if (unique_times.empty() || unique_times.back() != de.first) unique_times.push_back(de.first);
        }
    }

    double survival_prob = 1.0;
    int at_risk = n;
    std::vector<std::pair<double, double>> curve;

    size_t idx = 0;
    for (double event_time : unique_times) {
        int events_at_time = 0, censored_at_time = 0;
        while (idx < data.size() && data[idx].first == event_time) {
            if (data[idx].second == 1) ++events_at_time;
            else ++censored_at_time;
            ++idx;
        }
        if (at_risk > 0) survival_prob *= (1.0 - static_cast<double>(events_at_time) / at_risk);
        curve.push_back({event_time, survival_prob});
        at_risk -= (events_at_time + censored_at_time);
    }
    return curve;
}

bool check_non_increasing(const std::vector<std::pair<double, double>>& curve) {
    for (size_t i = 1; i < curve.size(); ++i) {
        if (curve[i].second > curve[i - 1].second + 1e-10) return false;
    }
    return !curve.empty();
}

