/*
 * Metropolis-Hastings MCMC Sampling.
 *
 * Oracle asserts:
 *   abs(mean_samples) < 0.5
 *   abs(var_samples - 5.0) < 1.0
 *   0.2 < acc_rate < 0.7
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <functional>

double mixture_target(double x) {
    return 0.5 * std::exp(-0.5 * (x + 2.0) * (x + 2.0)) +
           0.5 * std::exp(-0.5 * (x - 2.0) * (x - 2.0));
}

std::pair<std::vector<double>, double> metropolis_hastings(
    std::function<double(double)> target_pdf,
    double proposal_sd,
    int n_samples,
    double initial_x = 0.0,
    int seed = 42) {

    std::mt19937_64 rng(seed);
    std::normal_distribution<double> proposal(0.0, proposal_sd);
    std::uniform_real_distribution<double> uniform(0.0, 1.0);

    std::vector<double> samples;
    double x = initial_x;
    int n_accept = 0;

    for (int i = 0; i < n_samples; ++i) {
        double x_prop = x + proposal(rng);
        double log_ratio = std::min(0.0, std::log(target_pdf(x_prop)) - std::log(target_pdf(x)));
        if (std::log(uniform(rng)) < log_ratio) {
            x = x_prop;
            ++n_accept;
        }
        samples.push_back(x);
    }
    return {samples, n_accept / static_cast<double>(n_samples)};
}

int main() {
    auto [samples, acc_rate] = metropolis_hastings(mixture_target, 2.5, 6000, 0.0, 42);
    int n_burn = 1000;
    std::vector<double> keep(samples.begin() + n_burn, samples.end());

    double mean = 0.0;
    for (double x : keep) mean += x;
    mean /= keep.size();
    double var = 0.0;
    for (double x : keep) var += (x - mean) * (x - mean);
    var /= keep.size();

    assert(std::abs(mean) < 0.5);
    assert(std::abs(var - 5.0) < 1.0);
    assert(acc_rate > 0.2 && acc_rate < 0.7);

    std::cout << "metropolis_hastings_mcmc.cpp PASS: mean=" << mean
              << " var=" << var << " acc=" << acc_rate << std::endl;
    return 0;
}
