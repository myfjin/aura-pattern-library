double silverman_bandwidth(const std::vector<double>& samples) {
    int n = static_cast<int>(samples.size());
    double mean = std::accumulate(samples.begin(), samples.end(), 0.0) / n;
    double var = 0.0;
    for (double x : samples) var += (x - mean) * (x - mean);
    var /= n;
    return std::pow(4.0 / (3.0 * n), 1.0 / 5.0) * std::sqrt(var);
}

double gaussian_kernel_density(const std::vector<double>& samples, double x, double h) {
    int n = static_cast<int>(samples.size());
    double density = 0.0;
    const double norm = 1.0 / std::sqrt(2.0 * M_PI);
    for (double xi : samples) {
        double u = (x - xi) / h;
        density += norm * std::exp(-0.5 * u * u);
    }
    return density / (n * h);
}

double numeric_integral_kde(const std::vector<double>& samples,
                            double x_min, double x_max, int n_grid) {
    double h = silverman_bandwidth(samples);
    double dx = (x_max - x_min) / n_grid;
    double total = 0.0;
    for (int i = 0; i < n_grid; ++i) {
        double x = x_min + (i + 0.5) * dx;
        total += gaussian_kernel_density(samples, x, h) * dx;
    }
    return total;
}

