/*
 * Importance Sampling for Expectation Estimation.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <utility>

double target_pdf(double x) {
    return std::exp(-0.5 * (x - 2.0) * (x - 2.0));
}

double proposal_pdf(double x) {
    return std::exp(-0.125 * x * x) / std::sqrt(8.0 * M_PI);
}

std::pair<double, double> importance_sampling(std::mt19937& rng, int n_samples) {
    std::normal_distribution<double> proposal(0.0, 2.0);

    std::vector<double> samples, weights;
    for (int i = 0; i < n_samples; ++i) {
        double x = proposal(rng);
        samples.push_back(x);
        weights.push_back(target_pdf(x) / proposal_pdf(x));
    }

    double total_weight = 0.0;
    for (double w : weights) total_weight += w;

    double estimate = 0.0;
    for (int i = 0; i < n_samples; ++i) estimate += samples[i] * weights[i] / total_weight;

    double ess_denom = 0.0;
    for (double w : weights) ess_denom += (w / total_weight) * (w / total_weight);
    double ess = 1.0 / ess_denom;

    return {estimate, ess};
}

int main() {
    std::mt19937 rng(42);
    auto [is_estimate, ess] = importance_sampling(rng, 1000);

    assert(std::abs(is_estimate - 2.0) < 0.3);
    assert(ess > 50.0);

    std::cout << "importance_sampling.cpp PASS" << std::endl;
    return 0;
}
