/*
 * Haversine great-circle distance and initial bearing.
 */

#include <cmath>
#include <cassert>
#include <iostream>

double haversine_distance(double lat1, double lon1, double lat2, double lon2, double radius_km = 6371.0) {
    double lat1_rad = lat1 * M_PI / 180.0;
    double lon1_rad = lon1 * M_PI / 180.0;
    double lat2_rad = lat2 * M_PI / 180.0;
    double lon2_rad = lon2 * M_PI / 180.0;

    double dlat = lat2_rad - lat1_rad;
    double dlon = lon2_rad - lon1_rad;
    double a = std::sin(dlat / 2.0) * std::sin(dlat / 2.0) +
               std::cos(lat1_rad) * std::cos(lat2_rad) *
               std::sin(dlon / 2.0) * std::sin(dlon / 2.0);
    double c = 2.0 * std::asin(std::sqrt(a));
    return radius_km * c;
}

double initial_bearing(double lat1, double lon1, double lat2, double lon2) {
    double lat1_rad = lat1 * M_PI / 180.0;
    double lon1_rad = lon1 * M_PI / 180.0;
    double lat2_rad = lat2 * M_PI / 180.0;
    double lon2_rad = lon2 * M_PI / 180.0;

    double dlon = lon2_rad - lon1_rad;
    double x = std::sin(dlon) * std::cos(lat2_rad);
    double y = std::cos(lat1_rad) * std::sin(lat2_rad) -
               std::sin(lat1_rad) * std::cos(lat2_rad) * std::cos(dlon);
    double bearing_rad = std::atan2(x, y);
    double bearing_deg = bearing_rad * 180.0 / M_PI;
    return std::fmod(bearing_deg + 360.0, 360.0);
}

