/*
 * Bootstrap Confidence Interval for Sample Mean
 * 
 * Resample the observed data WITH replacement many times to build an empirical
 * distribution of sample statistics. Extract quantiles to form a 95% confidence interval.
 */

#include <vector>
#include <random>
#include <algorithm>
#include <cassert>
#include <iostream>
#include <numeric>

std::pair<double, double> bootstrap_ci(
    const std::vector<double>& data,
    int n_boots = 10000,
    double ci = 0.95
) {
    /* Compute bootstrap confidence interval for the sample mean. */
    int n = static_cast<int>(data.size());
    std::vector<double> bootstrap_means;
    bootstrap_means.reserve(n_boots);

    std::mt19937 rng(42);
    std::uniform_int_distribution<int> uniform(0, n - 1);

    for (int b = 0; b < n_boots; ++b) {
        // Resample with replacement
        double sum = 0.0;
        for (int i = 0; i < n; ++i) {
            sum += data[uniform(rng)];
        }
        bootstrap_means.push_back(sum / n);
    }

    // Sort to compute quantiles
    std::sort(bootstrap_means.begin(), bootstrap_means.end());

    // Compute bounds via percentile method
    double alpha = 1.0 - ci;
    int lower_idx = static_cast<int>(alpha / 2.0 * n_boots);
    int upper_idx = static_cast<int>((1.0 - alpha / 2.0) * n_boots);

    double lower_bound = bootstrap_means[lower_idx];
    double upper_bound = bootstrap_means[upper_idx];

    return {lower_bound, upper_bound};
}

int main() {
    std::mt19937 rng(42);
    std::normal_distribution<double> normal(100.0, 15.0);

    // Generate synthetic data: 30 samples from N(100, 15^2)
    const double true_mean = 100.0;
    std::vector<double> sample(30);
    for (int i = 0; i < 30; ++i) {
        sample[i] = normal(rng);
    }

    double observed_mean = std::accumulate(sample.begin(), sample.end(), 0.0) / 30.0;
    auto [lower, upper] = bootstrap_ci(sample, 5000);

    std::cout << "Sample mean: " << observed_mean << ", 95% CI: [" << lower << ", " << upper << "]" << std::endl;

    // Assertion: true mean should fall within CI
    assert(lower < true_mean && true_mean < upper);
    assert(upper - lower > 0.0);
    assert(upper - lower < 30.0);

    std::cout << "Bootstrap CI test PASSED" << std::endl;
    return 0;
}
