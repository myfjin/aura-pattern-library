/*
 * Chi-Square Test of Independence
 * 
 * Test whether two categorical variables are independent.
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <unordered_map>

struct ChiSquareResult {
    double chi2_statistic;
    double p_value_approx;
    bool is_significant;
};

ChiSquareResult chi_square_independence(const std::vector<std::vector<int>>& contingency_table) {
    /* Perform chi-square test of independence. */
    int n_rows = static_cast<int>(contingency_table.size());
    int n_cols = static_cast<int>(contingency_table[0].size());

    // Compute row and column totals
    std::vector<int> row_totals(n_rows, 0);
    std::vector<int> col_totals(n_cols, 0);
    int grand_total = 0;

    for (int i = 0; i < n_rows; ++i) {
        for (int j = 0; j < n_cols; ++j) {
            row_totals[i] += contingency_table[i][j];
            col_totals[j] += contingency_table[i][j];
            grand_total += contingency_table[i][j];
        }
    }

    // Compute chi-square statistic
    double chi2 = 0.0;
    for (int i = 0; i < n_rows; ++i) {
        for (int j = 0; j < n_cols; ++j) {
            int observed = contingency_table[i][j];
            double expected = (static_cast<double>(row_totals[i]) * col_totals[j]) / grand_total;
            if (expected > 0.0) {
                double diff = observed - expected;
                chi2 += diff * diff / expected;
            }
        }
    }

    // Degrees of freedom
    int df = (n_rows - 1) * (n_cols - 1);

    // Critical values for alpha=0.05
    static const std::unordered_map<int, double> critical_values = {
        {1, 3.841}, {2, 5.991}, {3, 7.815}, {4, 9.488}, {5, 11.070},
        {6, 12.592}, {7, 14.067}, {8, 15.507}, {9, 16.919}, {10, 18.307}
    };

    double critical_value = 3.841;  // Default
    auto it = critical_values.find(df);
    if (it != critical_values.end()) {
        critical_value = it->second;
    }

    bool is_significant = chi2 > critical_value;
    double p_value_approx = is_significant ? 0.05 : 0.95;

    return {chi2, p_value_approx, is_significant};
}

int main() {
    // Scenario 1: Independence (no association)
    std::vector<std::vector<int>> table_independent = {
        {10, 10, 10},
        {10, 10, 10}
    };
    auto [chi2_indep, p_indep, sig_indep] = chi_square_independence(table_independent);
    assert(!sig_indep);

    // Scenario 2: Strong association (diagonal dominance)
    std::vector<std::vector<int>> table_assoc = {
        {40, 5, 5},
        {5, 40, 5}
    };
    auto [chi2_assoc, p_assoc, sig_assoc] = chi_square_independence(table_assoc);
    assert(sig_assoc);

    std::cout << "Chi-square test PASSED" << std::endl;
    return 0;
}
