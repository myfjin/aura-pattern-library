#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <functional>

bool msprt_reject(std::function<double()> diff_gen, double alpha, double tau2, double v, int max_n) {
    double s = 0.0;
    for (int n = 1; n <= max_n; ++n) {
        s += diff_gen();
        double lam = std::sqrt(v / (v + n * tau2)) *
                     std::exp(tau2 * s * s / (2.0 * v * (v + n * tau2)));
        if (lam >= 1.0 / alpha) return true;
    }
    return false;
}

bool naive_peek_reject(std::function<double()> diff_gen, double alpha, double v, int max_n) {
    double s = 0.0;
    for (int n = 1; n <= max_n; ++n) {
        s += diff_gen();
        if (n >= 2) {
            double z = s / std::sqrt(v * n);
            double p = std::erfc(std::abs(z) / std::sqrt(2.0));
            if (p < alpha) return true;
        }
    }
    return false;
}

