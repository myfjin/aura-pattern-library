/*
 * Cluster Randomized ICC (Intracluster Correlation)
 * 
 * In cluster randomization, treatment is assigned at the cluster level, not the individual.
 * Intracluster correlation (ICC) means observations within a cluster are not independent,
 * so the naive per-observation SE is too small — its 95% CIs UNDER-cover the true effect.
 * Aggregating to cluster means and testing on those restores nominal coverage.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <utility>

double variance(const std::vector<double>& z) {
    int n = static_cast<int>(z.size());
    if (n < 2) return 0.0;
    double mu = 0.0;
    for (double v : z) mu += v;
    mu /= n;
    double sum_sq = 0.0;
    for (double v : z) {
        double diff = v - mu;
        sum_sq += diff * diff;
    }
    return sum_sq / (n - 1);
}

bool naive_ci_covers(
    const std::vector<double>& t_obs,
    const std::vector<double>& c_obs,
    double true_effect
) {
    /* Per-observation 95% CI for the ATE — ignores clustering (under-covers). */
    double mean_t = 0.0, mean_c = 0.0;
    for (double v : t_obs) mean_t += v;
    for (double v : c_obs) mean_c += v;
    mean_t /= t_obs.size();
    mean_c /= c_obs.size();

    double ate = mean_t - mean_c;
    double se = std::sqrt(variance(t_obs) / t_obs.size() + variance(c_obs) / c_obs.size());
    return std::abs(ate - true_effect) < 1.96 * se;
}

bool cluster_ci_covers(
    const std::vector<double>& t_means,
    const std::vector<double>& c_means,
    double true_effect
) {
    /* Cluster-level 95% CI: test on cluster means (n = #clusters) — correct coverage. */
    double mean_t = 0.0, mean_c = 0.0;
    for (double v : t_means) mean_t += v;
    for (double v : c_means) mean_c += v;
    mean_t /= t_means.size();
    mean_c /= c_means.size();

    double ate = mean_t - mean_c;
    double se = std::sqrt(variance(t_means) / t_means.size() + variance(c_means) / c_means.size());
    return std::abs(ate - true_effect) < 1.96 * se;
}

struct Dataset {
    std::vector<double> t_obs, c_obs, t_means, c_means;
};

Dataset make_dataset(int seed, int n_clusters, int m, double icc, double true_effect) {
    /* One cluster-randomized dataset. Returns (t_obs, c_obs, t_means, c_means). */
    std::mt19937 rng(seed);
    std::normal_distribution<double> normal(0.0, 1.0);

    auto arm = [&](double base) -> std::pair<std::vector<double>, std::vector<double>> {
        std::vector<double> obs, means;
        obs.reserve(n_clusters * m);
        means.reserve(n_clusters);

        for (int i = 0; i < n_clusters; ++i) {
            double cluster_effect = normal(rng) * std::sqrt(icc);
            std::vector<double> vals;
            vals.reserve(m);
            for (int j = 0; j < m; ++j) {
                double v = base + cluster_effect + normal(rng) * std::sqrt(1.0 - icc);
                vals.push_back(v);
                obs.push_back(v);
            }
            double mean = 0.0;
            for (double v : vals) mean += v;
            means.push_back(mean / m);
        }
        return {obs, means};
    };

    auto [t_obs, t_means] = arm(true_effect);
    auto [c_obs, c_means] = arm(0.0);

    return {t_obs, c_obs, t_means, c_means};
}

int main() {
    const int n_clusters = 10, m = 20;
    const double icc = 0.3, true_effect = 2.0;
    const int n_datasets = 400;

    int naive_cov = 0, cluster_cov = 0;

    for (int s = 0; s < n_datasets; ++s) {
        auto [t_obs, c_obs, t_means, c_means] = make_dataset(s, n_clusters, m, icc, true_effect);
        if (naive_ci_covers(t_obs, c_obs, true_effect)) naive_cov++;
        if (cluster_ci_covers(t_means, c_means, true_effect)) cluster_cov++;
    }

    double naive_rate = static_cast<double>(naive_cov) / n_datasets;
    double cluster_rate = static_cast<double>(cluster_cov) / n_datasets;

    // Defining property: naive CI under-covers (ICC ignored); cluster CI covers ~95%.
    assert(naive_rate < 0.85);
    assert(cluster_rate > 0.90);
    assert(cluster_rate > naive_rate);

    std::cout << "cluster_randomized_icc.cpp PASS" << std::endl;
    return 0;
}
