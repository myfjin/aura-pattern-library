/*
 * Holm correction (step-down Bonferroni) for multiple comparisons.
 *
 * Oracle asserts:
 *   fwer_unc_rate > fwer_bonf_rate
 *   fwer_unc_rate > fwer_holm_rate
 *   fwer_bonf_rate, fwer_holm_rate < 0.20
 *   fwer_holm_rate >= fwer_bonf_rate - 0.05
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <algorithm>

std::vector<bool> run_multiple_tests(const std::vector<double>& p_values, const std::string& method) {
    int m = static_cast<int>(p_values.size());
    std::vector<bool> rejections(m, false);
    if (method == "uncorrected") {
        for (int i = 0; i < m; ++i) rejections[i] = p_values[i] < 0.05;
    } else if (method == "bonferroni") {
        double threshold = 0.05 / m;
        for (int i = 0; i < m; ++i) rejections[i] = p_values[i] < threshold;
    } else if (method == "holm") {
        std::vector<int> idx(m);
        for (int i = 0; i < m; ++i) idx[i] = i;
        std::sort(idx.begin(), idx.end(), [&](int a, int b) { return p_values[a] < p_values[b]; });
        for (int rank = 0; rank < m; ++rank) {
            double threshold = 0.05 / (m - rank);
            if (p_values[idx[rank]] < threshold) rejections[idx[rank]] = true;
            else break;
        }
    }
    return rejections;
}

int main() {
    std::mt19937_64 rng(42);
    std::uniform_real_distribution<double> uniform(0.0, 1.0);

    int num_tests = 10, reps = 200;
    int fwer_unc = 0, fwer_bonf = 0, fwer_holm = 0;

    for (int r = 0; r < reps; ++r) {
        std::vector<double> p_values;
        for (int i = 0; i < num_tests; ++i) p_values.push_back(uniform(rng));

        auto unc = run_multiple_tests(p_values, "uncorrected");
        if (std::any_of(unc.begin(), unc.end(), [](bool b) { return b; })) ++fwer_unc;

        auto bonf = run_multiple_tests(p_values, "bonferroni");
        if (std::any_of(bonf.begin(), bonf.end(), [](bool b) { return b; })) ++fwer_bonf;

        auto holm = run_multiple_tests(p_values, "holm");
        if (std::any_of(holm.begin(), holm.end(), [](bool b) { return b; })) ++fwer_holm;
    }

    double fwer_unc_rate = fwer_unc / static_cast<double>(reps);
    double fwer_bonf_rate = fwer_bonf / static_cast<double>(reps);
    double fwer_holm_rate = fwer_holm / static_cast<double>(reps);

    assert(fwer_unc_rate > fwer_bonf_rate);
    assert(fwer_unc_rate > fwer_holm_rate);
    assert(fwer_bonf_rate < 0.20);
    assert(fwer_holm_rate < 0.20);
    assert(fwer_holm_rate >= fwer_bonf_rate - 0.05);

    std::cout << "multi_armed_holm_correction.cpp PASS" << std::endl;
    return 0;
}
