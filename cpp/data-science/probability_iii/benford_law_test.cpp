/*
 * Benford's Law Test
 * 
 * P(digit d) = log₁₀(1 + 1/d) for d ∈ {1,...,9}. Multiplicative data follows;
 * uniform data violates it. Chi-square test.
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>

int leading_digit(double x) {
    /*
     * Extract the leading (most-significant) decimal digit of a number.
     * Scales by powers of 10 into [1, 10).
     */
    x = std::abs(x);
    if (x == 0.0) return 0;
    while (x >= 10.0) x /= 10.0;
    while (x < 1.0) x *= 10.0;
    return static_cast<int>(x);
}

std::vector<double> benford_expected_frequencies(int n) {
    /* Expected frequencies for first digit under Benford's law. */
    std::vector<double> freqs(9);
    for (int d = 1; d <= 9; ++d) {
        freqs[d - 1] = n * std::log10(1.0 + 1.0 / d);
    }
    return freqs;
}

double benford_chi_square_test(const std::vector<double>& data) {
    /* Chi-square statistic for Benford's law fit. */
    std::vector<int> digit_counts(9, 0);
    for (const auto& x : data) {
        int d = leading_digit(x);
        if (d >= 1 && d <= 9) {
            digit_counts[d - 1]++;
        }
    }

    int n = static_cast<int>(data.size());
    auto expected = benford_expected_frequencies(n);

    double chi_sq = 0.0;
    for (int i = 0; i < 9; ++i) {
        if (expected[i] > 0.0) {
            double diff = digit_counts[i] - expected[i];
            chi_sq += diff * diff / expected[i];
        }
    }
    return chi_sq;
}

int main() {
    // Planted: multiplicative data (Benford-like).
    std::vector<double> multiplicative_data(100);
    for (int i = 0; i < 100; ++i) {
        multiplicative_data[i] = std::pow(2.0, i);
    }

    // Planted: uniform-distributed data (not Benford).
    std::vector<double> uniform_data;
    uniform_data.reserve(100);
    double x = 1.0;
    for (int i = 0; i < 100; ++i) {
        uniform_data.push_back(x);
        x += 9.99;  // Simple uniform-like spread
    }

    double chi_mult = benford_chi_square_test(multiplicative_data);
    double chi_unif = benford_chi_square_test(uniform_data);

    // Multiplicative should fit Benford better (lower chi-sq).
    assert(chi_mult < chi_unif);

    std::cout << "benford_law_test.cpp PASS" << std::endl;
    return 0;
}
