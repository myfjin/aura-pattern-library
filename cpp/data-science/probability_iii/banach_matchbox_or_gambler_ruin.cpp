/*
 * Gambler's Ruin
 * 
 * Absorption probability of a bounded ±1 random walk.
 * A gambler starts with wealth a against an opponent with b (total N = a+b); each play
 * moves wealth ±1 (P(+1)=p). "Ruin" = hitting 0 before N.
 * 
 * Core claim: the exact ruin probability matches simulation — verified on an ASYMMETRIC
 * game so the answer is not the self-symmetric ½ (where ruin ≡ survival and any sign error
 * would hide).
 */

#include <cmath>
#include <random>
#include <cassert>
#include <iostream>

double gamblers_ruin_exact(int a, int b, double p = 0.5) {
    /* Exact probability of RUIN (reaching 0 before a+b) starting from wealth a. */
    double q = 1.0 - p;
    int N = a + b;
    
    if (std::abs(p - 0.5) < 1e-10) {
        return static_cast<double>(b) / N;  // fair game: P(hit 0) = (N−a)/N = b/N
    }
    
    double r = q / p;
    // P_i = (r^N − r^i)/(r^N − 1) solves P_i = p·P_{i+1} + q·P_{i−1}, P_0=1, P_N=0.
    return (std::pow(r, N) - std::pow(r, a)) / (std::pow(r, N) - 1.0);
}

double gamblers_ruin_simulate(int a, int b, double p = 0.5, int num_sim = 1000) {
    /* Simulate gambler's ruin; returns the fraction of runs that hit 0. */
    std::mt19937 rng(42);
    std::uniform_real_distribution<double> uniform(0.0, 1.0);
    
    int ruin_count = 0;
    for (int sim = 0; sim < num_sim; ++sim) {
        int wealth = a;
        while (wealth > 0 && wealth < a + b) {
            wealth += (uniform(rng) < p) ? 1 : -1;
        }
        if (wealth == 0) {
            ruin_count++;
        }
    }
    return static_cast<double>(ruin_count) / num_sim;
}

int main() {
    // ASYMMETRIC fair game: a=5, b=15 ⇒ P(ruin) = 15/20 = 0.75 (NOT 0.5)
    int a = 5, b = 15;
    double exact_fair = gamblers_ruin_exact(a, b, 0.5);
    double sim_fair = gamblers_ruin_simulate(a, b, 0.5, 20000);
    
    assert(std::abs(exact_fair - static_cast<double>(b) / (a + b)) < 1e-9);
    assert(std::abs(exact_fair - sim_fair) < 0.03);
    
    // BIASED game favoring the gambler (p=0.6): ruin should be small (< 0.1).
    double exact_biased = gamblers_ruin_exact(10, 10, 0.6);
    double sim_biased = gamblers_ruin_simulate(10, 10, 0.6, 20000);
    
    assert(exact_biased < 0.1);
    assert(std::abs(exact_biased - sim_biased) < 0.03);
    
    std::cout << "gambler's_ruin.cpp PASS" << std::endl;
    return 0;
}
