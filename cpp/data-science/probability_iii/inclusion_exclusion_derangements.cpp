#include <cmath>
#include <cassert>
#include <iostream>

double factorial(int n) {
    double r = 1.0;
    for (int i = 2; i <= n; ++i) r *= i;
    return r;
}

double derangements_exact(int n) {
    if (n == 0) return 1.0;
    if (n == 1) return 0.0;
    double total = 0.0;
    for (int k = 0; k <= n; ++k) {
        double sign = (k % 2 == 0) ? 1.0 : -1.0;
        total += sign / factorial(k);
    }
    return std::round(factorial(n) * total);
}

