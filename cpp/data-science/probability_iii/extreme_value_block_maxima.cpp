std::pair<double,double> fit_gumbel(const std::vector<double>& block_maxima) {
    size_t n = block_maxima.size();
    double mean = 0.0;
    for (double x : block_maxima) mean += x;
    mean /= static_cast<double>(n);
    double variance = 0.0;
    for (double x : block_maxima) { double d = x - mean; variance += d*d; }
    variance /= static_cast<double>(n);
    const double gamma_euler = 0.5772;
    double sigma = std::sqrt(6.0 * variance) / M_PI;
    double mu = mean - gamma_euler * sigma;
    return {mu, sigma};
}

double gumbel_cdf(double x, double mu, double sigma) {
    if (sigma <= 0) return 0.0;
    return std::exp(-std::exp(-(x - mu) / sigma));
}

double gumbel_return_level(double T, double mu, double sigma) {
    return mu - sigma * std::log(std::log(T / (T - 1.0)));
}

