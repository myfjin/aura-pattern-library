#include <cassert>
#include <cmath>
#include <iostream>
#include <random>
#include <vector>
#include <tuple>

using namespace std;

static mt19937 rng(42);
static normal_distribution<double> noise(0.0, 10.0);

static double mean(const vector<double>& v) {
    double s = 0;
    for (double x : v) s += x;
    return s / v.size();
}

static tuple<vector<double>, vector<double>, vector<double>, vector<double>>
simulate_did_data(int n_per_group, double treatment_effect, double time_effect) {
    vector<double> pre_control, pre_treated, post_control, post_treated;
    for (int i = 0; i < n_per_group; ++i) {
        double pc = 100.0 + noise(rng);
        double pt = 100.0 + noise(rng);
        pre_control.push_back(pc);
        pre_treated.push_back(pt);
        post_control.push_back(pc + time_effect + noise(rng));
        post_treated.push_back(pt + time_effect + treatment_effect + noise(rng));
    }
    return {pre_control, post_control, pre_treated, post_treated};
}

static double estimate_did(const vector<double>& pre_control,
                           const vector<double>& post_control,
                           const vector<double>& pre_treated,
                           const vector<double>& post_treated) {
    double treated_change = mean(post_treated) - mean(pre_treated);
    double control_change = mean(post_control) - mean(pre_control);
    return treated_change - control_change;
}

int main() {
    const double treatment_effect = 20.0;
    const double time_trend = 5.0;

    auto [pre_c, post_c, pre_t, post_t] = simulate_did_data(100, treatment_effect, time_trend);
    double did_estimate = estimate_did(pre_c, post_c, pre_t, post_t);
    double bias = fabs(did_estimate - treatment_effect);
    assert(bias < 3.0);

    assert(estimate_did(pre_c, pre_c, pre_t, pre_t) < 1.0);
    double control_only_effect = estimate_did(pre_c, post_c, pre_c, post_c);
    assert(fabs(control_only_effect) < 2.0);

    cout << "True treatment effect: " << treatment_effect
         << " | DiD estimate: " << did_estimate
         << " | Bias: " << bias
         << " | Pre-period DiD: " << estimate_did(pre_c, pre_c, pre_t, pre_t)
         << " | PASS\n";
    return 0;
}
