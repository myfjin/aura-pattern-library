using VecD = std::vector<double>;
using VecI = std::vector<int>;

static double logistic(double x) {
    if (x >= 0.0) {
        double z = std::exp(-x);
        return 1.0 / (1.0 + z);
    } else {
        double z = std::exp(x);
        return z / (1.0 + z);
    }
}

// estimate_propensity_scores intentionally kept for parity with Python oracle but unused here

static std::pair<VecI, VecI> match_on_propensity(
    const VecD& ps, const VecI& T, double caliper) {
    std::vector<std::size_t> treated, control;
    for (std::size_t i = 0; i < T.size(); ++i) {
        if (T[i] == 1) treated.push_back(i);
        else control.push_back(i);
    }
    VecI matched_t, matched_c;
    std::set<std::size_t> used_control;
    for (std::size_t t_idx : treated) {
        double ps_t = ps[t_idx];
        int best_c = -1;
        double best_dist = caliper;
        for (std::size_t c_idx : control) {
            if (used_control.count(c_idx)) continue;
            double dist = std::abs(ps[c_idx] - ps_t);
            if (dist < best_dist) {
                best_dist = dist;
                best_c = static_cast<int>(c_idx);
            }
        }
        if (best_c >= 0) {
            matched_t.push_back(static_cast<int>(t_idx));
            matched_c.push_back(best_c);
            used_control.insert(static_cast<std::size_t>(best_c));
        }
    }
    return {matched_t, matched_c};
}

static double mean_group(const VecD& Y, const VecI& idxs) {
    double s = 0.0;
    for (int i : idxs) s += Y[static_cast<std::size_t>(i)];
    return s / static_cast<double>(idxs.size());
}

static double estimate_ate_naive(const VecI& T, const VecD& Y) {
    VecI y1, y0;
    for (std::size_t i = 0; i < T.size(); ++i) {
        if (T[i] == 1) y1.push_back(static_cast<int>(i));
        else y0.push_back(static_cast<int>(i));
    }
    return mean_group(Y, y1) - mean_group(Y, y0);
}

static double estimate_ate_matched(const VecD& Y,
                                   const VecI& matched_t,
                                   const VecI& matched_c) {
    return mean_group(Y, matched_t) - mean_group(Y, matched_c);
}

