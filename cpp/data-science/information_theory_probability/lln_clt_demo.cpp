#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <algorithm>

double empirical_mean(const std::vector<double>& samples) {
    double s = 0.0;
    for (double x : samples) s += x;
    return s / samples.size();
}

double empirical_std(const std::vector<double>& samples) {
    if (samples.size() < 2) return 0.0;
    double m = empirical_mean(samples);
    double s = 0.0;
    for (double x : samples) s += (x - m) * (x - m);
    return std::sqrt(s / (samples.size() - 1));
}

double coverage_percentile(const std::vector<double>& samples, double true_mean, double num_stds) {
    double sd = empirical_std(samples);
    if (sd < 1e-10) return 0.0;
    int within = 0;
    for (double x : samples) if (std::abs(x - true_mean) <= num_stds * sd) ++within;
    return within / static_cast<double>(samples.size());
}

double skewness(const std::vector<double>& samples) {
    if (samples.size() < 3) return 0.0;
    double m = empirical_mean(samples);
    double sd = empirical_std(samples);
    if (sd < 1e-10) return 0.0;
    double third = 0.0;
    for (double x : samples) third += std::pow(x - m, 3);
    third /= samples.size();
    return third / std::pow(sd, 3);
}

std::vector<double> sample_means(const std::vector<double>& source,
                                  int sample_size, int num_samples,
                                  std::mt19937_64& rng) {
    std::vector<double> means;
    std::uniform_int_distribution<size_t> pick(0, source.size() - 1);
    for (int i = 0; i < num_samples; ++i) {
        double s = 0.0;
        for (int j = 0; j < sample_size; ++j) s += source[pick(rng)];
        means.push_back(s / sample_size);
    }
    return means;
}

