/*
 * Hybrid Bisection–Newton Root-Finding
 * 
 * Combines bisection's guaranteed convergence with Newton's speed: bisect when
 * Newton drift is detected, switch back when safe.
 */

#include <cmath>
#include <functional>
#include <cassert>
#include <iostream>
#include <stdexcept>

double bisection_newton_hybrid(
    std::function<double(double)> f,
    std::function<double(double)> df,
    double a,
    double b,
    double tol = 1e-8,
    int max_iter = 100
) {
    /* Find root of f in [a, b] using hybrid bisection–Newton. */
    if (f(a) * f(b) > 0) {
        throw std::invalid_argument("f(a) and f(b) must have opposite signs");
    }

    double x = (a + b) / 2.0;

    for (int iteration = 0; iteration < max_iter; ++iteration) {
        double fx = f(x);
        if (std::abs(fx) < tol) {
            return x;
        }

        double dfx = df(x);
        if (std::abs(dfx) < 1e-14) {
            x = (a + b) / 2.0;
            continue;
        }

        double x_newton = x - fx / dfx;

        if (x_newton >= a && x_newton <= b && std::abs(x_newton - x) < (b - a) / 4.0) {
            x = x_newton;
        } else {
            x = (a + b) / 2.0;
            if (f(a) * f(x) < 0) {
                b = x;
            } else {
                a = x;
            }
        }
    }

    return x;
}

