/*
 * Adaptive Simpson's rule: automatic step refinement via error estimation.
 *
 * Compares Simpson's estimate on [a, b] with two estimates on [a, c] and [c, b].
 * If error is acceptable, return result; else recurse. Typical result: O(h⁴)
 * accuracy with far fewer function evals than fixed-step methods.
 */

#include <iostream>
#include <cmath>
#include <cassert>
#include <iomanip>

using namespace std;

// Basic Simpson's rule on [a, b]: (b-a) * (f(a) + 4*f(mid) + f(b)) / 6
double simpson_basic(double (*f)(double), double a, double b) {
    double mid = (a + b) / 2.0;
    return (b - a) * (f(a) + 4.0*f(mid) + f(b)) / 6.0;
}

// Recursively refine Simpson estimate until error < tol
double adaptive_simpson_recursive(double (*f)(double), double a, double b, 
                                   double tol, double whole, int depth = 0) {
    if (depth > 50) {
        return whole;
    }
    
    double mid = (a + b) / 2.0;
    double left = simpson_basic(f, a, mid);
    double right = simpson_basic(f, mid, b);
    double cumulative = left + right;
    
    // Error estimate: |cumulative - whole| / 15
    if (abs(cumulative - whole) <= 15.0 * tol) {
        return cumulative + (cumulative - whole) / 15.0;
    }
    
    return adaptive_simpson_recursive(f, a, mid, tol / 2.0, left, depth + 1) +
           adaptive_simpson_recursive(f, mid, b, tol / 2.0, right, depth + 1);
}

// Integrate f over [a, b] with adaptive Simpson's rule
double adaptive_simpson(double (*f)(double), double a, double b, double tol = 1e-6) {
    double whole = simpson_basic(f, a, b);
    return adaptive_simpson_recursive(f, a, b, tol, whole);
}

