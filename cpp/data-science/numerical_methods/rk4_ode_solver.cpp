/*
 * Fourth-order Runge-Kutta (RK4) solver for scalar ODEs y'=f(t,y). Each step
 * combines four slope samples (k1..k4) across the interval into a weighted average,
 * giving O(h^4) local accuracy — far better than Euler for the same step count.
 * Use to integrate initial-value problems where accuracy per step matters. Guarantee
 * (proven in main): integrating y'=-2y from y(0)=1 over 100 steps reproduces the
 * analytic solution e^-2 at t=1 to within 1e-5.
 */
#include <iostream>
#include <vector>
#include <cmath>
#include <cassert>
#include <functional>

using Func = std::function<double(double, double)>;

double rk4Step(Func f, double t, double y, double h) {
    double k1 = f(t, y);
    double k2 = f(t + h / 2.0, y + (h / 2.0) * k1);
    double k3 = f(t + h / 2.0, y + (h / 2.0) * k2);
    double k4 = f(t + h, y + h * k3);
    return y + (h / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4);
}

std::pair<std::vector<double>, std::vector<double>> rk4OdeSolver(
    Func f, double t0, double y0, double t_final, int num_steps) {
    double h = (t_final - t0) / num_steps;
    std::vector<double> t_vals = {t0}, y_vals = {y0};
    double t = t0, y = y0;
    for (int i = 0; i < num_steps; ++i) {
        y = rk4Step(f, t, y, h);
        t += h;
        t_vals.push_back(t);
        y_vals.push_back(y);
    }
    return {t_vals, y_vals};
}

int main() {
    auto f_planted = [](double t, double y) { (void)t; return -2.0 * y; };
    auto result = rk4OdeSolver(f_planted, 0.0, 1.0, 1.0, 100);
    double y_final = result.second.back();
    double expected = std::exp(-2.0);
    assert(std::abs(y_final - expected) < 1e-5);
    std::cout << "RK4_ODE_SOLVER PASS: y(1) = " << y_final << " expected " << expected << "\n";
    return 0;
}
