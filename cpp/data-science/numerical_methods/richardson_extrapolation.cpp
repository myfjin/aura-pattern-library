// Planted: ∫₀¹ x³ dx = 1/4.
double f_planted(double x) {
    return x * x * x;
}

// Midpoint rule: O(h²) error.
double midpoint_rule(double a, double b, double h) {
    int n = static_cast<int>((b - a) / h);
    if (n == 0) return 0.0;
    double result = 0.0;
    for (int i = 0; i < n; ++i) {
        double x_mid = a + i * h + h / 2.0;
        result += f_planted(x_mid) * h;
    }
    return result;
}

double make_integrator(double h) {
    return midpoint_rule(0.0, 1.0, h);
}

// Richardson extrapolation with error order p under step halving.
double richardson_extrapolate(double (*F)(double), double h, int p) {
    double f_h = F(h);
    double f_h_half = F(h / 2.0);
    double factor = std::pow(2.0, p);
    return (factor * f_h_half - f_h) / (factor - 1.0);
}

