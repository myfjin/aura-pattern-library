double gauss_legendre_4(std::function<double(double)> f, double a, double b) {
    const double nodes[4] = {-0.8611363115940526, -0.3399810435848563, 0.3399810435848563, 0.8611363115940526};
    const double weights[4] = {0.3478548451374538, 0.6521451548625460, 0.6521451548625460, 0.3478548451374538};

    double scale = (b - a) / 2.0;
    double shift = (a + b) / 2.0;

    double result = 0.0;
    for (int i = 0; i < 4; ++i) {
        result += weights[i] * f(shift + nodes[i] * scale);
    }
    return result * scale;
}

