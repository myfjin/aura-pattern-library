/* Fixed-point iteration: find x where g(x) = x. */
#include <cmath>
#include <cassert>
#include <iostream>

double fixed_point_iteration(double (*g)(double), double x0, double tol, int max_iter) {
    double x = x0;
    for (int i = 0; i < max_iter; ++i) {
        double x_next = g(x);
        if (std::abs(x_next - x) < tol) return x_next;
        x = x_next;
    }
    return x;
}

