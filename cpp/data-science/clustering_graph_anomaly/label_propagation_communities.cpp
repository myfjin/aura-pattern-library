/*
 * Label Propagation for Community Detection from scratch.
 *
 * Oracle asserts:
 *   num_communities >= 2
 *   c1_recovery >= 0.5
 *   c2_recovery >= 0.5
 */

#include <map>
#include <vector>
#include <cassert>
#include <iostream>
#include <algorithm>
#include <random>

std::map<int, int> label_propagation(
    const std::map<int, std::vector<int>>& graph,
    int max_iterations = 100,
    int seed = 42) {

    std::mt19937_64 rng(seed);
    std::vector<int> nodes;
    for (const auto& kv : graph) nodes.push_back(kv.first);
    std::map<int, int> labels;
    for (int node : nodes) labels[node] = node;

    for (int iter = 0; iter < max_iterations; ++iter) {
        auto old_labels = labels;
        std::shuffle(nodes.begin(), nodes.end(), rng);
        for (int node : nodes) {
            std::map<int, int> counts;
            for (int neighbor : graph.at(node)) ++counts[labels[neighbor]];
            if (!counts.empty()) {
                int max_count = 0;
                for (const auto& kv : counts) max_count = std::max(max_count, kv.second);
                std::vector<int> most_common;
                for (const auto& kv : counts) if (kv.second == max_count) most_common.push_back(kv.first);
                std::uniform_int_distribution<int> pick(0, static_cast<int>(most_common.size()) - 1);
                labels[node] = most_common[pick(rng)];
            }
        }
        if (labels == old_labels) break;
    }
    return labels;
}

int main() {
    std::map<int, std::vector<int>> graph = {
        {0, {1, 2}}, {1, {0, 2, 3}}, {2, {0, 1, 3}}, {3, {1, 2, 4}},
        {4, {3, 5, 6}}, {5, {4, 6, 7}}, {6, {4, 5, 7}}, {7, {5, 6}}
    };

    auto labels = label_propagation(graph, 50, 42);

    std::map<int, std::vector<int>> communities;
    for (const auto& kv : labels) communities[kv.second].push_back(kv.first);

    assert(communities.size() >= 2);

    std::vector<int> c1_nodes = {0, 1, 2, 3};
    std::vector<int> c2_nodes = {4, 5, 6, 7};

    auto match = [](const std::vector<int>& comm, const std::vector<int>& true_set) {
        int hits = 0;
        for (int n : comm) if (std::find(true_set.begin(), true_set.end(), n) != true_set.end()) ++hits;
        return static_cast<double>(hits) / true_set.size();
    };

    double best_c1 = 0.0, best_c2 = 0.0;
    for (const auto& kv : communities) {
        best_c1 = std::max(best_c1, match(kv.second, c1_nodes));
        best_c2 = std::max(best_c2, match(kv.second, c2_nodes));
    }

    assert(best_c1 >= 0.5);
    assert(best_c2 >= 0.5);

    std::cout << "label_propagation_communities.cpp PASS" << std::endl;
    return 0;
}
