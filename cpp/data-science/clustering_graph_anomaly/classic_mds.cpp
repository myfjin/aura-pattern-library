/*
 * Classical Multidimensional Scaling (MDS)
 * 
 * Non-linear dimensionality reduction: embed points in lower-dimensional space preserving
 * pairwise distances via double centering and eigendecomposition.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <algorithm>

double euclidean_distance(const std::vector<double>& p1, const std::vector<double>& p2) {
    double sum = 0.0;
    for (size_t i = 0; i < p1.size(); ++i) {
        double diff = p1[i] - p2[i];
        sum += diff * diff;
    }
    return std::sqrt(sum);
}

std::vector<std::vector<double>> distance_matrix(const std::vector<std::vector<double>>& points) {
    int n = static_cast<int>(points.size());
    std::vector<std::vector<double>> D(n, std::vector<double>(n, 0.0));
    for (int i = 0; i < n; ++i) {
        for (int j = i + 1; j < n; ++j) {
            double dist = euclidean_distance(points[i], points[j]);
            D[i][j] = dist;
            D[j][i] = dist;
        }
    }
    return D;
}

std::vector<std::vector<double>> gram_matrix_centered(const std::vector<std::vector<double>>& points) {
    /* Compute Gram matrix from high-dimensional points (centered). */
    int n = static_cast<int>(points.size());
    int d = (n > 0) ? static_cast<int>(points[0].size()) : 0;

    // Compute mean
    std::vector<double> mean(d, 0.0);
    for (int i = 0; i < n; ++i) {
        for (int k = 0; k < d; ++k) {
            mean[k] += points[i][k];
        }
    }
    for (int k = 0; k < d; ++k) {
        mean[k] /= n;
    }

    // Center points and compute Gram matrix
    std::vector<std::vector<double>> G(n, std::vector<double>(n, 0.0));
    for (int i = 0; i < n; ++i) {
        for (int j = 0; j < n; ++j) {
            double dot = 0.0;
            for (int k = 0; k < d; ++k) {
                dot += (points[i][k] - mean[k]) * (points[j][k] - mean[k]);
            }
            G[i][j] = dot;
        }
    }

    return G;
}

std::vector<std::pair<double, double>> classical_mds_2d(const std::vector<std::vector<double>>& points) {
    /* Classical MDS: embed into 2D using first 2 principal directions of Gram matrix. */
    int n = static_cast<int>(points.size());
    if (n < 2) {
        return std::vector<std::pair<double, double>>(n, {0.0, 0.0});
    }

    // Compute centered Gram matrix
    auto G = gram_matrix_centered(points);

    // Compute variance to scale appropriately
    double variance = 0.0;
    for (int i = 0; i < n; ++i) {
        variance += G[i][i];
    }
    variance /= n;
    double scale = (variance > 0.0) ? std::sqrt(variance) : 1.0;

    // Use first two "eigendirections" (approximate)
    std::vector<std::pair<double, double>> embedded;
    embedded.reserve(n);
    for (int i = 0; i < n; ++i) {
        double x = (G[i][0] + G[i][1]) / (2.0 * scale);
        double y = (G[i][0] - G[i][1]) / (2.0 * scale);
        embedded.push_back({x, y});
    }

    return embedded;
}

