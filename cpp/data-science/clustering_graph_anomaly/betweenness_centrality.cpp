/*
 * Betweenness Centrality
 * 
 * Measures how often a node lies on shortest paths between other nodes.
 * High betweenness indicates a "bridge" or connector node.
 */

#include <vector>
#include <map>
#include <queue>
#include <algorithm>
#include <cassert>
#include <iostream>
#include <limits>

std::map<int, double> betweenness_centrality(const std::map<int, std::vector<int>>& graph) {
    /*
     * Compute betweenness centrality for all nodes.
     * For each node v, count how many shortest paths between all pairs (s,t) pass through v.
     */
    std::vector<int> nodes;
    for (const auto& kv : graph) {
        nodes.push_back(kv.first);
    }
    int n = static_cast<int>(nodes.size());

    std::map<int, double> betweenness;
    for (int node : nodes) {
        betweenness[node] = 0.0;
    }

    // For each source node s
    for (int s : nodes) {
        // BFS to find distances and count shortest paths
        std::map<int, double> distances;
        std::map<int, int> path_counts;
        std::map<int, std::vector<int>> predecessors;

        for (int node : nodes) {
            distances[node] = std::numeric_limits<double>::infinity();
            path_counts[node] = 0;
            predecessors[node] = {};
        }

        distances[s] = 0;
        path_counts[s] = 1;

        std::queue<int> q;
        q.push(s);

        while (!q.empty()) {
            int u = q.front();
            q.pop();

            auto it = graph.find(u);
            if (it == graph.end()) continue;

            for (int v : it->second) {
                if (distances[v] == std::numeric_limits<double>::infinity()) {
                    distances[v] = distances[u] + 1;
                    q.push(v);
                }

                if (distances[v] == distances[u] + 1) {
                    predecessors[v].push_back(u);
                    path_counts[v] += path_counts[u];
                }
            }
        }

        // Dependency accumulation (reverse topological order)
        std::map<int, double> dependency;
        for (int node : nodes) {
            dependency[node] = 0.0;
        }

        std::sort(nodes.begin(), nodes.end(), [&](int a, int b) {
            return distances[a] > distances[b];
        });

        for (int w : nodes) {
            if (w != s) {
                for (int v : predecessors[w]) {
                    if (path_counts[w] > 0) {
                        dependency[v] += (static_cast<double>(path_counts[v]) / path_counts[w]) 
                                        * (1.0 + dependency[w]);
                    }
                }
            }
        }

        for (int node : nodes) {
            if (node != s) {
                betweenness[node] += dependency[node];
            }
        }
    }

    // Normalize by (n-1)(n-2)/2 for undirected
    double scale = (n > 2) ? 2.0 / ((n - 1) * (n - 2)) : 1.0;
    for (auto& kv : betweenness) {
        kv.second *= scale;
    }

    return betweenness;
}

int main() {
    // Create a graph with an obvious bridge: node 5 connects two clusters
    std::map<int, std::vector<int>> graph = {
        {0, {1, 2, 3, 5}},
        {1, {0, 2, 3, 5}},
        {2, {0, 1, 3, 5}},
        {3, {0, 1, 2, 5}},
        {5, {0, 1, 2, 3, 6, 7, 8, 9}},
        {6, {5, 7, 8, 9}},
        {7, {5, 6, 8, 9}},
        {8, {5, 6, 7, 9}},
        {9, {5, 6, 7, 8}},
    };

    auto betweenness = betweenness_centrality(graph);

    // Node 5 should have the highest betweenness (bridge between clusters)
    int max_node = 0;
    double max_score = -1.0;
    for (const auto& kv : betweenness) {
        if (kv.second > max_score) {
            max_score = kv.second;
            max_node = kv.first;
        }
    }

    assert(max_node == 5);
    assert(betweenness[5] > betweenness[0]);
    assert(betweenness[5] > betweenness[6]);

    std::cout << "betweenness_centrality.cpp: bridge node 5 identified (score " 
              << betweenness[5] << ") PASS" << std::endl;
    return 0;
}
