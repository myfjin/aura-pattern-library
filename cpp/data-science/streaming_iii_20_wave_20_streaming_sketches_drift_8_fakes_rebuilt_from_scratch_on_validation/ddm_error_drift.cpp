/* DDM (Drift Detection Method): detect concept drift via error rate monitoring.
 *
 * Core claim: DDM detects drift after sufficient samples, no false alarm on stationary.
 */
#include <cassert>
#include <cmath>
#include <iostream>
#include <random>
#include <vector>

std::pair<bool, int> ddm_error_drift(
    const std::vector<int>& error_stream,
    int min_samples = 30
) {
    assert(min_samples > 0);
    
    int n_err = 0;
    double p_min = 1e300;
    double s_min = 1e300;
    
    for (size_t i = 0; i < error_stream.size(); ++i) {
        n_err += error_stream[i];
        int n = static_cast<int>(i) + 1;
        double p = static_cast<double>(n_err) / n;
        double s = std::sqrt(p * (1.0 - p) / n);
        
        if (n < min_samples) continue;
        
        if (p + s < p_min + s_min) {
            p_min = p;
            s_min = s;
        }
        
        if (p + s >= p_min + 3.0 * s_min) {
            return {true, static_cast<int>(i)};
        }
    }
    return {false, -1};
}

int main() {
    std::mt19937 gen(42);
    std::uniform_real_distribution<double> uniform(0.0, 1.0);
    
    // Stationary: Bernoulli(0.15) error throughout
    std::vector<int> stationary;
    for (int i = 0; i < 600; ++i) {
        stationary.push_back(uniform(gen) < 0.15 ? 1 : 0);
    }
    
    // Drift: error jumps 0.10 -> 0.40 at index 400
    std::vector<int> drift;
    for (int i = 0; i < 400; ++i) {
        drift.push_back(uniform(gen) < 0.10 ? 1 : 0);
    }
    for (int i = 0; i < 300; ++i) {
        drift.push_back(uniform(gen) < 0.40 ? 1 : 0);
    }
    
    auto [det_s, idx_s] = ddm_error_drift(stationary);
    auto [det_d, idx_d] = ddm_error_drift(drift);
    
    assert(!det_s);
    assert(det_d && idx_d >= 400);
    
    std::cout << "DDM PASS" << std::endl;
    return 0;
}
