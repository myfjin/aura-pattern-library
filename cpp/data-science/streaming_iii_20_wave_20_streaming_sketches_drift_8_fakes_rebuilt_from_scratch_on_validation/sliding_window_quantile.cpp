// Exact sliding-window quantile via sorted-window maintenance.

double compute_quantile(const std::vector<double>& sorted_batch, double q) {
    if (sorted_batch.empty()) return 0.0;
    if (sorted_batch.size() == 1) return sorted_batch[0];
    double idx = q * (static_cast<double>(sorted_batch.size()) - 1.0);
    size_t lower = static_cast<size_t>(std::floor(idx));
    size_t upper = static_cast<size_t>(std::ceil(idx));
    if (lower == upper) return sorted_batch[lower];
    double alpha = idx - static_cast<double>(lower);
    return sorted_batch[lower] * (1.0 - alpha) + sorted_batch[upper] * alpha;
}

double sliding_window_quantile(const std::vector<double>& stream, int window_size, double q) {
    assert(q >= 0.0 && q <= 1.0 && window_size > 0);

    std::vector<double> batch;
    if (stream.size() < static_cast<size_t>(window_size)) {
        batch = stream;
    } else {
        batch.assign(stream.end() - window_size, stream.end());
    }
    std::sort(batch.begin(), batch.end());
    double true_quantile = compute_quantile(batch, q);

    std::deque<double> window;
    for (double val : stream) {
        window.push_back(val);
        if (window.size() > static_cast<size_t>(window_size)) window.pop_front();
    }

    std::vector<double> sorted_window(window.begin(), window.end());
    std::sort(sorted_window.begin(), sorted_window.end());
    double measured_quantile = compute_quantile(sorted_window, q);

    assert(std::abs(measured_quantile - true_quantile) < 1e-9);
    return measured_quantile;
}

