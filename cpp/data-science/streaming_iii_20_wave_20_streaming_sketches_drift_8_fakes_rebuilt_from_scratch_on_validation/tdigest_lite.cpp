// t-digest (merging variant) -- accurate tail quantiles in small space.
// deterministic: fixed seed and fixed synthetic stream.

static double tdigest_quantile(const vector<pair<double,int>>& centroids, double q) {
    long long total = 0;
    for (const auto& c : centroids) total += c.second;
    double target = q * (double)total;
    double cum = 0.0;
    double prev_center = centroids[0].first;
    double prev_q = 0.0;
    for (size_t i = 0; i < centroids.size(); ++i) {
        double mean = centroids[i].first;
        int count = centroids[i].second;
        double center = cum + count / 2.0;
        if (center >= target) {
            if (center == prev_q) return mean;
            double frac = (target - prev_q) / (center - prev_q);
            return prev_center + frac * (mean - prev_center);
        }
        prev_center = mean;
        prev_q = center;
        cum += count;
    }
    return centroids.back().first;
}

static vector<pair<double,int>> build_tdigest(const vector<double>& sorted_vals, double compression) {
    size_t n = sorted_vals.size();
    double delta = 1.0 / compression;
    vector<pair<double,int>> centroids;
    double c_mean = sorted_vals[0];
    int c_count = 1;
    double cum = 0.0;
    for (size_t i = 1; i < n; ++i) {
        double x = sorted_vals[i];
        double q = (cum + (c_count + 1) / 2.0) / (double)n;
        double limit = 4.0 * (double)n * delta * q * (1.0 - q);
        if ((double)(c_count + 1) <= max(1.0, limit)) {
            c_mean = (c_mean * c_count + x) / (c_count + 1);
            c_count += 1;
        } else {
            centroids.emplace_back(c_mean, c_count);
            cum += (double)c_count;
            c_mean = x;
            c_count = 1;
        }
    }
    centroids.emplace_back(c_mean, c_count);
    return centroids;
}

