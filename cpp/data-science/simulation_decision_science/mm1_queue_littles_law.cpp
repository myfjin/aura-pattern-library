#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>

void mm1_queue_littles_law() {
    std::mt19937_64 rng(42);
    std::exponential_distribution<double> arrivals(0.8);
    std::exponential_distribution<double> service(1.0);

    double lambda_rate = 0.8;
    double mu_rate = 1.0;
    double rho = lambda_rate / mu_rate;

    int n_arrivals = 1000;
    std::vector<std::pair<double, double>> queue;
    double time_now = 0.0;
    double total_time_in_system = 0.0;

    for (int i = 0; i < n_arrivals; ++i) {
        time_now += arrivals(rng);
        double svc = service(rng);
        double time_served;
        if (queue.empty()) {
            time_served = time_now + svc;
            total_time_in_system += svc;
        } else {
            double prev_end = queue.back().second;
            double wait = std::max(0.0, prev_end - time_now);
            time_served = time_now + wait + svc;
            total_time_in_system += wait + svc;
        }
        queue.push_back({time_now, time_served});
    }

    double L = total_time_in_system / n_arrivals;
    double W = L / lambda_rate;
    double littles_law_check = std::abs(lambda_rate * W - L) / L;
    assert(littles_law_check < 0.3);

    double expected_w = 1.0 / (mu_rate * (1.0 - rho));
    double expected_l = rho / (1.0 - rho);
    assert(W > 0.5 * expected_w && W < 2.0 * expected_w);
    assert(L > 0.5 * expected_l && L < 2.0 * expected_l);

    std::cout << "mm1_queue_littles_law.cpp PASS" << std::endl;
}

