// Discrete SIR epidemic model with conservation checks and R0 comparison.

struct SIRResult {
    std::vector<int> S_history;
    std::vector<int> I_history;
    std::vector<int> R_history;
};

static SIRResult simulate_sir(int N, double beta, double gamma, int n_steps = 100) {
    int S = N - 1;
    int I = 1;
    int R = 0;

    SIRResult res;
    res.S_history.push_back(S);
    res.I_history.push_back(I);
    res.R_history.push_back(R);

    for (int step = 0; step < n_steps; ++step) {
        int infections = 0;
        if (S > 0 && I > 0) {
            const int contact_rate = 5;
            int contacts = static_cast<int>(contact_rate * static_cast<double>(S) * I / N);
            infections = std::min(static_cast<int>(beta * contacts), S);
        }

        int recoveries = (I > 0) ? std::min(static_cast<int>(gamma * I), I) : 0;

        S -= infections;
        I += infections - recoveries;
        R += recoveries;

        res.S_history.push_back(S);
        res.I_history.push_back(I);
        res.R_history.push_back(R);

        assert(S + I + R == N);

        if (I == 0) break;
    }

    return res;
}

