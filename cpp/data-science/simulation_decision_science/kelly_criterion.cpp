/*
 * Kelly Criterion: optimal betting fraction for long-run log-growth.
 *
 * Oracle asserts:
 *   med_k > med_o
 *   logg_k > logg_o
 *   paired_wins / n_paths > 0.6
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <algorithm>

double simulate_wealth(double fraction, int n_bets, int seed_offset,
                       double p_win, double odds) {
    std::mt19937_64 rng(static_cast<uint64_t>(42 + seed_offset));
    std::uniform_real_distribution<double> dist(0.0, 1.0);
    double wealth = 1.0;
    for (int i = 0; i < n_bets; ++i) {
        if (dist(rng) < p_win) wealth *= (1.0 + fraction * odds);
        else wealth *= (1.0 - fraction);
    }
    return wealth;
}

int main() {
    double p_win = 0.6, p_lose = 0.4, odds = 1.0;
    double kelly_f = (p_win * odds - p_lose) / odds;

    int n_bets = 100, n_paths = 300;
    std::vector<double> term_k, term_o;
    int paired_wins = 0;
    for (int path = 0; path < n_paths; ++path) {
        double wk = simulate_wealth(kelly_f, n_bets, path, p_win, odds);
        double wo = simulate_wealth(2.0 * kelly_f, n_bets, path, p_win, odds);
        term_k.push_back(wk);
        term_o.push_back(wo);
        if (wk > wo) ++paired_wins;
    }

    std::sort(term_k.begin(), term_k.end());
    std::sort(term_o.begin(), term_o.end());
    double med_k = term_k[n_paths / 2];
    double med_o = term_o[n_paths / 2];

    double logg_k = 0.0, logg_o = 0.0;
    for (double w : term_k) logg_k += std::log(w);
    for (double w : term_o) logg_o += std::log(w);
    logg_k /= n_paths;
    logg_o /= n_paths;

    assert(med_k > med_o);
    assert(logg_k > logg_o);
    assert(static_cast<double>(paired_wins) / n_paths > 0.6);

    std::cout << "kelly_criterion.cpp PASS: med_K=" << med_k
              << " med_2K=" << med_o << std::endl;
    return 0;
}
