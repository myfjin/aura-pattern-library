/*
 * Householder reflection: zeros out components via hyperplane reflection.
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <utility>

std::pair<std::vector<double>, double> householder_reflection(const std::vector<double>& x) {
    int n = static_cast<int>(x.size());
    double norm_x = 0.0;
    for (double xi : x) norm_x += xi * xi;
    norm_x = std::sqrt(norm_x);

    if (norm_x < 1e-14) return {std::vector<double>(n, 0.0), 0.0};

    std::vector<double> v = x;
    if (x[0] >= 0.0) v[0] -= norm_x;
    else v[0] += norm_x;

    double norm_v = 0.0;
    for (double vi : v) norm_v += vi * vi;
    norm_v = std::sqrt(norm_v);
    if (norm_v < 1e-14) return {std::vector<double>(n, 0.0), 0.0};

    for (double& vi : v) vi /= norm_v;
    return {v, 2.0};
}

std::vector<double> apply_householder(const std::vector<double>& v, double beta,
                                       const std::vector<double>& x) {
    int n = static_cast<int>(x.size());
    double dot_product = 0.0;
    for (int i = 0; i < n; ++i) dot_product += v[i] * x[i];

    std::vector<double> result(n);
    for (int i = 0; i < n; ++i) result[i] = x[i] - beta * dot_product * v[i];
    return result;
}

