/* Distance metrics toolkit: Euclidean, Manhattan, Minkowski, Chebyshev, Cosine.
 * Core claim: all metrics match closed-form answers, symmetries hold,
 *             Minkowski specializes to Euclidean/Manhattan/Chebyshev.
 */
#include <cassert>
#include <cmath>
#include <iostream>
#include <vector>

double euclidean(const std::vector<double>& p, const std::vector<double>& q) {
    double s = 0.0;
    for (size_t i = 0; i < p.size(); ++i) s += (p[i] - q[i]) * (p[i] - q[i]);
    return std::sqrt(s);
}

double manhattan(const std::vector<double>& p, const std::vector<double>& q) {
    double s = 0.0;
    for (size_t i = 0; i < p.size(); ++i) s += std::abs(p[i] - q[i]);
    return s;
}

double chebyshev(const std::vector<double>& p, const std::vector<double>& q) {
    double mx = 0.0;
    for (size_t i = 0; i < p.size(); ++i) mx = std::max(mx, std::abs(p[i] - q[i]));
    return mx;
}

double minkowski(const std::vector<double>& p, const std::vector<double>& q, double order) {
    if (order >= 1e300) return chebyshev(p, q);
    double s = 0.0;
    for (size_t i = 0; i < p.size(); ++i) s += std::pow(std::abs(p[i] - q[i]), order);
    return std::pow(s, 1.0 / order);
}

double cosine_similarity(const std::vector<double>& p, const std::vector<double>& q) {
    double dot = 0.0, np = 0.0, nq = 0.0;
    for (size_t i = 0; i < p.size(); ++i) {
        dot += p[i] * q[i];
        np += p[i] * p[i];
        nq += q[i] * q[i];
    }
    return dot / (std::sqrt(np) * std::sqrt(nq));
}

double cosine_distance(const std::vector<double>& p, const std::vector<double>& q) {
    return 1.0 - cosine_similarity(p, q);
}

