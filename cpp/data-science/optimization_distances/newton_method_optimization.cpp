#include <utility>
// Newton's method for 1D minimization of f(x)=3x^2-12x+10.
// Also includes gradient descent for comparison.
#include <cassert>
#include <cmath>
#include <cstdio>
#include <stdexcept>

inline double f(double x) { return 3.0 * x * x - 12.0 * x + 10.0; }
inline double grad(double x) { return 6.0 * x - 12.0; }
inline double hess(double /*x*/) { return 6.0; }

std::pair<int, double> newton_method(double x_init, double tolerance = 1e-10,
                                     int max_iters = 100) {
    double x = x_init;
    for (int i = 0; i < max_iters; ++i) {
        double g = grad(x);
        if (std::fabs(g) < tolerance) return {i, x};
        double h = hess(x);
        if (std::fabs(h) < 1e-12) throw std::runtime_error("Hessian near zero");
        x -= g / h;
    }
    return {max_iters, x};
}

std::pair<int, double> gradient_descent(double x_init, double learning_rate = 0.1,
                                        double tolerance = 1e-10,
                                        int max_iters = 1000) {
    double x = x_init;
    for (int i = 0; i < max_iters; ++i) {
        double g = grad(x);
        if (std::fabs(g) < tolerance) return {i, x};
        x -= learning_rate * g;
    }
    return {max_iters, x};
}

int main() {
    double x_init = 0.0;
    auto [iters_newton, x_newton] = newton_method(x_init, 1e-10, 100);
    auto [iters_gd, x_gd] = gradient_descent(x_init, 0.1, 1e-10, 1000);

    assert(std::fabs(x_newton - 2.0) < 1e-8);
    assert(std::fabs(x_gd - 2.0) < 1e-6);
    assert(iters_newton < iters_gd);

    double f_newton = f(x_newton);
    double f_gd = f(x_gd);
    assert(std::fabs(f_newton - (-2.0)) < 1e-8);
    assert(std::fabs(f_gd - (-2.0)) < 1e-6);

    std::printf("newton_method_optimization.cpp: newton_iters=%d gd_iters=%d PASS\n",
                iters_newton, iters_gd);
    return 0;
}
