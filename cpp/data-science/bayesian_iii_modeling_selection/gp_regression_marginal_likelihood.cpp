/*
 * Gaussian-process regression: the marginal likelihood peaks at the true lengthscale.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <algorithm>

std::vector<std::vector<double>> rbf_matrix(const std::vector<double>& x, double ls, double noise) {
    int n = static_cast<int>(x.size());
    std::vector<std::vector<double>> K(n, std::vector<double>(n, 0.0));
    for (int i = 0; i < n; ++i) {
        for (int j = 0; j < n; ++j) {
            K[i][j] = std::exp(-0.5 * (x[i] - x[j]) * (x[i] - x[j]) / (ls * ls)) + (i == j ? noise : 0.0);
        }
    }
    return K;
}

std::vector<std::vector<double>> cholesky(const std::vector<std::vector<double>>& A) {
    int n = static_cast<int>(A.size());
    std::vector<std::vector<double>> L(n, std::vector<double>(n, 0.0));
    for (int i = 0; i < n; ++i) {
        for (int j = 0; j <= i; ++j) {
            double s = 0.0;
            for (int k = 0; k < j; ++k) s += L[i][k] * L[j][k];
            if (i == j) L[i][j] = std::sqrt(std::max(A[i][i] - s, 1e-12));
            else L[i][j] = (A[i][j] - s) / L[j][j];
        }
    }
    return L;
}

double gp_log_marginal_likelihood(const std::vector<double>& x, const std::vector<double>& y,
                                  double ls, double noise = 0.05) {
    int n = static_cast<int>(x.size());
    auto L = cholesky(rbf_matrix(x, ls, noise));

    std::vector<double> z(n, 0.0);
    for (int i = 0; i < n; ++i) {
        double s = 0.0;
        for (int k = 0; k < i; ++k) s += L[i][k] * z[k];
        z[i] = (y[i] - s) / L[i][i];
    }

    std::vector<double> alpha(n, 0.0);
    for (int i = n - 1; i >= 0; --i) {
        double s = 0.0;
        for (int k = i + 1; k < n; ++k) s += L[k][i] * alpha[k];
        alpha[i] = (z[i] - s) / L[i][i];
    }

    double logdet = 0.0;
    for (int i = 0; i < n; ++i) logdet += 2.0 * std::log(L[i][i]);

    double y_alpha = 0.0;
    for (int i = 0; i < n; ++i) y_alpha += y[i] * alpha[i];

    return -0.5 * y_alpha - 0.5 * logdet - 0.5 * n * std::log(2.0 * M_PI);
}

