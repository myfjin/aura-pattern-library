static mt19937 rng(42);

// Generate stick-breaking weights using Beta(1, α).
static vector<double> stick_breaking_process(double alpha, int num_breaks = 100) {
    vector<double> weights;
    double remaining = 1.0;
    gamma_distribution<double> gamma1(1.0, 1.0);
    gamma_distribution<double> gamma_alpha(alpha, 1.0);
    for (int i = 0; i < num_breaks; ++i) {
        double x = gamma1(rng);
        double y = gamma_alpha(rng);
        if (x + y == 0.0) break;
        double v = x / (x + y); // Beta(1, α)
        double weight = v * remaining;
        weights.push_back(weight);
        remaining *= (1.0 - v);
        if (remaining < 1e-8) break;
    }
    return weights;
}

static int count_active_clusters(const vector<double>& weights, double threshold = 0.01) {
    int active = 0;
    for (double w : weights) if (w > threshold) ++active;
    return active;
}

