/*
 * Beta-Binomial Overdispersion
 * 
 * Counts with a random per-trial success probability p ~ Beta(α, β) are OVERDISPERSED
 * relative to a binomial. Method-of-moments recovers (α, β) from the sample mean and variance.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <utility>
#include <limits>

// Sample from Beta(alpha, beta) using gamma variates
double sample_beta(std::mt19937& rng, double alpha, double beta) {
    std::gamma_distribution<double> gamma1(alpha, 1.0);
    std::gamma_distribution<double> gamma2(beta, 1.0);
    double x = gamma1(rng);
    double y = gamma2(rng);
    return x / (x + y);
}

// Gamma function approximation (Lanczos)
double lgamma_approx(double x) {
    return std::lgamma(x);
}

double beta_binomial_loglik(const std::vector<int>& counts, int n_trials, double alpha, double beta) {
    /* Log-likelihood of counts under Beta-Binomial(n_trials, α, β). */
    double ll = 0.0;
    for (int k : counts) {
        ll += lgamma_approx(alpha + k) + lgamma_approx(beta + n_trials - k) 
              - lgamma_approx(alpha + beta + n_trials)
              + lgamma_approx(alpha + beta) - lgamma_approx(alpha) - lgamma_approx(beta);
    }
    return ll;
}

double binomial_loglik(const std::vector<int>& counts, int n_trials, double p) {
    /* Log-likelihood under Binomial(n_trials, p). */
    if (p <= 0.0 || p >= 1.0) {
        return -std::numeric_limits<double>::infinity();
    }
    double ll = 0.0;
    for (int k : counts) {
        ll += k * std::log(p) + (n_trials - k) * std::log(1.0 - p);
    }
    return ll;
}

std::pair<double, double> moment_match_beta_binomial(const std::vector<int>& counts, int n_trials) {
    /* Recover (α, β) by method of moments (via the intra-class correlation ρ). */
    int m = static_cast<int>(counts.size());
    double mean = 0.0;
    for (int c : counts) mean += c;
    mean /= m;

    double var = 0.0;
    for (int c : counts) {
        double diff = c - mean;
        var += diff * diff;
    }
    var /= m;

    double mu = mean / n_trials;
    // var = n·μ(1−μ)·(1 + (n−1)ρ)  →  solve for ρ.
    double rho = (var / (n_trials * mu * (1.0 - mu)) - 1.0) / (n_trials - 1);
    rho = std::max(1e-3, std::min(0.99, rho));
    double scale = 1.0 / rho - 1.0;
    return {mu * scale, (1.0 - mu) * scale};
}

