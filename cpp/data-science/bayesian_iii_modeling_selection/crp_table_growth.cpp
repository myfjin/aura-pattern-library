/* Chinese Restaurant Process (CRP): expected number of tables ≈ α·ln(n).
 *
 * Core claim: E[#tables] ≈ α·ln(n) within tolerance (planted α).
 */
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <vector>

int crp_sample_num_tables(int n, double alpha, std::mt19937& gen) {
    /* Simulate CRP: n customers, α concentration. Returns number of occupied tables. */
    std::vector<int> tables;
    tables.push_back(1);  // First customer starts table 1.

    std::uniform_real_distribution<double> uniform(0.0, 1.0);

    for (int i = 1; i < n; ++i) {
        int total_size = 0;
        for (int s : tables) total_size += s;
        double new_table_prob = alpha / (alpha + static_cast<double>(total_size));

        if (uniform(gen) < new_table_prob) {
            tables.push_back(1);  // New table.
        } else {
            // Join existing table (uniformly weighted by size).
            int table_idx = static_cast<int>(uniform(gen) * tables.size());
            tables[table_idx] += 1;
        }
    }
    return static_cast<int>(tables.size());
}

