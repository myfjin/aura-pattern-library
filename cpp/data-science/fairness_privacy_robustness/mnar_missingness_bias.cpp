/*
 * Missing Not At Random (MNAR): bias in naive complete-case analysis.
 *
 * Oracle asserts:
 *   mnar_mean < true_mean
 *   mnar_bias > 5
 *   mcar_bias < mnar_bias
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <random>
#include <optional>

void mnar_missingness_bias() {
    std::mt19937_64 rng(42);
    std::uniform_real_distribution<double> val_dist(0.0, 100.0);
    std::uniform_real_distribution<double> prob(0.0, 1.0);

    int n = 200;
    std::vector<double> true_values;
    for (int i = 0; i < n; ++i) true_values.push_back(val_dist(rng));

    std::vector<std::optional<double>> mnar_observed, mcar_observed;
    for (double val : true_values) {
        mnar_observed.push_back(prob(rng) < (val > 70.0 ? 0.7 : 0.1) ? std::optional<double>() : val);
        mcar_observed.push_back(prob(rng) < 0.3 ? std::optional<double>() : val);
    }

    auto cc_mean = [](const std::vector<std::optional<double>>& obs) {
        double s = 0.0;
        int c = 0;
        for (const auto& v : obs) if (v.has_value()) { s += v.value(); ++c; }
        return s / c;
    };

    double true_mean = 0.0;
    for (double v : true_values) true_mean += v;
    true_mean /= n;

    double mnar_mean = cc_mean(mnar_observed);
    double mcar_mean = cc_mean(mcar_observed);
    double mnar_bias = std::abs(mnar_mean - true_mean);
    double mcar_bias = std::abs(mcar_mean - true_mean);

    assert(mnar_mean < true_mean);
    assert(mnar_bias > 5.0);
    assert(mcar_bias < mnar_bias);

    std::cout << "mnar_missingness_bias.cpp PASS" << std::endl;
}

int main() {
    mnar_missingness_bias();
    return 0;
}
