#include <vector>
#include <cmath>
#include <random>
#include <algorithm>
#include <cassert>
#include <iostream>
#include <tuple>

double gk_quantile_summary(const std::vector<double>& stream, double epsilon, double q) {
    int n = static_cast<int>(stream.size());
    int true_rank = static_cast<int>(q * (n - 1));
    std::vector<double> batch = stream;
    std::sort(batch.begin(), batch.end());
    double true_quantile = batch[true_rank];

    // Simplified GK summary
    std::vector<std::tuple<double, int, int>> summary;

    for (int i = 0; i < n; ++i) {
        double val = stream[i];
        size_t pos = summary.size();
        for (size_t j = 0; j < summary.size(); ++j) {
            if (val <= std::get<0>(summary[j])) {
                pos = j;
                break;
            }
        }
        summary.insert(summary.begin() + pos, {val, i, 0});

        int k = std::max(1, static_cast<int>(1.0 / (2.0 * epsilon)));
        if (static_cast<int>(summary.size()) > 2 * k) {
            std::vector<std::tuple<double, int, int>> compressed;
            for (size_t j = 0; j < summary.size(); ++j) {
                if (j % 2 == 0 || j == summary.size() - 1) {
                    compressed.push_back(summary[j]);
                }
            }
            summary = compressed;
        }
    }

    double target_rank = q * n;
    std::sort(summary.begin(), summary.end(),
        [](const auto& a, const auto& b) { return std::get<0>(a) < std::get<0>(b); });
    int idx = static_cast<int>(target_rank * summary.size() / n);
    double measured_quantile = std::get<0>(summary[idx]);

    double error_bound = 2.0 * epsilon * n;
    assert(std::abs(measured_quantile - true_quantile) <= error_bound + 1e-6);

    return measured_quantile;
}

