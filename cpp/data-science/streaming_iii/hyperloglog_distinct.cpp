uint64_t splitmix64(uint64_t x) {
    x += 0x9e3779b97f4a7c15ULL;
    x = (x ^ (x >> 30)) * 0xbf58476d1ce4e5b9ULL;
    x = (x ^ (x >> 27)) * 0x94d049bb133111ebULL;
    return x ^ (x >> 31);
}

uint64_t hash64(int x) {
    return splitmix64(static_cast<uint64_t>(x) + 0x123456789abcdef0ULL);
}

int hyperloglog_distinct(const std::vector<int>& stream, int p) {
    assert(p >= 4 && p <= 16);
    int m = 1 << p;
    int suffix_bits = 64 - p;
    std::vector<int> registers(m, 0);

    for (int elem : stream) {
        uint64_t h = hash64(elem);
        int idx = static_cast<int>(h >> suffix_bits);
        uint64_t w = h & ((1ULL << suffix_bits) - 1);
        int rank = (w == 0) ? suffix_bits + 1 : suffix_bits - (64 - __builtin_clzll(w)) + 1;
        if (rank > registers[idx]) registers[idx] = rank;
    }

    double alpha = 0.7213 / (1.0 + 1.079 / m);
    double inv_sum = 0.0;
    for (int r : registers) inv_sum += std::pow(2.0, -r);
    double estimate = alpha * m * m / inv_sum;

    int zeros = static_cast<int>(std::count(registers.begin(), registers.end(), 0));
    if (estimate <= 2.5 * m && zeros > 0) {
        estimate = m * std::log(static_cast<double>(m) / zeros);
    }

    return static_cast<int>(std::round(estimate));
}

