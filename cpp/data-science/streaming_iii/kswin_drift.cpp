double ks_statistic(const std::vector<double>& w1, const std::vector<double>& w2) {
    int n = static_cast<int>(w1.size()), m = static_cast<int>(w2.size());
    int i = 0, j = 0;
    double d_max = 0.0;
    while (i < n && j < m) {
        double d = std::abs(i / static_cast<double>(n) - j / static_cast<double>(m));
        d_max = std::max(d_max, d);
        if (w1[i] <= w2[j]) ++i; else ++j;
    }
    d_max = std::max(d_max, std::abs((n - i) / static_cast<double>(n)));
    return d_max;
}

bool kswin_drift(const std::vector<double>& stream, int window_size = 100, double alpha = 0.05) {
    assert(window_size > 0 && 0.0 < alpha && alpha < 1.0);
    if (static_cast<int>(stream.size()) < 2 * window_size) return false;

    auto w1 = std::vector<double>(stream.begin(), stream.begin() + window_size);
    auto w2 = std::vector<double>(stream.end() - window_size, stream.end());
    std::sort(w1.begin(), w1.end());
    std::sort(w2.begin(), w2.end());

    double ks = ks_statistic(w1, w2);
    int n = window_size;
    double critical = std::sqrt(-0.5 * std::log(alpha / 2.0) / n);
    bool detected = ks > critical;

    double mean1 = std::accumulate(w1.begin(), w1.end(), 0.0) / n;
    double mean2 = std::accumulate(w2.begin(), w2.end(), 0.0) / n;
    double true_shift = std::abs(mean2 - mean1);

    if (true_shift > 2.0) assert(detected);
    else assert(!detected);

    return detected;
}

