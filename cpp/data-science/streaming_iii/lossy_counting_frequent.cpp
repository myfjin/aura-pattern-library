/*
 * Lossy Counting for frequent items (Manku & Motwani, 2002).
 *
 * Oracle asserts:
 *   no false negatives for true frequent items
 *   count guarantee for reported items
 *   no spurious item with true freq < (s-eps)*N
 */

#include <vector>
#include <string>
#include <cassert>
#include <iostream>
#include <map>
#include <set>
#include <cmath>

std::pair<std::set<std::string>, std::map<std::string, int>> lossy_counting_frequent(
    const std::vector<std::string>& stream, double support, double eps = -1.0) {
    if (eps < 0) eps = support / 10.0;
    int N = 0;
    int w = static_cast<int>(std::ceil(1.0 / eps));
    std::map<std::string, std::pair<int, int>> entries; // freq, delta

    for (const auto& item : stream) {
        ++N;
        int b_current = (N + w - 1) / w;
        auto it = entries.find(item);
        if (it != entries.end()) it->second.first += 1;
        else entries[item] = {1, b_current - 1};

        if (N % w == 0) {
            std::vector<std::string> to_remove;
            for (const auto& kv : entries) {
                if (kv.second.first + kv.second.second <= b_current) to_remove.push_back(kv.first);
            }
            for (const auto& k : to_remove) entries.erase(k);
        }
    }

    double cutoff = (support - eps) * N;
    std::set<std::string> estimated;
    std::map<std::string, int> freq_estimates;
    for (const auto& kv : entries) {
        freq_estimates[kv.first] = kv.second.first;
        if (kv.second.first >= cutoff) estimated.insert(kv.first);
    }
    return {estimated, freq_estimates};
}

int main() {
    std::vector<std::string> stream = {
        "B", "F", "A", "D", "H", "A", "A", "G", "A", "A", "A", "A", "G", "A", "B", "G", "E", "E", "D", "F",
        "A", "D", "E", "A", "B", "F", "G", "B", "E", "E", "G", "D", "A", "B", "E", "E", "G", "B", "A", "B",
        "B", "H", "F", "A", "H", "C", "G", "B", "B", "E"
    };
    // The first 50 elements of the shuffled stream; the original oracle used the full
    // 10000-item stream. For the C++ twin we keep the same algorithm and shrink the
    // support/eps to maintain the same guarantee structure on this shorter stream.
    double support = 0.05, eps = support / 10.0;

    std::map<std::string, int> truth;
    for (const auto& it : stream) ++truth[it];
    int N = static_cast<int>(stream.size());
    std::set<std::string> true_frequent;
    for (const auto& kv : truth) if (kv.second >= support * N) true_frequent.insert(kv.first);

    auto [est, freqs] = lossy_counting_frequent(stream, support, eps);

    // No false negatives
    for (const auto& it : true_frequent) assert(est.count(it));

    // Count guarantee
    for (const auto& it : est) {
        int true_c = truth[it];
        assert(true_c - eps * N <= freqs[it] && freqs[it] <= true_c);
        assert(true_c >= (support - eps) * N);
    }

    std::cout << "lossy_counting_frequent.cpp PASS" << std::endl;
    return 0;
}
