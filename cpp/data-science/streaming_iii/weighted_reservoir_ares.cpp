// A-Res: sample k items with probability proportional to weight.
vector<int> weighted_reservoir_ares(const vector<pair<int,double>>& stream, int k,
                                    std::mt19937& rng) {
    assert(k > 0);
    std::uniform_real_distribution<double> u(0.0, 1.0);
    // min-heap keyed by (key, tiebreak, value)
    using HeapItem = std::tuple<double, int, int>;
    std::priority_queue<HeapItem, vector<HeapItem>, std::greater<HeapItem>> heap;
    for (size_t i = 0; i < stream.size(); ++i) {
        int value = stream[i].first;
        double weight = stream[i].second;
        if (weight <= 0.0) continue;
        double key = std::pow(u(rng), 1.0 / weight);
        if ((int)heap.size() < k) {
            heap.emplace(key, (int)i, value);
        } else if (key > std::get<0>(heap.top())) {
            heap.pop();
            heap.emplace(key, (int)i, value);
        }
    }
    vector<int> result;
    while (!heap.empty()) {
        result.push_back(std::get<2>(heap.top()));
        heap.pop();
    }
    return result;
}

