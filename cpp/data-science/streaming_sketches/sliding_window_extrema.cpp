// Sliding window min/max via monotonic deque, verified against brute force.

std::vector<std::pair<double, double>> brute_force_minmax(const std::vector<double>& data, int window_size) {
    std::vector<std::pair<double, double>> results;
    for (size_t i = 0; i + window_size <= data.size(); ++i) {
        auto window = data.begin() + i;
        auto mn = *std::min_element(window, window + window_size);
        auto mx = *std::max_element(window, window + window_size);
        results.emplace_back(mn, mx);
    }
    return results;
}

std::vector<std::pair<double, double>> deque_minmax(const std::vector<double>& data, int window_size) {
    std::deque<std::pair<int, double>> min_deque;
    std::deque<std::pair<int, double>> max_deque;
    std::vector<std::pair<double, double>> results;

    for (int i = 0; i < static_cast<int>(data.size()); ++i) {
        double val = data[i];

        while (!min_deque.empty() && min_deque.front().first <= i - window_size) min_deque.pop_front();
        while (!max_deque.empty() && max_deque.front().first <= i - window_size) max_deque.pop_front();

        while (!min_deque.empty() && min_deque.back().second >= val) min_deque.pop_back();
        min_deque.emplace_back(i, val);

        while (!max_deque.empty() && max_deque.back().second <= val) max_deque.pop_back();
        max_deque.emplace_back(i, val);

        if (i >= window_size - 1) {
            results.emplace_back(min_deque.front().second, max_deque.front().second);
        }
    }
    return results;
}

