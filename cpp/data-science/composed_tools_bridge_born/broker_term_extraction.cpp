#include <map>

std::unordered_map<std::string, std::unordered_set<std::string>> cooccurrence_graph(
    const std::vector<std::vector<std::string>>& sentences
) {
    /* ADJACENT-pair windowing: all-pairs-in-sentence would give the bridging sentence
     * a DIRECT edge that bypasses the broker — erasing the very brokerage being measured. */
    std::unordered_map<std::string, std::unordered_set<std::string>> g;
    for (const auto& words : sentences) {
        for (size_t i = 0; i + 1 < words.size(); ++i) {
            const auto& a = words[i];
            const auto& b = words[i + 1];
            if (a != b) {
                g[a].insert(b);
                g[b].insert(a);
            }
        }
    }
    return g;
}

std::unordered_map<std::string, double> betweenness(
    const std::unordered_map<std::string, std::unordered_set<std::string>>& g
) {
    /* Brandes' algorithm (unweighted): fraction of shortest paths through each node. */
    std::unordered_map<std::string, double> bc;
    for (const auto& kv : g) {
        bc[kv.first] = 0.0;
    }

    for (const auto& s_kv : g) {
        const std::string& s = s_kv.first;
        std::vector<std::string> stack;
        std::unordered_map<std::string, std::vector<std::string>> preds;
        std::unordered_map<std::string, double> sigma;
        std::unordered_map<std::string, int> dist;

        for (const auto& v_kv : g) {
            preds[v_kv.first] = {};
            sigma[v_kv.first] = 0.0;
            dist[v_kv.first] = -1;
        }
        sigma[s] = 1.0;
        dist[s] = 0;

        std::queue<std::string> q;
        q.push(s);

        while (!q.empty()) {
            std::string v = q.front();
            q.pop();
            stack.push_back(v);

            auto it = g.find(v);
            if (it != g.end()) {
                for (const auto& w : it->second) {
                    if (dist[w] < 0) {
                        dist[w] = dist[v] + 1;
                        q.push(w);
                    }
                    if (dist[w] == dist[v] + 1) {
                        sigma[w] += sigma[v];
                        preds[w].push_back(v);
                    }
                }
            }
        }

        std::unordered_map<std::string, double> delta;
        for (const auto& v_kv : g) {
            delta[v_kv.first] = 0.0;
        }

        while (!stack.empty()) {
            std::string w = stack.back();
            stack.pop_back();
            for (const auto& v : preds[w]) {
                if (sigma[w] > 0) {
                    delta[v] += (sigma[v] / sigma[w]) * (1.0 + delta[w]);
                }
            }
            if (w != s) {
                bc[w] += delta[w];
            }
        }
    }

    return bc;
}

