#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <algorithm>
#include <random>
#include <map>
#include <utility>
#include <functional>

using Point = std::pair<double, double>;

struct KDNode {
    Point point;
    int label;
    int axis;
    KDNode* left = nullptr;
    KDNode* right = nullptr;
};

long long tree_counter = 0;
long long brute_counter = 0;

KDNode* build_kdtree(std::vector<std::pair<Point, int>>& items, int depth = 0) {
    if (items.empty()) return nullptr;
    int axis = depth % 2;
    std::sort(items.begin(), items.end(),
              [axis](const auto& a, const auto& b) {
                  return axis == 0 ? a.first.first < b.first.first : a.first.second < b.first.second;
              });
    int mid = items.size() / 2;
    KDNode* node = new KDNode{items[mid].first, items[mid].second, axis};
    std::vector<std::pair<Point, int>> left_items(items.begin(), items.begin() + mid);
    std::vector<std::pair<Point, int>> right_items(items.begin() + mid + 1, items.end());
    node->left = build_kdtree(left_items, depth + 1);
    node->right = build_kdtree(right_items, depth + 1);
    return node;
}

double sqdist(const Point& a, const Point& b, bool count) {
    if (count) ++tree_counter;
    double dx = a.first - b.first;
    double dy = a.second - b.second;
    return dx * dx + dy * dy;
}

double sqdist_brute(const Point& a, const Point& b) {
    ++brute_counter;
    double dx = a.first - b.first;
    double dy = a.second - b.second;
    return dx * dx + dy * dy;
}

std::vector<std::pair<double, int>> knn_tree(KDNode* root, const Point& q, int k) {
    std::vector<std::pair<double, int>> best; // sorted ascending, kept size <= k
    std::function<void(KDNode*)> visit = [&](KDNode* node) {
        if (!node) return;
        double d = sqdist(q, node->point, true);
        if (static_cast<int>(best.size()) < k || d < best.back().first) {
            best.push_back({d, node->label});
            std::sort(best.begin(), best.end());
            if (static_cast<int>(best.size()) > k) best.resize(k);
        }
        double axis_gap = node->axis == 0 ? q.first - node->point.first : q.second - node->point.second;
        KDNode* near = axis_gap <= 0 ? node->left : node->right;
        KDNode* far = axis_gap <= 0 ? node->right : node->left;
        visit(near);
        if (static_cast<int>(best.size()) < k || axis_gap * axis_gap < best.back().first) visit(far);
    };
    visit(root);
    return best;
}

std::vector<std::pair<double, int>> knn_brute(const std::vector<std::pair<Point, int>>& items,
                                      const Point& q, int k) {
    std::vector<std::pair<double, int>> ds;
    for (const auto& item : items) ds.push_back({sqdist_brute(q, item.first), item.second});
    std::sort(ds.begin(), ds.end());
    ds.resize(k);
    return ds;
}

int majority(const std::vector<std::pair<double, int>>& neigh) {
    std::map<int, int> votes;
    for (const auto& n : neigh) ++votes[n.second];
    int best = 0, best_count = -1;
    for (const auto& kv : votes) {
        if (kv.second > best_count || (kv.second == best_count && kv.first > best)) {
            best_count = kv.second; best = kv.first;
        }
    }
    return best;
}

int main() {
    std::mt19937_64 rng(42);
    std::normal_distribution<double> c0(0.0, 1.0), c1(3.0, 1.0);
    std::vector<std::pair<Point, int>> train;
    for (int i = 0; i < 1000; ++i) train.push_back({{c0(rng), c0(rng)}, 0});
    for (int i = 0; i < 1000; ++i) train.push_back({{c1(rng), c1(rng)}, 1});

    std::normal_distribution<double> qdist(1.5, 2.0);
    std::vector<Point> queries;
    for (int i = 0; i < 300; ++i) queries.push_back({qdist(rng), qdist(rng)});

    KDNode* root = build_kdtree(train);
    int k = 5, agree = 0;
    for (const auto& q : queries) {
        auto nt = knn_tree(root, q, k);
        auto nb = knn_brute(train, q, k);
        for (size_t i = 0; i < nt.size(); ++i) {
            assert(std::abs(nt[i].first - nb[i].first) < 1e-9);
        }
        if (majority(nt) == majority(nb)) ++agree;
    }

    assert(agree == static_cast<int>(queries.size()));
    double ratio = static_cast<double>(tree_counter) / static_cast<double>(brute_counter);
    assert(ratio < 0.40);

    std::cout << "knn_kdtree_accelerated.cpp PASS: ratio=" << ratio << std::endl;
    return 0;
}
