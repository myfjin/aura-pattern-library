/*
 * Grid Search vs Random Search: Demonstrating Random Search Efficiency
 */

#include <functional>
#include <map>
#include <string>
#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <utility>

double evaluate_model(const std::map<std::string, double>& params, std::mt19937& rng) {
    double important = params.at("important");
    std::normal_distribution<double> noise(0.0, 0.01);
    return -(important - 0.7) * (important - 0.7) + noise(rng);
}

std::tuple<std::map<std::string, double>, double, int> grid_search(
    const std::map<std::string, std::pair<double, double>>& param_ranges,
    int num_values, std::mt19937& rng) {

    std::map<std::string, std::vector<double>> grids;
    for (const auto& [param, range] : param_ranges) {
        double low = range.first, high = range.second;
        for (int i = 0; i < num_values; ++i) {
            grids[param].push_back(low + (high - low) * i / (num_values - 1));
        }
    }

    std::vector<std::string> param_names;
    for (const auto& kv : param_ranges) param_names.push_back(kv.first);

    double best_score = -1e18;
    std::map<std::string, double> best_params;
    int num_evals = 0;

    std::function<void(int, std::map<std::string, double>&)> enumerate;
    enumerate = [&](int idx, std::map<std::string, double>& current) {
        if (idx == static_cast<int>(param_names.size())) {
            double score = evaluate_model(current, rng);
            num_evals++;
            if (score > best_score) {
                best_score = score;
                best_params = current;
            }
            return;
        }
        const auto& param = param_names[idx];
        for (double val : grids[param]) {
            current[param] = val;
            enumerate(idx + 1, current);
        }
    };

    std::map<std::string, double> current;
    enumerate(0, current);

    return {best_params, best_score, num_evals};
}

std::tuple<std::map<std::string, double>, double, int> random_search(
    const std::map<std::string, std::pair<double, double>>& param_ranges,
    int num_samples, std::mt19937& rng) {

    double best_score = -1e18;
    std::map<std::string, double> best_params;

    for (int s = 0; s < num_samples; ++s) {
        std::map<std::string, double> params;
        for (const auto& [param, range] : param_ranges) {
            std::uniform_real_distribution<double> uniform(range.first, range.second);
            params[param] = uniform(rng);
        }
        double score = evaluate_model(params, rng);
        if (score > best_score) {
            best_score = score;
            best_params = params;
        }
    }

    return {best_params, best_score, num_samples};
}

int main() {
    std::mt19937 rng(42);

    std::map<std::string, std::pair<double, double>> param_ranges = {
        {"important", {0.0, 1.0}},
        {"useless1", {0.0, 1.0}},
        {"useless2", {0.0, 1.0}}
    };

    auto [grid_params, grid_score, grid_evals] = grid_search(param_ranges, 3, rng);
    auto [random_params, random_score, random_evals] = random_search(param_ranges, 20, rng);

    assert(random_score > grid_score - 0.05);
    assert(random_evals < grid_evals);
    assert(random_score > -0.1);

    std::cout << "grid_vs_random_search.cpp PASS" << std::endl;
    return 0;
}
