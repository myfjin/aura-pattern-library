#include <iostream>
#include <vector>
#include <cstring>
#include <map>
#include <variant>
#include <cassert>
#include <utility>

using std::string;
using std::map;
using std::variant;
using std::vector;
using std::pair;

struct Record {
    string category;
    string region;
    int amount;
};

static map<string, map<string, int>> pivot_table(
    const vector<Record>& records,
    const string& agg_func) {
    map<string, map<string, int>> pivot;
    for (const auto& r : records) {
        if (agg_func == "sum") {
            pivot[r.category][r.region] += r.amount;
        } else if (agg_func == "count") {
            pivot[r.category][r.region] += 1;
        }
    }
    return pivot;
}

static pair<map<string, int>, map<string, int>> compute_margins(
    const map<string, map<string, int>>& pivot) {
    map<string, int> row_totals, col_totals;
    for (const auto& [row, cols] : pivot) {
        int total = 0;
        for (const auto& [col, val] : cols) {
            total += val;
            col_totals[col] += val;
        }
        row_totals[row] = total;
    }
    return {row_totals, col_totals};
}

int main() {
    vector<Record> records = {
        {"A", "US", 100},
        {"A", "US", 50},
        {"A", "EU", 75},
        {"B", "US", 30},
        {"B", "EU", 80},
        {"B", "EU", 45},
    };

    auto pivot = pivot_table(records, "sum");
    auto [row_totals, col_totals] = compute_margins(pivot);

    int total_from_rows = 0;
    for (const auto& [k, v] : row_totals) total_from_rows += v;
    int total_from_cols = 0;
    for (const auto& [k, v] : col_totals) total_from_cols += v;
    int total_from_records = 0;
    for (const auto& r : records) total_from_records += r.amount;

    assert(total_from_rows == total_from_records);
    assert(total_from_cols == total_from_records);
    assert(pivot["A"]["US"] == 150);
    assert(pivot["B"]["EU"] == 125);
    assert(row_totals["A"] == 225);
    assert(row_totals["B"] == 155);

    std::cout << "Pivot: A/US=" << pivot["A"]["US"] << " | B/EU=" << pivot["B"]["EU"]
              << " | Row totals: A=" << row_totals["A"] << " B=" << row_totals["B"]
              << " | Grand total: " << total_from_rows << " | PASS\n";
    return 0;
}
