/* CSV Type Inference: Detect column types from string values.
 *
 * Core claim: numeric, float, date, str, and missing-value detection work.
 */
#include <cassert>
#include <cctype>
#include <iostream>
#include <map>
#include <regex>
#include <string>
#include <vector>

std::string infer_type(const std::string& value) {
    if (value.empty()) return "missing";
    
    // Check for date pattern YYYY-MM-DD
    std::regex date_pattern(R"(\d{4}-\d{2}-\d{2})");
    if (std::regex_match(value, date_pattern)) return "date";
    
    // Check if all digits (int)
    bool all_digits = !value.empty();
    for (char c : value) {
        if (!std::isdigit(c) && c != '-') {
            all_digits = false;
            break;
        }
    }
    if (all_digits) return "int";
    
    // Check if float
    bool has_dot = false;
    bool is_float = !value.empty();
    for (char c : value) {
        if (c == '.') has_dot = true;
        else if (!std::isdigit(c) && c != '-') {
            is_float = false;
            break;
        }
    }
    if (is_float && has_dot) return "float";
    
    return "str";
}

std::map<std::string, std::string> infer_column_types(const std::vector<std::vector<std::string>>& rows) {
    std::map<std::string, std::string> types;
    if (rows.empty() || rows[0].size() < 2) return types;
    
    // First row is headers
    std::vector<std::string> headers = rows[0];
    
    for (size_t col = 0; col < headers.size(); ++col) {
        std::string col_type = "missing";
        for (size_t r = 1; r < rows.size(); ++r) {
            if (col < rows[r].size()) {
                std::string cell_type = infer_type(rows[r][col]);
                if (cell_type != "missing") {
                    col_type = cell_type;
                    break;
                }
            }
        }
        types[headers[col]] = col_type;
    }
    return types;
}

