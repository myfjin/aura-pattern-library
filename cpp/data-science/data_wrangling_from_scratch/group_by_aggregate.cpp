/*
 * Group-By Aggregation (Multi-Key).
 */

#include <vector>
#include <map>
#include <string>
#include <cassert>
#include <iostream>
#include <utility>
#include <algorithm>

struct Record {
    std::string category;
    std::string region;
    int value;
};

std::map<std::pair<std::string, std::string>, double> group_by_aggregate(
    const std::vector<Record>& records,
    const std::vector<std::string>& group_keys,
    const std::string& agg_col,
    const std::string& agg_func
) {
    std::map<std::pair<std::string, std::string>, std::vector<double>> groups;

    for (const auto& record : records) {
        std::pair<std::string, std::string> key = {record.category, record.region};
        if (record.category > record.region) key = {record.region, record.category};
        // Simple 2-key handling: for this oracle, keys are category and region
        groups[{record.category, record.region}].push_back(record.value);
    }

    std::map<std::pair<std::string, std::string>, double> result;
    for (const auto& [key, values] : groups) {
        if (agg_func == "sum") {
            double sum = 0.0;
            for (double v : values) sum += v;
            result[key] = sum;
        } else if (agg_func == "mean") {
            double sum = 0.0;
            for (double v : values) sum += v;
            result[key] = sum / values.size();
        } else if (agg_func == "count") {
            result[key] = values.size();
        } else if (agg_func == "min") {
            result[key] = *std::min_element(values.begin(), values.end());
        } else if (agg_func == "max") {
            result[key] = *std::max_element(values.begin(), values.end());
        }
    }

    return result;
}

std::map<std::string, double> group_by_aggregate_single(
    const std::vector<Record>& records,
    const std::string& group_key,
    const std::string& agg_func
) {
    std::map<std::string, std::vector<double>> groups;
    for (const auto& record : records) {
        std::string key = (group_key == "category") ? record.category : record.region;
        groups[key].push_back(record.value);
    }

    std::map<std::string, double> result;
    for (const auto& [key, values] : groups) {
        if (agg_func == "mean") {
            double sum = 0.0;
            for (double v : values) sum += v;
            result[key] = sum / values.size();
        } else if (agg_func == "count") {
            result[key] = values.size();
        } else if (agg_func == "min") {
            result[key] = *std::min_element(values.begin(), values.end());
        }
    }
    return result;
}

