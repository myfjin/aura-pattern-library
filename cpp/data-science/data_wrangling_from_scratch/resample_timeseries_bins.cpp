#include <cassert>
#include <cstdio>
#include <map>
#include <cstring>
#include <string>
#include <tuple>
#include <vector>

struct Record {
    std::string timestamp;
    double value;
};

std::tuple<int, int, int, int> parse_timestamp(const std::string& ts) {
    int year, month, day, hour, minute;
    sscanf(ts.c_str(), "%d-%d-%d %d:%d", &year, &month, &day, &hour, &minute);
    return {year, month, day, hour};
}

std::map<std::tuple<int, int, int, int>, double> bucket_hourly(
    const std::vector<Record>& records) {
    std::map<std::tuple<int, int, int, int>, double> buckets;
    for (const auto& r : records) {
        auto key = parse_timestamp(r.timestamp);
        buckets[key] += r.value;
    }
    return buckets;
}

std::map<std::tuple<int, int, int>, double> bucket_daily(
    const std::vector<Record>& records) {
    std::map<std::tuple<int, int, int>, double> buckets;
    for (const auto& r : records) {
        auto [year, month, day, hour] = parse_timestamp(r.timestamp);
        std::tuple<int, int, int> key = {year, month, day};
        buckets[key] += r.value;
    }
    return buckets;
}

std::map<std::tuple<int, int, int, int>, double> brute_force_hourly(
    const std::vector<Record>& records) {
    std::map<std::tuple<int, int, int, int>, double> result;
    for (const auto& r : records) {
        auto key = parse_timestamp(r.timestamp);
        double total = 0.0;
        for (const auto& s : records) {
            if (parse_timestamp(s.timestamp) == key) total += s.value;
        }
        result[key] = total;
    }
    return result;
}

