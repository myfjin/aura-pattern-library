// Soundex phonetic encoding.

char soundex_digit(char c) {
    switch (std::toupper(static_cast<unsigned char>(c))) {
        case 'B': case 'F': case 'P': case 'V': return '1';
        case 'C': case 'G': case 'J': case 'K': case 'Q': case 'S': case 'X': case 'Z': return '2';
        case 'D': case 'T': return '3';
        case 'L': return '4';
        case 'M': case 'N': return '5';
        case 'R': return '6';
        default: return '0';
    }
}

std::string soundex(std::string_view name) {
    if (name.empty()) return "";
    std::string upper;
    upper.reserve(name.size());
    for (char ch : name) upper.push_back(std::toupper(static_cast<unsigned char>(ch)));

    std::string code;
    code.push_back(upper[0]);
    char prev_digit = soundex_digit(upper[0]);

    for (size_t i = 1; i < upper.size(); ++i) {
        char digit = soundex_digit(upper[i]);
        if (digit != '0' && digit != prev_digit) {
            code.push_back(digit);
            if (code.size() == 4) break;
        }
        prev_digit = digit;
    }

    code.append("000");
    code.resize(4);
    return code;
}

