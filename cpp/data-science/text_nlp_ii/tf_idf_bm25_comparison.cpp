// TF-IDF vs BM25 comparison on length-biased documents.

vector<double> tf_idf(const vector<vector<string>>& docs, const vector<string>& query) {
    size_t num_docs = docs.size();
    unordered_map<string, double> idf;
    unordered_set<string> vocab;
    for (const auto& d : docs) for (const string& t : d) vocab.insert(t);
    for (const string& term : vocab) {
        size_t doc_count = 0;
        for (const auto& d : docs) {
            unordered_set<string> s(d.begin(), d.end());
            if (s.count(term)) ++doc_count;
        }
        idf[term] = log((double)num_docs / (1.0 + (double)doc_count));
    }

    vector<double> scores;
    for (const auto& doc : docs) {
        double score = 0.0;
        for (const string& term : query) {
            int tf = count(doc.begin(), doc.end(), term);
            score += (double)tf * idf[term];
        }
        scores.push_back(score);
    }
    return scores;
}

vector<double> bm25(const vector<vector<string>>& docs, const vector<string>& query, double k1=1.5, double b=0.75) {
    size_t num_docs = docs.size();
    unordered_map<string, double> idf;
    unordered_set<string> vocab;
    for (const auto& d : docs) for (const string& t : d) vocab.insert(t);
    for (const string& term : vocab) {
        size_t doc_count = 0;
        for (const auto& d : docs) {
            unordered_set<string> s(d.begin(), d.end());
            if (s.count(term)) ++doc_count;
        }
        idf[term] = log(((double)num_docs - (double)doc_count + 0.5) / ((double)doc_count + 0.5) + 1.0);
    }

    double total_len = 0.0;
    for (const auto& d : docs) total_len += (double)d.size();
    double avg_len = num_docs ? total_len / (double)num_docs : 1.0;

    vector<double> scores;
    for (const auto& doc : docs) {
        double score = 0.0;
        for (const string& term : query) {
            int tf = count(doc.begin(), doc.end(), term);
            double norm_factor = k1 * (1.0 - b + b * (double)doc.size() / avg_len);
            score += idf[term] * (double)tf * (k1 + 1.0) / ((double)tf + norm_factor);
        }
        scores.push_back(score);
    }
    return scores;
}

