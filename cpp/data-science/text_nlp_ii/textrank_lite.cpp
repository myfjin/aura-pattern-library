// TextRank lite: sentence ranking via Jaccard-similarity graph centrality.

double jaccard_similarity(const vector<string>& a, const vector<string>& b) {
    unordered_set<string> sa(a.begin(), a.end());
    unordered_set<string> sb(b.begin(), b.end());
    if (sa.empty() || sb.empty()) return 0.0;
    size_t inter = 0;
    for (const string& w : sa) if (sb.count(w)) ++inter;
    size_t uni = sa.size() + sb.size() - inter;
    return uni > 0 ? (double)inter / (double)uni : 0.0;
}

vector<double> textrank_sentences(const vector<vector<string>>& sentences, double damping=0.85, int iterations=50) {
    size_t n = sentences.size();
    if (n == 0) return {};
    vector<vector<double>> W(n, vector<double>(n, 0.0));
    for (size_t i = 0; i < n; ++i)
        for (size_t j = 0; j < n; ++j)
            if (i != j) W[i][j] = jaccard_similarity(sentences[i], sentences[j]);

    vector<double> out_degree(n, 0.0);
    for (size_t j = 0; j < n; ++j)
        for (size_t k = 0; k < n; ++k) out_degree[j] += W[j][k];

    vector<double> ranks(n, 1.0 / (double)n);
    for (int it = 0; it < iterations; ++it) {
        vector<double> new_ranks(n, 0.0);
        for (size_t i = 0; i < n; ++i) {
            double incoming = 0.0;
            for (size_t j = 0; j < n; ++j) {
                if (i != j && out_degree[j] > 0.0)
                    incoming += (W[j][i] / out_degree[j]) * ranks[j];
            }
            new_ranks[i] = (1.0 - damping) / (double)n + damping * incoming;
        }
        ranks.swap(new_ranks);
    }
    return ranks;
}

