/*
 * Complement Naive Bayes: robust on imbalanced text via the negative-class model.
 *
 * Oracle asserts:
 *   nb_pred(["good","bad"]) == 0
 *   cnb_pred(["good","bad"]) == 1
 *   cnb_rec > nb_rec
 *   clear minority doc correct
 */

#include <vector>
#include <string>
#include <map>
#include <set>
#include <cmath>
#include <cassert>
#include <iostream>
#include <tuple>

using Doc = std::vector<std::string>;

std::tuple<std::map<int, std::map<std::string, double>>, std::map<int, double>, std::set<std::string>> naive_bayes_fit(
    const std::vector<Doc>& docs, const std::vector<int>& labels) {
    std::set<int> classes;
    std::set<std::string> vocab;
    for (int c : labels) classes.insert(c);
    for (const auto& d : docs) for (const auto& w : d) vocab.insert(w);
    int V = vocab.size(), N = docs.size();
    std::map<int, std::map<std::string, double>> loglik;
    std::map<int, double> logprior;
    for (int c : classes) {
        std::map<std::string, int> counts;
        int class_count = 0, total = 0;
        for (size_t i = 0; i < docs.size(); ++i) {
            if (labels[i] == c) {
                ++class_count;
                for (const auto& w : docs[i]) { ++counts[w]; ++total; }
            }
        }
        for (const auto& w : vocab) loglik[c][w] = std::log((counts[w] + 1.0) / (total + V));
        logprior[c] = std::log(class_count / static_cast<double>(N));
    }
    return {loglik, logprior, vocab};
}

int naive_bayes_predict(const Doc& doc,
                       const std::map<int, std::map<std::string, double>>& loglik,
                       const std::map<int, double>& logprior,
                       const std::set<std::string>& vocab) {
    int best = 0;
    double best_score = -1e18;
    for (const auto& kv : loglik) {
        int c = kv.first;
        double s = logprior.at(c);
        for (const auto& w : doc) if (vocab.count(w)) s += kv.second.at(w);
        if (s > best_score) { best_score = s; best = c; }
    }
    return best;
}

std::tuple<std::map<int, std::map<std::string, double>>, std::set<std::string>> complement_nb_fit(
    const std::vector<Doc>& docs, const std::vector<int>& labels) {
    std::set<int> classes;
    std::set<std::string> vocab;
    for (int c : labels) classes.insert(c);
    for (const auto& d : docs) for (const auto& w : d) vocab.insert(w);
    int V = vocab.size();
    std::map<int, std::map<std::string, double>> comp_weights;
    for (int c : classes) {
        std::map<std::string, int> counts;
        int total = 0;
        for (size_t i = 0; i < docs.size(); ++i) {
            if (labels[i] != c) {
                for (const auto& w : docs[i]) { ++counts[w]; ++total; }
            }
        }
        for (const auto& w : vocab) comp_weights[c][w] = std::log((counts[w] + 1.0) / (total + V));
    }
    return {comp_weights, vocab};
}

int complement_nb_predict(const Doc& doc,
                          const std::map<int, std::map<std::string, double>>& comp_weights,
                          const std::set<std::string>& vocab) {
    int best = 0;
    double best_score = 1e18;
    for (const auto& kv : comp_weights) {
        int c = kv.first;
        double s = 0.0;
        for (const auto& w : doc) if (vocab.count(w)) s += kv.second.at(w);
        if (s < best_score) { best_score = s; best = c; }
    }
    return best;
}

int main() {
    std::vector<Doc> train_docs(90, Doc{"good", "nice"});
    train_docs.insert(train_docs.end(), 10, Doc{"bad", "awful"});
    std::vector<int> train_labels(90, 0);
    train_labels.insert(train_labels.end(), 10, 1);

    // Keep the fit results as named tuples: C++17 forbids capturing structured bindings in a
    // lambda (clang++ -pedantic rejects; g++ accepted it as an extension). std::get in the
    // lambda avoids the capture entirely.
    auto nb_model = naive_bayes_fit(train_docs, train_labels);
    auto cnb_model = complement_nb_fit(train_docs, train_labels);

    std::vector<std::pair<Doc, int>> test = {
        {Doc{"good", "nice"}, 0}, {Doc{"bad", "awful"}, 1},
        {Doc{"good", "bad"}, 1}, {Doc{"good", "bad"}, 0}
    };
    // Actually oracle uses a lambda minority_recall over specific test set; replicate.
    auto nb_pred = [&](const Doc& d) {
        return naive_bayes_predict(d, std::get<0>(nb_model), std::get<1>(nb_model), std::get<2>(nb_model)); };
    auto cnb_pred = [&](const Doc& d) {
        return complement_nb_predict(d, std::get<0>(cnb_model), std::get<1>(cnb_model)); };

    assert(nb_pred(Doc{"good", "bad"}) == 0);
    assert(cnb_pred(Doc{"good", "bad"}) == 1);

    int nb_cor = 0, cnb_cor = 0, tot = 0;
    for (const auto& [d, y] : test) {
        if (y == 1) {
            ++tot;
            if (nb_pred(d) == 1) ++nb_cor;
            if (cnb_pred(d) == 1) ++cnb_cor;
        }
    }
    assert(cnb_cor > nb_cor);
    assert(nb_pred(Doc{"bad", "awful"}) == 1);
    assert(cnb_pred(Doc{"bad", "awful"}) == 1);

    std::cout << "naive_bayes_complement.cpp PASS" << std::endl;
    return 0;
}
