/* Zipf's law: rank-frequency relationship in natural language. */
#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <algorithm>

double fit_zipf(const std::vector<double>& freqs) {
    std::vector<double> sf = freqs;
    std::sort(sf.begin(), sf.end(), std::greater<double>());
    int n = static_cast<int>(sf.size());
    std::vector<double> log_ranks(n), log_freqs(n);
    for (int i = 0; i < n; ++i) {
        log_ranks[i] = std::log(i + 1.0);
        log_freqs[i] = sf[i] > 0 ? std::log(sf[i]) : 0.0;
    }
    double mr = 0.0, mf = 0.0;
    for (int i = 0; i < n; ++i) { mr += log_ranks[i]; mf += log_freqs[i]; }
    mr /= n; mf /= n;
    double cov = 0.0, var = 0.0;
    for (int i = 0; i < n; ++i) {
        cov += (log_ranks[i] - mr) * (log_freqs[i] - mf);
        var += (log_ranks[i] - mr) * (log_ranks[i] - mr);
    }
    cov /= n; var /= n;
    return var > 0 ? -cov / var : 0.0;
}

int main() {
    std::vector<double> natural_freqs, uniform_freqs;
    for (int i = 0; i < 50; ++i) natural_freqs.push_back(10.0 * std::pow(i + 1.0, -1.2));
    uniform_freqs.assign(50, 10.0);
    double slope_natural = fit_zipf(natural_freqs);
    double slope_uniform = fit_zipf(uniform_freqs);
    std::cout << "natural slope=" << slope_natural << " uniform slope=" << slope_uniform << "\n";
    assert(0.5 < slope_natural && slope_natural < 2.0);
    assert(slope_uniform < 0.5);
    std::cout << "zipf_law_fit PASS\n";
    return 0;
}
