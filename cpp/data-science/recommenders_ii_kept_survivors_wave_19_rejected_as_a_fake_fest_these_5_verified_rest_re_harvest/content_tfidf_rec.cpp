/*
 * Content-Based TF-IDF Recommendation
 * 
 * Recommend items similar in content using cosine similarity.
 */

#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>
#include <unordered_map>
#include <algorithm>

double tfidf_similarity(const std::vector<double>& doc1, const std::vector<double>& doc2) {
    /* Cosine similarity of two documents (word counts). */
    double dot = 0.0, norm1 = 0.0, norm2 = 0.0;
    for (size_t i = 0; i < doc1.size(); ++i) {
        dot += doc1[i] * doc2[i];
        norm1 += doc1[i] * doc1[i];
        norm2 += doc2[i] * doc2[i];
    }
    return dot / (std::sqrt(norm1) * std::sqrt(norm2) + 1e-10);
}

int main() {
    // Planted: item content (bag-of-words).
    // Items 0,1 are topic A; items 2,3 are topic B.
    std::unordered_map<int, std::vector<double>> items = {
        {0, {10.0, 5.0, 1.0, 1.0}},   // Topic A heavy.
        {1, {8.0, 6.0, 1.0, 1.0}},    // Topic A.
        {2, {1.0, 1.0, 10.0, 5.0}},   // Topic B heavy.
        {3, {1.0, 1.0, 8.0, 6.0}},    // Topic B.
    };

    // Query: item 0 (topic A). Should recommend item 1 as top-1.
    int query_item = 0;
    const auto& query_content = items[query_item];

    // Compute similarity to all items.
    std::unordered_map<int, double> similarities;
    for (const auto& kv : items) {
        similarities[kv.first] = tfidf_similarity(query_content, kv.second);
    }

    // Top-1 recommendation (excluding self).
    int top_1_candidate = -1;
    double max_sim = -1.0;
    for (const auto& kv : similarities) {
        if (kv.first != query_item && kv.second > max_sim) {
            max_sim = kv.second;
            top_1_candidate = kv.first;
        }
    }

    // Top-1 should be item 1 (same topic A, not self).
    assert(top_1_candidate == 1);

    std::cout << "content_tfidf_rec.cpp PASS" << std::endl;
    return 0;
}
