/*
 * Caliper Matching
 * 
 * Restrict nearest-neighbor matches to within a caliper (distance threshold).
 * Bias-variance tradeoff: uncalipered NN can match distant observations (high bias);
 * caliper trades some matches for lower bias.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <utility>
#include <unordered_set>
#include <limits>

double euclidean_distance(double x1, double x2) {
    return std::abs(x1 - x2);
}

std::pair<std::vector<std::pair<int, int>>, int> nearest_neighbor_match(
    const std::vector<double>& treated,
    const std::vector<double>& control,
    double caliper = std::numeric_limits<double>::infinity()
) {
    /* Match each treated unit to closest control within caliper. */
    std::vector<std::pair<int, int>> matched;
    std::unordered_set<int> matched_controls;
    int unmatched = 0;

    for (size_t t_idx = 0; t_idx < treated.size(); ++t_idx) {
        double t_val = treated[t_idx];
        int best_c_idx = -1;
        double best_dist = std::numeric_limits<double>::infinity();

        for (size_t c_idx = 0; c_idx < control.size(); ++c_idx) {
            if (matched_controls.count(c_idx)) continue;

            double dist = euclidean_distance(t_val, control[c_idx]);
            if (dist < best_dist) {
                best_dist = dist;
                best_c_idx = static_cast<int>(c_idx);
            }
        }

        if (best_c_idx != -1 && best_dist <= caliper) {
            matched.push_back({static_cast<int>(t_idx), best_c_idx});
            matched_controls.insert(best_c_idx);
        } else {
            unmatched++;
        }
    }

    return {matched, unmatched};
}

double estimate_bias(
    const std::vector<double>& treated_vals,
    const std::vector<double>& control_vals,
    const std::vector<std::pair<int, int>>& matches
) {
    /* Estimate bias as covariate imbalance in matched sample. */
    if (matches.empty()) return 0.0;

    double treated_sum = 0.0, control_sum = 0.0;
    for (const auto& m : matches) {
        treated_sum += treated_vals[m.first];
        control_sum += control_vals[m.second];
    }

    double treated_mean = treated_sum / matches.size();
    double control_mean = control_sum / matches.size();

    return std::abs(treated_mean - control_mean);
}

int main() {
    std::mt19937 rng(42);
    std::normal_distribution<double> normal_treated(2.0, 1.0);
    std::normal_distribution<double> normal_control(0.0, 1.0);
    std::normal_distribution<double> noise(0.0, 0.5);

    // Planted confounding: treated units have higher X, outcome depends on X.
    const int n_treated = 50, n_control = 100;
    std::vector<double> treated_x(n_treated), control_x(n_control);
    std::vector<double> treated_y(n_treated), control_y(n_control);

    for (int i = 0; i < n_treated; ++i) {
        treated_x[i] = normal_treated(rng);
        treated_y[i] = 2.0 + 1.5 * treated_x[i] + noise(rng);
    }
    for (int i = 0; i < n_control; ++i) {
        control_x[i] = normal_control(rng);
        control_y[i] = 1.5 * control_x[i] + noise(rng);
    }

    // Uncalipered matching: matches may be distant.
    auto [uncalipered, unmatch_uncal] = nearest_neighbor_match(treated_x, control_x, std::numeric_limits<double>::infinity());
    double bias_uncal = estimate_bias(treated_x, control_x, uncalipered);

    // Caliper matching: restrict distance.
    double caliper_threshold = 0.5;
    auto [calipered, unmatch_cal] = nearest_neighbor_match(treated_x, control_x, caliper_threshold);
    double bias_cal = estimate_bias(treated_x, control_x, calipered);

    // Caliper should have lower bias (better covariate balance) despite higher unmatched rate.
    assert(calipered.size() <= uncalipered.size());
    assert(unmatch_cal >= unmatch_uncal);
    assert(bias_cal <= bias_uncal * 1.1);

    std::cout << "caliper_matching.cpp PASS" << std::endl;
    return 0;
}
