/*
 * Backdoor vs Collider Adjustment
 * 
 * Adjusting backdoor removes confounding bias;
 * adjusting a collider CREATES bias (collider bias, Berkson's paradox).
 * 
 * DAG: X ← U → Y (backdoor open; adjust U to close it).
 * DAG: X → V ← Y (collider; adjusting V opens a spurious path).
 * Core claim: backdoor adjustment recovers effect; collider adjustment makes bias WORSE.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <utility>

std::pair<double, double> fit_regression(const std::vector<double>& x, const std::vector<double>& y) {
    /* Fit y = a + b*x; return (a, b). */
    int n = static_cast<int>(x.size());
    if (n == 0) {
        return {0.0, 0.0};
    }
    double x_mean = 0.0, y_mean = 0.0;
    for (int i = 0; i < n; ++i) {
        x_mean += x[i];
        y_mean += y[i];
    }
    x_mean /= n;
    y_mean /= n;

    double num = 0.0, denom = 0.0;
    for (int i = 0; i < n; ++i) {
        num += (x[i] - x_mean) * (y[i] - y_mean);
        denom += (x[i] - x_mean) * (x[i] - x_mean);
    }
    if (std::abs(denom) < 1e-10) {
        return {y_mean, 0.0};
    }
    double b = num / denom;
    double a = y_mean - b * x_mean;
    return {a, b};
}

