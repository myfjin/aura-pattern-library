/*
 * Autocovariance and Power Spectral Density (Periodogram)
 * 
 * Periodogram = DFT of autocovariance function.
 * For a signal with strong periodicity, the periodogram should show a peak at that frequency.
 * We plant a periodic signal and verify the periodogram peaks at the correct frequency.
 */

#include <vector>
#include <cmath>
#include <random>
#include <cassert>
#include <iostream>
#include <algorithm>

std::vector<double> autocovariance(const std::vector<double>& signal, int max_lag) {
    /*
     * Compute autocovariance at lags 0, 1, ..., max_lag.
     */
    int n = static_cast<int>(signal.size());
    double sum = 0.0;
    for (const auto& s : signal) {
        sum += s;
    }
    double mean_signal = sum / n;

    std::vector<double> acov;
    acov.reserve(max_lag + 1);
    for (int lag = 0; lag <= max_lag; ++lag) {
        double cov = 0.0;
        for (int i = 0; i < n - lag; ++i) {
            cov += (signal[i] - mean_signal) * (signal[i + lag] - mean_signal);
        }
        acov.push_back(cov / n);
    }

    return acov;
}

std::vector<double> periodogram_from_acov(const std::vector<double>& acov) {
    /*
     * Compute periodogram via FFT of autocovariance.
     * Periodogram[k] = |FFT(acov)[k]|.
     */
    int m = static_cast<int>(acov.size());

    // Compute DFT of autocovariance
    std::vector<double> periodogram;
    periodogram.reserve(m / 2 + 1);
    for (int k = 0; k <= m / 2; ++k) {
        double real_part = 0.0;
        double imag_part = 0.0;

        for (int n = 0; n < m; ++n) {
            double angle = -2.0 * M_PI * k * n / m;
            real_part += acov[n] * std::cos(angle);
            imag_part += acov[n] * std::sin(angle);
        }

        double magnitude = std::sqrt(real_part * real_part + imag_part * imag_part);
        periodogram.push_back(magnitude);
    }

    return periodogram;
}

int main() {
    std::mt19937 rng(42);
    std::normal_distribution<double> normal(0.0, 0.1);

    // Create periodic signal: 10 Hz component
    const int fs = 100;  // Sampling frequency
    const double duration = 1.0;
    const int n_samples = static_cast<int>(fs * duration);

    const double freq = 10.0;
    std::vector<double> signal;
    signal.reserve(n_samples);
    for (int t = 0; t < n_samples; ++t) {
        signal.push_back(std::sin(2.0 * M_PI * freq * t / fs) + normal(rng));
    }

    // Compute autocovariance
    const int max_lag = 50;
    auto acov = autocovariance(signal, max_lag);

    // Compute periodogram
    auto periodogram = periodogram_from_acov(acov);

    // Find peak (excluding very low frequencies which are DC)
    int peak_idx = 2;
    for (size_t i = 3; i < periodogram.size(); ++i) {
        if (periodogram[i] > periodogram[peak_idx]) {
            peak_idx = static_cast<int>(i);
        }
    }

    // Frequency mapping: index k corresponds to k * fs / len(periodogram) Hz
    // But acov-based periodogram: bin k <-> k * fs / (2 * max_lag) Hz
    double freq_resolution = fs / static_cast<double>(acov.size());
    double detected_freq = peak_idx * freq_resolution;

    // Check: peak should be near the planted frequency
    double freq_error = std::abs(detected_freq - freq);

    assert(freq_error < 2.0);  // Periodogram peak should be close to planted frequency
    assert(periodogram[peak_idx] > periodogram[peak_idx - 1]);  // Peak is local max
    assert(periodogram[peak_idx] > periodogram[peak_idx + 1]);  // Peak is local max

    std::cout << "Planted frequency: " << freq << " Hz | "
              << "Detected frequency: " << detected_freq << " Hz | "
              << "Peak value: " << periodogram[peak_idx] << " | "
              << "Error: " << freq_error << " Hz | PASS" << std::endl;
    return 0;
}
