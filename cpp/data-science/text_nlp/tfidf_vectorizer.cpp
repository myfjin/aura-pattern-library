    vector<string> corpus = {
        "apple banana cherry",
        "apple apple orange",
        "banana cherry date",
        "date fig grape",
        "grape apple fruit",
    };

    TFIDFVectorizer tfidf(true);
    tfidf.fit(corpus);

    vector<vector<double>> vectors;
    for (const string& doc : corpus) vectors.push_back(tfidf.get_dense_vector(doc));

    assert(tfidf.idf.at("apple") < tfidf.idf.at("date"));

