// TF-IDF Vectorizer: learn IDF from corpus, transform documents to sparse/dense vectors.

static vector<string> tokenize(const string& text) {
    vector<string> out;
    regex re(R"(\b[a-z]+\b)");
    string lower;
    lower.reserve(text.size());
    for (char c : text) lower.push_back(tolower(c));
    for (sregex_iterator it(lower.begin(), lower.end(), re), end; it != end; ++it)
        out.push_back((*it).str());
    return out;
}

class TFIDFVectorizer {
public:
    bool smooth_idf;
    unordered_map<string, double> idf;
    map<string, int> vocab; // sorted gives stable IDs
    int doc_count = 0;

    TFIDFVectorizer(bool smooth=true) : smooth_idf(smooth) {}

    void fit(const vector<string>& documents) {
        doc_count = (int)documents.size();
        unordered_map<string, int> doc_freq;
        for (const string& doc : documents) {
            auto words = tokenize(doc);
            unordered_set<string> uniq(words.begin(), words.end());
            for (const string& w : uniq) doc_freq[w]++;
        }
        for (const auto& kv : doc_freq) vocab[kv.first] = 0;
        int id = 0;
        for (auto& kv : vocab) kv.second = id++;
        for (const auto& kv : doc_freq) {
            if (smooth_idf) idf[kv.first] = log((doc_count + 1.0) / (kv.second + 1.0)) + 1.0;
            else idf[kv.first] = log((double)doc_count / (double)kv.second);
        }
    }

    unordered_map<int, double> transform(const string& text) const {
        unordered_map<int, double> tfidf;
        auto words = tokenize(text);
        unordered_map<string, int> tf;
        for (const string& w : words) {
            auto it = vocab.find(w);
            if (it != vocab.end()) tf[w]++;
        }
        for (const auto& kv : tf) {
            int wid = vocab.at(kv.first);
            tfidf[wid] = (double)kv.second * idf.at(kv.first);
        }
        return tfidf;
    }

    vector<double> get_dense_vector(const string& text) const {
        vector<double> dense(vocab.size(), 0.0);
        auto sparse = transform(text);
        for (const auto& kv : sparse) dense[kv.first] = kv.second;
        return dense;
    }
};

double cosine_similarity(const vector<double>& a, const vector<double>& b) {
    double dot=0, n1=0, n2=0;
    size_t n = a.size();
    for (size_t i=0;i<n;++i){ dot += a[i]*b[i]; n1 += a[i]*a[i]; n2 += b[i]*b[i]; }
    if (n1==0 || n2==0) return 0.0;
    return dot / (sqrt(n1)*sqrt(n2));
}

