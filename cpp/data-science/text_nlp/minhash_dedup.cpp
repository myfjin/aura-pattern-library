/*
 * MinHash Signatures for Near-Duplicate Detection.
 *
 * Oracle asserts:
 *   signatures computed for each doc
 *   self-similarity == 1.0
 *   MinHash estimate within 0.15 of exact Jaccard for doc0/doc1
 *   known similar pairs detected
 *   exact Jaccard symmetric
 */

#include <string>
#include <vector>
#include <set>
#include <map>
#include <sstream>
#include <algorithm>
#include <cassert>
#include <iostream>

class MinHashDedup {
public:
    explicit MinHashDedup(int num_hashes = 256) : num_hashes_(num_hashes) {
        for (int i = 0; i < num_hashes; ++i) seeds_.push_back(i);
    }

    std::set<std::string> tokenize(const std::string& text) const {
        std::string lower;
        for (unsigned char c : text) lower += std::tolower(c);
        std::set<std::string> words;
        std::istringstream iss(lower);
        std::string w;
        while (iss >> w) words.insert(w);
        return words;
    }

    unsigned int hash_shingle(const std::string& shingle, int seed) const {
        std::string input = std::to_string(seed) + ":" + shingle;
        unsigned int hash = 2166136261u;
        for (unsigned char c : input) {
            hash ^= c;
            hash *= 16777619u;
        }
        return hash;
    }

    std::vector<unsigned int> compute_signature(const std::string& text) const {
        auto shingles = tokenize(text);
        std::vector<unsigned int> signature;
        for (int seed : seeds_) {
            unsigned int min_hash = 0xFFFFFFFF;
            for (const auto& s : shingles) min_hash = std::min(min_hash, hash_shingle(s, seed));
            if (min_hash == 0xFFFFFFFF) min_hash = 0;
            signature.push_back(min_hash);
        }
        return signature;
    }

    void fit_signatures(const std::vector<std::string>& documents) {
        signatures_.clear();
        for (const auto& doc : documents) signatures_.push_back(compute_signature(doc));
    }

    double estimated_jaccard(const std::vector<unsigned int>& sig1,
                             const std::vector<unsigned int>& sig2) const {
        if (sig1.size() != sig2.size()) return 0.0;
        int matches = 0;
        for (size_t i = 0; i < sig1.size(); ++i) if (sig1[i] == sig2[i]) ++matches;
        return matches / static_cast<double>(sig1.size());
    }

    static double exact_jaccard(const std::set<std::string>& a, const std::set<std::string>& b) {
        if (a.empty() && b.empty()) return 1.0;
        int inter = 0;
        for (const auto& x : a) if (b.count(x)) ++inter;
        int uni = static_cast<int>(a.size() + b.size() - inter);
        if (uni == 0) return 0.0;
        return inter / static_cast<double>(uni);
    }

    std::vector<std::tuple<int, int, double>> find_similar_pairs(double threshold) const {
        std::vector<std::tuple<int, int, double>> pairs;
        for (size_t i = 0; i < signatures_.size(); ++i) {
            for (size_t j = i + 1; j < signatures_.size(); ++j) {
                double sim = estimated_jaccard(signatures_[i], signatures_[j]);
                if (sim >= threshold) pairs.push_back({static_cast<int>(i), static_cast<int>(j), sim});
            }
        }
        return pairs;
    }

    const std::vector<std::vector<unsigned int>>& signatures() const { return signatures_; }

private:
    int num_hashes_;
    std::vector<int> seeds_;
    std::vector<std::vector<unsigned int>> signatures_;
};

