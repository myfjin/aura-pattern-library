struct EWMAMetric {
    double alpha;
    std::optional<double> value;
    int count = 0;
    explicit EWMAMetric(double alpha_=0.3) : alpha(alpha_) {}
    double update(double x) {
        ++count;
        if (!value.has_value()) value = x;
        else value = alpha * x + (1.0 - alpha) * value.value();
        return value.value();
    }
};

struct SMAMetric {
    size_t window_size;
    std::vector<double> values;
    explicit SMAMetric(size_t ws=10) : window_size(ws) {}
    double update(double x) {
        values.push_back(x);
        if (values.size() > window_size) values.erase(values.begin());
        double s = 0.0;
        for (double v : values) s += v;
        return s / static_cast<double>(values.size());
    }
};

