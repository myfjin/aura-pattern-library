    std::map<std::string, int> funnel = {
        {"visit", n_visit},
        {"signup", signup_count},
        {"trial", trial_count},
        {"purchase", purchase_count}
    };

    std::map<std::string, std::pair<double, double>> rates_ci;
    std::map<std::string, double> rates_point;

