std::pair<double, double> wilson_confidence_interval(int successes, int trials, double confidence = 0.95) {
    if (trials == 0) return {0.0, 1.0};
    double z = (confidence == 0.95) ? 1.96 : (confidence == 0.90) ? 1.645 : 1.96;
    double p_hat = static_cast<double>(successes) / static_cast<double>(trials);
    double z_sq = z * z;
    double denom = 1.0 + z_sq / static_cast<double>(trials);
    double center = (p_hat + z_sq / (2.0 * trials)) / denom;
    double margin = z * std::sqrt(p_hat * (1.0 - p_hat) / trials +
                                  z_sq / (4.0 * trials * trials)) / denom;
    return {std::max(0.0, center - margin), std::min(1.0, center + margin)};
}

