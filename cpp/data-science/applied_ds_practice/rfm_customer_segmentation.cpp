/*
RFM customer segmentation: derives recency, frequency, and monetary value per
user from a transaction log, quartile-scores each axis (recency reversed so
recent buyers score high), and maps the R/F/M scores to segments such as whale,
frequent, at_risk, and churned. Use for behavioral customer tiering. Oracle:
on planted whale/regular/churned cohorts, whale and churned each capture >10
users and the whale average frequency exceeds the churned average.
*/
#include <algorithm>
#include <cassert>
#include <cstdio>
#include <map>
#include <random>
#include <set>
#include <string>
#include <vector>

struct Transaction {
    int user_id;
    int purchase_date;
    double amount;
};

struct Metrics {
    int recency = 0;
    int frequency = 0;
    double monetary = 0.0;
};

std::map<int, Metrics> compute_rfm_metrics(const std::vector<Transaction>& transactions) {
    std::map<int, Metrics> user_metrics;
    int max_date = transactions[0].purchase_date;
    for (const auto& t : transactions) {
        if (t.purchase_date > max_date) max_date = t.purchase_date;
    }

    for (const auto& t : transactions) {
        Metrics& m = user_metrics[t.user_id];
        m.frequency += 1;
        m.monetary += t.amount;
        m.recency = max_date - t.purchase_date;
    }
    return user_metrics;
}

std::map<double, int> quartile_score(const std::vector<double>& values, bool recency_flag) {
    std::set<double> unique(values.begin(), values.end());
    std::vector<double> sorted_vals(unique.begin(), unique.end());
    int n = static_cast<int>(sorted_vals.size());

    int q1_idx = std::max(0, n / 4 - 1);
    int q2_idx = std::max(0, n / 2 - 1);
    int q3_idx = std::max(0, 3 * n / 4 - 1);

    double b1 = sorted_vals[q1_idx];
    double b2 = sorted_vals[q2_idx];
    double b3 = sorted_vals[q3_idx];

    std::map<double, int> score_map;
    for (double v : values) {
        int score;
        if (v <= b1) score = 1;
        else if (v <= b2) score = 2;
        else if (v <= b3) score = 3;
        else score = 4;

        if (recency_flag) score = 5 - score;
        score_map[v] = score;
    }
    return score_map;
}

std::string segment_from_rfm(int r, int f, int m) {
    if (r >= 3 && f >= 3 && m >= 3) return "whale";
    if (r <= 2 && f <= 2 && m <= 2) return "churned";
    if (f >= 3 && m >= 3) return "frequent";
    if (r <= 2) return "at_risk";
    return "regular";
}

int main() {
    std::mt19937 gen(42);
    std::vector<Transaction> transactions;

    // Whale customers: frequent, high spend, recent.
    for (int u_id = 0; u_id < 20; ++u_id) {
        std::uniform_int_distribution<int> freq_dist(8, 15);
        std::uniform_real_distribution<double> amount_dist(100.0, 500.0);
        std::uniform_int_distribution<int> days_dist(0, 30);
        int freq = freq_dist(gen);
        for (int i = 0; i < freq; ++i) {
            int days_ago = days_dist(gen);
            double amount = amount_dist(gen);
            transactions.push_back({u_id, 100 - days_ago, amount});
        }
    }

    // Regular customers: moderate activity.
    for (int u_id = 20; u_id < 60; ++u_id) {
        std::uniform_int_distribution<int> freq_dist(2, 5);
        std::uniform_real_distribution<double> amount_dist(20.0, 100.0);
        std::uniform_int_distribution<int> days_dist(0, 90);
        int freq = freq_dist(gen);
        for (int i = 0; i < freq; ++i) {
            int days_ago = days_dist(gen);
            double amount = amount_dist(gen);
            transactions.push_back({u_id, 100 - days_ago, amount});
        }
    }

    // Churned customers: old activity, low frequency, low spend.
    for (int u_id = 60; u_id < 100; ++u_id) {
        std::uniform_int_distribution<int> freq_dist(1, 2);
        std::uniform_real_distribution<double> amount_dist(5.0, 30.0);
        std::uniform_int_distribution<int> days_dist(200, 365);
        int freq = freq_dist(gen);
        for (int i = 0; i < freq; ++i) {
            int days_ago = days_dist(gen);
            double amount = amount_dist(gen);
            transactions.push_back({u_id, 100 - days_ago, amount});
        }
    }

    auto user_metrics = compute_rfm_metrics(transactions);

    std::vector<double> recencies, frequencies, monetaries;
    for (const auto& kv : user_metrics) {
        recencies.push_back(kv.second.recency);
        frequencies.push_back(kv.second.frequency);
        monetaries.push_back(kv.second.monetary);
    }

    auto r_score_map = quartile_score(recencies, true);
    auto f_score_map = quartile_score(frequencies, false);
    auto m_score_map = quartile_score(monetaries, false);

    std::map<std::string, std::vector<int>> segments;
    for (const auto& kv : user_metrics) {
        int r = r_score_map[kv.second.recency];
        int f = f_score_map[kv.second.frequency];
        int m = m_score_map[kv.second.monetary];
        segments[segment_from_rfm(r, f, m)].push_back(kv.first);
    }

    assert(segments["whale"].size() > 10);
    assert(segments["churned"].size() > 10);

    double avg_whale_freq = 0.0, avg_churned_freq = 0.0;
    for (int u : segments["whale"]) avg_whale_freq += user_metrics[u].frequency;
    for (int u : segments["churned"]) avg_churned_freq += user_metrics[u].frequency;
    avg_whale_freq /= segments["whale"].size();
    avg_churned_freq /= segments["churned"].size();

    assert(avg_whale_freq > avg_churned_freq);

    printf("RFM Customer Segmentation\n");
    for (const auto& seg : {"whale", "frequent", "regular", "at_risk", "churned"}) {
        const auto& users = segments[seg];
        if (!users.empty()) {
            printf("%-15s: %2zu customers\n", seg, users.size());
        }
    }
    printf("  Whale avg frequency:   %.1f\n", avg_whale_freq);
    printf("  Churned avg frequency: %.1f\n", avg_churned_freq);
    printf("  Archetype separation: ok\n");
    printf("rfm_customer_segmentation.cpp PASS\n");
    return 0;
}
