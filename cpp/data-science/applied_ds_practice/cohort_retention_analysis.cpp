/*
 * Cohort Retention Analysis
 * 
 * Group users by cohort, track which cohorts return in subsequent periods,
 * and compute retention curves.
 */

#include <vector>
#include <string>
#include <unordered_map>
#include <unordered_set>
#include <algorithm>
#include <cassert>
#include <iostream>
#include <random>
#include <map>

struct Event {
    int user_id;
    std::string cohort;
    int period;
};

std::unordered_map<std::string, std::map<int, int>> build_cohort_table(const std::vector<Event>& events) {
    /* Build cohort retention table from events. */
    std::unordered_map<std::string, std::map<int, std::unordered_set<int>>> cohort_data;

    for (const auto& event : events) {
        cohort_data[event.cohort][event.period].insert(event.user_id);
    }

    // Convert sets to counts
    std::unordered_map<std::string, std::map<int, int>> cohort_table;
    for (const auto& kv : cohort_data) {
        for (const auto& p : kv.second) {
            cohort_table[kv.first][p.first] = static_cast<int>(p.second.size());
        }
    }

    return cohort_table;
}

std::unordered_map<std::string, std::vector<double>> compute_retention_rates(
    const std::unordered_map<std::string, std::map<int, int>>& cohort_table
) {
    /* Compute retention rates: users active in period p / users active in period 0. */
    std::unordered_map<std::string, std::vector<double>> retention_rates;

    for (const auto& kv : cohort_table) {
        const auto& cohort = kv.first;
        const auto& periods = kv.second;

        auto it = periods.find(0);
        if (it == periods.end() || it->second == 0) continue;

        int cohort_size = it->second;
        std::vector<double> rates;

        for (const auto& p : periods) {
            double rate = static_cast<double>(p.second) / cohort_size;
            rates.push_back(rate);
        }

        retention_rates[cohort] = rates;
    }

    return retention_rates;
}

int main() {
    std::mt19937 rng(42);
    std::uniform_real_distribution<double> uniform(0.0, 1.0);

    std::vector<Event> events;

    // Cohort A: 200 users, high retention (80% per period)
    for (int user_id = 0; user_id < 200; ++user_id) {
        events.push_back({user_id, "A", 0});
        for (int period = 1; period < 5; ++period) {
            if (uniform(rng) < std::pow(0.8, period)) {
                events.push_back({user_id, "A", period});
            }
        }
    }

    // Cohort B: 200 users, poor retention (50% per period)
    for (int user_id = 200; user_id < 400; ++user_id) {
        events.push_back({user_id, "B", 0});
        for (int period = 1; period < 5; ++period) {
            if (uniform(rng) < std::pow(0.5, period)) {
                events.push_back({user_id, "B", period});
            }
        }
    }

    // Build cohort table and compute retention
    auto cohort_table = build_cohort_table(events);
    auto retention_rates = compute_retention_rates(cohort_table);

    // Assertions: verify planted difference
    const auto& rates_a = retention_rates["A"];
    const auto& rates_b = retention_rates["B"];

    // Cohort A should have better (higher) retention at each period (starting p=1)
    for (size_t p = 1; p < rates_a.size(); ++p) {
        assert(rates_a[p] > rates_b[p]);
    }

    // At period 4, difference should be large
    assert(rates_a.back() > rates_b.back() * 2.0);

    std::cout << "cohort_retention_analysis.cpp PASS" << std::endl;
    return 0;
}
