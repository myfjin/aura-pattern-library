/*
Posterior contraction for a Gaussian mean under a Gaussian prior: the posterior
standard deviation is sqrt(1/(n + 1/prior_var)), which shrinks as data grows.
Use to reason about how fast Bayesian uncertainty collapses with sample size.
Oracle: going from n=50 to n=200 the posterior sd strictly decreases, and the
ratio sd(n2)/sd(n1) matches the theoretical sqrt(n1/n2) to within 0.1.
*/
#include <cassert>
#include <cmath>
#include <iostream>
#include <random>
#include <vector>

double posterior_std_gaussian(const std::vector<double>& data, double prior_mu, double prior_sigma_sq) {
    (void)prior_mu;
    std::size_t n = data.size();
    double posterior_var = 1.0 / (static_cast<double>(n) + 1.0 / prior_sigma_sq);
    return std::sqrt(posterior_var);
}

int main() {
    std::mt19937 gen(42);
    std::normal_distribution<double> dist(2.0, 1.0);

    int n1 = 50;
    std::vector<double> data1(n1);
    for (int i = 0; i < n1; ++i) data1[i] = dist(gen);
    double posterior_sd1 = posterior_std_gaussian(data1, 0.0, 10.0);

    int n2 = 200;
    std::vector<double> data2(n2);
    for (int i = 0; i < n2; ++i) data2[i] = dist(gen);
    double posterior_sd2 = posterior_std_gaussian(data2, 0.0, 10.0);

    double contraction_ratio = posterior_sd2 / posterior_sd1;
    double expected_ratio = std::sqrt(static_cast<double>(n1) / n2);

    assert(std::abs(contraction_ratio - expected_ratio) < 0.1);
    assert(posterior_sd2 < posterior_sd1);

    std::cout << "PASS" << std::endl;
    return 0;
}
