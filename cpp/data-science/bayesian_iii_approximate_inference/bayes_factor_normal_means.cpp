/*
 * Bayes Factor for Comparing Two Normal Means
 * 
 * BF = p(data|H1) / p(data|H0). Core claim: BF>1 when H1 is true AND BF<1 when H0 is true
 * (BOTH directions asserted; the two-sided test).
 */

#include <vector>
#include <cmath>
#include <random>
#include <numeric>
#include <cassert>
#include <iostream>
#include <limits>

double bayes_factor_normal(const std::vector<double>& data, double prior_var_h1 = 1.0) {
    /*
     * Compute Bayes factor for H1: θ ~ N(0, prior_var_h1) vs H0: θ=0.
     * Assumes data ~ N(θ, 1.0). Uses conjugate priors and closed-form marginal likelihoods.
     */
    int n = static_cast<int>(data.size());
    double S = std::accumulate(data.begin(), data.end(), 0.0);

    // Conjugate closed form: log BF = -1/2 log(1 + n*tau2) + 1/2 * tau2 * S^2 / (1 + n*tau2).
    // (The shipped version used y_mean^2*n/denom = S^2/(n*denom), missing the n*tau2 factor —
    // the wrong-math twin bug; snapshot preserved as bayes_factor_normal_means.BROKEN.cpp.)
    double denom = 1.0 + n * prior_var_h1;
    double log_bf = -0.5 * std::log(denom) + 0.5 * prior_var_h1 * S * S / denom;
    return (log_bf < 700.0) ? std::exp(log_bf) : std::numeric_limits<double>::infinity();
}

int main() {
    std::mt19937 rng(42);
    std::normal_distribution<double> normal(0.0, 1.0);

    // Case 1: data comes from H1 (θ_true = 2.0).
    const double theta_true_h1 = 2.0;
    std::vector<double> data_h1(30);
    for (int i = 0; i < 30; ++i) {
        data_h1[i] = normal(rng) + theta_true_h1;
    }
    double bf_h1 = bayes_factor_normal(data_h1, 1.0);

    // Case 2: data comes from H0 (θ_true = 0.0).
    const double theta_true_h0 = 0.0;
    std::vector<double> data_h0(30);
    for (int i = 0; i < 30; ++i) {
        data_h0[i] = normal(rng) + theta_true_h0;
    }
    double bf_h0 = bayes_factor_normal(data_h0, 1.0);

    // Under H1: BF should be > 1 (evidence for H1).
    assert(bf_h1 > 1.0);

    // Under H0: BF should be < 1 (evidence for H0).
    assert(bf_h0 < 1.0);

    std::cout << "bayes_factor_normal_means.cpp PASS" << std::endl;
    return 0;
}
