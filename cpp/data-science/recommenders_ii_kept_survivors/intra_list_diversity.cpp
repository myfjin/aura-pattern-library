#include <vector>
#include <cmath>
#include <cassert>
#include <iostream>

double avg_dissimilarity(const std::vector<std::vector<double>>& items) {
    int m = static_cast<int>(items.size());
    double total = 0.0;
    int count = 0;
    for (int i = 0; i < m; ++i) {
        for (int j = i + 1; j < m; ++j) {
            double dist = 0.0;
            int d = static_cast<int>(items[i].size());
            for (int k = 0; k < d; ++k) {
                double diff = items[i][k] - items[j][k];
                dist += diff * diff;
            }
            total += std::sqrt(dist);
            ++count;
        }
    }
    return count > 0 ? total / count : 0.0;
}

