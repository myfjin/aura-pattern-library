type BackpressureQ struct {
	q         chan string
	maxSize   int
	peakDepth int
	refused   int
	timeout   time.Duration
}

// NewBackpressureQ creates a new bounded queue.
func NewBackpressureQ(size int, timeout time.Duration) *BackpressureQ {
	return &BackpressureQ{
		q:       make(chan string, size),
		maxSize: size,
		timeout: timeout,
	}
}

// PutItem tries to put item; returns true if accepted, false if refused.
func (b *BackpressureQ) PutItem(item string) bool {
	select {
	case b.q <- item:
		currentSize := len(b.q)
		if currentSize > b.peakDepth {
			b.peakDepth = currentSize
		}
		return true
	default:
		b.refused++
		return false
	}
}

// GetItem tries to get item with timeout.
func (b *BackpressureQ) GetItem() (string, bool) {
	select {
	case item := <-b.q:
		return item, true
	case <-time.After(b.timeout):
		return "", false
	}
}

