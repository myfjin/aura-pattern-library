type CPUThrottle struct {
	maxConcurrent  int
	currentRunning int
	peakConcurrent int
	refused        int
	lock           sync.Mutex
	sem            chan struct{}
}

func newCPUThrottle(maxConcurrent int) *CPUThrottle {
	return &CPUThrottle{
		maxConcurrent: maxConcurrent,
		sem:           make(chan struct{}, maxConcurrent),
	}
}

func (t *CPUThrottle) spawnWorker(workFn func()) bool {
	select {
	case t.sem <- struct{}{}:
	default:
		t.lock.Lock()
		t.refused++
		t.lock.Unlock()
		return false
	}

	go func() {
		t.lock.Lock()
		t.currentRunning++
		if t.currentRunning > t.peakConcurrent {
			t.peakConcurrent = t.currentRunning
		}
		t.lock.Unlock()

		workFn()

		t.lock.Lock()
		t.currentRunning--
		t.lock.Unlock()
		<-t.sem
	}()
	return true
}

func cpuWork() {
	start := time.Now()
	for time.Since(start) < 100*time.Millisecond {
		sum := 0
		for i := 0; i < 1000; i++ {
			sum += i * i
		}
		_ = sum
	}
}

