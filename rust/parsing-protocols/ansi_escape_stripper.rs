    // Ground truth: plain text
    let text1 = "hello world";
    assert_eq!(AnsiStripper::strip(text1), "hello world");

    // Ground truth: ANSI SGR color escape (CSI format: ESC [ ... m)
    let text2 = "normal \x1b[31mred\x1b[0m text";
    assert_eq!(AnsiStripper::strip(text2), "normal red text");

    // Ground truth: multiple escapes
    let text3 = "\x1b[1m\x1b[32mbold green\x1b[0m";
