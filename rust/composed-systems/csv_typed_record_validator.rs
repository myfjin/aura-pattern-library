#[derive(Clone, Debug)]
struct Record {
    name: String,
    age: i32,
    #[allow(dead_code)]
    email: String,
}

fn parse_csv_line(line: &str) -> Vec<String> {
    let mut fields = Vec::new();
    let mut current = String::new();
    let mut in_quotes = false;
    for ch in line.chars() {
        match ch {
            '"' => in_quotes = !in_quotes,
            ',' if !in_quotes => {
                fields.push(current.clone());
                current.clear();
            }
            _ => current.push(ch),
        }
    }
    fields.push(current);
    fields
}

fn validate_record(fields: &[String]) -> Option<Record> {
    if fields.len() != 3 { return None; }

    let name = fields[0].trim().to_string();
    let age: i32 = fields[1].trim().parse().ok()?;
    let email = fields[2].trim().to_string();

    // Validation rules: name non-empty, age > 0 and < 150, email contains @
    if name.is_empty() || age <= 0 || age >= 150 || !email.contains('@') {
        return None;
    }

    Some(Record { name, age, email })
}

