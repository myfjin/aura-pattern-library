    // Stage 1: Parse CSV lines
    let lines = vec![
        "Alice,25,alice@example.com",
        "Bob,150,bob@test.com",           // age out of range
        "Charlie,30,charlie_no_at.com",   // email missing @
        "David,35,david@work.com",
        ",40,empty@test.com",              // name empty
    ];

    let mut parsed_records = Vec::new();
    for line in &lines {
        let fields = parse_csv_line(line);
        parsed_records.push(fields);
    }

    // Stage 2: Type coercion and validation
    let mut valid = Vec::new();
