use std::collections::HashMap;

struct Histogram {
    buckets: HashMap<usize, usize>,
    #[allow(dead_code)]
    max_buckets: usize,
}

impl Histogram {
    fn new(max_buckets: usize) -> Self {
        Histogram {
            buckets: HashMap::new(),
            max_buckets,
        }
    }

    fn observe(&mut self, value: usize) {
        let bucket_key = (value / 10) * 10; // bucket by tens
        let count = self.buckets.entry(bucket_key).or_insert(0);
        *count += 1;
    }

    fn percentile(&self, p: usize) -> Option<usize> {
        // Simple percentile: find bucket where cumulative count >= p% of total
        let total: usize = self.buckets.values().sum();
        let target = (total * p) / 100;
        let mut cumsum = 0;
        let mut sorted_keys: Vec<_> = self.buckets.keys().collect();
        sorted_keys.sort();
        for key in sorted_keys {
            cumsum += self.buckets[key];
            if cumsum >= target {
                return Some(*key);
            }
        }
        None
    }
}

