use std::collections::BinaryHeap;

#[derive(Clone, Debug, Eq, PartialEq)]
struct Task {
    id: usize,
    priority: usize, // Higher = more important
}

impl Ord for Task {
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        self.priority.cmp(&other.priority)
    }
}

impl PartialOrd for Task {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

fn main() {
    // Stage 1: Enqueue tasks with priorities
    let mut queue = BinaryHeap::new();
    queue.push(Task { id: 1, priority: 5 });
    queue.push(Task { id: 2, priority: 10 });
    queue.push(Task { id: 3, priority: 3 });
    queue.push(Task { id: 4, priority: 8 });

    // Stage 2: Token-bucket gate (admit at limited rate)
    let tokens_per_interval = 2;
    let mut available_tokens = 2;
    let mut dispatched = Vec::new();

    // Simulate dispatching with token gate
    for _ in 0..3 {
        while available_tokens > 0 && !queue.is_empty() {
            if let Some(task) = queue.pop() {
                dispatched.push(task.id);
                available_tokens -= 1;
            }
        }
        available_tokens = tokens_per_interval; // Refill tokens for next interval
    }

    // Stage 3: Verify dispatch order (highest priority first)
    // Expected order: 10, 8, 5, 3 (sorted by priority, highest first)
    // But with token gate admitting 2 per interval, we get:
    // Interval 1: dispatch 10, 8 (top 2 priorities)
    // Interval 2: dispatch 5, 3 (next 2)
    // Interval 3: queue empty

    assert_eq!(dispatched.len(), 4, "All 4 tasks dispatched");
    assert_eq!(dispatched[0], 2, "Highest priority task (id=2, p=10) first");
    assert_eq!(dispatched[1], 4, "Second highest priority (id=4, p=8)");
    assert_eq!(dispatched[2], 1, "Third priority (id=1, p=5)");
    assert_eq!(dispatched[3], 3, "Lowest priority (id=3, p=3)");

    // Verify token gate limited dispatch
    // If no gate, all 4 would dispatch immediately
    assert!(available_tokens == tokens_per_interval, "Tokens refilled");

    println!("token_gated_priority_scheduler: PASS");
}
