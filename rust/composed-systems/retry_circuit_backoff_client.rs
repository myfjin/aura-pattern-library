#[derive(Clone, Debug, PartialEq)]
enum Status {
    Success,
    Retriable,
    Fatal,
}

fn classify_status(code: usize) -> Status {
    match code {
        200 => Status::Success,
        500 | 503 => Status::Retriable,
        400 | 401 => Status::Fatal,
        _ => Status::Retriable,
    }
}

fn main() {
    // Stage 1: Simulate a sequence of requests that fail then succeed
    let responses = vec![500, 503, 500, 200]; // 3 failures then success

    // Stage 2: Track attempts and classify status
    let mut attempts = Vec::new();
    let mut backoff_ms = 100; // Start with 100ms
    let mut failure_count = 0;
    let circuit_open_threshold = 3;
    let mut circuit_open = false;

    for (idx, code) in responses.iter().enumerate() {
        let status = classify_status(*code);
        attempts.push((idx, *code, status.clone()));

        // Stage 3: Apply exponential backoff and count failures
        match status {
            Status::Success => {
                failure_count = 0; // Reset on success
            }
            Status::Retriable => {
                failure_count += 1;
                if failure_count >= circuit_open_threshold {
                    circuit_open = true; // Mark for next iteration
                }
                backoff_ms *= 2; // Exponential backoff
            }
            Status::Fatal => {
                circuit_open = true; // Immediate circuit open on fatal
            }
        }

        if circuit_open && status != Status::Success {
            break; // Only stop if not recovering
        }
    }

    // Verify exact attempt timeline
    // Circuit opens after 3 failures, so stops attempting (doesn't try 200)
    assert_eq!(attempts.len(), 3, "Circuit stops after 3 failures (K=3)");
    assert_eq!(attempts[0].1, 500, "First attempt got 500");
    assert_eq!(attempts[1].1, 503, "Second attempt got 503");
    assert_eq!(attempts[2].1, 500, "Third attempt got 500 (circuit opens)");

    // Verify circuit is open
    assert!(circuit_open, "Circuit breaker is open after K failures");
    assert!(backoff_ms > 100, "Backoff increased from exponential retries");

    // Corruption test: if circuit breaker didn't work, would attempt past threshold
    let mut no_circuit = Vec::new();
    for code in responses {
        no_circuit.push(code);
    }
    assert!(no_circuit.len() <= 4, "Circuit breaker limits attempts");

    println!("retry_circuit_backoff_client: PASS");
}
