#[derive(Clone, Debug)]
struct Backend {
    id: usize,
    healthy: bool,
}

fn main() {
    // Stage 1: Health-probe backends
    let mut backends = vec![
        Backend { id: 1, healthy: true },
        Backend { id: 2, healthy: true },
        Backend { id: 3, healthy: true },
    ];

    // Stage 2: LB selects healthy backend (round-robin on healthy subset)
    let mut routing_sequence = Vec::new();
    let mut current_idx = 0;

    for request_id in 0..5 {
        let healthy_backends: Vec<usize> = backends.iter().enumerate()
            .filter_map(|(idx, b)| if b.healthy { Some(idx) } else { None })
            .collect();

        if !healthy_backends.is_empty() {
            let selected_idx = healthy_backends[current_idx % healthy_backends.len()];
            routing_sequence.push((request_id, backends[selected_idx].id));
            current_idx += 1;
        }
    }

    assert_eq!(routing_sequence.len(), 5, "All requests routed");

    // Stage 3: Simulate backend 2 dropping (health check fails)
    backends[1].healthy = false;

    // Stage 4: LB failover to remaining healthy backends
    let mut failover_sequence = Vec::new();
    current_idx = 0;

    for request_id in 5..8 {
        let healthy_backends: Vec<usize> = backends.iter().enumerate()
            .filter_map(|(idx, b)| if b.healthy { Some(idx) } else { None })
            .collect();

        if !healthy_backends.is_empty() {
            let selected_idx = healthy_backends[current_idx % healthy_backends.len()];
            failover_sequence.push((request_id, backends[selected_idx].id));
            current_idx += 1;
        }
    }

    assert_eq!(failover_sequence.len(), 3, "Failover handled 3 requests");
    for (_, backend_id) in &failover_sequence {
        assert_ne!(*backend_id, 2, "Backend 2 not selected after drop");
    }

    // Stage 5: Recovery - backend 2 comes back
    backends[1].healthy = true;

    // Verify recovery
    let healthy_now: Vec<usize> = backends.iter().enumerate()
        .filter_map(|(_, b)| if b.healthy { Some(b.id) } else { None })
        .collect();
    assert_eq!(healthy_now.len(), 3, "All backends healthy after recovery");

    println!("health_checked_lb_router: PASS");
}
