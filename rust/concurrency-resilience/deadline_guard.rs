use std::time::{Instant, Duration};

struct Deadline {
    instant: Option<Instant>,
}

impl Deadline {
    fn new(duration: Option<Duration>) -> Self {
        Deadline {
            instant: duration.map(|d| Instant::now() + d),
        }
    }

    fn child_deadline(&self, child_budget: Duration) -> Deadline {
        match self.instant {
            Some(parent_instant) => {
                let remaining = parent_instant.saturating_duration_since(Instant::now());
                let child_instant = Instant::now() + child_budget.min(remaining);
                Deadline {
                    instant: Some(child_instant),
                }
            }
            None => Deadline {
                instant: Some(Instant::now() + child_budget),
            },
        }
    }

    fn is_expired(&self) -> bool {
        match self.instant {
            Some(deadline) => Instant::now() >= deadline,
            None => false,
        }
    }

    fn remaining(&self) -> Option<Duration> {
        self.instant.and_then(|deadline| {
            let now = Instant::now();
            if now >= deadline {
                Some(Duration::from_secs(0))
            } else {
                Some(deadline.saturating_duration_since(now))
            }
        })
    }
}

