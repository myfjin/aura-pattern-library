use std::sync::{Arc, Condvar, Mutex};
use std::thread;

struct RendezvousChannel<T> {
    value: Mutex<Option<T>>,
    sender_cond: Condvar,
    receiver_cond: Condvar,
}

impl<T> RendezvousChannel<T> {
    fn new() -> Self {
        RendezvousChannel {
            value: Mutex::new(None),
            sender_cond: Condvar::new(),
            receiver_cond: Condvar::new(),
        }
    }

    fn send(&self, val: T) {
        let mut v = self.value.lock().expect("lock poisoned");
        *v = Some(val);
        self.receiver_cond.notify_one();
        // Wait for receiver to take the value
        while v.is_some() {
            v = self.sender_cond.wait(v).expect("wait failed");
        }
    }

    fn recv(&self) -> T {
        let mut v = self.value.lock().expect("lock poisoned");
        while v.is_none() {
            v = self.receiver_cond.wait(v).expect("wait failed");
        }
        let val = v.take().expect("value disappeared");
        self.sender_cond.notify_one();
        val
    }
}

