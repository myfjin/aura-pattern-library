use std::sync::{Arc, Mutex};

// Shared log to track cleanup order.
type CleanupLog = Arc<Mutex<Vec<String>>>;

struct Resource {
    id: String,
    log: CleanupLog,
}

impl Drop for Resource {
    fn drop(&mut self) {
        let mut log = self.log.lock().expect("log poisoned");
        log.push(self.id.clone());
    }
}

fn main() {
    let log: CleanupLog = Arc::new(Mutex::new(Vec::new()));

    // Scope to test RAII.
    {
        let _r1 = Resource {
            id: "resource_1".to_string(),
            log: Arc::clone(&log),
        };
        let _r2 = Resource {
            id: "resource_2".to_string(),
            log: Arc::clone(&log),
        };
        let _r3 = Resource {
            id: "resource_3".to_string(),
            log: Arc::clone(&log),
        };
        // When this scope ends, resources drop in reverse order: r3, r2, r1
    }

    let cleanup_order = log.lock().expect("log poisoned").clone();

    // THE ONE LAW: cleanup is in reverse acquisition order.
    assert_eq!(cleanup_order.len(), 3, "not all resources cleaned up");
    assert_eq!(cleanup_order[0], "resource_3", "first cleanup should be r3");
    assert_eq!(cleanup_order[1], "resource_2", "second cleanup should be r2");
    assert_eq!(cleanup_order[2], "resource_1", "third cleanup should be r1");

    println!("graceful_shutdown: {} resources, cleanup order {} → {} → {} — PASS",
        3,
        cleanup_order[2],
        cleanup_order[1],
        cleanup_order[0]
    );
}
