use std::sync::atomic::{AtomicU64, AtomicBool, Ordering};
use std::sync::Arc;
use std::thread;

struct OnceInit {
    done: AtomicBool,
}

impl OnceInit {
    fn new() -> Self {
        OnceInit {
            done: AtomicBool::new(false),
        }
    }

    fn call_once<F>(&self, f: F)
    where
        F: FnOnce(),
    {
        if self.done.load(Ordering::Acquire) {
            return;
        }
        loop {
            match self.done.compare_exchange(false, true, Ordering::Acquire, Ordering::Relaxed) {
                Ok(_) => {
                    f();
                    return;
                }
                Err(_) => {
                    // Another thread is running the closure; wait for it to finish
                    loop {
                        if self.done.load(Ordering::Acquire) {
                            return;
                        }
                        std::hint::spin_loop();
                    }
                }
            }
        }
    }
}

fn main() {
    let n_threads = 16;
    let once = Arc::new(OnceInit::new());
    let init_counter = Arc::new(AtomicU64::new(0));

    let mut handles = Vec::new();
    for _ in 0..n_threads {
        let o = Arc::clone(&once);
        let ic = Arc::clone(&init_counter);
        handles.push(thread::spawn(move || {
            o.call_once(|| {
                ic.fetch_add(1, Ordering::Relaxed);
            });
        }));
    }

    for h in handles {
        h.join().expect("thread panicked");
    }

    let count = init_counter.load(Ordering::Relaxed);
    assert_eq!(count, 1, "init closure ran {} times, expected exactly 1", count);

    println!("once_init_guard: {} threads, init closure ran exactly 1 time — PASS", n_threads);
}
