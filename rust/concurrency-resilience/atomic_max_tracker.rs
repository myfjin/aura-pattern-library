use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::thread;

struct MaxTracker {
    max: AtomicU64,
}

impl MaxTracker {
    fn new() -> Self {
        MaxTracker { max: AtomicU64::new(0) }
    }

    fn update(&self, val: u64) {
        loop {
            let cur = self.max.load(Ordering::Relaxed);
            if val <= cur {
                break; // already have a larger value
            }
            match self.max.compare_exchange(cur, val, Ordering::Release, Ordering::Relaxed) {
                Ok(_) => break,
                Err(_) => std::hint::spin_loop(),
            }
        }
    }

    fn get(&self) -> u64 {
        self.max.load(Ordering::Acquire)
    }
}

