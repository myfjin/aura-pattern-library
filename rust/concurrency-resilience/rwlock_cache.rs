use std::collections::HashMap;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Arc, RwLock};
use std::thread;

struct Cache {
    map: RwLock<HashMap<u64, u64>>,
    loads: AtomicU64, // times the loader actually ran
}

impl Cache {
    fn new() -> Self {
        Cache {
            map: RwLock::new(HashMap::new()),
            loads: AtomicU64::new(0),
        }
    }

    fn get_or_fill(&self, key: u64) -> u64 {
        // Fast path: shared read lock.
        if let Some(&v) = self.map.read().expect("read poisoned").get(&key) {
            return v;
        }
        // Slow path: exclusive write lock, re-check under it (double-checked locking).
        let mut w = self.map.write().expect("write poisoned");
        if let Some(&v) = w.get(&key) {
            return v;
        }
        self.loads.fetch_add(1, Ordering::Relaxed);
        let v = key * 10; // the "expensive" load
        w.insert(key, v);
        v
    }
}

fn main() {
    let cache = Arc::new(Cache::new());
    let n_threads: usize = 16;
    let key: u64 = 7;

    let mut handles = Vec::new();
    for _ in 0..n_threads {
        let c = Arc::clone(&cache);
        handles.push(thread::spawn(move || {
            let mut last = 0u64;
            for _ in 0..1_000 {
                last = c.get_or_fill(key);
            }
            last
        }));
    }
    let results: Vec<u64> = handles.into_iter().map(|h| h.join().expect("panic")).collect();

    // THE ONE LAW: the loader ran exactly once despite the concurrent herd.
    let loads = cache.loads.load(Ordering::Relaxed);
    assert_eq!(loads, 1, "loader ran {loads} times (herd not suppressed)");

    // Every reader converged on the same, correct value.
    assert!(results.iter().all(|&v| v == key * 10), "readers disagreed on cached value");

    println!("rwlock_cache: {n_threads} readers, loader ran once, value {} — PASS", key * 10);
}
