use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, Condvar, Mutex};
use std::thread;

struct Barrier {
    n: usize,
    arrived: Mutex<usize>,
    cond: Condvar,
}

impl Barrier {
    fn new(n: usize) -> Self {
        Barrier {
            n,
            arrived: Mutex::new(0),
            cond: Condvar::new(),
        }
    }

    fn wait(&self) {
        let mut arrived = self.arrived.lock().expect("lock poisoned");
        *arrived += 1;
        if *arrived < self.n {
            // Not all arrived yet; wait for the last arrival to notify.
            while *arrived < self.n {
                arrived = self.cond.wait(arrived).expect("wait failed");
            }
        } else {
            // Last to arrive; release everyone.
            self.cond.notify_all();
        }
    }
}

fn main() {
    let n_threads = 8;
    let barrier = Arc::new(Barrier::new(n_threads));

    // Shared witness: how many threads have arrived at the barrier point.
    let arrived_witness = Arc::new(AtomicUsize::new(0));

    let mut handles = Vec::new();
    for _ in 0..n_threads {
        let b = Arc::clone(&barrier);
        let w = Arc::clone(&arrived_witness);

        handles.push(thread::spawn(move || {
            // Announce arrival BEFORE crossing the barrier.
            w.fetch_add(1, Ordering::SeqCst);
            b.wait();
            // If the barrier held, every thread has already announced arrival.
            let seen = w.load(Ordering::SeqCst);
            assert_eq!(seen, n_threads, "left barrier with only {seen}/{n_threads} arrived");
        }));
    }

    for h in handles {
        h.join().expect("thread panicked");
    }

    assert_eq!(
        arrived_witness.load(Ordering::SeqCst),
        n_threads,
        "not all threads reached the barrier"
    );

    println!("barrier_sync: {n_threads} threads synchronized, none left before all arrived — PASS");
}
