struct OTPState {
    failed_attempts: u32,
    last_attempt: u64,
    locked_until: u64,
}

fn attempt_otp(state: &mut OTPState, code: u32, correct: u32, now: u64, max_attempts: u32, lock_duration: u64) -> bool {
    const RESET_WINDOW: u64 = 300;

    if now < state.locked_until {
        return false;
    }

    if now - state.last_attempt > RESET_WINDOW {
        state.failed_attempts = 0;
    }

    if code == correct {
        state.failed_attempts = 0;
        state.last_attempt = now;
        return true;
    }

    state.failed_attempts += 1;
    state.last_attempt = now;

    if state.failed_attempts >= max_attempts {
        state.locked_until = now + lock_duration;
        return false;
    }

    false
}

fn main() {
    let mut state = OTPState {
        failed_attempts: 0,
        last_attempt: 0,
        locked_until: 0,
    };
    let correct_code = 123456u32;

    // Correct code succeeds
    assert!(attempt_otp(&mut state, correct_code, correct_code, 100, 3, 60));
    assert_eq!(state.failed_attempts, 0);

    // Wrong code increments counter
    assert!(!attempt_otp(&mut state, 999999, correct_code, 101, 3, 60));
    assert_eq!(state.failed_attempts, 1);

    // More failures
    assert!(!attempt_otp(&mut state, 111111, correct_code, 102, 3, 60));
    assert_eq!(state.failed_attempts, 2);

    // Third failure locks account
    assert!(!attempt_otp(&mut state, 222222, correct_code, 103, 3, 60));
    assert_eq!(state.failed_attempts, 3);
    assert_eq!(state.locked_until, 163); // 103 + 60

    // Locked: even correct code rejected
    assert!(!attempt_otp(&mut state, correct_code, correct_code, 150, 3, 60));

    // After lock expires
    assert!(attempt_otp(&mut state, correct_code, correct_code, 164, 3, 60));
    assert_eq!(state.failed_attempts, 0);

    // Reset window: long time between attempts clears counter
    assert!(!attempt_otp(&mut state, 999999, correct_code, 500, 3, 60));
    assert_eq!(state.failed_attempts, 1); // Reset happened at 500

    println!("otp_lockout ... PASS");
}
