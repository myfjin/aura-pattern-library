fn hmac_sha256(key: &[u8], msg: &[u8]) -> [u8; 32] {
    let mut key_padded = [0u8; 64];
    if key.len() <= 64 { key_padded[..key.len()].copy_from_slice(key); } else {
        let h = sha256_hash(key); key_padded[..32].copy_from_slice(&h);
    }
    let mut ipad = [0x36u8; 64]; let mut opad = [0x5cu8; 64];
    for i in 0..64 { ipad[i] ^= key_padded[i]; opad[i] ^= key_padded[i]; }
    let mut inner = ipad.to_vec(); inner.extend_from_slice(msg);
    let inner_hash = sha256_hash(&inner);
    let mut outer = opad.to_vec(); outer.extend_from_slice(&inner_hash);
    sha256_hash(&outer)
}

fn pbkdf2(password: &[u8], salt: &[u8], iterations: u32, output_len: usize) -> Vec<u8> {
    let mut result = Vec::new();
    let block_size = 32;
    let block_count = (output_len + block_size - 1) / block_size;
    for i in 1..=block_count {
        let mut u = {
            let mut msg = salt.to_vec();
            msg.extend_from_slice(&(i as u32).to_be_bytes());
            hmac_sha256(password, &msg)
        };
        let mut t = u;
        for _ in 1..iterations {
            u = hmac_sha256(password, &u);
            for j in 0..32 {
                t[j] ^= u[j];
            }
        }
        result.extend_from_slice(&t);
    }
    result.truncate(output_len);
    result
}

fn const_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() { return false; }
    let mut diff = 0u8;
    for i in 0..a.len() {
        diff |= a[i] ^ b[i];
    }
    diff == 0
}

fn hash_password(password: &str, salt: &[u8]) -> Vec<u8> {
    pbkdf2(password.as_bytes(), salt, 10000, 32)
}

fn verify_password(password: &str, salt: &[u8], stored_hash: &[u8]) -> bool {
    let computed = hash_password(password, salt);
    const_eq(&computed, stored_hash)
}

