struct SessionToken {
    id: String,
    issued_at: u64,
    expires_at: u64,
}

fn issue_token(id: &str, now: u64, ttl: u64) -> SessionToken {
    SessionToken {
        id: id.to_string(),
        issued_at: now,
        expires_at: now + ttl,
    }
}

fn validate_token(token: &SessionToken, now: u64, revoked: &std::collections::HashSet<String>) -> bool {
    if now < token.issued_at || now >= token.expires_at { return false; }
    if revoked.contains(&token.id) { return false; }
    true
}

