struct Connection {
    last_used: u64,
}

struct ConnectionPoolManager {
    max_size: usize,
    idle_timeout: u64,
    connections: Vec<Connection>,
}

impl ConnectionPoolManager {
    fn new(max_size: usize, idle_timeout: u64) -> Self {
        Self {
            max_size,
            idle_timeout,
            connections: Vec::new(),
        }
    }

    fn try_acquire(&mut self, now: u64) -> Option<usize> {
        // Evict idle connections
        self.connections.retain(|c| now - c.last_used < self.idle_timeout);

        if self.connections.len() < self.max_size {
            let id = self.connections.len();
            self.connections.push(Connection {
                last_used: now,
            });
            Some(id)
        } else {
            None
        }
    }

    fn release(&mut self, _conn_id: usize, now: u64) {
        // Mark all as used (simple model)
        for c in &mut self.connections {
            c.last_used = now;
        }
    }

    fn size(&self) -> usize {
        self.connections.len()
    }
}

