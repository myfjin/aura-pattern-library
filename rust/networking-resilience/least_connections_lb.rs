struct LeastConnectionsLB {
    backends: Vec<usize>, // in-flight count per backend
}

impl LeastConnectionsLB {
    fn new(num_backends: usize) -> Self {
        Self {
            backends: vec![0; num_backends],
        }
    }

    fn acquire(&mut self) -> usize {
        let idx = self.backends
            .iter()
            .enumerate()
            .min_by_key(|(_, &count)| count)
            .map(|(i, _)| i)
            .unwrap();
        self.backends[idx] += 1;
        idx
    }

    fn release(&mut self, backend_id: usize) {
        self.backends[backend_id] = self.backends[backend_id].saturating_sub(1);
    }

    fn count(&self, backend_id: usize) -> usize {
        self.backends[backend_id]
    }
}

