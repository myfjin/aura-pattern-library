    // Test 1: First 3 acquires should go to backend 0
    let mut lb = LeastConnectionsLB::new(3);
    assert_eq!(lb.acquire(), 0, "First acquire to backend 0");
    assert_eq!(lb.acquire(), 1, "Second acquire to backend 1");
    assert_eq!(lb.acquire(), 2, "Third acquire to backend 2");

    // Test 2: Next acquire goes to backend with least (all tied at 1, pick first)
    assert_eq!(lb.acquire(), 0, "Fourth acquire to backend 0 (tied at 1)");

    // Test 3: Release from backend 1, acquire should go to backend 1
    lb.release(1);
    assert_eq!(lb.count(1), 0, "Backend 1 has 0 after release");
    assert_eq!(lb.acquire(), 1, "Next acquire goes to backend 1 (now empty)");

