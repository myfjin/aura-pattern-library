struct WeightedRoundRobinLB {
    schedule: Vec<usize>,
    index: usize,
}

impl WeightedRoundRobinLB {
    fn new(backends: Vec<(usize, i32)>) -> Self {
        // Build a deterministic schedule by repeating each backend by its weight
        let mut schedule = Vec::new();
        for (id, weight) in backends {
            for _ in 0..weight {
                schedule.push(id);
            }
        }
        Self {
            schedule,
            index: 0,
        }
    }

    fn select(&mut self) -> usize {
        let result = self.schedule[self.index % self.schedule.len()];
        self.index += 1;
        result
    }
}

