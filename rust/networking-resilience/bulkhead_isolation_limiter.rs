// Bulkhead concurrency limiter: caps simultaneous in-flight work at max_concurrent.
// try_acquire admits a caller and increments the count only while below the cap,
// returning false otherwise; release decrements (saturating at zero). Use to fence
// off one resource pool so a flood in it can't exhaust the whole process. Guarantees:
// current load never exceeds max_concurrent and never underflows; asserts drive it to
// the cap, confirm the first over-limit acquire is refused, then re-admits after release.
struct BulkheadIsolationLimiter {
    max_concurrent: usize,
    current: usize,
}

impl BulkheadIsolationLimiter {
    fn new(max_concurrent: usize) -> Self {
        Self {
            max_concurrent,
            current: 0,
        }
    }

    fn try_acquire(&mut self) -> bool {
        if self.current < self.max_concurrent {
            self.current += 1;
            true
        } else {
            false
        }
    }

    fn release(&mut self) {
        if self.current > 0 {
            self.current -= 1;
        }
    }

    fn current_load(&self) -> usize {
        self.current
    }
}

fn main() {
    // Test 1: Acquire up to max
    let mut limiter = BulkheadIsolationLimiter::new(3);
    assert!(limiter.try_acquire(), "First acquire succeeds");
    assert!(limiter.try_acquire(), "Second acquire succeeds");
    assert!(limiter.try_acquire(), "Third acquire succeeds");
    assert_eq!(limiter.current_load(), 3, "Load should be 3");

    // Test 2: Fourth should be refused
    assert!(!limiter.try_acquire(), "Fourth acquire refused");
    assert_eq!(limiter.current_load(), 3, "Load unchanged");

    // Test 3: Release and re-acquire
    limiter.release();
    assert_eq!(limiter.current_load(), 2, "Load decreased to 2");
    assert!(limiter.try_acquire(), "Acquire succeeds after release");
    assert_eq!(limiter.current_load(), 3, "Load back to 3");

    // Test 4: Exact sequence
    let mut limiter2 = BulkheadIsolationLimiter::new(2);
    assert!(limiter2.try_acquire(), "Acquire 1");
    assert!(limiter2.try_acquire(), "Acquire 2");
    assert!(!limiter2.try_acquire(), "Acquire 3 refused");
    assert!(!limiter2.try_acquire(), "Acquire 4 refused");
    limiter2.release();
    assert!(limiter2.try_acquire(), "Acquire after release succeeds");
    assert!(!limiter2.try_acquire(), "Next still refused");

    println!("bulkhead_isolation_limiter: PASS");
}
