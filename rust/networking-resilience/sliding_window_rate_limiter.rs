// Sliding-window rate limiter keyed on caller-supplied timestamps (no wall clock).
// allow(now) first evicts every recorded event with ts <= now - window_seconds, then admits
// (and records) the request only if fewer than `capacity` events remain inside the window.
// Use to enforce "at most N events per rolling window" deterministically in tests or replay.
// Guarantees: never more than `capacity` admits within any window_seconds span; once old
// events age out the full capacity becomes available again.
struct SlidingWindowRateLimiter {
    capacity: usize,
    window_seconds: u64,
    events: Vec<u64>,
}

impl SlidingWindowRateLimiter {
    fn new(capacity: usize, window_seconds: u64) -> Self {
        Self {
            capacity,
            window_seconds,
            events: Vec::new(),
        }
    }

    fn allow(&mut self, now: u64) -> bool {
        // Remove events outside the window
        let cutoff = now.saturating_sub(self.window_seconds);
        self.events.retain(|&ts| ts > cutoff);

        if self.events.len() < self.capacity {
            self.events.push(now);
            true
        } else {
            false
        }
    }
}

fn main() {
    let mut limiter = SlidingWindowRateLimiter::new(3, 10);

    // Seed: deterministic sequence
    let now_base = 1000u64;

    // Test 1: Within capacity, should admit all
    let mut admitted = 0;
    for i in 0..3 {
        if limiter.allow(now_base + i) {
            admitted += 1;
        }
    }
    assert_eq!(admitted, 3, "First 3 should be admitted");

    // Test 2: Exceed capacity, should deny
    let mut denied = 0;
    for i in 3..6 {
        if !limiter.allow(now_base + i) {
            denied += 1;
        }
    }
    assert_eq!(denied, 3, "Next 3 should be denied");

    // Test 3: After window expires, events should be cleared
    // At time now_base + 15, all events from [1000..1009] fall outside window
    let mut admitted_after_expire = 0;
    for i in 0..3 {
        if limiter.allow(now_base + 15 + i) {
            admitted_after_expire += 1;
        }
    }
    assert_eq!(admitted_after_expire, 3, "After expiry, 3 new should be admitted");

    // Test 4: Verify exact count
    let mut limiter2 = SlidingWindowRateLimiter::new(5, 20);
    let mut count = 0;
    for i in 0..10 {
        if limiter2.allow(100 + i) {
            count += 1;
        }
    }
    assert_eq!(count, 5, "Exactly 5 admitted before cap");
    assert_eq!(limiter2.allow(100 + 10), false, "6th rejected");

    println!("sliding_window_rate_limiter: PASS");
}
