fn crc32c(data: &[u8]) -> u32 {
    let mut crc = 0xffffffffu32;
    for &byte in data {
        crc ^= byte as u32;
        for _ in 0..8 {
            if crc & 1 != 0 {
                crc = (crc >> 1) ^ 0x82f63b78; // Castagnoli polynomial (reversed)
            } else {
                crc >>= 1;
            }
        }
    }
    crc ^ 0xffffffffu32
}

fn main() {
    // CANONICAL test vector: "123456789" → 0xE3069283
    let test_data = b"123456789";
    let result = crc32c(test_data);
    assert_eq!(result, 0xe3069283, "CRC-32/Castagnoli('123456789') = {:#010x}, expected 0xe3069283", result);

    // Verify empty string
    let empty = crc32c(b"");
    assert_ne!(empty, 0xffffffffu32, "CRC of empty should not be initial value");

    // Verify determinism and differences
    let data_a = crc32c(b"test");
    let data_a2 = crc32c(b"test");
    assert_eq!(data_a, data_a2, "CRC not deterministic");

    let data_b = crc32c(b"tests");
    assert_ne!(data_a, data_b, "Different data should have different CRC");

    // Property: single byte vs longer data
    let single = crc32c(&[0x31]); // '1'
    let from_test = crc32c(&[0x31, 0x32, 0x33]); // '123'
    assert_ne!(single, from_test);

    // Property: append changes CRC
    let data1 = b"hello";
    let data2 = b"helloworld";
    let crc1 = crc32c(data1);
    let crc2 = crc32c(data2);
    assert_ne!(crc1, crc2);

    // Property: different data produces different CRC
    let data_a = b"test_a";
    let data_b = b"test_b";
    let crc_a = crc32c(data_a);
    let crc_b = crc32c(data_b);
    assert_ne!(crc_a, crc_b);

    println!("crc32c_castagnoli ... PASS");
}
