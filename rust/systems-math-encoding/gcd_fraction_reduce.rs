fn gcd(mut a: u64, mut b: u64) -> u64 {
    while b != 0 {
        let temp = b;
        b = a % b;
        a = temp;
    }
    a
}

fn reduce_fraction(num: u64, den: u64) -> (u64, u64) {
    assert!(den != 0, "denominator cannot be zero");
    let g = gcd(num, den);
    (num / g, den / g)
}

