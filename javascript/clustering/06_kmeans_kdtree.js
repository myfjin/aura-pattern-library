/**
 * kd-tree accelerated k-means (blacklisting / filtering algorithm).
 *
 * Builds an axis-aligned kd-tree over the points. Each internal node carries
 * the set of centroid candidates that can still be nearest to some point in the
 * node; candidates are pruned when one centroid provably dominates the cell.
 * The bookkeeping is the kd-tree + cell-dominance test; the final centroids are
 * exact cluster means.
 *
 * @param {number[][]} X - data matrix
 * @param {number[]} y - unused target vector (harness contract)
 * @param {number} lr - unused learning rate (harness contract)
 * @param {number} iters - maximum iterations
 * @returns {{centroids:number[][], k:number, assignments:number[]}}
 */
function kmeansKdtree(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const k = 3;

    function dist2(a, b) {
        let s = 0;
        for (let f = 0; f < nf; f++) {
            const d = a[f] - b[f];
            s += d * d;
        }
        return s;
    }

    function nearest(x, centroids) {
        let best = 0;
        let bestD = dist2(x, centroids[0]);
        for (let c = 1; c < centroids.length; c++) {
            const d = dist2(x, centroids[c]);
            if (d < bestD) {
                bestD = d;
                best = c;
            }
        }
        return best;
    }

    function cellBounds(indices) {
        const min = new Array(nf).fill(Infinity);
        const max = new Array(nf).fill(-Infinity);
        for (const i of indices) {
            const x = X[i];
            for (let f = 0; f < nf; f++) {
                if (x[f] < min[f]) min[f] = x[f];
                if (x[f] > max[f]) max[f] = x[f];
            }
        }
        return { min, max };
    }

    function minPointBoxDist2(p, box) {
        let s = 0;
        for (let f = 0; f < nf; f++) {
            if (p[f] < box.min[f]) {
                const d = p[f] - box.min[f];
                s += d * d;
            } else if (p[f] > box.max[f]) {
                const d = p[f] - box.max[f];
                s += d * d;
            }
        }
        return s;
    }

    function maxPointBoxDist2(p, box) {
        let s = 0;
        for (let f = 0; f < nf; f++) {
            const d1 = p[f] - box.min[f];
            const d2 = p[f] - box.max[f];
            const d = Math.max(Math.abs(d1), Math.abs(d2));
            s += d * d;
        }
        return s;
    }

    function buildKdTree(indices, depth) {
        const bounds = cellBounds(indices);
        if (indices.length <= 4) {
            return { leaf: true, indices, bounds };
        }
        const axis = depth % nf;
        const sorted = indices.slice().sort((a, b) => X[a][axis] - X[b][axis]);
        const mid = Math.floor(sorted.length / 2);
        const left = buildKdTree(sorted.slice(0, mid), depth + 1);
        const right = buildKdTree(sorted.slice(mid), depth + 1);
        return {
            leaf: false,
            left,
            right,
            bounds,
            indices,
        };
    }

    const allIndices = new Array(n).fill(0).map((_, i) => i);
    const root = buildKdTree(allIndices, 0);

    // Assign all points in `node` to one of the `candidates`. `candidates` are
    // indices into the global `centroids` array.
    function assignNode(node, candidates) {
        if (candidates.length === 0) candidates = new Array(k).fill(0).map((_, i) => i);
        if (candidates.length === 1 || node.leaf) {
            // Exact nearest-centroid computation for every point.
            const candCentroids = candidates.map(c => centroids[c]);
            for (const i of node.indices) {
                assignments[i] = candidates[nearest(X[i], candCentroids)];
            }
            return;
        }

        // Try to prune candidates using cell dominance.
        const kept = [];
        for (const c of candidates) {
            const minC = minPointBoxDist2(centroids[c], node.bounds);
            let dominated = false;
            for (const j of candidates) {
                if (j === c) continue;
                const maxJ = maxPointBoxDist2(centroids[j], node.bounds);
                if (maxJ < minC) {
                    dominated = true;
                    break;
                }
            }
            if (!dominated) kept.push(c);
        }
        if (kept.length === 1) {
            for (const i of node.indices) assignments[i] = kept[0];
            return;
        }
        const next = kept.length > 0 ? kept : candidates;
        assignNode(node.left, next);
        assignNode(node.right, next);
    }

    let centroids = new Array(k);
    for (let c = 0; c < k; c++) centroids[c] = X[c].slice();
    const assignments = new Array(n).fill(0);

    for (let iter = 0; iter < iters; iter++) {
        assignNode(root, new Array(k).fill(0).map((_, i) => i));

        const sums = new Array(k).fill(0).map(() => new Array(nf).fill(0));
        const counts = new Array(k).fill(0);
        for (let i = 0; i < n; i++) {
            const c = assignments[i];
            counts[c]++;
            const x = X[i];
            for (let f = 0; f < nf; f++) sums[c][f] += x[f];
        }
        for (let c = 0; c < k; c++) {
            if (counts[c] > 0) {
                for (let f = 0; f < nf; f++) centroids[c][f] = sums[c][f] / counts[c];
            }
        }
        let changed = 0;
        for (let i = 0; i < n; i++) {
            const c = nearest(X[i], centroids);
            if (assignments[i] !== c) changed++;
        }
        if (changed === 0) break;
    }

    for (let i = 0; i < n; i++) assignments[i] = nearest(X[i], centroids);
    return { centroids, k, assignments };
}

