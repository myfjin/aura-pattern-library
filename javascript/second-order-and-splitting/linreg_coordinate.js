/** * Coordinate descent for linear regression.
 * Alternates between a closed-form intercept update and closed-form updates
 * for each weight coordinate. lr is unused.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - number of full passes over coordinates
 * @returns {{weights: number[], bias: number}}
 */
function coordinateDescentRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const weights = new Array(nf).fill(0.0);
    let bias = 0.0;

    // Cache column squared norms.
    const colSq = [];
    for (let j = 0; j < nf; j++) {
        let s = 0.0;
        for (let i = 0; i < n; i++) {
            s += X[i][j] * X[i][j];
        }
        colSq.push(s);
    }

    for (let pass = 0; pass < iters; pass++) {
        // Update bias: b = mean(y - X w)
        let bSum = 0.0;
        for (let i = 0; i < n; i++) {
            let pred = 0.0;
            for (let j = 0; j < nf; j++) {
                pred += weights[j] * X[i][j];
            }
            bSum += y[i] - pred;
        }
        bias = bSum / n;

        // Update each weight coordinate holding others fixed.
        for (let j = 0; j < nf; j++) {
            let num = 0.0;
            for (let i = 0; i < n; i++) {
                let predOther = bias;
                for (let k = 0; k < nf; k++) {
                    if (k !== j) predOther += weights[k] * X[i][k];
                }
                num += X[i][j] * (y[i] - predOther);
            }
            const den = colSq[j];
            weights[j] = den > 1e-12 ? num / den : weights[j];
        }
    }

    return { weights: weights, bias: bias };
}

