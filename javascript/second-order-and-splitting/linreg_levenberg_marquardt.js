/**
 * Linear regression via Levenberg-Marquardt (damped Gauss-Newton).
 * Solves the nonlinear least-squares problem min 0.5*sum r_i^2 where
 * r_i = (bias + w^T X_i) - y_i. For a linear model this reduces to a
 * regularised normal-equations solve at each step.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - maximum LM iterations
 * @returns {{weights: number[], bias: number}}
 */
function levenbergMarquardtRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // A = [1 | X]
    const A = [];
    for (let i = 0; i < n; i++) {
        A.push([1.0].concat(X[i]));
    }

    // Precompute AtA and Aty
    const AtA = [];
    for (let r = 0; r < m; r++) {
        const row = [];
        for (let c = 0; c < m; c++) {
            let s = 0.0;
            for (let i = 0; i < n; i++) {
                s += A[i][r] * A[i][c];
            }
            row.push(s);
        }
        AtA.push(row);
    }
    const Aty = [];
    for (let r = 0; r < m; r++) {
        let s = 0.0;
        for (let i = 0; i < n; i++) {
            s += A[i][r] * y[i];
        }
        Aty.push(s);
    }

    function loss(theta) {
        let s = 0.0;
        for (let i = 0; i < n; i++) {
            let pred = 0.0;
            for (let j = 0; j < m; j++) {
                pred += A[i][j] * theta[j];
            }
            const e = pred - y[i];
            s += e * e;
        }
        return 0.5 * s;
    }

    let theta = new Array(m).fill(0.0);
    let lambda = 0.01;
    let currentLoss = loss(theta);
    const maxIter = Math.max(1, iters);

    for (let step = 0; step < maxIter; step++) {
        // Gradient g = AtA*theta - Aty
        const g = [];
        for (let r = 0; r < m; r++) {
            let s = -Aty[r];
            for (let c = 0; c < m; c++) {
                s += AtA[r][c] * theta[c];
            }
            g.push(s);
        }

        // Build (AtA + lambda*I)
        const M = [];
        for (let r = 0; r < m; r++) {
            const row = [];
            for (let c = 0; c < m; c++) {
                row.push(AtA[r][c] + (r === c ? lambda : 0.0));
            }
            M.push(row);
        }

        // Solve M * delta = -g via Gaussian elimination with partial pivoting
        const aug = [];
        for (let r = 0; r < m; r++) {
            aug.push(M[r].concat([-g[r]]));
        }
        for (let col = 0; col < m; col++) {
            let pivot = col;
            for (let row = col + 1; row < m; row++) {
                if (Math.abs(aug[row][col]) > Math.abs(aug[pivot][col])) {
                    pivot = row;
                }
            }
            [aug[col], aug[pivot]] = [aug[pivot], aug[col]];
            const piv = aug[col][col];
            if (Math.abs(piv) < 1e-12) continue;
            for (let j = col; j <= m; j++) {
                aug[col][j] /= piv;
            }
            for (let row = 0; row < m; row++) {
                if (row === col) continue;
                const factor = aug[row][col];
                for (let j = col; j <= m; j++) {
                    aug[row][j] -= factor * aug[col][j];
                }
            }
        }
        const delta = [];
        for (let r = 0; r < m; r++) {
            delta.push(aug[r][m]);
        }

        const thetaTrial = [];
        for (let j = 0; j < m; j++) {
            thetaTrial.push(theta[j] + delta[j]);
        }
        const trialLoss = loss(thetaTrial);

        if (trialLoss < currentLoss) {
            theta = thetaTrial;
            currentLoss = trialLoss;
            lambda *= 0.1;
        } else {
            lambda *= 10.0;
        }

        if (currentLoss < 1e-12) break;
    }

    return { weights: theta.slice(1), bias: theta[0] };
}
