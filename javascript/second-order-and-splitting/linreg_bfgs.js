/**
 * Linear regression via BFGS quasi-Newton optimization.
 * Minimises the ordinary least-squares objective f(theta)=0.5*||A*theta-y||^2
 * where A=[1|X]. Uses a rank-2 inverse-Hessian update with exact line search
 * for the quadratic objective.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - maximum BFGS iterations
 * @returns {{weights: number[], bias: number}}
 */
function bfgsRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // A = [1 | X]
    const A = [];
    for (let i = 0; i < n; i++) {
        A.push([1.0].concat(X[i]));
    }

    // Precompute AtA and Aty for gradients
    const AtA = [];
    for (let r = 0; r < m; r++) {
        const row = [];
        for (let c = 0; c < m; c++) {
            let s = 0.0;
            for (let i = 0; i < n; i++) {
                s += A[i][r] * A[i][c];
            }
            row.push(s);
        }
        AtA.push(row);
    }
    const Aty = [];
    for (let r = 0; r < m; r++) {
        let s = 0.0;
        for (let i = 0; i < n; i++) {
            s += A[i][r] * y[i];
        }
        Aty.push(s);
    }

    function gradient(theta) {
        const g = [];
        for (let r = 0; r < m; r++) {
            let s = -Aty[r];
            for (let c = 0; c < m; c++) {
                s += AtA[r][c] * theta[c];
            }
            g.push(s);
        }
        return g;
    }

    function matVec(M, v) {
        const out = [];
        for (let i = 0; i < m; i++) {
            let s = 0.0;
            for (let j = 0; j < m; j++) {
                s += M[i][j] * v[j];
            }
            out.push(s);
        }
        return out;
    }

    function dot(a, b) {
        let s = 0.0;
        for (let i = 0; i < a.length; i++) {
            s += a[i] * b[i];
        }
        return s;
    }

    let theta = new Array(m).fill(0.0);
    let g = gradient(theta);

    // Inverse Hessian approximation H, initialised to identity
    const H = [];
    for (let i = 0; i < m; i++) {
        const row = [];
        for (let j = 0; j < m; j++) {
            row.push(i === j ? 1.0 : 0.0);
        }
        H.push(row);
    }

    const maxIter = Math.max(1, iters);
    for (let step = 0; step < maxIter; step++) {
        const gradSq = dot(g, g);
        if (gradSq < 1e-18) break;

        const p = matVec(H, g).map(v => -v);
        const pAp = [];
        for (let i = 0; i < m; i++) {
            let s = 0.0;
            for (let j = 0; j < m; j++) {
                s += AtA[i][j] * p[j];
            }
            pAp.push(s);
        }
        const denom = dot(p, pAp);
        if (Math.abs(denom) < 1e-18) break;
        const alpha = -dot(g, p) / denom;

        const sVec = [];
        for (let i = 0; i < m; i++) {
            sVec.push(alpha * p[i]);
            theta[i] += sVec[i];
        }
        const gNew = gradient(theta);
        const yVec = [];
        for (let i = 0; i < m; i++) {
            yVec.push(gNew[i] - g[i]);
        }
        g = gNew;

        const ys = dot(yVec, sVec);
        if (Math.abs(ys) < 1e-18) break;
        const rho = 1.0 / ys;

        // H = (I - rho s y^T) H (I - rho y s^T) + rho s s^T
        const Hy = matVec(H, yVec);
        const syH = [];
        for (let j = 0; j < m; j++) {
            let s = 0.0;
            for (let i = 0; i < m; i++) {
                s += sVec[i] * H[i][j];
            }
            syH.push(s);
        }
        for (let i = 0; i < m; i++) {
            for (let j = 0; j < m; j++) {
                H[i][j] += rho * sVec[i] * sVec[j]
                    - rho * sVec[i] * Hy[j]
                    - rho * yVec[i] * syH[j]
                    + rho * rho * yVec[i] * dot(sVec, Hy) * sVec[j];
            }
        }
    }

    return { weights: theta.slice(1), bias: theta[0] };
}
