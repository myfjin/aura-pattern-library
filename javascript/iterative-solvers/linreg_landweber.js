/**
 * Linear regression via Landweber iteration.
 * Repeatedly applies the fixed-step iteration
 *   theta_{k+1} = theta_k - alpha * A^T(A*theta_k - y)
 * which is gradient descent on the OLS objective. The step alpha is chosen
 * safely relative to the spectral norm of A.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - number of Landweber iterations
 * @returns {{weights: number[], bias: number}}
 */
function landweberRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // A = [1 | X]
    const A = [];
    for (let i = 0; i < n; i++) {
        A.push([1.0].concat(X[i]));
    }

    // Estimate spectral-norm squared by Frobenius norm squared of A.
    let frobSq = 0.0;
    for (let i = 0; i < n; i++) {
        for (let j = 0; j < m; j++) {
            frobSq += A[i][j] * A[i][j];
        }
    }
    const alpha = 0.9 / frobSq;

    const theta = new Array(m).fill(0.0);
    const maxIter = Math.max(1, iters);

    for (let step = 0; step < maxIter; step++) {
        // residual r = A*theta - y
        const r = [];
        for (let i = 0; i < n; i++) {
            let pred = 0.0;
            for (let j = 0; j < m; j++) {
                pred += A[i][j] * theta[j];
            }
            r.push(pred - y[i]);
        }

        // A^T * r
        const grad = new Array(m).fill(0.0);
        for (let j = 0; j < m; j++) {
            let s = 0.0;
            for (let i = 0; i < n; i++) {
                s += A[i][j] * r[i];
            }
            grad[j] = s;
        }

        for (let j = 0; j < m; j++) {
            theta[j] -= alpha * grad[j];
        }
    }

    return { weights: theta.slice(1), bias: theta[0] };
}
