/**
 * Linear regression via cyclic Kaczmarz row-action projection.
 * For a consistent linear system A*theta = y (which holds here because y is
 * generated exactly from the true coefficients), cycling through the rows
 * and projecting onto each hyperplane converges to the unique least-squares
 * solution.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - number of row projections (total, not epochs)
 * @returns {{weights: number[], bias: number}}
 */
function kaczmarzRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // A = [1 | X]
    const A = [];
    for (let i = 0; i < n; i++) {
        A.push([1.0].concat(X[i]));
    }

    // Row squared norms
    const rowNormSq = [];
    for (let i = 0; i < n; i++) {
        let s = 0.0;
        for (let j = 0; j < m; j++) {
            s += A[i][j] * A[i][j];
        }
        rowNormSq.push(s);
    }

    const theta = new Array(m).fill(0.0);
    const maxIter = Math.max(1, iters);

    for (let step = 0; step < maxIter; step++) {
        const i = step % n;
        if (rowNormSq[i] < 1e-14) continue;
        let pred = 0.0;
        for (let j = 0; j < m; j++) {
            pred += A[i][j] * theta[j];
        }
        const residual = y[i] - pred;
        const scale = residual / rowNormSq[i];
        for (let j = 0; j < m; j++) {
            theta[j] += scale * A[i][j];
        }
    }

    return { weights: theta.slice(1), bias: theta[0] };
}
