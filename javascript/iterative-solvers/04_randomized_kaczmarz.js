/**
 * Randomized Kaczmarz for linear regression.
 *
 * Unlike cyclic Kaczmarz, rows are picked with probability proportional to
 * their squared norm using a seeded PRNG local to this file. This is a
 * structurally different row-action method from the cyclic variant in batch 4.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused learning rate (harness contract)
 * @param {number} iters - number of row projections
 * @returns {{weights: number[], bias: number}}
 */
function randomizedKaczmarzRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // Seeded PRNG local to this fixture.
    let rngState = 20240811 >>> 0;
    function rand() {
        rngState = ((rngState * 1664525 + 1013904223) & 0xFFFFFFFF) >>> 0;
        return rngState / 0x100000000;
    }

    const A = new Array(n);
    for (let i = 0; i < n; i++) {
        A[i] = new Array(m);
        A[i][0] = 1.0;
        for (let j = 0; j < nf; j++) A[i][j + 1] = X[i][j];
    }

    const rowNormSq = new Array(n);
    let totalWeight = 0;
    for (let i = 0; i < n; i++) {
        let s = 0;
        for (let j = 0; j < m; j++) s += A[i][j] * A[i][j];
        rowNormSq[i] = s;
        totalWeight += s;
    }

    // Build a discrete CDF for row sampling.
    const cdf = new Array(n);
    let acc = 0;
    for (let i = 0; i < n; i++) {
        acc += rowNormSq[i] / totalWeight;
        cdf[i] = acc;
    }

    function sampleRow() {
        const u = rand();
        let lo = 0, hi = n - 1;
        while (lo < hi) {
            const mid = Math.floor((lo + hi) / 2);
            if (cdf[mid] < u) lo = mid + 1;
            else hi = mid;
        }
        return lo;
    }

    const theta = new Array(m).fill(0.0);
    for (let step = 0; step < iters; step++) {
        const i = sampleRow();
        if (rowNormSq[i] < 1e-14) continue;
        let pred = 0.0;
        for (let j = 0; j < m; j++) pred += A[i][j] * theta[j];
        const residual = y[i] - pred;
        const scale = residual / rowNormSq[i];
        for (let j = 0; j < m; j++) theta[j] += scale * A[i][j];
    }

    return { weights: theta.slice(1), bias: theta[0] };
}

