/**
 * Linear regression via LSQR, the iterative least-squares solver based on
 * Golub-Kahan bidiagonalisation of A = [1 | X]. LSQR minimises ||A theta - y||
 * without forming A^T A explicitly. This differs from batch 3's LU, batch 2's
 * Cholesky and the direct normal-equation solvers.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - maximum LSQR iterations
 * @returns {{weights: number[], bias: number}}
 */
function lsqrRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // A = [1 | X]
    const A = [];
    for (let i = 0; i < n; i++) {
        A.push([1.0].concat(X[i]));
    }

    // Matrix-vector helpers.
    function matVec(v) {
        const out = [];
        for (let i = 0; i < n; i++) {
            let s = 0.0;
            for (let j = 0; j < m; j++) {
                s += A[i][j] * v[j];
            }
            out.push(s);
        }
        return out;
    }

    function transMatVec(u) {
        const out = [];
        for (let j = 0; j < m; j++) {
            let s = 0.0;
            for (let i = 0; i < n; i++) {
                s += A[i][j] * u[i];
            }
            out.push(s);
        }
        return out;
    }

    function norm(v) {
        let s = 0.0;
        for (let i = 0; i < v.length; i++) {
            s += v[i] * v[i];
        }
        return Math.sqrt(s);
    }

    function scaleInPlace(v, c) {
        for (let i = 0; i < v.length; i++) {
            v[i] *= c;
        }
    }

    function addScaled(dest, src, scale) {
        for (let i = 0; i < dest.length; i++) {
            dest[i] += scale * src[i];
        }
    }

    // LSQR initialisation.
    let u = y.slice();
    const beta = norm(u);
    if (beta > 1e-12) {
        scaleInPlace(u, 1.0 / beta);
    }
    let v = transMatVec(u);
    let alpha = norm(v);
    if (alpha > 1e-12) {
        scaleInPlace(v, 1.0 / alpha);
    }

    let w = v.slice();
    let phiBar = beta;
    let rhoBar = alpha;
    const theta = new Array(m).fill(0.0);

    const maxIter = Math.max(1, Math.min(iters, 4 * m));
    for (let step = 0; step < maxIter; step++) {
        // Bidiagonalisation step.
        const Av = matVec(v);
        for (let i = 0; i < n; i++) {
            u[i] = Av[i] - alpha * u[i];
        }
        const betaNew = norm(u);
        if (betaNew > 1e-12) {
            scaleInPlace(u, 1.0 / betaNew);
        }
        const Atu = transMatVec(u);
        for (let j = 0; j < m; j++) {
            v[j] = Atu[j] - betaNew * v[j];
        }
        const alphaNew = norm(v);
        if (alphaNew > 1e-12) {
            scaleInPlace(v, 1.0 / alphaNew);
        }

        // Givens rotation to eliminate betaNew below diagonal.
        const rho = Math.sqrt(rhoBar * rhoBar + betaNew * betaNew);
        const c = rhoBar / rho;
        const s = betaNew / rho;
        const thetaG = s * alphaNew;
        rhoBar = -c * alphaNew;
        const phi = c * phiBar;
        phiBar = s * phiBar;

        // Update solution and search direction.
        for (let j = 0; j < m; j++) {
            theta[j] += (phi / rho) * w[j];
            w[j] = v[j] - (thetaG / rho) * w[j];
        }

        alpha = alphaNew;
    }

    return { weights: theta.slice(1), bias: theta[0] };
}
