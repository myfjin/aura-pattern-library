/**
 * Linear regression via Modified Gram-Schmidt QR decomposition.
 * Computes the reduced QR factorisation of A=[1|X] with immediate
 * orthogonalisation, then solves R*theta = Q^T*y. This differs from
 * batch 2 classical Gram-Schmidt and batch 3 Givens QR.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - unused (signature compatibility)
 * @returns {{weights: number[], bias: number}}
 */
function modifiedGramSchmidtRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // A = [1 | X]
    const A = [];
    for (let i = 0; i < n; i++) {
        A.push([1.0].concat(X[i]));
    }

    // Q initially a deep copy of A; R starts zero.
    const Q = [];
    for (let i = 0; i < n; i++) {
        Q.push(A[i].slice());
    }
    const R = [];
    for (let k = 0; k < m; k++) {
        R.push(new Array(m).fill(0.0));
    }

    // Modified Gram-Schmidt
    for (let k = 0; k < m; k++) {
        let norm = 0.0;
        for (let i = 0; i < n; i++) {
            norm += Q[i][k] * Q[i][k];
        }
        norm = Math.sqrt(norm);
        R[k][k] = norm;
        if (norm > 1e-12) {
            for (let i = 0; i < n; i++) {
                Q[i][k] /= norm;
            }
        }
        for (let j = k + 1; j < m; j++) {
            let dot = 0.0;
            for (let i = 0; i < n; i++) {
                dot += Q[i][k] * Q[i][j];
            }
            R[k][j] = dot;
            for (let i = 0; i < n; i++) {
                Q[i][j] -= dot * Q[i][k];
            }
        }
    }

    // Q^T y
    const Qty = [];
    for (let k = 0; k < m; k++) {
        let s = 0.0;
        for (let i = 0; i < n; i++) {
            s += Q[i][k] * y[i];
        }
        Qty.push(s);
    }

    // Back-substitution: R theta = Q^T y
    const theta = new Array(m).fill(0.0);
    for (let i = m - 1; i >= 0; i--) {
        let s = Qty[i];
        for (let j = i + 1; j < m; j++) {
            s -= R[i][j] * theta[j];
        }
        theta[i] = Math.abs(R[i][i]) > 1e-12 ? s / R[i][i] : 0.0;
    }

    return { weights: theta.slice(1), bias: theta[0] };
}
