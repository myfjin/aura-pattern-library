/**
 * Linear regression via Givens-rotation QR decomposition.
 * Applies plane rotations to reduce A = [1 | X] to upper triangular form R
 * while simultaneously transforming y, then back-substitutes.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - unused (signature compatibility)
 * @returns {{weights: number[], bias: number}}
 */
function givensQrRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // A = [1 | X]
    const A = [];
    for (let i = 0; i < n; i++) {
        A.push([1.0].concat(X[i]));
    }

    // Work copies: R and transformed target c.
    const R = [];
    for (let i = 0; i < n; i++) {
        R.push(A[i].slice());
    }
    const c = y.slice();

    // Apply Givens rotations to zero R[i][j] for i > j.
    for (let j = 0; j < m; j++) {
        for (let i = n - 1; i > j; i--) {
            const a = R[i - 1][j];
            const b = R[i][j];
            const r = Math.sqrt(a * a + b * b);
            if (r < 1e-14) continue;
            const cosVal = a / r;
            const sinVal = b / r;
            // Rotate rows i-1 and i of R
            for (let k = j; k < m; k++) {
                const a_k = R[i - 1][k];
                const b_k = R[i][k];
                R[i - 1][k] = cosVal * a_k + sinVal * b_k;
                R[i][k] = -sinVal * a_k + cosVal * b_k;
            }
            // Rotate entries of c
            const a_y = c[i - 1];
            const b_y = c[i];
            c[i - 1] = cosVal * a_y + sinVal * b_y;
            c[i] = -sinVal * a_y + cosVal * b_y;
        }
    }

    // Back-substitution using the top m rows of R.
    const theta = new Array(m).fill(0.0);
    for (let i = m - 1; i >= 0; i--) {
        let s = c[i];
        for (let k = i + 1; k < m; k++) {
            s -= R[i][k] * theta[k];
        }
        theta[i] = s / R[i][i];
    }

    return { weights: theta.slice(1), bias: theta[0] };
}
