/**
 * Linear regression via LU decomposition with partial pivoting.
 * Builds A^T A theta = A^T y and solves with LU factorization.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - unused (signature compatibility)
 * @returns {{weights: number[], bias: number}}
 */
function luRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // A = [1 | X]
    const A = [];
    for (let i = 0; i < n; i++) {
        A.push([1.0].concat(X[i]));
    }

    // A^T A and A^T y
    const AtA = [];
    for (let r = 0; r < m; r++) {
        const row = [];
        for (let c = 0; c < m; c++) {
            let s = 0.0;
            for (let i = 0; i < n; i++) {
                s += A[i][r] * A[i][c];
            }
            row.push(s);
        }
        AtA.push(row);
    }
    const Aty = [];
    for (let r = 0; r < m; r++) {
        let s = 0.0;
        for (let i = 0; i < n; i++) {
            s += A[i][r] * y[i];
        }
        Aty.push(s);
    }

    // LU with partial pivoting on AtA
    const L = [];
    const U = [];
    for (let r = 0; r < m; r++) {
        L.push(new Array(m).fill(0.0));
        U.push(AtA[r].slice());
    }
    const P = [];
    for (let i = 0; i < m; i++) P.push(i);

    for (let k = 0; k < m; k++) {
        let pivot = k;
        for (let i = k + 1; i < m; i++) {
            if (Math.abs(U[i][k]) > Math.abs(U[pivot][k])) {
                pivot = i;
            }
        }
        if (pivot !== k) {
            [U[k], U[pivot]] = [U[pivot], U[k]];
            [P[k], P[pivot]] = [P[pivot], P[k]];
        }
        L[k][k] = 1.0;
        for (let i = k + 1; i < m; i++) {
            const factor = U[i][k] / U[k][k];
            L[i][k] = factor;
            for (let j = k; j < m; j++) {
                U[i][j] -= factor * U[k][j];
            }
        }
    }

    // Forward substitution: L z = P Aty
    const Pb = [];
    for (let i = 0; i < m; i++) {
        Pb.push(Aty[P[i]]);
    }
    const z = [];
    for (let i = 0; i < m; i++) {
        let s = Pb[i];
        for (let j = 0; j < i; j++) {
            s -= L[i][j] * z[j];
        }
        z.push(s);
    }

    // Back substitution: U theta = z
    const theta = new Array(m).fill(0.0);
    for (let i = m - 1; i >= 0; i--) {
        let s = z[i];
        for (let j = i + 1; j < m; j++) {
            s -= U[i][j] * theta[j];
        }
        theta[i] = s / U[i][i];
    }

    return { weights: theta.slice(1), bias: theta[0] };
}
