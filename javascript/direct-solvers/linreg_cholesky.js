/**
 * Linear regression via Cholesky decomposition of A^T A.
 * lr and iters are unused.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - unused (signature compatibility)
 * @param {number} iters - unused (signature compatibility)
 * @returns {{weights: number[], bias: number}}
 */
function choleskyRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const m = nf + 1;

    // A = [1 | X]
    const A = [];
    for (let i = 0; i < n; i++) {
        A.push([1.0].concat(X[i]));
    }

    // A^T A and A^T y
    const AtA = [];
    for (let r = 0; r < m; r++) {
        const row = [];
        for (let c = 0; c < m; c++) {
            let s = 0.0;
            for (let i = 0; i < n; i++) {
                s += A[i][r] * A[i][c];
            }
            row.push(s);
        }
        AtA.push(row);
    }
    const Aty = [];
    for (let r = 0; r < m; r++) {
        let s = 0.0;
        for (let i = 0; i < n; i++) {
            s += A[i][r] * y[i];
        }
        Aty.push(s);
    }

    // Cholesky: AtA = L L^T
    const L = [];
    for (let r = 0; r < m; r++) {
        L.push(new Array(m).fill(0.0));
    }
    for (let i = 0; i < m; i++) {
        for (let j = 0; j <= i; j++) {
            let s = AtA[i][j];
            for (let k = 0; k < j; k++) {
                s -= L[i][k] * L[j][k];
            }
            if (i === j) {
                L[i][j] = s > 0 ? Math.sqrt(s) : 1e-8;
            } else {
                L[i][j] = L[j][j] !== 0 ? s / L[j][j] : 0.0;
            }
        }
    }

    // Forward: L z = Aty
    const z = [];
    for (let i = 0; i < m; i++) {
        let s = Aty[i];
        for (let k = 0; k < i; k++) {
            s -= L[i][k] * z[k];
        }
        z.push(L[i][i] !== 0 ? s / L[i][i] : 0.0);
    }

    // Backward: L^T theta = z
    const theta = new Array(m).fill(0.0);
    for (let i = m - 1; i >= 0; i--) {
        let s = z[i];
        for (let k = i + 1; k < m; k++) {
            s -= L[k][i] * theta[k];
        }
        theta[i] = L[i][i] !== 0 ? s / L[i][i] : 0.0;
    }

    return { weights: theta.slice(1), bias: theta[0] };
}

