/**
 * Recursive divide-and-conquer summation statistics.
 *
 * Sums are computed recursively, splitting the array until it reaches a small
 * base case. This minimises the depth of sequential accumulation and often
 * improves accuracy compared to a single linear pass.
 *
 * @param {number[][]} X - data matrix (column 0 used)
 * @param {number[]} y - target values
 * @param {number} lr - unused learning rate (harness contract)
 * @param {number} iters - unused iteration count (harness contract)
 * @returns {{statsX:{mean:number,variance:number}, statsY:{mean:number,variance:number}, correlation:number, covariance:number}}
 */
function recursiveSummation(X, y, lr, iters) {
    const xs = X.map(row => row[0]);
    const ys = y;
    const n = xs.length;

    function recSum(vals, lo, hi) {
        if (hi - lo <= 4) {
            let s = 0;
            for (let i = lo; i < hi; i++) s += vals[i];
            return s;
        }
        const mid = lo + Math.floor((hi - lo) / 2);
        return recSum(vals, lo, mid) + recSum(vals, mid, hi);
    }

    function recSumSq(vals, mean, lo, hi) {
        if (hi - lo <= 4) {
            let s = 0;
            for (let i = lo; i < hi; i++) {
                const d = vals[i] - mean;
                s += d * d;
            }
            return s;
        }
        const mid = lo + Math.floor((hi - lo) / 2);
        return recSumSq(vals, mean, lo, mid) + recSumSq(vals, mean, mid, hi);
    }

    const meanX = recSum(xs, 0, n) / n;
    const meanY = recSum(ys, 0, n) / n;
    const varianceX = recSumSq(xs, meanX, 0, n) / n;
    const varianceY = recSumSq(ys, meanY, 0, n) / n;

    function recCov(lo, hi) {
        if (hi - lo <= 4) {
            let s = 0;
            for (let i = lo; i < hi; i++) s += (xs[i] - meanX) * (ys[i] - meanY);
            return s;
        }
        const mid = lo + Math.floor((hi - lo) / 2);
        return recCov(lo, mid) + recCov(mid, hi);
    }

    const cov = recCov(0, n) / n;
    const correlation = varianceX > 0 && varianceY > 0 ? cov / Math.sqrt(varianceX * varianceY) : 0;

    return {
        statsX: { mean: meanX, variance: varianceX },
        statsY: { mean: meanY, variance: varianceY },
        correlation,
        covariance: cov,
    };
}

