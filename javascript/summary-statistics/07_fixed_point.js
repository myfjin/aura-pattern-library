/**
 * Scaled fixed-point / integer accumulation statistics.
 *
 * Scales floating-point values into a fixed-point representation based on the
 * observed data range, accumulates integer-like scaled sums, then converts
 * back. This avoids many round-off errors in the accumulation step.
 *
 * @param {number[][]} X - data matrix (column 0 used)
 * @param {number[]} y - target values
 * @param {number} lr - unused learning rate (harness contract)
 * @param {number} iters - unused iteration count (harness contract)
 * @returns {{statsX:{mean:number,variance:number}, statsY:{mean:number,variance:number}, correlation:number, covariance:number}}
 */
function fixedPointSum(X, y, lr, iters) {
    const xs = X.map(row => row[0]);
    const ys = y;
    const n = xs.length;

    function scaleParams(vals) {
        let min = Infinity;
        let max = -Infinity;
        for (let i = 0; i < vals.length; i++) {
            const v = vals[i];
            if (v < min) min = v;
            if (v > max) max = v;
        }
        if (!isFinite(min) || !isFinite(max)) return { scale: 1, offset: 0 };
        const span = max - min;
        const scale = span === 0 ? 1 : span ? (Math.pow(2, 52) / Math.max(Math.abs(min), Math.abs(max))) : 1;
        // Clamp to a safe exponent to avoid overflow.
        const safeScale = Math.min(scale, 1e15);
        return { scale: safeScale, offset: (min + max) / 2 };
    }

    function fixedSum(vals, scale, offset) {
        let s = 0;
        for (let i = 0; i < vals.length; i++) s += Math.round((vals[i] - offset) * scale);
        return s / scale + offset * vals.length;
    }

    function fixedMean(vals) {
        const { scale, offset } = scaleParams(vals);
        return fixedSum(vals, scale, offset) / vals.length;
    }

    const meanX = fixedMean(xs);
    const meanY = fixedMean(ys);

    function fixedSumSq(vals, mean) {
        const diffs = vals.map(v => v - mean);
        const { scale, offset } = scaleParams(diffs);
        let s = 0;
        for (let i = 0; i < diffs.length; i++) {
            const d = Math.round((diffs[i] - offset) * scale);
            s += d * d;
        }
        return s / (scale * scale) + 2 * offset * fixedSum(diffs, scale, offset) / scale - offset * offset * diffs.length;
    }

    const varianceX = fixedSumSq(xs, meanX) / n;
    const varianceY = fixedSumSq(ys, meanY) / n;

    function fixedCov(xv, yv, mx, my) {
        const dx = xv.map(v => v - mx);
        const dy = yv.map(v => v - my);
        const vals = dx.map((v, i) => v * dy[i]);
        const { scale, offset } = scaleParams(vals);
        return fixedSum(vals, scale, offset) / xv.length;
    }

    const cov = fixedCov(xs, ys, meanX, meanY);

    const correlation = varianceX > 0 && varianceY > 0 ? cov / Math.sqrt(varianceX * varianceY) : 0;

    return {
        statsX: { mean: meanX, variance: varianceX },
        statsY: { mean: meanY, variance: varianceY },
        correlation,
        covariance: cov,
    };
}

