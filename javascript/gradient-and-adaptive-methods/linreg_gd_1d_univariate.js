/**
 * Univariate linear regression via batch gradient descent
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - learning rate
 * @param {number} iters - number of iterations
 * @returns {{weights: number[], bias: number}}
 */
function univariateGd(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const weights = new Array(nf).fill(0.0);
    let bias = 0.0;

    for (let i = 0; i < iters; i++) {
        const dw = new Array(nf).fill(0.0);
        let db = 0.0;
        for (let j = 0; j < n; j++) {
            let pred = bias;
            for (let k = 0; k < nf; k++) {
                pred += weights[k] * X[j][k];
            }
            const err = pred - y[j];
            db += err;
            for (let k = 0; k < nf; k++) {
                dw[k] += err * X[j][k];
            }
        }
        db /= n;
        for (let k = 0; k < nf; k++) {
            dw[k] /= n;
        }
        for (let k = 0; k < nf; k++) {
            weights[k] -= lr * dw[k];
        }
        bias -= lr * db;
    }

    return { weights: weights, bias: bias };
}


