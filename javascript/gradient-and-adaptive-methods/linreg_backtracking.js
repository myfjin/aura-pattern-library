/**
 * Gradient descent with backtracking line search (Armijo condition) for
 * linear regression.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - initial step size
 * @param {number} iters - number of outer iterations
 * @returns {{weights: number[], bias: number}}
 */
function backtrackingLineSearchGd(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const weights = new Array(nf).fill(0.0);
    let bias = 0.0;
    const c = 1e-4;
    const rho = 0.5;

    function computeGradient(w, b) {
        const dw = new Array(nf).fill(0.0);
        let db = 0.0;
        for (let i = 0; i < n; i++) {
            let pred = b;
            for (let j = 0; j < nf; j++) {
                pred += w[j] * X[i][j];
            }
            const err = pred - y[i];
            db += err;
            for (let j = 0; j < nf; j++) {
                dw[j] += err * X[i][j];
            }
        }
        db /= n;
        for (let j = 0; j < nf; j++) {
            dw[j] /= n;
        }
        return { dw: dw, db: db };
    }

    function loss(w, b) {
        let s = 0.0;
        for (let i = 0; i < n; i++) {
            let pred = b;
            for (let j = 0; j < nf; j++) {
                pred += w[j] * X[i][j];
            }
            const err = pred - y[i];
            s += err * err;
        }
        return s / (2.0 * n);
    }

    for (let it = 0; it < iters; it++) {
        const grad = computeGradient(weights, bias);
        const gradSq = grad.db * grad.db + grad.dw.reduce((acc, g) => acc + g * g, 0.0);
        if (gradSq < 1e-18) break;

        const currentLoss = loss(weights, bias);
        let step = lr;
        let accepted = false;
        for (let trial = 0; trial < 30; trial++) {
            const wNew = [];
            for (let j = 0; j < nf; j++) {
                wNew.push(weights[j] - step * grad.dw[j]);
            }
            const bNew = bias - step * grad.db;
            if (loss(wNew, bNew) <= currentLoss - c * step * gradSq) {
                for (let j = 0; j < nf; j++) {
                    weights[j] = wNew[j];
                }
                bias = bNew;
                accepted = true;
                break;
            }
            step *= rho;
        }
        if (!accepted) {
            // Fallback: take a very small fixed step rather than stalling.
            for (let j = 0; j < nf; j++) {
                weights[j] -= 1e-6 * grad.dw[j];
            }
            bias -= 1e-6 * grad.db;
        }
    }

    return { weights: weights, bias: bias };
}
