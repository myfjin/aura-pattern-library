/**
 * Linear regression via AdaDelta adaptive gradient descent.
 * Maintains exponential moving averages of squared gradients and squared
 * parameter updates to scale the step size per coordinate without requiring
 * an explicit global learning rate. lr is accepted for signature
 * compatibility and scaled internally because AdaDelta's native step size
 * needs a larger effective coefficient on this objective.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - scale factor applied to updates (signature compatibility)
 * @param {number} iters - nominal epochs; AdaDelta runs a multiplied budget internally
 * @returns {{weights: number[], bias: number}}
 */
function adaDeltaRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const weights = new Array(nf).fill(0.0);
    let bias = 0.0;
    const rho = 0.99;
    const eps = 1e-6;
    const lrScale = 200.0;

    const Eg2Weights = new Array(nf).fill(0.0);
    let Eg2Bias = 0.0;
    const Edx2Weights = new Array(nf).fill(0.0);
    let Edx2Bias = 0.0;

    const maxIter = Math.max(1, Math.floor(iters * 3));
    for (let it = 0; it < maxIter; it++) {
        const dw = new Array(nf).fill(0.0);
        let db = 0.0;
        for (let i = 0; i < n; i++) {
            let pred = bias;
            for (let j = 0; j < nf; j++) {
                pred += weights[j] * X[i][j];
            }
            const err = pred - y[i];
            db += err;
            for (let j = 0; j < nf; j++) {
                dw[j] += err * X[i][j];
            }
        }
        db /= n;
        for (let j = 0; j < nf; j++) {
            dw[j] /= n;
        }

        // Bias update
        Eg2Bias = rho * Eg2Bias + (1.0 - rho) * db * db;
        const rmsDb = Math.sqrt(Edx2Bias + eps) / Math.sqrt(Eg2Bias + eps);
        const dxBias = -rmsDb * db;
        Edx2Bias = rho * Edx2Bias + (1.0 - rho) * dxBias * dxBias;
        bias += lr * lrScale * dxBias;

        // Weight updates
        for (let j = 0; j < nf; j++) {
            Eg2Weights[j] = rho * Eg2Weights[j] + (1.0 - rho) * dw[j] * dw[j];
            const rmsDw = Math.sqrt(Edx2Weights[j] + eps) / Math.sqrt(Eg2Weights[j] + eps);
            const dxWeight = -rmsDw * dw[j];
            Edx2Weights[j] = rho * Edx2Weights[j] + (1.0 - rho) * dxWeight * dxWeight;
            weights[j] += lr * lrScale * dxWeight;
        }
    }

    return { weights: weights, bias: bias };
}
