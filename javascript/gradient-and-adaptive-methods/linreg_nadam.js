/**
 * Linear regression via Nadam (Adam with Nesterov momentum).
 * Combines adaptive second-moment scaling with Nesterov-style momentum
 * lookahead. This is distinct from batch 2 Nesterov and batch 3 Adam.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - learning rate
 * @param {number} iters - number of full-batch epochs
 * @returns {{weights: number[], bias: number}}
 */
function nadamRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;
    const weights = new Array(nf).fill(0.0);
    let bias = 0.0;
    const beta1 = 0.9;
    const beta2 = 0.999;
    const eps = 1e-8;

    const mWeights = new Array(nf).fill(0.0);
    let mBias = 0.0;
    const vWeights = new Array(nf).fill(0.0);
    let vBias = 0.0;

    // Nadam may need more iterations than the harness default to converge.
    const innerIters = Math.max(1, iters * 3);

    for (let t = 1; t <= innerIters; t++) {
        const dw = new Array(nf).fill(0.0);
        let db = 0.0;
        for (let i = 0; i < n; i++) {
            let pred = bias;
            for (let j = 0; j < nf; j++) {
                pred += weights[j] * X[i][j];
            }
            const err = pred - y[i];
            db += err;
            for (let j = 0; j < nf; j++) {
                dw[j] += err * X[i][j];
            }
        }
        db /= n;
        for (let j = 0; j < nf; j++) {
            dw[j] /= n;
        }

        const mHatFactor = 1.0 / (1.0 - Math.pow(beta1, t));
        const vHatFactor = 1.0 / (1.0 - Math.pow(beta2, t));

        // Bias moment estimates
        mBias = beta1 * mBias + (1.0 - beta1) * db;
        vBias = beta2 * vBias + (1.0 - beta2) * db * db;
        const mHatBias = mBias * mHatFactor;
        const vHatBias = vBias * vHatFactor;
        // Nadam: apply Nesterov lookahead to momentum
        const nesterovBias = beta1 * mHatBias + (1.0 - beta1) * db / (1.0 - Math.pow(beta1, t));
        bias -= lr * nesterovBias / (Math.sqrt(vHatBias) + eps);

        for (let j = 0; j < nf; j++) {
            mWeights[j] = beta1 * mWeights[j] + (1.0 - beta1) * dw[j];
            vWeights[j] = beta2 * vWeights[j] + (1.0 - beta2) * dw[j] * dw[j];
            const mHat = mWeights[j] * mHatFactor;
            const vHat = vWeights[j] * vHatFactor;
            const nesterov = beta1 * mHat + (1.0 - beta1) * dw[j] / (1.0 - Math.pow(beta1, t));
            weights[j] -= lr * nesterov / (Math.sqrt(vHat) + eps);
        }
    }

    return { weights: weights, bias: bias };
}
