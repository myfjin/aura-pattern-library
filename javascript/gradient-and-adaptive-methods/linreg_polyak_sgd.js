/**
 * Linear regression via Polyak-averaged stochastic gradient descent.
 * Performs one-sample SGD with a fixed learning rate and returns the average
 * of the iterates (Polyak averaging), which reduces variance compared with
 * plain SGD. The random order is produced by a deterministic LCG seeded
 * inside the file, so output is independent of the harness-injected RNG.
 * This differs from batch 2's plain SGD.
 *
 * @param {number[][]} X - design matrix
 * @param {number[]} y - target values
 * @param {number} lr - learning rate (used)
 * @param {number} iters - SGD epochs; total steps = iters * n
 * @returns {{weights: number[], bias: number}}
 */
function polyakSgdRegression(X, y, lr, iters) {
    const n = X.length;
    const nf = X[0].length;

    // Deterministic LCG; seed fixed inside the fixture.
    let state = 12345 >>> 0;
    function random() {
        state = ((state * 1664525 + 1013904223) & 0xFFFFFFFF) >>> 0;
        return state / 0x100000000;
    }

    // Initialise weights and bias.
    let weights = new Array(nf).fill(0.0);
    let bias = 0.0;

    // Running sum of iterates for Polyak averaging.
    let weightSum = new Array(nf).fill(0.0);
    let biasSum = 0.0;
    let count = 0;

    const epochs = Math.max(1, iters);
    const usedLr = lr > 0 ? lr : 0.05;

    for (let epoch = 0; epoch < epochs; epoch++) {
        // Fisher-Yates shuffle with the seeded LCG.
        const order = [];
        for (let i = 0; i < n; i++) {
            order.push(i);
        }
        for (let i = n - 1; i > 0; i--) {
            const j = Math.floor(random() * (i + 1));
            const tmp = order[i];
            order[i] = order[j];
            order[j] = tmp;
        }

        for (let s = 0; s < n; s++) {
            const idx = order[s];
            const row = X[idx];
            let pred = bias;
            for (let j = 0; j < nf; j++) {
                pred += weights[j] * row[j];
            }
            const err = pred - y[idx];
            for (let j = 0; j < nf; j++) {
                weights[j] -= usedLr * err * row[j];
            }
            bias -= usedLr * err;

            for (let j = 0; j < nf; j++) {
                weightSum[j] += weights[j];
            }
            biasSum += bias;
            count += 1;
        }
    }

    const outWeights = [];
    for (let j = 0; j < nf; j++) {
        outWeights.push(weightSum[j] / count);
    }
    return { weights: outWeights, bias: biasSum / count };
}
